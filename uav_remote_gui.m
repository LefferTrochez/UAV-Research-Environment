    function [tStart,tStop,nSamples] = ...
            simulationTimeSpanFromOutput(simOut)
        tStart = ...
            NaN;
        tStop = ...
            NaN;
        nSamples = ...
            0;
        outputVariables = ...
            who( ...
                simOut);
        if ismember( ...
                'liveTelemetryLog', ...
                outputVariables)
            liveLog = ...
                simOut.liveTelemetryLog;
            if isa( ...
                    liveLog, ...
                    'Simulink.SimulationData.Signal')
                liveLog = ...
                    liveLog.Values;
            end
            if isa( ...
                    liveLog, ...
                    'timeseries')
                timeVector = ...
                    double( ...
                        liveLog.Time(:));
                timeVector = ...
                    timeVector( ...
                        isfinite(timeVector));
                if ~isempty(timeVector)
                    tStart = ...
                        timeVector(1);
                    tStop = ...
                        timeVector(end);
                    nSamples = ...
                        numel(timeVector);
                end
            end
        end
        if (~isfinite(tStart) || ~isfinite(tStop)) && ...
                ismember( ...
                    'tout', ...
                    outputVariables)
            try
                toutValue = ...
                    simOut.tout;
                if isa( ...
                        toutValue, ...
                        'timeseries')

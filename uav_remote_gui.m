    function axisLimits = localFixedAxisInterval( ...
            values, ...
            marginFraction, ...
            minimumMargin, ...
            minimumSpan)
        values = ...
            double( ...
                values(:));
        values = ...
            values( ...
                isfinite(values));
        if isempty(values)
            axisLimits = ...
                [-1 1];
            return;
        end
        valueMinimum = ...
            min(values);
        valueMaximum = ...
            max(values);
        plannedSpan = ...
            valueMaximum - ...
            valueMinimum;
        effectiveSpan = ...
            max( ...
                plannedSpan, ...
                minimumSpan);
        center = ...
            0.5 * ...
            (valueMinimum + valueMaximum);
        if plannedSpan < minimumSpan
            valueMinimum = ...
                center - ...
                0.5*minimumSpan;
            valueMaximum = ...
                center + ...
                0.5*minimumSpan;
        end
        margin = ...
            max( ...
                minimumMargin, ...
                marginFraction * ...
                effectiveSpan);
        axisLimits = [ ...
            valueMinimum-margin, ...
            valueMaximum+margin];
    end

    function ready = simulationOutputReady()
        ready = false;
        try
            if ~evalin( ...
                    'base', ...
                    'exist(''out'',''var'')')
                return;
            end
            simOut = evalin( ...
                'base', ...
                'out');
            if ~isa( ...
                    simOut, ...
                    'Simulink.SimulationOutput')
                return;
            end
            variables = who( ...
                simOut);
            requiredVariables = { ...
                'trueStatesLog', ...
                'estStatesLog', ...
                'estimatorComparisonLog', ...
                'cgsLog', ...
                'omegaLog', ...
                'controlAxesLog', ...
                'cmdAttitudeLog', ...
                'cmdAngularRateLog', ...
                'selectedEulerLog', ...
                'selectedAngularRateLog', ...
                'liveTelemetryLog', ...
                'MissionPlanLog'};
            ready = all( ...
                ismember( ...
                    requiredVariables, ...
                    variables));
        catch
            ready = false;

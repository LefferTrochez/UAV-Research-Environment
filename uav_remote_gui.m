    function changeUAVModel(src,~)
        recordBenchmarkConfigurationChange( ...
            'UAV_MODEL', ...
            false);
        previousModel = evalin( ...
            'base', ...
            'UAV_MODEL');
        assignin( ...
            'base', ...
            'UAV_MODEL', ...
            src.Value);
        oldDefault = sprintf( ...
            'StateEstimator_L%d', ...
            previousModel);
        if strcmp( ...
                strtrim(resultNameField.Value), ...
                oldDefault)
            resultNameField.Value = sprintf( ...
                'StateEstimator_L%d', ...
                src.Value);
        end
        fprintf( ...
            'UAV Model: L%d\n', ...
            src.Value);
    end
    function changeOperatorMode(src,~)
        try
            simStatus = get_param( ...
                mdl, ...
                'SimulationStatus');
            if ~strcmpi( ...
                    simStatus, ...
                    'stopped')
                currentMode = evalin( ...
                    'base', ...
                    'OPERATOR_MODE');
                src.Value = ...
                    double(currentMode);
                uialert( ...
                    fig, ...
                    ['Operator Mode can only be changed while the ', ...
                     'simulation is stopped.'], ...
                    'Operator Mode Locked');
                return;
            end
            modeValue = ...
                uint8(src.Value);
            setOperatorModeValue( ...
                modeValue);
            setArmCommand( ...
                false);
            trajectoryRequestID = ...
                uint32(0);
            setRunTrajectoryRequestID( ...
                trajectoryRequestID);
            if modeValue == uint8(1)
                stopField.Enable = ...
                    'off';
                applyAutomaticStopTime();
                armButton.Enable = ...
                    'off';
                runTrajectoryButton.Enable = ...
                    'off';
                disarmButton.Enable = ...
                    'off';
                statusLabel.Text = ...
                    'Ready - Operator mode: AUTOMATIC';
                fprintf( ...
                    'Operator Mode: AUTOMATIC\n');
            else
                stopField.Enable = ...
                    'on';
                armButton.Enable = ...
                    'off';
                runTrajectoryButton.Enable = ...
                    'off';
                disarmButton.Enable = ...
                    'off';
                statusLabel.Text = ...
                    'Ready - Operator mode: MANUAL';
                fprintf( ...
                    'Operator Mode: MANUAL\n');
            end
        catch ME
            uialert( ...
                fig, ...
                ME.message, ...
                'Operator Mode Error');
        end
    end

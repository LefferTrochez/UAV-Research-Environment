    function value = sanitizeSimulationMetadataForExport(value)
        sensitiveFields = { ...
            'UserID', ...
            'UserName', ...
            'MachineName', ...
            'HostName', ...
            'ModelFilePath', ...
            'FilePath', ...
            'ProjectRoot', ...
            'ResultsFolder', ...
            'RunFolder', ...
            'TlogPath', ...
            'Author', ...
            'Creator', ...
            'LastModifiedBy', ...
            'Organization', ...
            'Affiliation', ...
            'Email'};
        if isstruct(value)
            names = ...
                fieldnames(value);
            for iField = 1:numel(names)
                fieldName = ...
                    names{iField};
                if any(strcmpi(fieldName,sensitiveFields))
                    value = ...
                        rmfield( ...
                            value, ...
                            fieldName);
                    continue;
                end
                for iElement = 1:numel(value)
                    value(iElement).(fieldName) = ...
                        sanitizeSimulationMetadataForExport( ...
                            value(iElement).(fieldName));
                end
            end
        elseif iscell(value)
            for iElement = 1:numel(value)
                value{iElement} = ...
                    sanitizeSimulationMetadataForExport( ...
                        value{iElement});
            end
        elseif isstring(value)
            for iElement = 1:numel(value)
                if ismissing(value(iElement))
                    continue;
                end
                valueText = ...
                    char(value(iElement));
                if containsSensitiveMetadataText( ...
                        valueText)
                    value(iElement) = ...
                        "";
                end
            end
        elseif ischar(value)
            if containsSensitiveMetadataText( ...
                    value)
                value = ...
                    '';
            end
        end
    end
    function detected = containsSensitiveMetadataText(valueText)
        detected = ...
            false;
        valueText = ...
            char( ...
                string(valueText));
        trimmedValue = ...
            strtrim(valueText);
        if isempty(trimmedValue)
            return;
        end
        if ~isempty( ...
                regexp( ...
                    valueText, ...
                    '[A-Za-z]:[\\/]', ...
                    'once'))
            detected = ...
                true;
            return;
        end
        if startsWith( ...
                trimmedValue, ...
                '\\')
            detected = ...
                true;
            return;
        end
        if ~isempty( ...
                regexp( ...
                    valueText, ...
                    '(^|\\s)/[A-Za-z0-9._-]+/', ...
                    'once'))
            detected = ...
                true;
            return;
        end
        if ~isempty( ...
                regexpi( ...
                    valueText, ...
                    'https?://', ...
                    'once'))
            detected = ...
                true;
            return;
        end
        if ~isempty( ...
                regexp( ...
                    valueText, ...
                    '[A-Za-z0-9._%+\\-]+@[A-Za-z0-9.\\-]+\\.[A-Za-z]{2,}', ...
                    'once'))
            detected = ...
                true;
        end
    end

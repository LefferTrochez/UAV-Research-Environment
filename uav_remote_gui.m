    function changePacingEnable(src,~)
        recordBenchmarkConfigurationChange( ...
            'PACING_ENABLE', ...
            logical(src.Value));
        try
            if src.Value
                set_param( ...
                    mdl, ...
                    'EnablePacing', ...
                    'on');
                if benchmarkRunState.active
                    statusLabel.Text = ...
                        ['Pacing enabled - computational-cost benchmark ', ...
                         'will be marked INVALID'];
                end
                set_param( ...
                    mdl, ...
                    'PacingRate', ...
                    num2str( ...
                        paceSlider.Value));
            else
                set_param( ...
                    mdl, ...
                    'EnablePacing', ...
                    'off');
            end
        catch ME
            warning( ...
                'Unable to modify simulation pacing: %s', ...
                ME.message);
        end
    end

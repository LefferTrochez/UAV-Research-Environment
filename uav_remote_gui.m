    function stopTime_s = getAutomaticProtocolStopTime()
        if ~evalin( ...
                'base', ...
                'exist(''AUTO_PROTOCOL'',''var'')')
            error( ...
                'QuadrotorFramework:MissingAutomaticProtocol', ...
                ['AUTO_PROTOCOL was not found in the MATLAB base ', ...
                 'workspace. Run initialize_project.m first.']);
        end
        if ~evalin( ...
                'base', ...
                'exist(''TRAJECTORY_ID'',''var'')')
            error( ...
                'QuadrotorFramework:MissingTrajectoryID', ...
                ['TRAJECTORY_ID was not found in the MATLAB base ', ...
                 'workspace. Run initialize_project.m first.']);
        end
        protocol = evalin( ...
            'base', ...
            'AUTO_PROTOCOL');
        trajectoryID = double( ...
            evalin( ...
                'base', ...
                'TRAJECTORY_ID'));
        if ~isfield(protocol,'schedule_s') || ...
                isempty(protocol.schedule_s)
            error( ...
                'QuadrotorFramework:InvalidAutomaticProtocol', ...
                'AUTO_PROTOCOL.schedule_s is missing or empty.');
        end
        numberOfProtocols = ...
            size( ...
                protocol.schedule_s, ...
                1);
        if trajectoryID < 1 || ...
                trajectoryID > numberOfProtocols
            error( ...
                'QuadrotorFramework:InvalidTrajectoryID', ...
                ['TRAJECTORY_ID = %d does not correspond to a row ', ...
                 'in AUTO_PROTOCOL.schedule_s.'], ...
                trajectoryID);
        end
        if isfield(protocol,'column') && ...
                isfield(protocol.column,'stop')
            stopColumn = ...
                protocol.column.stop;
        else
            stopColumn = ...
                4;
        end
        stopTime_s = ...
            double( ...
                protocol.schedule_s( ...
                    trajectoryID, ...
                    stopColumn));
        if ~isfinite(stopTime_s) || ...
                stopTime_s <= 0
            error( ...
                'QuadrotorFramework:InvalidAutomaticStopTime', ...
                'Automatic protocol STOP time must be finite and > 0.');
        end
    end

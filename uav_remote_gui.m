    function generateComputationalCostMetrics()
        if ~evalin( ...
                'base', ...
                'exist(''out'',''var'')')
            error( ...
                'QuadrotorFramework:MissingOutputForComputationalCost', ...
                'Simulation output "out" is unavailable.');
        end
        simOut = ...
            evalin( ...
                'base', ...
                'out');
        if ~isa( ...
                simOut, ...
                'Simulink.SimulationOutput')
            error( ...
                'QuadrotorFramework:InvalidOutputForComputationalCost', ...
                '"out" must be a Simulink.SimulationOutput object.');
        end
        finalizeBenchmarkRunCapture();
        BenchmarkRunSnapshot = ...
            benchmarkRunState;
        try
            simulationMetadata = ...
                simOut.SimulationMetadata;
        catch
            try
                simulationMetadata = ...
                    getSimulationMetadata( ...
                        simOut);
            catch ME
                error( ...
                    'QuadrotorFramework:SimulationMetadataUnavailable', ...
                    ['Unable to access Simulink SimulationMetadata: ', ...
                     '%s'], ...
                    ME.message);
            end
        end
        TimingInfo = ...
            simulationMetadata.TimingInfo;
        ModelInfo = ...
            simulationMetadata.ModelInfo;
        ExecutionInfo = ...
            simulationMetadata.ExecutionInfo;
        SimulationMetadataSnapshot = ...
            struct();
        SimulationMetadataSnapshot.TimingInfo = ...
            sanitizeSimulationMetadataForExport( ...
                TimingInfo);
        SimulationMetadataSnapshot.ModelInfo = ...
            sanitizeSimulationMetadataForExport( ...
                ModelInfo);
        SimulationMetadataSnapshot.ExecutionInfo = ...
            sanitizeSimulationMetadataForExport( ...
                ExecutionInfo);
        InitializationElapsedWallTime_s = ...
            metadataNumericField( ...
                TimingInfo, ...
                'InitializationElapsedWallTime', ...
                NaN);
        ExecutionElapsedWallTime_s = ...
            metadataNumericField( ...
                TimingInfo, ...
                'ExecutionElapsedWallTime', ...
                NaN);
        TerminationElapsedWallTime_s = ...
            metadataNumericField( ...
                TimingInfo, ...
                'TerminationElapsedWallTime', ...
                NaN);
        TotalElapsedWallTime_s = ...
            metadataNumericField( ...
                TimingInfo, ...
                'TotalElapsedWallTime', ...
                NaN);
        WallClockTimestampStart = ...
            string( ...
                metadataTextField( ...
                    TimingInfo, ...
                    'WallClockTimestampStart', ...
                    ''));
        WallClockTimestampStop = ...
            string( ...
                metadataTextField( ...
                    TimingInfo, ...
                    'WallClockTimestampStop', ...
                    ''));
        [SimulationStartTime_s, ...
         SimulationStopTime_s, ...
         LiveTelemetrySamples] = ...
            simulationTimeSpanFromOutput( ...
                simOut);
        SimulatedRunDuration_s = ...
            SimulationStopTime_s - ...
            SimulationStartTime_s;
        if ~isfinite(SimulatedRunDuration_s) || ...
                SimulatedRunDuration_s <= 0
            SimulatedRunDuration_s = ...
                NaN;
        end
        DetectedMissions = ...
            0;
        MissionStartTime_s = ...
            NaN;
        MissionEndTime_s = ...
            NaN;
        PhysicalMissionDuration_s = ...
            NaN;
        MissionCompleted = ...
            false;
        FailsafeAborted = ...
            false;
        if evalin( ...
                'base', ...
                'exist(''MissionMetrics'',''var'')')
            MissionMetricsLocal = ...
                evalin( ...
                    'base', ...
                    'MissionMetrics');
            if istable(MissionMetricsLocal)
                DetectedMissions = ...
                    height( ...
                        MissionMetricsLocal);
                if DetectedMissions > 0
                    variableNames = ...
                        MissionMetricsLocal.Properties.VariableNames;
                    if ismember( ...
                            'StartTime_s', ...
                            variableNames)
                        finiteStart = ...
                            double( ...
                                MissionMetricsLocal.StartTime_s);
                        finiteStart = ...
                            finiteStart( ...
                                isfinite(finiteStart));
                        if ~isempty(finiteStart)
                            MissionStartTime_s = ...
                                min(finiteStart);
                        end
                    end
                    if ismember( ...
                            'MissionDuration_s', ...
                            variableNames)
                        durations = ...
                            double( ...
                                MissionMetricsLocal.MissionDuration_s);
                        finiteDurations = ...
                            durations( ...
                                isfinite(durations) & ...
                                durations >= 0);
                        if ~isempty(finiteDurations)
                            PhysicalMissionDuration_s = ...
                                sum(finiteDurations);
                        end
                        if ismember( ...
                                'StartTime_s', ...
                                variableNames)
                            candidateEnds = ...
                                double(MissionMetricsLocal.StartTime_s) + ...
                                durations;
                            candidateEnds = ...
                                candidateEnds( ...
                                    isfinite(candidateEnds));
                            if ~isempty(candidateEnds)
                                MissionEndTime_s = ...
                                    max(candidateEnds);
                            end
                        elseif DetectedMissions == 1 && ...
                                isfinite(MissionStartTime_s) && ...
                                isfinite(PhysicalMissionDuration_s)
                            MissionEndTime_s = ...
                                MissionStartTime_s + ...
                                PhysicalMissionDuration_s;
                        end
                    end
                    if ismember( ...
                            'Completed', ...
                            variableNames)
                        MissionCompleted = ...
                            DetectedMissions == 1 && ...
                            all( ...
                                logical( ...
                                    MissionMetricsLocal.Completed));
                    end
                    if ismember( ...
                            'FailsafeAborted', ...
                            variableNames)
                        FailsafeAborted = ...
                            any( ...
                                logical( ...
                                    MissionMetricsLocal.FailsafeAborted));
                    end
                end
            end
        end
        SolverType = ...
            "";
        SolverName = ...
            "";
        SolverMaxStepSize_s = ...
            NaN;
        SolverFixedStepSize_s = ...
            NaN;
        SolverStepStatisticsAvailable = ...
            false;
        SolverInfo = ...
            struct();
        if isstruct(ModelInfo) && ...
                isfield(ModelInfo,'SolverInfo')
            SolverInfo = ...
                ModelInfo.SolverInfo;
            SolverType = ...
                string( ...
                    metadataTextField( ...
                        SolverInfo, ...
                        'Type', ...
                        ''));
            SolverName = ...
                string( ...
                    metadataTextField( ...
                        SolverInfo, ...
                        'Solver', ...
                        ''));
            SolverMaxStepSize_s = ...
                metadataNumericField( ...
                    SolverInfo, ...
                    'MaxStepSize', ...
                    NaN);
            SolverFixedStepSize_s = ...
                metadataNumericField( ...
                    SolverInfo, ...
                    'FixedStepSize', ...
                    NaN);
        end
        SimulationMetadataSnapshot.SolverInfo = ...
            sanitizeSimulationMetadataForExport( ...
                SolverInfo);
        StopEvent = ...
            string( ...
                metadataTextField( ...
                    ExecutionInfo, ...
                    'StopEvent', ...
                    ''));
        StopEventTime_s = ...
            metadataNumericField( ...
                ExecutionInfo, ...
                'StopEventTime', ...
                NaN);
        if isfinite(StopEventTime_s) && ...
                isfinite(SimulationStartTime_s) && ...
                StopEventTime_s >= SimulationStartTime_s
            SimulationStopTime_s = ...
                StopEventTime_s;
            SimulatedRunDuration_s = ...
                SimulationStopTime_s - ...
                SimulationStartTime_s;
        end
        SimulationErrorPresent = ...
            false;
        WarningCount = ...
            0;
        if isstruct(ExecutionInfo)
            if isfield(ExecutionInfo,'ErrorDiagnostic')
                SimulationErrorPresent = ...
                    ~isempty( ...
                        ExecutionInfo.ErrorDiagnostic);
            end
            if isfield(ExecutionInfo,'WarningDiagnostics')
                WarningCount = ...
                    numel( ...
                        ExecutionInfo.WarningDiagnostics);
            end
        end
        NaturalStop = ...
            contains( ...
                lower( ...
                    StopEvent), ...
                'stop') && ...
            contains( ...
                lower( ...
                    StopEvent), ...
                'time');
        RealTimeFactor_RTF = ...
            NaN;
        ComputationalTimeFactor_CTF = ...
            NaN;
        if isfinite(SimulatedRunDuration_s) && ...
                SimulatedRunDuration_s > 0 && ...
                isfinite(ExecutionElapsedWallTime_s) && ...
                ExecutionElapsedWallTime_s > 0
            RealTimeFactor_RTF = ...
                SimulatedRunDuration_s / ...
                ExecutionElapsedWallTime_s;
            ComputationalTimeFactor_CTF = ...
                ExecutionElapsedWallTime_s / ...
                SimulatedRunDuration_s;
        end
        BenchmarkConfigAvailable = ...
            false;
        ComputationalCostEnabled = ...
            true;
        RequirePacingDisabled = ...
            true;
        MetricSampleRate_Hz = ...
            NaN;
        if evalin( ...
                'base', ...
                'exist(''BENCHMARK_METRICS'',''var'')')
            benchmarkConfig = ...
                evalin( ...
                    'base', ...
                    'BENCHMARK_METRICS');
            if isstruct(benchmarkConfig)
                BenchmarkConfigAvailable = ...
                    true;
                if isfield(benchmarkConfig,'sampleRate_Hz')
                    MetricSampleRate_Hz = ...
                        double( ...
                            benchmarkConfig.sampleRate_Hz);
                end
                if isfield(benchmarkConfig,'computationalCost') && ...
                        isstruct(benchmarkConfig.computationalCost)
                    costConfig = ...
                        benchmarkConfig.computationalCost;
                    if isfield(costConfig,'enabled')
                        ComputationalCostEnabled = ...
                            logical( ...
                                costConfig.enabled);
                    end
                    if isfield(costConfig,'requirePacingDisabled')
                        RequirePacingDisabled = ...
                            logical( ...
                                costConfig.requirePacingDisabled);
                    end
                end
            end
        end
        BenchmarkCaptureValid = ...
            logical( ...
                BenchmarkRunSnapshot.captureValid);
        UAVModel = ...
            double( ...
                BenchmarkRunSnapshot.uavModel);
        DisturbancesEnabled = ...
            logical( ...
                BenchmarkRunSnapshot.disturbancesEnabled);
        OperatorMode = ...
            double( ...
                BenchmarkRunSnapshot.operatorMode);
        TrajectoryID = ...
            double( ...
                BenchmarkRunSnapshot.trajectoryID);
        TrajectoryName = ...
            string( ...
                BenchmarkRunSnapshot.trajectoryName);
        NumWaypoints = ...
            double( ...
                BenchmarkRunSnapshot.numWaypoints);
        PacingEnabledAtStart = ...
            logical( ...
                BenchmarkRunSnapshot.pacingEnabledAtStart);
        PacingRateAtStart = ...
            double( ...
                BenchmarkRunSnapshot.pacingRateAtStart);
        PacingEverEnabled = ...
            logical( ...
                BenchmarkRunSnapshot.pacingEverEnabled);
        PacingConfigurationChangedDuringRun = ...
            logical( ...
                BenchmarkRunSnapshot.pacingConfigurationChangedDuringRun);
        ExperimentConfigurationChangedDuringRun = ...
            logical( ...
                BenchmarkRunSnapshot.experimentConfigurationChangedDuringRun);
        ConfigurationChangeCount = ...
            double( ...
                BenchmarkRunSnapshot.configurationChangeCount);
        MeasurementContext = ...
            "GUI_SIMULATION_WITH_LIVE_MONITORING";
        invalidReasons = ...
            strings(0,1);
        if ~ComputationalCostEnabled
            invalidReasons(end+1,1) = ...
                "computational-cost-disabled";
        end
        if ~BenchmarkCaptureValid
            invalidReasons(end+1,1) = ...
                "gui-benchmark-run-snapshot-unavailable";
        end
        if ~BenchmarkConfigAvailable
            invalidReasons(end+1,1) = ...
                "benchmark-config-unavailable";
        end
        if ~isfinite(ExecutionElapsedWallTime_s) || ...
                ExecutionElapsedWallTime_s <= 0
            invalidReasons(end+1,1) = ...
                "invalid-execution-wall-time";
        end
        if ~isfinite(SimulatedRunDuration_s) || ...
                SimulatedRunDuration_s <= 0
            invalidReasons(end+1,1) = ...
                "invalid-simulated-run-duration";
        end
        if RequirePacingDisabled && ...
                PacingEverEnabled
            invalidReasons(end+1,1) = ...
                "pacing-enabled";
        end
        if ExperimentConfigurationChangedDuringRun
            invalidReasons(end+1,1) = ...
                "experiment-configuration-changed-during-run";
        end
        if PacingConfigurationChangedDuringRun
            invalidReasons(end+1,1) = ...
                "pacing-configuration-changed-during-run";
        end
        if OperatorMode ~= 1
            invalidReasons(end+1,1) = ...
                "operator-mode-not-automatic";
        end
        if DetectedMissions ~= 1
            invalidReasons(end+1,1) = ...
                "expected-exactly-one-mission";
        end
        if ~MissionCompleted
            invalidReasons(end+1,1) = ...
                "mission-not-completed";
        end
        if FailsafeAborted
            invalidReasons(end+1,1) = ...
                "failsafe-aborted";
        end
        if SimulationErrorPresent
            invalidReasons(end+1,1) = ...
                "simulation-error";
        end
        if ~NaturalStop
            invalidReasons(end+1,1) = ...
                "simulation-did-not-reach-configured-stop-time";
        end
        OfficialComputationalBenchmark = ...
            isempty( ...
                invalidReasons);
        if OfficialComputationalBenchmark
            ComputationalBenchmarkStatus = ...
                "VALID";
            ComputationalBenchmarkInvalidReason = ...
                "";
        else
            ComputationalBenchmarkStatus = ...
                "INVALID";
            ComputationalBenchmarkInvalidReason = ...
                strjoin( ...
                    invalidReasons, ...
                    "; ");
        end
        ComputationalCostMetrics = ...
            table( ...
                UAVModel, ...
                TrajectoryID, ...
                TrajectoryName, ...
                NumWaypoints, ...
                DisturbancesEnabled, ...
                OperatorMode, ...
                DetectedMissions, ...
                MissionCompleted, ...
                FailsafeAborted, ...
                SimulationStartTime_s, ...
                SimulationStopTime_s, ...
                SimulatedRunDuration_s, ...
                MissionStartTime_s, ...
                MissionEndTime_s, ...
                PhysicalMissionDuration_s, ...
                InitializationElapsedWallTime_s, ...
                ExecutionElapsedWallTime_s, ...
                TerminationElapsedWallTime_s, ...
                TotalElapsedWallTime_s, ...
                RealTimeFactor_RTF, ...
                ComputationalTimeFactor_CTF, ...
                SolverType, ...
                SolverName, ...
                SolverMaxStepSize_s, ...
                SolverFixedStepSize_s, ...
                SolverStepStatisticsAvailable, ...
                StopEvent, ...
                StopEventTime_s, ...
                NaturalStop, ...
                SimulationErrorPresent, ...
                WarningCount, ...
                LiveTelemetrySamples, ...
                MetricSampleRate_Hz, ...
                PacingEnabledAtStart, ...
                PacingRateAtStart, ...
                PacingEverEnabled, ...
                PacingConfigurationChangedDuringRun, ...
                ExperimentConfigurationChangedDuringRun, ...
                ConfigurationChangeCount, ...
                MeasurementContext, ...
                BenchmarkCaptureValid, ...
                BenchmarkConfigAvailable, ...
                OfficialComputationalBenchmark, ...
                ComputationalBenchmarkStatus, ...
                ComputationalBenchmarkInvalidReason, ...
                WallClockTimestampStart, ...
                WallClockTimestampStop);
        assignin( ...
            'base', ...
            'ComputationalCostMetrics', ...
            ComputationalCostMetrics);
        assignin( ...
            'base', ...
            'BenchmarkRunSnapshot', ...
            BenchmarkRunSnapshot);
        assignin( ...
            'base', ...
            'SimulationMetadataSnapshot', ...
            SimulationMetadataSnapshot);
        fprintf('\n');
        fprintf( ...
            '============================================================\n');
        fprintf( ...
            ' COMPUTATIONAL COST METRICS\n');
        fprintf( ...
            '============================================================\n');
        fprintf( ...
            'Initialization wall time: %.6f s\n', ...
            InitializationElapsedWallTime_s);
        fprintf( ...
            'Execution wall time:      %.6f s\n', ...
            ExecutionElapsedWallTime_s);
        fprintf( ...
            'Termination wall time:    %.6f s\n', ...
            TerminationElapsedWallTime_s);
        fprintf( ...
            'Total wall time:          %.6f s\n', ...
            TotalElapsedWallTime_s);
        fprintf( ...
            'Simulated run duration:   %.6f s\n', ...
            SimulatedRunDuration_s);
        fprintf( ...
            'RTF:                      %.6f\n', ...
            RealTimeFactor_RTF);
        fprintf( ...
            'CTF:                      %.6f\n', ...
            ComputationalTimeFactor_CTF);
        fprintf( ...
            'Solver:                   %s / %s\n', ...
            char(SolverType), ...
            char(SolverName));
        fprintf( ...
            'Pacing ever enabled:      %s\n', ...
            logicalToTextBenchmark( ...
                PacingEverEnabled));
        fprintf( ...
            'Official cost benchmark:  %s\n', ...
            char(ComputationalBenchmarkStatus));
        if ~OfficialComputationalBenchmark
            fprintf( ...
                'Invalid reason:          %s\n', ...
                char(ComputationalBenchmarkInvalidReason));
        end
        fprintf( ...
            '============================================================\n\n');
        disp( ...
            ComputationalCostMetrics);
    end

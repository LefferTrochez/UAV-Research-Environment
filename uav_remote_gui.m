        else
            motorSpeedsForVisual = motorSpeeds;
        end
        [missionPlan,numWaypoints,maxWaypoints,missionPlanDecoded] = ...
            decodeTelemetryTrajectory( ...
                Telemetry);
        if missionPlanDecoded
            missionWaypointsNED = ...

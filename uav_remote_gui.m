    function startSimulation(~,~)
        try
            assignin( ...
                'base', ...
                'SAVE_METRICS_REQUESTED', ...
                false);
            setArmCommand( ...
                false);
            trajectoryRequestID = ...
                uint32(0);
            setRunTrajectoryRequestID( ...
                trajectoryRequestID);
            setOperatorModeValue( ...
                uint8(operatorModeDrop.Value));
            if isAutomaticOperatorMode()
                applyAutomaticStopTime();
            end
            assignin( ...
                'base', ...
                'UAV_MODEL', ...
                modelDrop.Value);
            assignin( ...
                'base', ...
                'DIST_ENABLE', ...
                logical(distCheck.Value));
            if ~isAutomaticOperatorMode()
                set_param( ...
                    mdl, ...
                    'StopTime', ...
                    num2str( ...
                        stopField.Value));
            end
            set_param( ...
                mdl, ...
                'ReturnWorkspaceOutputs', ...
                'on');
            set_param( ...
                mdl, ...
                'ReturnWorkspaceOutputsName', ...
                'out');
            if paceCheck.Value
                set_param( ...
                    mdl, ...
                    'EnablePacing', ...
                    'on');
                set_param( ...
                    mdl, ...
                    'PacingRate', ...
                    num2str( ...
                        paceSlider.Value));
            else
                set_param( ...
                    mdl, ...
                    'EnablePacing', ...
                    'off');
            end
            beginBenchmarkRunCapture();
            evalin( ...
                'base', ...
                'clear out');
            resetLiveStatusDisplay();
            openLiveTrajectoryWindow();
            startPostProcessMonitor();
            simStatus = get_param( ...
                mdl, ...
                'SimulationStatus');
            if strcmpi( ...
                    simStatus, ...
                    'stopped')
                statusLabel.Text = ...
                    'Simulation initializing...';
                startButton.Enable = ...
                    'off';
                operatorModeDrop.Enable = ...
                    'off';
                armButton.Enable = ...
                    'off';
                runTrajectoryButton.Enable = ...
                    'off';
                disarmButton.Enable = ...
                    'off';
                setLivePhase( ...
                    'SIMULATION INITIALIZING', ...
                    [0.92 0.92 0.82]);
                updateLiveTrajectoryWaitingState( ...
                    'initializing');
                postMonitorRunCommandIssued = ...
                    true;
                set_param( ...
                    mdl, ...
                    'SimulationCommand', ...
                    'start');
                startLiveStatusMonitor();
            end
        catch ME
            benchmarkRunState.active = ...
                false;

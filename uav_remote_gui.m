            telemetryLength >= (59 + 4*3) && ...
            mod(telemetryLength-59,4) == 0;
        legacyTelemetryValid = ...
            telemetryLength == 58;
        if ~genericTelemetryValid && ...
                ~legacyTelemetryValid
            return;
        end
        requiredCoreIndices = [ ...
            1:14, ...
            43:58];
        if ~all( ...
                isfinite( ...
                    Telemetry(requiredCoreIndices)))
            return;
        end
        telemetryTime = double(Telemetry(1));
        phaseValue = double(Telemetry(2));
        missionActive = logical(Telemetry(3));
        cgsComplete = logical(Telemetry(4));
        modeValue = double(Telemetry(5));
        armed = logical(Telemetry(6));
        missionComplete = logical(Telemetry(7));
        landed = logical(Telemetry(8));
        positionRef = reshape( ...
            double(Telemetry(9:11)), ...
            3, ...
            1);
        operationalPosition = reshape( ...
            double(Telemetry(12:14)), ...
            3, ...
            1);

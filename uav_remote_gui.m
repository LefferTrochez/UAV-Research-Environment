    function checkSimulationFinished(~,~)
        if isempty(fig) || ~isvalid(fig)
            stopPostProcessMonitor();
            return;
        end
        try
            simStatus = get_param( ...
                mdl, ...
                'SimulationStatus');
        catch
            stopPostProcessMonitor();
            return;
        end
        if ~postMonitorRunCommandIssued
            return;
        end
        if ~strcmpi( ...
                simStatus, ...
                'stopped')
            return;
        end
        finalizeBenchmarkRunCapture();
        stopLiveStatusMonitor();
        startButton.Enable = ...
            'on';
        operatorModeDrop.Enable = ...
            'on';
        if isAutomaticOperatorMode()
            stopField.Enable = ...
                'off';
        else
            stopField.Enable = ...
                'on';
        end
        armButton.Enable = ...
            'off';
        runTrajectoryButton.Enable = ...
            'off';
        disarmButton.Enable = ...
            'off';
        setArmCommand( ...
                false);
        setLivePhase( ...
            'SIMULATION STOPPED', ...
            [0.90 0.90 0.90]);
        setStatusLamp(armedLamp,false);
        setStatusLamp(activeLamp,false);
        setStatusLamp(completeLamp,false);
        setStatusLamp(landedLamp,false);
        updateLiveTrajectoryWaitingState( ...
            'stopped');
        if ~simulationOutputReady()
            postProcessAttempts = ...
                postProcessAttempts + 1;
            if postProcessAttempts >= ...
                    MAX_POSTPROCESS_ATTEMPTS
                stopPostProcessMonitor();
                statusLabel.Text = ...
                    'Simulation finished - logs unavailable';
                warning( ...
                    ['Simulation finished, but the expected ', ...
                     'SimulationOutput logs were not found.']);
            end
            return;
        end
        stopPostProcessMonitor();
        assignin( ...
            'base', ...
            'SAVE_METRICS_REQUESTED', ...
            false);
        try
            statusLabel.Text = ...
                'Generating figures and metrics...';
            drawnow;
            runAllPostProcessing();
            statusLabel.Text = ...
                'Simulation complete - UAV command: DISARMED';
        catch ME
            statusLabel.Text = ...
                'Post-processing error';
            warning( ...
                'Post-processing failed: %s', ...
                ME.message);
        end
    end

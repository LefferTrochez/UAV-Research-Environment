    function updateLiveStatus(varargin)
        if isempty(fig) || ~isvalid(fig)
            stopLiveStatusMonitor();
            return;
        end
        try
            simStatus = get_param( ...
                mdl, ...
                'SimulationStatus');
        catch
            return;
        end
        if strcmpi(simStatus,'stopped')
            setLivePhase( ...
                'SIMULATION STOPPED', ...
                [0.90 0.90 0.90]);
            setStatusLamp(armedLamp,false);
            setStatusLamp(activeLamp,false);
            setStatusLamp(completeLamp,false);
            setStatusLamp(landedLamp,false);
            armButton.Enable = 'off';
            runTrajectoryButton.Enable = 'off';
            disarmButton.Enable = 'off';
            updateLiveTrajectoryWaitingState( ...
                'stopped');
            return;
        end
        runtimeSafe = ...
            strcmpi(simStatus,'running') || ...
            strcmpi(simStatus,'paused');
        if ~runtimeSafe
            phaseText = upper( ...
                strrep( ...
                    char(simStatus), ...
                    '_', ...
                    ' '));
            setLivePhase( ...
                ['SIMULATION ' phaseText], ...
                [0.92 0.92 0.82]);
            setStatusLamp(armedLamp,false);
            setStatusLamp(activeLamp,false);
            setStatusLamp(completeLamp,false);
            setStatusLamp(landedLamp,false);
            armButton.Enable = 'off';
            runTrajectoryButton.Enable = 'off';
            disarmButton.Enable = 'off';
            statusLabel.Text = ...
                ['Simulation ' lower(char(simStatus)) '...'];
            updateLiveTrajectoryWaitingState( ...
                char(simStatus));
            return;
        end
        [Telemetry,telemetryOK] = ...
            readLiveTelemetry();
        if ~telemetryOK
            setLivePhase( ...
                'RUNNING - WAITING FOR TELEMETRY', ...
                [0.82 0.88 0.98]);
            setStatusLamp(armedLamp,false);
            setStatusLamp(activeLamp,false);
            setStatusLamp(completeLamp,false);
            setStatusLamp(landedLamp,false);
            armButton.Enable = 'off';
            runTrajectoryButton.Enable = 'off';
            disarmButton.Enable = 'off';
            statusLabel.Text = ...
                'Simulation running - waiting for live telemetry...';
            updateLiveTrajectoryWaitingState( ...
                'waiting for telemetry');
            return;
        end
        simulationTime = double(Telemetry(1));
        phaseValue = double(Telemetry(2));
        missionActive = logical(Telemetry(3));
        cgsComplete = logical(Telemetry(4));
        modeValue = double(Telemetry(5));
        armed = logical(Telemetry(6));
        flightMissionComplete = logical(Telemetry(7));
        landed = logical(Telemetry(8));
        [~,numWaypoints,~,trajectoryMetadataOK] = ...
            decodeTelemetryTrajectory( ...
                Telemetry);
        if ~trajectoryMetadataOK && ...
                numWaypoints < 3
            numWaypoints = ...
                inferSelectedNumWaypointsFromWorkspace( ...
                    Inf);
        end
        completeForDisplay = ...
            cgsComplete || ...
            flightMissionComplete;
        setStatusLamp(armedLamp,armed);
        setStatusLamp(activeLamp,missionActive);
        setStatusLamp(completeLamp,completeForDisplay);
        setStatusLamp(landedLamp,landed);
        if isAutomaticOperatorMode()
            armButton.Enable = 'off';
            runTrajectoryButton.Enable = 'off';
            disarmButton.Enable = 'off';
        elseif ~armed
            armButton.Enable = 'on';
            runTrajectoryButton.Enable = 'off';
            disarmButton.Enable = 'off';
        elseif missionActive
            armButton.Enable = 'off';
            runTrajectoryButton.Enable = 'off';
            disarmButton.Enable = 'on';
        elseif landed
            armButton.Enable = 'off';
            runTrajectoryButton.Enable = 'on';
            disarmButton.Enable = 'on';
        elseif round(phaseValue) == 0
            armButton.Enable = 'off';
            runTrajectoryButton.Enable = 'on';
            disarmButton.Enable = 'on';
        else
            armButton.Enable = 'off';
            runTrajectoryButton.Enable = 'off';
            disarmButton.Enable = 'on';
        end
        if ~armed
            setLivePhase( ...
                'DISARMED', ...
                [0.88 0.88 0.88]);
            statusLabel.Text = sprintf( ...
                'Simulation running - DISARMED - t = %.1f s', ...
                simulationTime);
        elseif landed
            setLivePhase( ...
                'LANDED ARMED', ...
                [0.76 0.92 0.76]);
            statusLabel.Text = sprintf( ...
                'Mission complete - LANDED ARMED - t = %.1f s', ...
                simulationTime);
        elseif completeForDisplay
            setLivePhase( ...
                'LANDING CONFIRMATION', ...
                [1.00 0.87 0.62]);
            statusLabel.Text = sprintf( ...
                'Landing confirmation - t = %.1f s', ...
                simulationTime);
        else

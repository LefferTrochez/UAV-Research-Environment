    function [Telemetry,ok] = readLiveTelemetry()
        persistent lastWarnedInvalidTelemetryLength
        Telemetry = ...
            zeros(0,1);
        ok = ...
            false;
        if isempty(lastWarnedInvalidTelemetryLength)
            lastWarnedInvalidTelemetryLength = ...
                -1;
        end
        if getSimulinkBlockHandle( ...
                telemetry_block) == -1
            return;
        end
        try
            runtimeObject = get_param( ...
                telemetry_block, ...
                'RuntimeObject');
            if isempty(runtimeObject)
                return;
            end
            runtimeData = ...
                runtimeObject.OutputPort(1).Data;
            if isempty(runtimeData)
                return;
            end
            runtimeData = ...
                double( ...
                    runtimeData(:));
            telemetryLength = ...
                numel( ...
                    runtimeData);
            if telemetryLength == 58
                Telemetry = ...
                    runtimeData;
                ok = ...
                    true;
                return;
            end
            genericLengthValid = ...
                telemetryLength >= (59 + 4*3) && ...
                mod(telemetryLength-59,4) == 0;
            if ~genericLengthValid
                if lastWarnedInvalidTelemetryLength ~= ...
                        telemetryLength
                    warning( ...
                        'QuadrotorFramework:InvalidLiveTelemetrySize', ...
                        ['Live Telemetry/Telemetry_Pack returned %d ', ...
                         'elements. Expected legacy 58 or generic ', ...
                         '59 + 4*MAX_WAYPOINTS with MAX_WAYPOINTS >= 3.'], ...
                        telemetryLength);
                    lastWarnedInvalidTelemetryLength = ...
                        telemetryLength;
                end
                return;
            end
            Telemetry = ...
                runtimeData;
            ok = ...
                true;
            lastWarnedInvalidTelemetryLength = ...
                -1;
        catch
            Telemetry = ...
                zeros(0,1);
            ok = ...
                false;
        end
    end
    function [missionPlan,numWaypoints,maxWaypoints,ok] = ...
            decodeTelemetryTrajectory(Telemetry)
        missionPlan = ...
            zeros(4,0);
        numWaypoints = ...
            0;
        maxWaypoints = ...
            0;
        ok = ...
            false;
        if isempty(Telemetry)
            return;
        end
        Telemetry = ...
            double( ...
                Telemetry(:));
        telemetryLength = ...
            numel( ...
                Telemetry);
        if telemetryLength == 58
            maxWaypoints = ...
                7;
            numWaypoints = ...
                7;
            missionPlan = ...
                zeros(4,7);
            missionPlan(1,:) = ...
                Telemetry(15:21).';
            missionPlan(2,:) = ...
                Telemetry(22:28).';
            missionPlan(3,:) = ...
                Telemetry(29:35).';
            missionPlan(4,:) = ...
                Telemetry(36:42).';
            ok = ...
                all(isfinite(missionPlan(:)));
            return;
        end
        if telemetryLength < (59 + 4*3) || ...
                mod(telemetryLength-59,4) ~= 0
            return;
        end
        maxWaypoints = ...
            (telemetryLength-59) / ...
            4;
        rawNumWaypoints = ...
            Telemetry(59);
        numWaypointsValid = ...
            isfinite(rawNumWaypoints) && ...
            rawNumWaypoints >= 1 && ...
            rawNumWaypoints <= maxWaypoints && ...
            abs( ...
                rawNumWaypoints - ...
                round(rawNumWaypoints)) < 1.0e-9;
        if numWaypointsValid
            numWaypoints = ...
                round( ...
                    rawNumWaypoints);
        else
            numWaypoints = ...
                inferSelectedNumWaypointsFromWorkspace( ...
                    maxWaypoints);
        end
        if numWaypoints < 1 || ...
                numWaypoints > maxWaypoints
            return;
        end
        northStart = ...
            60;
        eastStart = ...
            60 + ...
            maxWaypoints;
        downStart = ...
            60 + ...
            2*maxWaypoints;
        yawStart = ...
            60 + ...
            3*maxWaypoints;
        missionPlanBuffer = ...
            zeros( ...
                4, ...
                maxWaypoints);
        missionPlanBuffer(1,:) = ...
            Telemetry( ...
                northStart : ...
                northStart+maxWaypoints-1).';
        missionPlanBuffer(2,:) = ...
            Telemetry( ...
                eastStart : ...
                eastStart+maxWaypoints-1).';
        missionPlanBuffer(3,:) = ...
            Telemetry( ...
                downStart : ...
                downStart+maxWaypoints-1).';
        missionPlanBuffer(4,:) = ...
            Telemetry( ...
                yawStart : ...
                yawStart+maxWaypoints-1).';
        missionPlan = ...
            missionPlanBuffer( ...
                :, ...
                1:numWaypoints);
        ok = ...
            all(isfinite(missionPlan(:)));
    end
    function numWaypoints = ...
            inferSelectedNumWaypointsFromWorkspace(maxWaypoints)
        numWaypoints = ...
            0;
        try
            if evalin( ...
                    'base', ...
                    'exist(''TRAJECTORY_CONFIG'',''var'')')
                trajectoryConfig = ...
                    evalin( ...
                        'base', ...
                        'TRAJECTORY_CONFIG');
                if isstruct(trajectoryConfig) && ...
                        isfield( ...
                            trajectoryConfig, ...
                            'selectedNumWaypoints')
                    candidate = ...
                        double( ...
                            trajectoryConfig.selectedNumWaypoints);
                    upperBoundValid = ...
                        isinf(maxWaypoints) || ...
                        candidate <= maxWaypoints;
                    if isscalar(candidate) && ...
                            isfinite(candidate) && ...
                            candidate >= 3 && ...
                            upperBoundValid && ...
                            abs(candidate-round(candidate)) < 1.0e-9
                        numWaypoints = ...
                            round(candidate);
                    end
                end
            end
        catch
            numWaypoints = ...
                0;
        end
    end
    function [name,color] = ...
            missionPhaseName(phaseValue,numWaypoints)
        phaseID = ...
            round( ...
                double(phaseValue));
        numWaypoints = ...
            double( ...
                numWaypoints);
        if ~isscalar(numWaypoints) || ...
                ~isfinite(numWaypoints) || ...
                numWaypoints < 3 || ...
                abs(numWaypoints-round(numWaypoints)) > 1.0e-9
            numWaypoints = ...
                inferSelectedNumWaypointsFromWorkspace( ...
                    Inf);
        end
        if numWaypoints < 3
            if phaseID == 0
                name = ...
                    'ARMED IDLE / WAITING';
                color = ...
                    [0.82 0.88 0.98];
            else
                name = ...
                    sprintf( ...
                        'PHASE %d', ...
                        phaseID);
                color = ...
                    [0.95 0.80 0.80];
            end
            return;
        end
        numWaypoints = ...
            round( ...
                numWaypoints);
        landingPhase = ...
            2*numWaypoints - ...
            3;
        completePhase = ...
            2*numWaypoints - ...
            2;
        abortedPhase = ...
            2*numWaypoints - ...
            1;
        if phaseID == 0
            name = ...
                'ARMED IDLE / WAITING';
            color = ...
                [0.82 0.88 0.98];
            return;
        end
        if phaseID == landingPhase
            name = ...
                'LANDING';
            color = ...
                [1.00 0.87 0.62];
            return;
        end
        if phaseID == completePhase
            name = ...
                'MISSION COMPLETE';
            color = ...
                [0.86 0.82 0.96];
            return;
        end
        if phaseID == abortedPhase
            name = ...
                'NAVIGATION FAILSAFE / ABORTED';
            color = ...
                [0.95 0.72 0.72];
            return;
        end
        if phaseID >= 1 && ...
                phaseID < landingPhase
            isHoldPhase = ...
                mod(phaseID,2) == 0;
            if isHoldPhase
                targetIndex = ...
                    (phaseID + 2) / ...
                    2;
            else
                targetIndex = ...
                    (phaseID + 3) / ...
                    2;
            end
            targetIndex = ...
                round( ...
                    targetIndex);
            if targetIndex == 2
                targetName = ...
                    'TAKEOFF';
            elseif targetIndex == numWaypoints-1
                targetName = ...
                    'PRE-LAND WAYPOINT';
            else
                waypointNumber = ...
                    targetIndex - ...
                    2;
                targetName = ...
                    sprintf( ...
                        'WAYPOINT %d', ...
                        waypointNumber);
            end
            if isHoldPhase
                name = ...
                    ['HOLD - ' targetName];
                color = ...
                    [0.82 0.94 0.88];
            else
                name = ...
                    targetName;
                color = ...
                    [0.76 0.92 0.76];
            end
            return;
        end
        name = ...
            sprintf( ...
                'UNKNOWN PHASE (%d)', ...
                phaseID);
        color = ...
            [0.95 0.80 0.80];
    end

    function updateLiveTrajectoryFromTelemetry(Telemetry)
        trajectoryFig = findall( ...
            groot, ...
            'Type','figure', ...
            'Tag','UAV_Trajectory_3D');
        if isempty(trajectoryFig)
            openLiveTrajectoryWindow();

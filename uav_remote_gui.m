            state.numWaypoints = ...
                uint16(0);
        end
        if ~isfield(state,'maxWaypoints') || ...
                ~isscalar(state.maxWaypoints)
            state.maxWaypoints = ...
                NaN;
        end
        if missionPlanDecoded
            state.numWaypoints = ...
                uint16( ...
                    numWaypoints);
            state.maxWaypoints = ...
                maxWaypoints;
        end
        if ~isfield(state,'missionHistoryStarted')
            state.missionHistoryStarted = false;
        end

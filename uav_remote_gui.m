        end
        missionPlanFinite = ...
            missionPlanDecoded && ...
            ~isempty(missionPlan) && ...
            all(isfinite(missionPlan(:)));
        missionPlanReady = ...
            missionPlanFinite && ...
            numWaypoints >= 3 && ...
            localMissionPlanGeometryReady( ...
                missionWaypointsNED);

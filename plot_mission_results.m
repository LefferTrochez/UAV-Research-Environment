            tEnd < tStart || ...
            ~isfinite(sampleRateHz) || ...
            sampleRateHz <= 0
        tGrid = ...
            zeros(0,1);
        return;
    end
    if abs(tEnd-tStart) <= 1e-12
        tGrid = ...
            tStart;
        return;
    end
    dt = ...
        1.0 / ...
        sampleRateHz;
    numberOfFullSteps = ...
        floor( ...
            (tEnd-tStart) / ...
            dt);
    tGrid = ...
        tStart + ...
        (0:numberOfFullSteps).' * ...
        dt;
    if isempty(tGrid)
        tGrid = ...
            [tStart;tEnd];
    elseif tGrid(end) < tEnd - 1e-10
        tGrid(end+1,1) = ...
            tEnd;
    else
        tGrid(end) = ...
            tEnd;
    end
end

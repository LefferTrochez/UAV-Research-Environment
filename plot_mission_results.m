function Xquery = resampleMatrixMission(tSource,XSource,tQuery)
    tSource = ...
        double( ...
            tSource(:));
    tQuery = ...
        double( ...
            tQuery(:));
    if size(XSource,1) ~= numel(tSource)
        error( ...
            'Source matrix row count does not match source time vector.');
    end
    if isempty(tQuery)
        Xquery = ...
            zeros( ...
                0, ...
                size(XSource,2));
        return;
    end
    if numel(tSource) == numel(tQuery) && ...
            all(abs(tSource-tQuery) <= 1e-12)
        Xquery = ...
            XSource;
        return;
    end
    finiteTime = ...
        isfinite(tSource);
    tSource = ...
        tSource(finiteTime);
    XSource = ...
        XSource(finiteTime,:);
    [tUnique,uniqueIndex] = ...
        unique( ...
            tSource, ...
            'stable');
    XUnique = ...
        XSource( ...
            uniqueIndex, ...
            :);
    if isempty(tUnique)
        Xquery = ...
            NaN( ...
                numel(tQuery), ...
                size(XSource,2));
        return;
    end
    if numel(tUnique) == 1
        Xquery = ...
            repmat( ...
                XUnique(1,:), ...
                numel(tQuery), ...
                1);
        return;
    end
    Xquery = ...
        zeros( ...
            numel(tQuery), ...
            size(XUnique,2));
    for column = 1:size(XUnique,2)
        Xquery(:,column) = ...
            interp1( ...
                tUnique, ...
                XUnique(:,column), ...
                tQuery, ...
                'linear', ...
                'extrap');
    end
end
function X = timeseriesDataToMatrixMission(data,nt)
    D = ...
        squeeze( ...
            data);
    if isempty(D)
        X = ...
            zeros(0,0);
        return;
    end
    if nt == 1
        X = ...
            reshape( ...
                D, ...
                1, ...
                []);
        return;
    end
    if isvector(D)
        if numel(D) == nt
            X = ...
                D(:);
        else
            error( ...
                ['Unable to determine logged signal ', ...
                 'orientation.']);
        end
        return;
    end
    if size(D,1) == nt
        X = ...
            reshape( ...
                D, ...
                nt, ...
                []);
    elseif size(D,2) == nt
        X = ...
            D.';
    elseif size(D,ndims(D)) == nt
        order = [ ...
            ndims(D), ...
            1:(ndims(D)-1)];
        D = ...
            permute( ...
                D, ...
                order);
        X = ...
            reshape( ...
                D, ...
                nt, ...
                []);
    else
        error( ...
            ['Unable to match logged signal dimensions ', ...
             'with its time vector.']);
    end
end

    false( ...
        size(t));
for missionIndex = 1:numberOfMissions
    missionStartIdx = ...
        missionStartIndices(missionIndex);
    StartTime_s(missionIndex) = ...
        t(missionStartIdx);
    if missionIndex < numberOfMissions
        missionSearchEndIdx = ...
            missionStartIndices(missionIndex+1) - 1;
    else
        missionSearchEndIdx = ...
            numel(t);
    end
    missionSearchIndices = ...
        missionStartIdx:missionSearchEndIdx;
    [missionPlan,missionNumWaypoints,missionPlanValid] = ...
        missionPlanAtTelemetryRowMission( ...
            Telemetry(missionStartIdx,:));
    if ~missionPlanValid || ...
            missionNumWaypoints < 3
        error( ...
            'QuadrotorFramework:MissionPlanUnavailable', ...
            ['Unable to decode a valid MissionPlan at the start of ', ...
             'mission %d.'], ...
            missionIndex);
    end
    NumWaypoints(missionIndex) = ...
        missionNumWaypoints;
    ExpectedNavigationWaypoints(missionIndex) = ...
        missionNumWaypoints - ...
        2;
    landingPhase = ...
        2*missionNumWaypoints - ...
        3;
    completePhase = ...
        2*missionNumWaypoints - ...
        2;
    abortedPhase = ...
        2*missionNumWaypoints - ...
        1;
    missionNumSignal = ...
        NumWaypointsSignal( ...
            missionSearchIndices);
    missionNumSignal = ...
        missionNumSignal( ...
            isfinite(missionNumSignal) & ...
            missionNumSignal > 0);
    if ~isempty(missionNumSignal) && ...
            any( ...
                round(missionNumSignal) ~= ...
                missionNumWaypoints)
        warning( ...
            'QuadrotorFramework:MissionWaypointCountChanged', ...
            ['NumWaypoints changed during mission %d. Metrics use the ', ...
             'mission-start geometry.'], ...
            missionIndex);
    end
    cgsCompleteRising = ...
        CGSComplete & ...
        ~[false;CGSComplete(1:end-1)];
    landedRising = ...
        Landed & ...
        ~[false;Landed(1:end-1)];
    relativeCompleteIdx = ...
        find( ...
            cgsCompleteRising(missionSearchIndices), ...
            1, ...
            'first');
    if isempty(relativeCompleteIdx)
        cgsCompleteIdx = ...
            NaN;
    else
        cgsCompleteIdx = ...
            missionSearchIndices(relativeCompleteIdx);
    end
    relativeLandedIdx = ...
        find( ...
            landedRising(missionSearchIndices), ...
            1, ...
            'first');
    if isempty(relativeLandedIdx)
        landedIdx = ...
            NaN;
    else
        landedIdx = ...
            missionSearchIndices(relativeLandedIdx);
    end
    relativeAbortIdx = ...
        find( ...
            Phase(missionSearchIndices) == abortedPhase, ...
            1, ...
            'first');
    if isempty(relativeAbortIdx)
        abortIdx = ...
            NaN;
    else
        abortIdx = ...
            missionSearchIndices(relativeAbortIdx);
    end
    NavigationCompleted(missionIndex) = ...
        isfinite(cgsCompleteIdx);
    LandedConfirmed(missionIndex) = ...
        isfinite(landedIdx);
    FailsafeAborted(missionIndex) = ...
        isfinite(abortIdx);
    Completed(missionIndex) = ...
        NavigationCompleted(missionIndex) && ...
        LandedConfirmed(missionIndex) && ...
        ~FailsafeAborted(missionIndex);
    if isfinite(landedIdx)
        missionPhysicalEndIdx = ...
            landedIdx;
        MissionDuration_s(missionIndex) = ...
            t(landedIdx) - ...
            t(missionStartIdx);
        MissionCompletionTime_s(missionIndex) = ...
            MissionDuration_s(missionIndex);
    elseif isfinite(abortIdx)
        missionPhysicalEndIdx = ...
            abortIdx;
        MissionDuration_s(missionIndex) = ...
            t(abortIdx) - ...
            t(missionStartIdx);
    elseif isfinite(cgsCompleteIdx)
        missionPhysicalEndIdx = ...
            cgsCompleteIdx;
        MissionDuration_s(missionIndex) = ...
            t(cgsCompleteIdx) - ...
            t(missionStartIdx);
    else
        missionPhysicalEndIdx = ...
            missionSearchEndIdx;
        MissionDuration_s(missionIndex) = ...
            t(missionSearchEndIdx) - ...
            t(missionStartIdx);
    end
    missionPlotMask( ...
        missionStartIdx:missionPhysicalEndIdx) = ...
        true;
    if isfinite(cgsCompleteIdx)
        NavigationCompleteTime_s(missionIndex) = ...
            t(cgsCompleteIdx) - ...
            t(missionStartIdx);
        pathEndIdx = ...
            cgsCompleteIdx;
        PathMetricWindowComplete(missionIndex) = ...
            true;
    elseif isfinite(abortIdx)
        pathEndIdx = ...
            abortIdx;
    elseif isfinite(landedIdx)
        pathEndIdx = ...
            landedIdx;
    else
        pathEndIdx = ...
            missionSearchEndIdx;
    end
    navigationPlotMask( ...
        missionStartIdx:pathEndIdx) = ...
        true;
    metricTime = ...
        buildMetricTimeGridMission( ...
            t(missionStartIdx), ...
            t(pathEndIdx), ...
            MetricSampleRate_Hz);
    refMetric = ...
        resampleMatrixMission( ...
            t, ...
            PositionRef, ...
            metricTime);
    trueMetric = ...
        resampleMatrixMission( ...
            t, ...
            PositionTrue, ...
            metricTime);
    selectedMetric = ...
        resampleMatrixMission( ...
            t, ...
            PositionSelected, ...
            metricTime);
    trueErrorMetricNED = ...
        trueMetric - ...
        refMetric;
    selectedErrorMetricNED = ...
        selectedMetric - ...
        refMetric;
    trueErrorMetric3D = ...
        sqrt( ...
            sum( ...
                trueErrorMetricNED.^2, ...
                2));
    trueErrorMetricHorizontal = ...
        sqrt( ...
            trueErrorMetricNED(:,1).^2 + ...
            trueErrorMetricNED(:,2).^2);
    trueErrorMetricVertical = ...
        abs( ...
            trueErrorMetricNED(:,3));
    selectedErrorMetric3D = ...
        sqrt( ...
            sum( ...
                selectedErrorMetricNED.^2, ...
                2));
    PathTrackingRMSE_m(missionIndex) = ...
        rootMeanSquareMission( ...
            trueErrorMetric3D);
    HorizontalPathRMSE_m(missionIndex) = ...
        rootMeanSquareMission( ...
            trueErrorMetricHorizontal);
    VerticalPathRMSE_m(missionIndex) = ...
        rootMeanSquareMission( ...
            trueErrorMetricVertical);
    PathTrackingMAE_m(missionIndex) = ...
        finiteMeanMission( ...
            abs( ...
                trueErrorMetric3D));
    P95PathTrackingError_m(missionIndex) = ...
        finitePercentileMission( ...
            trueErrorMetric3D, ...
            95);
    MaxPathTrackingError_m(missionIndex) = ...
        finiteMaximumMission( ...
            trueErrorMetric3D);
    SelectedPathTrackingRMSE_m(missionIndex) = ...
        rootMeanSquareMission( ...
            selectedErrorMetric3D);
    ReferencePathLength_m(missionIndex) = ...
        pathLengthMission( ...
            refMetric);
    TruePathLength_m(missionIndex) = ...
        pathLengthMission( ...
            trueMetric);
    if isfinite(TruePathLength_m(missionIndex)) && ...
            TruePathLength_m(missionIndex) > 1e-12 && ...
            isfinite(ReferencePathLength_m(missionIndex))
        PathEfficiency(missionIndex) = ...
            ReferencePathLength_m(missionIndex) / ...
            TruePathLength_m(missionIndex);
        if ReferencePathLength_m(missionIndex) > 1e-12
            ExcessPath_pct(missionIndex) = ...
                100 * ...
                ( ...
                    TruePathLength_m(missionIndex) / ...
                    ReferencePathLength_m(missionIndex) - ...
                    1 ...
                );
        end
    end
    currentMissionWaypointArrivalErrors = ...
        zeros(0,1);
    currentMissionHoldRMSE = ...
        zeros(0,1);
    currentMissionOvershoot = ...
        zeros(0,1);
    for pointIndex = 2:(missionNumWaypoints-1)
        movePhase = ...
            2*pointIndex - ...
            3;
        holdPhase = ...
            2*pointIndex - ...
            2;
        relativeMoveStart = ...
            find( ...
                Phase(missionSearchIndices) == movePhase, ...
                1, ...
                'first');
        relativeHoldStart = ...
            find( ...
                Phase(missionSearchIndices) == holdPhase, ...
                1, ...
                'first');
        if isempty(relativeMoveStart) || ...
                isempty(relativeHoldStart)
            continue;
        end
        moveStartIdx = ...
            missionSearchIndices(relativeMoveStart);
        holdStartIdx = ...
            missionSearchIndices(relativeHoldStart);
        if holdStartIdx <= moveStartIdx
            continue;
        end
        holdIndices = ...
            missionSearchIndices( ...
                Phase(missionSearchIndices) == holdPhase);
        holdIndices = ...
            holdIndices( ...
                holdIndices >= holdStartIdx);
        if isempty(holdIndices)
            continue;
        end
        holdEndIdx = ...
            holdIndices(end);
        targetPosition = ...
            missionPlan( ...
                1:3, ...
                pointIndex).';
        previousTargetPosition = ...
            missionPlan( ...
                1:3, ...
                pointIndex-1).';
        arrivalTrue = ...
            PositionTrue( ...
                holdStartIdx, ...
                :);
        arrivalErrorNED = ...
            arrivalTrue - ...
            targetPosition;
        arrivalErrorHorizontal = ...
            sqrt( ...
                arrivalErrorNED(1)^2 + ...
                arrivalErrorNED(2)^2);
        arrivalErrorVertical = ...
            abs( ...
                arrivalErrorNED(3));
        arrivalError3D = ...
            norm( ...
                arrivalErrorNED);
        timeToWaypoint = ...
            t(holdStartIdx) - ...
            t(moveStartIdx);
        holdMetricTime = ...
            buildMetricTimeGridMission( ...
                t(holdStartIdx), ...
                t(holdEndIdx), ...
                MetricSampleRate_Hz);
        holdTruePosition = ...
            resampleMatrixMission( ...
                t, ...
                PositionTrue, ...
                holdMetricTime);
        holdErrorNED = ...
            holdTruePosition - ...
            targetPosition;
        holdError3D = ...
            sqrt( ...
                sum( ...
                    holdErrorNED.^2, ...
                    2));
        holdRMSE = ...
            rootMeanSquareMission( ...
                holdError3D);
        holdMaxError = ...
            finiteMaximumMission( ...
                holdError3D);
        holdStdAxes = ...
            finiteColumnStdMission( ...
                holdTruePosition);
        holdStabilityStd = ...
            norm( ...
                holdStdAxes);
        segmentDirection = ...
            targetPosition - ...
            previousTargetPosition;
        segmentDistance = ...
            norm( ...
                segmentDirection);
        if segmentDistance > 1e-9
            directionUnit = ...
                segmentDirection / ...
                segmentDistance;
            overshootMetricTime = ...
                buildMetricTimeGridMission( ...
                    t(moveStartIdx), ...
                    t(holdEndIdx), ...
                    MetricSampleRate_Hz);
            overshootTruePosition = ...
                resampleMatrixMission( ...
                    t, ...
                    PositionTrue, ...
                    overshootMetricTime);
            displacementBeyondTarget = ...
                overshootTruePosition - ...
                targetPosition;
            projectedBeyondTarget = ...
                displacementBeyondTarget * ...
                directionUnit.';
            overshoot = ...
                max( ...
                    0, ...
                    finiteMaximumMission( ...
                        projectedBeyondTarget));
        else
            overshoot = ...
                0;
        end
        waypointName = ...
            genericWaypointNameMission( ...
                pointIndex, ...
                missionNumWaypoints, ...
                missionPlan);
        row = ...
            struct();
        row.Mission = ...
            missionIndex;
        row.TrajectoryID = ...
            TrajectoryIDValue;
        row.TrajectoryName = ...
            string(TrajectoryNameValue);
        row.PointIndex = ...
            pointIndex;
        row.Waypoint = ...
            waypointName;
        row.MovePhase = ...
            movePhase;
        row.HoldPhase = ...
            holdPhase;
        row.TargetNorth_m = ...
            targetPosition(1);
        row.TargetEast_m = ...
            targetPosition(2);
        row.TargetDown_m = ...
            targetPosition(3);
        row.SegmentStartTime_s = ...
            t(moveStartIdx);
        row.ArrivalTime_s = ...
            t(holdStartIdx);
        row.TimeToWaypoint_s = ...
            timeToWaypoint;
        row.ArrivalError3D_m = ...
            arrivalError3D;
        row.ArrivalErrorHorizontal_m = ...
            arrivalErrorHorizontal;
        row.ArrivalErrorVertical_m = ...
            arrivalErrorVertical;
        row.HoldRMSE_m = ...
            holdRMSE;
        row.HoldMaxError_m = ...
            holdMaxError;
        row.HoldStabilityStd_m = ...
            holdStabilityStd;
        row.Overshoot_m = ...
            overshoot;
        WaypointRows(end+1) = ...
            row;
        currentMissionWaypointArrivalErrors(end+1,1) = ...
            arrivalError3D;
        currentMissionHoldRMSE(end+1,1) = ...
            holdRMSE;
        currentMissionOvershoot(end+1,1) = ...
            overshoot;
    end
    CompletedWaypoints(missionIndex) = ...
        numel( ...
            currentMissionWaypointArrivalErrors);
    MeanWaypointArrivalError_m(missionIndex) = ...
        finiteMeanMission( ...
            currentMissionWaypointArrivalErrors);
    MaxWaypointArrivalError_m(missionIndex) = ...
        finiteMaximumMission( ...
            currentMissionWaypointArrivalErrors);
    MeanHoldRMSE_m(missionIndex) = ...
        finiteMeanMission( ...
            currentMissionHoldRMSE);
    MaxHoldRMSE_m(missionIndex) = ...
        finiteMaximumMission( ...
            currentMissionHoldRMSE);
    MaxOvershoot_m(missionIndex) = ...
        finiteMaximumMission( ...
            currentMissionOvershoot);
    relativeLandingStart = ...
        find( ...
            Phase(missionSearchIndices) == landingPhase, ...
            1, ...
            'first');
    if ~isempty(relativeLandingStart)
        landingStartIdx = ...
            missionSearchIndices(relativeLandingStart);
        if isfinite(landedIdx) && ...
                landedIdx >= landingStartIdx
            LandingTime_s(missionIndex) = ...
                t(landedIdx) - ...
                t(landingStartIdx);
            landingTarget = ...
                PhysicalHomePosition;
            landingErrorNED = ...
                PositionTrue( ...
                    landedIdx, ...
                    :) - ...
                landingTarget;
            LandingHorizontalError_m(missionIndex) = ...
                sqrt( ...
                    landingErrorNED(1)^2 + ...
                    landingErrorNED(2)^2);
            LandingVerticalError_m(missionIndex) = ...
                abs( ...
                    landingErrorNED(3));
            Landing3DError_m(missionIndex) = ...
                norm( ...
                    landingErrorNED);
        end
    end
    completePhaseSeen = ...
        any( ...
            Phase(missionSearchIndices) == ...
            completePhase);
    if NavigationCompleted(missionIndex) && ...
            ~completePhaseSeen
        warning( ...
            'QuadrotorFramework:CompleteSignalPhaseMismatch', ...
            ['CGS Complete was observed during mission %d, but the ', ...
             'generic COMPLETE phase (%d) was not present.'], ...
            missionIndex, ...
            completePhase);
    end
end

WaypointRows = ...
    struct( ...
        'Mission',{}, ...
        'TrajectoryID',{}, ...
        'TrajectoryName',{}, ...
        'PointIndex',{}, ...
        'Waypoint',{}, ...
        'MovePhase',{}, ...
        'HoldPhase',{}, ...
        'TargetNorth_m',{}, ...
        'TargetEast_m',{}, ...
        'TargetDown_m',{}, ...
        'SegmentStartTime_s',{}, ...
        'ArrivalTime_s',{}, ...
        'TimeToWaypoint_s',{}, ...
        'ArrivalError3D_m',{}, ...
        'ArrivalErrorHorizontal_m',{}, ...
        'ArrivalErrorVertical_m',{}, ...
        'HoldRMSE_m',{}, ...
        'HoldMaxError_m',{}, ...
        'HoldStabilityStd_m',{}, ...
        'Overshoot_m',{});
missionPlotMask = ...
    false( ...
        size(t));

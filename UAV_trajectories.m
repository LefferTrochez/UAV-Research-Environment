function trajectory = createTrajectoryDefinition( ...
    trajectoryID, ...
    trajectoryName, ...
    waypointsRelativeNED_m, ...
    yaw_rad, ...
    passThroughIntermediate)
    if nargin < 5
        passThroughIntermediate = ...
            false;
    end
    trajectory = ...
        struct();
    idNumeric = ...
        double( ...
            trajectoryID);
    if ~isscalar(idNumeric) || ...
            ~isfinite(idNumeric) || ...
            idNumeric ~= round(idNumeric) || ...
            idNumeric < 1
        error( ...
            'QuadrotorFramework:InvalidTrajectoryDefinitionID', ...
            'Trajectory ID must be a finite positive integer.');
    end
    trajectory.id = ...
        uint16( ...
            idNumeric);
    nameValue = ...
        strtrim( ...
            string( ...
                trajectoryName));
    if ~isscalar(nameValue) || ...
            ismissing(nameValue) || ...
            strlength(nameValue) == 0
        error( ...
            'QuadrotorFramework:InvalidTrajectoryDefinitionName', ...
            'Trajectory name must be a nonempty scalar string.');
    end
    trajectory.name = ...
        nameValue;
    if ~isscalar(passThroughIntermediate)
        error( ...
            'QuadrotorFramework:InvalidPassThroughDefinition', ...
            ['passThroughIntermediate for trajectory "%s" ', ...
             'must be scalar.'], ...
            char(nameValue));
    end
    trajectory.passThroughIntermediate = ...
        logical( ...
            passThroughIntermediate);
    waypoints = ...
        double( ...
            waypointsRelativeNED_m);
    if ndims(waypoints) ~= 2 || ...
            size(waypoints,2) ~= 3 || ...
            size(waypoints,1) < 3
        error( ...
            'QuadrotorFramework:InvalidTrajectoryDefinitionWaypoints', ...
            ['Trajectory "%s" must contain at least three ', ...
             '[North East Down] waypoints in an [N x 3] matrix.'], ...
            char(nameValue));
    end
    if any(~isfinite(waypoints(:)))
        error( ...
            'QuadrotorFramework:NonFiniteTrajectoryDefinitionWaypoint', ...
            'Trajectory "%s" contains NaN or Inf.', ...
            char(nameValue));
    end
    numberOfWaypoints = ...
        size( ...
            waypoints, ...
            1);
    trajectory.waypointsRelativeNED_m = ...
        waypoints;
    trajectory.numWaypoints = ...
        uint16( ...
            numberOfWaypoints);
    pointRoles = ...
        repmat( ...
            "NAVIGATION", ...
            numberOfWaypoints, ...
            1);
    pointRoles(1) = ...
        "HOME";
    if numberOfWaypoints >= 2
        pointRoles(2) = ...
            "TAKEOFF";
    end
    if numberOfWaypoints >= 3
        pointRoles(end-1) = ...
            "PRE_LAND";
    end
    pointRoles(end) = ...
        "LAND";
    trajectory.pointRoles = ...
        pointRoles;
    if isempty(yaw_rad)
        yawReference = ...
            generateAutomaticYaw( ...
                waypoints);
        trajectory.yawMode = ...
            "automatic";
    else
        yawReference = ...
            double( ...
                yaw_rad(:));
        if numel(yawReference) ~= numberOfWaypoints
            error( ...
                'QuadrotorFramework:TrajectoryYawLengthMismatch', ...
                ['Trajectory "%s" must provide one yaw value for ', ...
                 'every waypoint.'], ...
                char(nameValue));
        end
        if any(~isfinite(yawReference))
            error( ...
                'QuadrotorFramework:NonFiniteTrajectoryYaw', ...
                'Trajectory "%s" contains NaN or Inf yaw values.', ...
                char(nameValue));
        end
        yawReference = ...
            wrapAnglePiLocal( ...
                yawReference);
        trajectory.yawMode = ...
            "explicit";
    end
    trajectory.yaw_rad = ...
        yawReference;
    trajectory.missionPlanRelative = ...
        [ ...
            waypoints.';
            yawReference.' ...
        ];
    deltaPosition = ...
        diff( ...
            waypoints, ...
            1, ...
            1);
    segmentLength3D = ...
        sqrt( ...
            sum( ...
                deltaPosition.^2, ...
                2));
    segmentLengthHorizontal = ...
        sqrt( ...
            deltaPosition(:,1).^2 + ...
            deltaPosition(:,2).^2);
    deltaDown = ...
        deltaPosition(:,3);
    segmentAscent = ...
        max( ...
            -deltaDown, ...
            0);
    segmentDescent = ...
        max( ...
            deltaDown, ...
            0);
    deltaYaw = ...
        wrapAnglePiLocal( ...
            diff( ...
                yawReference));
    relativeAltitude = ...
        -waypoints(:,3);
    trajectory.metrics = ...
        struct();
    trajectory.metrics.nominalPathLength3D_m = ...
        sum( ...
            segmentLength3D);
    trajectory.metrics.nominalHorizontalPathLength_m = ...
        sum( ...
            segmentLengthHorizontal);
    trajectory.metrics.totalAscent_m = ...
        sum( ...
            segmentAscent);
    trajectory.metrics.totalDescent_m = ...
        sum( ...
            segmentDescent);
    trajectory.metrics.maximumRelativeAltitude_m = ...
        max( ...
            relativeAltitude);
    trajectory.metrics.minimumRelativeAltitude_m = ...
        min( ...
            relativeAltitude);
    trajectory.metrics.totalAbsYawChange_rad = ...
        sum( ...
            abs( ...
                deltaYaw));
    trajectory.metrics.totalAbsYawChange_deg = ...
        rad2deg( ...
            trajectory.metrics.totalAbsYawChange_rad);
    trajectory.metrics.numberOfSegments = ...
        numberOfWaypoints - 1;
    trajectory.segmentLength3D_m = ...
        segmentLength3D;
    trajectory.segmentLengthHorizontal_m = ...
        segmentLengthHorizontal;
end
function yawReference = generateAutomaticYaw(waypoints)
    numberOfWaypoints = ...
        size( ...
            waypoints, ...
            1);
    yawReference = ...
        zeros( ...
            numberOfWaypoints, ...
            1);
    horizontalTolerance_m = ...
        1e-9;
    firstHorizontalYawFound = ...
        false;
    firstHorizontalYaw = ...
        0.0;
    for pointIndex = 2:numberOfWaypoints
        deltaNorth = ...
            waypoints(pointIndex,1) - ...
            waypoints(pointIndex-1,1);
        deltaEast = ...
            waypoints(pointIndex,2) - ...
            waypoints(pointIndex-1,2);
        horizontalDistance = ...
            hypot( ...
                deltaNorth, ...
                deltaEast);
        if horizontalDistance > horizontalTolerance_m
            currentYaw = ...
                atan2( ...
                    deltaEast, ...
                    deltaNorth);
            currentYaw = ...
                atan2( ...
                    sin(currentYaw), ...
                    cos(currentYaw));
            yawReference(pointIndex) = ...
                currentYaw;
            if ~firstHorizontalYawFound
                firstHorizontalYaw = ...
                    currentYaw;
                firstHorizontalYawFound = ...
                    true;
            end
        else
            yawReference(pointIndex) = ...
                yawReference(pointIndex-1);
        end
    end
    if firstHorizontalYawFound
        yawReference(1) = ...
            firstHorizontalYaw;
        for pointIndex = 2:numberOfWaypoints
            deltaNorth = ...
                waypoints(pointIndex,1) - ...
                waypoints(pointIndex-1,1);
            deltaEast = ...
                waypoints(pointIndex,2) - ...
                waypoints(pointIndex-1,2);
            if hypot( ...
                    deltaNorth, ...
                    deltaEast) > horizontalTolerance_m
                break;
            end
            yawReference(pointIndex) = ...
                firstHorizontalYaw;
        end
    end
    yawReference = ...
        wrapAnglePiLocal( ...
            yawReference);
end
function angleWrapped = wrapAnglePiLocal(angle)
    angleWrapped = ...
        atan2( ...
            sin(angle), ...
            cos(angle));

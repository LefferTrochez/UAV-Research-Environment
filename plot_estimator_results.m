for missionIndex = 1:numberOfMissions
    missionStartIdx = ...
        missionStartIndices(missionIndex);
    missionStartTime = ...
        tLiveTelemetry(missionStartIdx);
    if missionIndex < numberOfMissions
        missionSearchEndIdx = ...
            missionStartIndices(missionIndex+1) - ...
            1;
    else
        missionSearchEndIdx = ...
            numel( ...
                tLiveTelemetry);
    end
    missionSearchIndices = ...
        missionStartIdx:missionSearchEndIdx;
    relativeLandedIdx = ...
        find( ...
            LandedTelemetry(missionSearchIndices), ...
            1, ...
            'first');
    if isempty(relativeLandedIdx)
        missionEndIdx = ...
            missionSearchEndIdx;
        landedConfirmed = ...
            false;
    else
        missionEndIdx = ...
            missionSearchIndices(relativeLandedIdx);
        landedConfirmed = ...
            true;
    end
    missionEndTime = ...
        tLiveTelemetry(missionEndIdx);
    effectiveMetricStart = ...
        max([ ...
            missionStartTime, ...
            METRIC_START_TIME, ...
            commonSignalStartTime]);
    effectiveMetricEnd = ...
        min( ...
            missionEndTime, ...
            commonSignalEndTime);
    MissionStartTime_s(missionIndex) = ...
        missionStartTime;
    MissionDuration_s(missionIndex) = ...
        max( ...
            0.0, ...
            missionEndTime - ...
            missionStartTime);
    MetricWindowStart_s(missionIndex) = ...
        effectiveMetricStart;
    MetricWindowEnd_s(missionIndex) = ...
        effectiveMetricEnd;
    LandedConfirmed(missionIndex) = ...
        landedConfirmed;
    MetricWindowComplete(missionIndex) = ...
        landedConfirmed && ...
        effectiveMetricEnd >= effectiveMetricStart;
    if effectiveMetricEnd >= effectiveMetricStart
        currentMetricTime = ...
            buildEstimatorMetricTimeGrid( ...
                effectiveMetricStart, ...
                effectiveMetricEnd, ...
                METRIC_SAMPLE_RATE_HZ);
        MetricSamples(missionIndex) = ...
            numel( ...
                currentMetricTime);
        if ~isempty(currentMetricTime)
            MetricWindowDuration_s(missionIndex) = ...
                currentMetricTime(end) - ...
                currentMetricTime(1);
            metricTimeGrid = [ ...
                metricTimeGrid; ...
                currentMetricTime];
        end
    end
end

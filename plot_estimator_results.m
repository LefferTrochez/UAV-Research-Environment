function [t,X] = ts2matrix(ts)
    t = ...
        ts.Time(:);
    D = squeeze( ...
        ts.Data);
    nt = ...
        numel(t);
    if isvector(D)
        if numel(D) == nt
            X = ...
                D(:);
        else
            X = reshape( ...
                D, ...
                1, ...
                []);
        end
        return;
    end
    if size(D,1) == nt
        X = reshape( ...
            D, ...
            nt, ...
            []);
    elseif size(D,2) == nt
        X = ...
            D.';
    elseif size(D,ndims(D)) == nt
        order = [ ...
            ndims(D), ...
            1:(ndims(D)-1)];
        D = permute( ...
            D, ...
            order);
        X = reshape( ...
            D, ...
            nt, ...
            []);
    else
        error( ...
            ['Unable to match timeseries data dimensions ', ...
             'with the time vector.']);
    end
end

function tGrid = buildEstimatorMetricTimeGrid( ...
    tStart, ...
    tEnd, ...
    sampleRateHz)
    if ~isfinite(tStart) || ...
            ~isfinite(tEnd) || ...
            tEnd < tStart || ...
            ~isfinite(sampleRateHz) || ...
            sampleRateHz <= 0
        tGrid = ...
            zeros(0,1);
        return;
    end
    if abs(tEnd-tStart) <= 1e-12
        tGrid = ...
            tStart;
        return;
    end
    dt = ...
        1.0 / ...
        sampleRateHz;
    numberOfFullSteps = ...
        floor( ...
            (tEnd-tStart) / ...
            dt);
    tGrid = ...
        tStart + ...
        (0:numberOfFullSteps).' * ...
        dt;
    if isempty(tGrid)
        tGrid = ...
            [tStart;tEnd];
    elseif tGrid(end) < tEnd - 1e-10
        tGrid(end+1,1) = ...
            tEnd;
    else
        tGrid(end) = ...
            tEnd;
    end
end
function Xquery = resampleEstimatorMatrix( ...
    tSource, ...
    XSource, ...
    tQuery)
    tSource = ...
        double( ...
            tSource(:));
    tQuery = ...
        double( ...
            tQuery(:));
    XSource = ...
        double(XSource);
    if size(XSource,1) ~= numel(tSource)
        error( ...
            ['Estimator source matrix row count does not match ', ...
             'its source time vector.']);
    end
    if isempty(tQuery)
        Xquery = ...
            zeros( ...
                0, ...
                size(XSource,2));
        return;
    end
    finiteTimeMask = ...
        isfinite(tSource);
    tSource = ...
        tSource( ...
            finiteTimeMask);
    XSource = ...
        XSource( ...
            finiteTimeMask, ...
            :);
    [tUnique,uniqueIndex] = ...
        unique( ...
            tSource, ...
            'stable');
    XUnique = ...
        XSource( ...
            uniqueIndex, ...
            :);
    if isempty(tUnique)
        Xquery = ...
            NaN( ...
                numel(tQuery), ...
                size(XSource,2));
        return;
    end
    if any(tQuery < tUnique(1)-1e-9) || ...
            any(tQuery > tUnique(end)+1e-9)
        error( ...
            'Requested estimator metric grid exceeds source-log bounds.');
    end
    if numel(tUnique) == 1
        Xquery = ...
            repmat( ...
                XUnique(1,:), ...
                numel(tQuery), ...
                1);
        return;
    end
    Xquery = ...
        NaN( ...
            numel(tQuery), ...
            size(XUnique,2));
    for column = 1:size(XUnique,2)
        sourceColumn = ...
            XUnique(:,column);
        finiteSignalMask = ...
            isfinite(sourceColumn);
        if nnz(finiteSignalMask) == 0
            continue;
        end
        tSignal = ...
            tUnique( ...
                finiteSignalMask);
        xSignal = ...
            sourceColumn( ...
                finiteSignalMask);
        if numel(tSignal) == 1
            Xquery(:,column) = ...
                xSignal(1);
        else
            Xquery(:,column) = ...
                interp1( ...
                    tSignal, ...
                    xSignal, ...
                    tQuery, ...
                    'linear', ...
                    NaN);
        end
    end
end
function value = finiteEstimatorPercentile(x,percentile)
    x = ...
        sort( ...
            double( ...
                x( ...
                    isfinite(x))));
    x = ...
        x(:);
    if isempty(x)
        value = ...
            NaN;
        return;
    end
    percentile = ...
        min( ...
            100, ...
            max( ...
                0, ...
                double(percentile)));
    if numel(x) == 1
        value = ...
            x(1);
        return;
    end
    rankPosition = ...
        1 + ...
        (numel(x)-1) * ...
        percentile / ...
        100;
    lowerIndex = ...
        floor( ...
            rankPosition);
    upperIndex = ...
        ceil( ...
            rankPosition);
    if lowerIndex == upperIndex
        value = ...
            x(lowerIndex);
    else
        alpha = ...
            rankPosition - ...
            lowerIndex;
        value = ...
            (1-alpha)*x(lowerIndex) + ...
            alpha*x(upperIndex);
    end
end

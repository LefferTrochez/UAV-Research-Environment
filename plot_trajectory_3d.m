function fallbackCount = calculateFallbackSampleCount3D(t,nSamples)
    dt = ...
        medianPositiveDiff3D(t);
    if ~isfinite(dt) || ...
            dt <= 0.0
        dt = ...
            1e-3;
    end
    fallbackCount = ...
        min( ...
            nSamples, ...
            max( ...
                1, ...
                round( ...
                    0.5 / dt)));
end

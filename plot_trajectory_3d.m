function MissionPlan = extractMissionPlan3D(logValue)
    if isa( ...
            logValue, ...
            'Simulink.SimulationData.Signal')
        logValue = ...
            logValue.Values;
    end
    if isnumeric(logValue)
        numericPlan = ...
            double(logValue);
        if ismatrix(numericPlan) && ...
                size(numericPlan,1) == 4 && ...
                size(numericPlan,2) >= 3
            MissionPlan = ...
                numericPlan;
            return;
        end
        if ismatrix(numericPlan) && ...
                size(numericPlan,2) == 4 && ...
                size(numericPlan,1) >= 3
            MissionPlan = ...
                numericPlan.';
            return;
        end
        error( ...
            'QuadrotorFramework:InvalidMissionPlanNumericLog', ...
            ['Numeric MissionPlanLog must be [4 x M] with M >= 3. ', ...
             'Received %s.'], ...
            mat2str(size(numericPlan)));
    end
    if ~isa(logValue,'timeseries')
        error( ...
            'QuadrotorFramework:InvalidMissionPlanLog', ...
            ['MissionPlanLog must be a timeseries, ', ...
             'Simulink.SimulationData.Signal, or numeric [4 x M].']);
    end
    D = ...
        double(logValue.Data);
    dataSize = ...
        size(D);
    numberOfTimeSamples = ...
        numel( ...
            logValue.Time);
    if ismatrix(D) && ...
            size(D,1) == 4 && ...
            size(D,2) >= 3
        MissionPlan = ...
            D;
        return;
    end
    if ismatrix(D) && ...
            size(D,2) == 4 && ...
            size(D,1) >= 3 && ...
            numberOfTimeSamples == 1
        MissionPlan = ...
            D.';
        return;
    end
    if ndims(D) >= 3 && ...
            size(D,1) == 4 && ...
            size(D,2) >= 3
        numberOfSamples = ...
            size(D,3);
        for k = numberOfSamples:-1:1
            candidate = ...
                D(:,:,k);
            if size(candidate,1) == 4 && ...
                    size(candidate,2) >= 3 && ...
                    all(isfinite(candidate(:)))
                MissionPlan = ...
                    candidate;
                return;
            end
        end
    end
    if ndims(D) >= 3 && ...
            size(D,2) == 4 && ...
            size(D,3) >= 3
        numberOfSamples = ...
            size(D,1);
        for k = numberOfSamples:-1:1
            candidate = ...
                squeeze( ...
                    D(k,:,:));
            if size(candidate,1) == 4 && ...
                    size(candidate,2) >= 3 && ...
                    all(isfinite(candidate(:)))
                MissionPlan = ...
                    candidate;
                return;
            end
        end
    end
    if ndims(D) >= 3 && ...
            size(D,1) >= 3 && ...
            size(D,2) == 4
        numberOfSamples = ...
            size(D,3);
        for k = numberOfSamples:-1:1
            candidate = ...
                D(:,:,k).';
            if size(candidate,1) == 4 && ...
                    size(candidate,2) >= 3 && ...
                    all(isfinite(candidate(:)))
                MissionPlan = ...
                    candidate;
                return;
            end
        end
    end
    error( ...
        'QuadrotorFramework:CannotExtractMissionPlan', ...
        ['Unable to extract a generic [4 x MAX_WAYPOINTS] MissionPlan ', ...
         'from MissionPlanLog. Logged data dimensions were %s.'], ...
        mat2str(dataSize));
end
function NumWaypoints = extractNumWaypoints3D(Telemetry,maxWaypoints)
    if size(Telemetry,2) < 59
        NumWaypoints = ...
            inferWorkspaceNumWaypoints3D( ...
                maxWaypoints);
        warning( ...
            'QuadrotorFramework:LegacyTelemetryWithoutNumWaypoints', ...
            ['Telemetry column 59 is unavailable. NumWaypoints=%d was ', ...
             'recovered from the workspace/fixed buffer.'], ...
            NumWaypoints);
        return;
    end
    raw = ...
        double( ...
            Telemetry(:,59));
    rounded = ...
        round(raw);
    valid = ...
        isfinite(raw) & ...
        raw >= 1 & ...
        raw <= maxWaypoints & ...
        abs(raw-rounded) < 1.0e-9;
    values = ...
        rounded(valid);
    if isempty(values)
        NumWaypoints = ...
            inferWorkspaceNumWaypoints3D( ...
                maxWaypoints);
        warning( ...
            'QuadrotorFramework:MissingValidNumWaypointsTelemetry', ...
            ['No valid positive NumWaypoints sample was found in ', ...
             'Telemetry(59). Using %d.'], ...
            NumWaypoints);
        return;
    end
    uniqueValues = ...
        unique(values);
    if numel(uniqueValues) > 1
        error( ...
            'QuadrotorFramework:ChangingNumWaypointsDuringRun', ...
            ['NumWaypoints changed during one simulation run: %s. ', ...
             'A benchmark run must use one fixed trajectory.'], ...
            mat2str(uniqueValues.'));
    end
    NumWaypoints = ...
        double( ...
            uniqueValues(1));
end
function MissionPlan = extractGenericMissionPlanTelemetry3D( ...
    Telemetry, ...
    maxWaypoints, ...
    NumWaypoints)
    MissionPlan = ...
        [];
    requiredWidth = ...
        59 + ...
        4*maxWaypoints;
    if size(Telemetry,2) < requiredWidth
        return;
    end
    northStart = ...
        60;
    eastStart = ...
        60 + ...
        maxWaypoints;
    downStart = ...
        60 + ...
        2*maxWaypoints;
    yawStart = ...
        60 + ...
        3*maxWaypoints;
    for row = size(Telemetry,1):-1:1
        candidate = ...
            zeros( ...
                4, ...
                NumWaypoints);
        candidate(1,:) = ...
            Telemetry( ...
                row, ...
                northStart:northStart+NumWaypoints-1);
        candidate(2,:) = ...
            Telemetry( ...
                row, ...
                eastStart:eastStart+NumWaypoints-1);
        candidate(3,:) = ...
            Telemetry( ...
                row, ...
                downStart:downStart+NumWaypoints-1);
        candidate(4,:) = ...
            Telemetry( ...
                row, ...
                yawStart:yawStart+NumWaypoints-1);
        if all(isfinite(candidate(:)))
            MissionPlan = ...
                double(candidate);
            return;
        end
    end
end
function NumWaypoints = inferWorkspaceNumWaypoints3D(maxWaypoints)
    NumWaypoints = ...
        maxWaypoints;
    try
        if evalin( ...
                'base', ...
                'exist(''TRAJECTORY_CONFIG'',''var'')')
            cfg = ...
                evalin( ...
                    'base', ...
                    'TRAJECTORY_CONFIG');
            if isstruct(cfg) && ...
                    isfield(cfg,'selectedNumWaypoints')
                candidate = ...
                    double( ...
                        cfg.selectedNumWaypoints);
                if isscalar(candidate) && ...
                        isfinite(candidate) && ...
                        candidate >= 3 && ...
                        candidate <= maxWaypoints && ...
                        abs(candidate-round(candidate)) < 1.0e-9
                    NumWaypoints = ...
                        round(candidate);
                end
            end
        end
    catch
    end
end

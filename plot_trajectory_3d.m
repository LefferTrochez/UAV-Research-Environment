function [axisLimits,margin] = ...
    fixedAxisInterval3D( ...
        values, ...
        marginFraction, ...
        minimumMargin, ...
        minimumSpan)
    values = ...
        double(values(:));
    values = ...
        values(isfinite(values));
    if isempty(values)
        axisLimits = ...
            [-1 1];
        margin = ...
            1;
        return;
    end
    valueMinimum = ...
        min(values);
    valueMaximum = ...
        max(values);
    plannedSpan = ...
        valueMaximum - ...
        valueMinimum;
    effectiveSpan = ...
        max( ...
            plannedSpan, ...
            minimumSpan);
    center = ...
        0.5 * ...
        (valueMinimum + valueMaximum);
    if plannedSpan < minimumSpan
        valueMinimum = ...
            center - ...
            0.5*minimumSpan;
        valueMaximum = ...
            center + ...
            0.5*minimumSpan;
    end
    margin = ...
        max( ...
            minimumMargin, ...
            marginFraction * ...
            effectiveSpan);
    axisLimits = [ ...
        valueMinimum-margin, ...
        valueMaximum+margin];
end
function [t,X] = ts2matrix3D(ts)
    if isa( ...
            ts, ...
            'Simulink.SimulationData.Signal')
        ts = ...
            ts.Values;
    end
    if ~isa( ...
            ts, ...
            'timeseries')
        error( ...
            'Expected a MATLAB timeseries object.');
    end
    t = ...
        ts.Time(:);
    D = ...
        squeeze( ...
            ts.Data);
    nt = ...
        numel(t);
    if nt == 1
        X = ...
            reshape( ...
                D, ...
                1, ...
                []);
        return;
    end
    if isvector(D)
        if numel(D) == nt
            X = ...
                D(:);
        else
            error( ...
                ['Unable to determine signal orientation ', ...
                 'from timeseries dimensions.']);
        end
        return;
    end
    if size(D,1) == nt
        X = ...
            reshape( ...
                D, ...
                nt, ...
                []);
    elseif size(D,2) == nt
        X = ...
            D.';
    elseif size(D,ndims(D)) == nt
        order = [ ...
            ndims(D), ...
            1:(ndims(D)-1)];
        D = ...
            permute( ...
                D, ...
                order);
        X = ...
            reshape( ...
                D, ...
                nt, ...
                []);
    else
        error( ...
            ['Unable to match timeseries data dimensions ', ...
             'with its time vector.']);
    end
end

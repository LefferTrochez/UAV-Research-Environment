function addDirectionArrows3D(ax,X,Y,Z,numberOfArrows,sceneScale)
    X = ...
        X(:);
    Y = ...
        Y(:);
    Z = ...
        Z(:);
    valid = ...
        isfinite(X) & ...
        isfinite(Y) & ...
        isfinite(Z);
    X = ...
        X(valid);
    Y = ...
        Y(valid);
    Z = ...
        Z(valid);
    if numel(X) < 3
        return;
    end
    dX = ...
        diff(X);
    dY = ...
        diff(Y);
    dZ = ...
        diff(Z);
    ds = ...
        sqrt( ...
            dX.^2 + ...
            dY.^2 + ...
            dZ.^2);
    cumulativeDistance = [ ...
        0; ...
        cumsum(ds)];
    totalDistance = ...
        cumulativeDistance(end);
    if ~isfinite(totalDistance) || ...
            totalDistance <= 1e-6
        return;
    end
    numberOfArrows = ...
        max( ...
            1, ...
            round(numberOfArrows));
    arrowLength = ...
        max( ...
            0.18, ...
            0.060 * sceneScale);
    targetDistances = ...
        linspace( ...
            0.08*totalDistance, ...
            0.92*totalDistance, ...
            numberOfArrows);
    firstArrow = ...
        true;
    for k = 1:numel(targetDistances)
        i = ...
            find( ...
                cumulativeDistance >= targetDistances(k), ...
                1, ...
                'first');
        if isempty(i) || ...
                i >= numel(X)
            continue;
        end
        forwardDistance = ...
            min( ...
                totalDistance, ...
                cumulativeDistance(i) + ...
                arrowLength);
        j = ...
            find( ...
                cumulativeDistance >= forwardDistance, ...
                1, ...
                'first');
        if isempty(j) || ...
                j <= i
            continue;
        end
        arrowDX = ...
            X(j) - ...
            X(i);
        arrowDY = ...
            Y(j) - ...
            Y(i);
        arrowDZ = ...
            Z(j) - ...
            Z(i);
        if norm([arrowDX arrowDY arrowDZ]) <= 1e-9
            continue;
        end
        if firstArrow
            displayName = ...
                'Trajectory Direction';
            firstArrow = ...
                false;
        else
            displayName = ...
                '';
        end
        STYLE = trajectoryStyle3D();
        hArrow = ...
            quiver3( ...
                ax, ...
                X(i), ...
                Y(i), ...
                Z(i), ...
                arrowDX, ...
                arrowDY, ...
                arrowDZ, ...
                0, ...
                'Color',STYLE.referenceColor, ...
                'LineWidth',STYLE.directionLineWidth, ...
                'MaxHeadSize',STYLE.directionHeadSize);
        if isempty(displayName)
            hArrow.HandleVisibility = ...
                'off';
        else
            hArrow.DisplayName = ...
                displayName;
        end
    end
end

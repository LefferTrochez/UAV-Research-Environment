function T = quadrotorPoseMatrix3D(positionPlot,eulerRPY)
    positionPlot = ...
        reshape( ...
            double(positionPlot), ...
            3, ...
            1);
    eulerRPY = ...
        reshape( ...
            double(eulerRPY), ...
            3, ...
            1);
    roll = ...
        eulerRPY(1);
    pitch = ...
        eulerRPY(2);
    yaw = ...
        eulerRPY(3);
    cr = cos(roll);
    sr = sin(roll);
    cp = cos(pitch);
    sp = sin(pitch);
    cy = cos(yaw);
    sy = sin(yaw);
    R_NB = [ ...
        cy*cp, ...
        cy*sp*sr - sy*cr, ...
        cy*sp*cr + sy*sr; ...
        sy*cp, ...
        sy*sp*sr + cy*cr, ...
        sy*sp*cr - cy*sr; ...
        -sp, ...
        cp*sr, ...
        cp*cr];
    P = [ ...
        0 1 0; ...
        1 0 0; ...
        0 0 -1];
    R_plot_body = ...
        P * ...
        R_NB;
    T = ...
        eye(4);
    T(1:3,1:3) = ...
        R_plot_body;
    T(1:3,4) = ...
        positionPlot;
end

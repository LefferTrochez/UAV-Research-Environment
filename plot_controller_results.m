        matrixSaturationFractionController( ...
            OmegaMetric, ...
            limits.motorMin, ...
            limits.motorMax);
    ThrustAxisRMS_rad_s(missionIndex) = ...
        finiteRMSController( ...
            thrustMetric);
    RollAxisRMS_rad_s(missionIndex) = ...
        finiteRMSController( ...
            rollAxisMetric);
    PitchAxisRMS_rad_s(missionIndex) = ...
        finiteRMSController( ...
            pitchAxisMetric);
    YawAxisRMS_rad_s(missionIndex) = ...
        finiteRMSController( ...
            yawAxisMetric);
    PeakAbsThrustAxis_rad_s(missionIndex) = ...
        finiteMaximumController( ...
            abs(thrustMetric));
    PeakAbsRollAxis_rad_s(missionIndex) = ...
        finiteMaximumController( ...
            abs(rollAxisMetric));
    PeakAbsPitchAxis_rad_s(missionIndex) = ...
        finiteMaximumController( ...
            abs(pitchAxisMetric));
    PeakAbsYawAxis_rad_s(missionIndex) = ...
        finiteMaximumController( ...
            abs(yawAxisMetric));
    ThrustAxisSaturationFraction(missionIndex) = ...
        symmetricSaturationFractionController( ...
            thrustMetric, ...
            limits.thrustAxisAbsMax);
    RollAxisSaturationFraction(missionIndex) = ...
        symmetricSaturationFractionController( ...
            rollAxisMetric, ...
            limits.rollAxisAbsMax);
    PitchAxisSaturationFraction(missionIndex) = ...

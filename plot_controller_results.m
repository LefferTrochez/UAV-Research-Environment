function tGrid = buildControllerMetricTimeGrid( ...
    tStart, ...
    tEnd, ...
    sampleRateHz)
    if ~isfinite(tStart) || ...
            ~isfinite(tEnd) || ...
            tEnd < tStart || ...
            ~isfinite(sampleRateHz) || ...
            sampleRateHz <= 0
        tGrid = ...
            zeros(0,1);
        return;
    end
    if abs(tEnd-tStart) <= 1e-12
        tGrid = ...
            tStart;
        return;
    end
    dt = ...
        1.0 / ...
        sampleRateHz;
    numberOfFullSteps = ...
        floor( ...
            (tEnd-tStart) / ...
            dt);
    tGrid = ...
        tStart + ...
        (0:numberOfFullSteps).' * ...
        dt;
    if isempty(tGrid)
        tGrid = ...
            [tStart;tEnd];
    elseif tGrid(end) < tEnd - 1e-10
        tGrid(end+1,1) = ...
            tEnd;
    else
        tGrid(end) = ...
            tEnd;
    end
end
function Xquery = resampleControllerMatrix( ...
    tSource, ...
    XSource, ...
    tQuery)
    tSource = ...
        double( ...
            tSource(:));
    tQuery = ...
        double( ...
            tQuery(:));
    XSource = ...
        double(XSource);
    if isvector(XSource)
        XSource = ...
            XSource(:);
    end
    if size(XSource,1) ~= numel(tSource)
        error( ...
            'Controller source matrix rows do not match source time.');
    end
    if isempty(tQuery)
        Xquery = ...
            zeros( ...
                0, ...
                size(XSource,2));
        return;
    end
    finiteTimeMask = ...
        isfinite(tSource);
    tSource = ...
        tSource( ...
            finiteTimeMask);
    XSource = ...
        XSource( ...
            finiteTimeMask, ...
            :);
    [tUnique,uniqueIndex] = ...
        unique( ...
            tSource, ...
            'stable');
    XUnique = ...
        XSource( ...
            uniqueIndex, ...
            :);
    if isempty(tUnique)
        Xquery = ...
            NaN( ...
                numel(tQuery), ...
                size(XSource,2));
        return;
    end
    if any(tQuery < tUnique(1)-1e-9) || ...
            any(tQuery > tUnique(end)+1e-9)
        error( ...
            ['Requested controller metric window exceeds ', ...
             'source-log bounds.']);
    end
    if numel(tUnique) == 1
        Xquery = ...
            repmat( ...
                XUnique(1,:), ...
                numel(tQuery), ...
                1);
        return;
    end
    Xquery = ...
        NaN( ...
            numel(tQuery), ...
            size(XUnique,2));
    for column = 1:size(XUnique,2)
        sourceColumn = ...
            XUnique(:,column);
        finiteSignalMask = ...
            isfinite(sourceColumn);
        if nnz(finiteSignalMask) == 0
            continue;
        end
        tSignal = ...
            tUnique( ...
                finiteSignalMask);
        xSignal = ...
            sourceColumn( ...
                finiteSignalMask);
        if numel(tSignal) == 1
            Xquery(:,column) = ...
                xSignal(1);
        else
            Xquery(:,column) = ...
                interp1( ...
                    tSignal, ...
                    xSignal, ...
                    tQuery, ...
                    'linear', ...
                    NaN);
        end
    end
end

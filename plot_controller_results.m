completeRising = ...
    CGSComplete & ...
    ~[false;CGSComplete(1:end-1)];
landedRising = ...
    Landed & ...
    ~[false;Landed(1:end-1)];
for missionIndex = 1:numberOfMissions
    missionStartIdx = ...
        missionStartIndices(missionIndex);
    missionStartTime = ...
        tTelemetry(missionStartIdx);
    MissionStartTime_s(missionIndex) = ...
        missionStartTime;
    if missionIndex < numberOfMissions
        missionSearchEndIdx = ...
            missionStartIndices(missionIndex+1) - ...
            1;
    else
        missionSearchEndIdx = ...
            numel(tTelemetry);
    end
    missionSearchIndices = ...
        missionStartIdx:missionSearchEndIdx;
    missionNumWaypoints = ...
        NumWaypointsSignal(missionStartIdx);
    if ~isfinite(missionNumWaypoints) || ...
            missionNumWaypoints < 3
        missionNumWaypoints = ...
            controllerWorkspaceNumWaypoints();
    end
    if ~isfinite(missionNumWaypoints) || ...
            missionNumWaypoints < 3
        missionNumWaypoints = ...
            3;
    end
    missionNumWaypoints = ...
        round( ...
            missionNumWaypoints);
    NumWaypoints(missionIndex) = ...
        missionNumWaypoints;
    abortedPhase = ...
        2*missionNumWaypoints - ...
        1;
    relativeNavigationEndIdx = ...
        find( ...
            completeRising(missionSearchIndices), ...
            1, ...
            'first');
    if isempty(relativeNavigationEndIdx)
        cgsCompleteIdx = ...
            NaN;
    else
        cgsCompleteIdx = ...
            missionSearchIndices( ...
                relativeNavigationEndIdx);
    end
    relativeLandedIdx = ...
        find( ...
            landedRising(missionSearchIndices), ...
            1, ...
            'first');
    if isempty(relativeLandedIdx)
        landedIdx = ...
            NaN;
    else
        landedIdx = ...
            missionSearchIndices( ...
                relativeLandedIdx);
    end
    relativeAbortIdx = ...
        find( ...
            Phase(missionSearchIndices) == ...
            abortedPhase, ...
            1, ...
            'first');
    if isempty(relativeAbortIdx)
        abortIdx = ...
            NaN;
    else
        abortIdx = ...
            missionSearchIndices( ...
                relativeAbortIdx);
    end
    FailsafeAborted(missionIndex) = ...
        isfinite( ...
            abortIdx);
    if isfinite(landedIdx)
        missionEndIdx = ...
            landedIdx;
        MissionWindowComplete(missionIndex) = ...
            true;
    elseif isfinite(abortIdx)
        missionEndIdx = ...
            abortIdx;
    else
        missionEndIdx = ...
            missionSearchEndIdx;
    end
    missionEndTime = ...
        tTelemetry(missionEndIdx);
    if ~isfinite(missionEndTime) || ...
            missionEndTime < missionStartTime
        error( ...
            'QuadrotorFramework:InvalidControllerMissionWindow', ...
            'Invalid mission window detected for mission %d.', ...
            missionIndex);
    end
    MissionEndTime_s(missionIndex) = ...
        missionEndTime;
    MissionDuration_s(missionIndex) = ...
        missionEndTime - ...
        missionStartTime;
    missionWindowStarts(missionIndex) = ...
        missionStartTime;
    missionWindowEnds(missionIndex) = ...
        missionEndTime;
    if isfinite(cgsCompleteIdx)
        navigationEndIdx = ...
            cgsCompleteIdx;
        NavigationWindowComplete(missionIndex) = ...
            true;
    elseif isfinite(abortIdx)
        navigationEndIdx = ...
            abortIdx;
    elseif isfinite(landedIdx)
        navigationEndIdx = ...
            landedIdx;
    else
        navigationEndIdx = ...
            missionSearchEndIdx;
    end
    navigationEndTime = ...
        tTelemetry(navigationEndIdx);
    NavigationEndTime_s(missionIndex) = ...
        navigationEndTime;
    NavigationDuration_s(missionIndex) = ...
        max( ...
            0.0, ...
            navigationEndTime - ...
            missionStartTime);
    navigationWindowStarts(missionIndex) = ...
        missionStartTime;
    navigationWindowEnds(missionIndex) = ...
        navigationEndTime;
    missionMetricTime = ...
        buildControllerMetricTimeGrid( ...
            missionStartTime, ...
            missionEndTime, ...
            MetricSampleRate_Hz);
    MissionMetricSamples(missionIndex) = ...
        numel( ...
            missionMetricTime);
    if isempty(missionMetricTime)
        continue;
    end
    OmegaMetric = ...
        resampleControllerMatrix( ...
            tOmega, ...
            Omega, ...
            missionMetricTime);
    thrustMetric = ...
        resampleControllerMatrix( ...
            tThrust, ...
            thrustAxis, ...
            missionMetricTime);
    rollAxisMetric = ...
        resampleControllerMatrix( ...
            tRollAxis, ...
            rollAxis, ...
            missionMetricTime);
    pitchAxisMetric = ...
        resampleControllerMatrix( ...
            tPitchAxis, ...
            pitchAxis, ...
            missionMetricTime);
    yawAxisMetric = ...
        resampleControllerMatrix( ...
            tYawAxis, ...
            yawAxis, ...
            missionMetricTime);
    MeanMotorSpeed_rad_s(missionIndex) = ...
        finiteMeanController( ...
            OmegaMetric(:));
    RMSMotorSpeed_rad_s(missionIndex) = ...
        finiteRMSController( ...
            OmegaMetric(:));
    PeakMotorSpeed_rad_s(missionIndex) = ...
        finiteMaximumController( ...
            OmegaMetric(:));
    MotorSpeedStd_rad_s(missionIndex) = ...
        finiteStdController( ...
            OmegaMetric(:));
    motorDifferential = ...
        rowRangeController( ...
            OmegaMetric);
    MeanMotorDifferential_rad_s(missionIndex) = ...
        finiteMeanController( ...
            motorDifferential);
    PeakMotorDifferential_rad_s(missionIndex) = ...
        finiteMaximumController( ...
            motorDifferential);
    omegaSquaredTotal = ...
        finiteRowSumSquaresController( ...
            OmegaMetric);
    MeanTotalOmegaSquared_rad2_s2(missionIndex) = ...
        finiteMeanController( ...
            omegaSquaredTotal);
    IntegratedOmegaSquared_rad2_s(missionIndex) = ...
        finiteTrapzController( ...
            missionMetricTime, ...
            omegaSquaredTotal);
    if MissionDuration_s(missionIndex) > 1e-12
        MotorCommandVariationRate_rad_s2(missionIndex) = ...
            matrixTotalVariationController( ...
                OmegaMetric) / ...
            MissionDuration_s(missionIndex);
    end

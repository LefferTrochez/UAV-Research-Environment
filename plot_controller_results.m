            yawAxisMetric, ...
            limits.yawAxisAbsMax);
    navigationMetricTime = ...
        buildControllerMetricTimeGrid( ...
            missionStartTime, ...
            navigationEndTime, ...
            MetricSampleRate_Hz);
    NavigationMetricSamples(missionIndex) = ...
        numel( ...
            navigationMetricTime);
    if isempty(navigationMetricTime)
        continue;
    end
    CmdAttitudeMetric = ...
        resampleControllerMatrix( ...
            tCmdAttitude, ...
            CmdAttitude, ...
            navigationMetricTime);
    EulerSelectedMetric = ...

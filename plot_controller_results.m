    X, ...
    lowerLimit, ...
    upperLimit)
    if ~isscalar(lowerLimit) || ...
            ~isscalar(upperLimit) || ...
            ~isfinite(lowerLimit) || ...
            ~isfinite(upperLimit) || ...
            upperLimit <= lowerLimit
        fraction = ...
            NaN;
        return;
    end
    X = ...
        double(X);
    valid = ...
        isfinite(X);
    if ~any(valid(:))
        fraction = ...
            NaN;
        return;
    end
    tolerance = ...
        max( ...
            1e-9, ...
            1e-6 * ...
            max(abs([lowerLimit upperLimit])));
    saturated = ...
        valid & ...
        ( ...
            X <= lowerLimit + tolerance | ...
            X >= upperLimit - tolerance ...
        );
    fraction = ...
        nnz(saturated) / ...
        nnz(valid);
end
function fraction = symmetricSaturationFractionController( ...
    x, ...
    absoluteLimit)
    if ~isscalar(absoluteLimit) || ...
            ~isfinite(absoluteLimit) || ...
            absoluteLimit <= 0
        fraction = ...
            NaN;
        return;
    end
    x = ...
        double( ...
            x(:));
    valid = ...
        isfinite(x);
    if ~any(valid)
        fraction = ...
            NaN;
        return;
    end
    tolerance = ...
        max( ...
            1e-9, ...
            1e-6*absoluteLimit);
    fraction = ...
        nnz( ...
            valid & ...
            abs(x) >= ...
            absoluteLimit - ...
            tolerance) / ...
        nnz(valid);
end
function mask = multiWindowMaskController( ...
    t, ...
    windowStarts, ...
    windowEnds)
    t = ...
        double( ...
            t(:));
    mask = ...
        false( ...
            size(t));
    for windowIndex = 1:numel(windowStarts)
        tStart = ...
            windowStarts(windowIndex);
        tEnd = ...
            windowEnds(windowIndex);
        if isfinite(tStart) && ...
                isfinite(tEnd) && ...
                tEnd >= tStart
            mask = ...
                mask | ...
                ( ...
                    isfinite(t) & ...
                    t >= tStart & ...
                    t <= tEnd ...
                );
        end
    end
end
function Xmasked = maskRowsController(X,mask)
    Xmasked = ...
        double(X);
    mask = ...
        logical( ...
            mask(:));
    if size(Xmasked,1) ~= numel(mask)
        error( ...
            'Plot mask length does not match signal row count.');
    end
    Xmasked( ...
        ~mask, ...
        :) = ...
        NaN;
end
function [t,X] = extractSignal(signal)
    if isa( ...
            signal, ...
            'Simulink.SimulationData.Signal')
        signal = ...
            signal.Values;
    end
    if ~isa( ...
            signal, ...
            'timeseries')
        error( ...
            'Expected a logged timeseries signal.');
    end
    t = ...
        signal.Time(:);
    X = ...
        timeseriesDataToMatrix( ...
            signal.Data, ...
            numel(t));
end
function [t,X] = extractBusField(bus,path)
    value = ...
        bus;
    for k = 1:numel(path)
        fieldName = ...
            path{k};
        if isa( ...
                value, ...
                'Simulink.SimulationData.Signal')
            value = ...
                value.Values;
        end
        if isstruct(value)
            if ~isfield( ...
                    value, ...
                    fieldName)
                error( ...
                    'Logged bus does not contain field "%s".', ...
                    fieldName);
            end
            value = ...
                value.(fieldName);
        elseif isobject(value)
            if ~isprop( ...
                    value, ...
                    fieldName)
                error( ...
                    'Logged bus does not contain field "%s".', ...
                    fieldName);
            end
            value = ...
                value.(fieldName);
        else
            error( ...
                'Unable to access logged bus field "%s".', ...
                fieldName);
        end
    end
    [t,X] = ...
        extractSignal( ...
            value);
end
function X = timeseriesDataToMatrix(data,nt)
    D = ...
        squeeze( ...
            data);
    if isempty(D)
        X = ...
            zeros(0,0);
        return;
    end
    if nt == 1
        X = ...
            reshape( ...
                D, ...
                1, ...
                []);
        return;
    end
    if isvector(D)
        if numel(D) == nt
            X = ...
                D(:);
        else
            error( ...
                ['Unable to determine logged signal ', ...
                 'orientation.']);
        end
        return;
    end
    if size(D,1) == nt
        X = ...
            reshape( ...
                D, ...
                nt, ...
                []);
    elseif size(D,2) == nt
        X = ...
            D.';
    elseif size(D,ndims(D)) == nt
        order = [ ...
            ndims(D), ...
            1:(ndims(D)-1)];
        D = ...
            permute( ...
                D, ...
                order);
        X = ...
            reshape( ...
                D, ...
                nt, ...
                []);
    else
        error( ...
            ['Unable to match logged signal dimensions ', ...
             'with its time vector.']);
    end
end

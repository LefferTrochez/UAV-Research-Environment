    error( ...
        'QuadrotorFramework:ControllerStageSafetyFieldType', ...
        'Stage %d safety field "%s" must be a finite logical scalar.', ...
        stageIndex, ...
        fieldName);
end
value = ...
    logical(rawValue);
end

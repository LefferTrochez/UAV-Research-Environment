function seeds = localValidatedSeedOffsets(rawSeeds,label)
seeds = ...
    double( ...
        rawSeeds(:));
if isempty(seeds)
    error( ...
        'QuadrotorFramework:ControllerFinalValidationSeeds', ...
        '%s requires at least one seed.', ...
        label);
end
if any(~isfinite(seeds))
    error( ...
        'QuadrotorFramework:ControllerFinalValidationSeeds', ...
        '%s seeds must be finite.', ...
        label);
end
if numel(unique(seeds)) ~= numel(seeds)
    error( ...
        'QuadrotorFramework:ControllerFinalValidationSeeds', ...
        '%s seeds must be unique.', ...
        label);
end
end
function mask = localUsableRunMask(R,numberOfSeeds)
mask = ...
    false( ...
        numberOfSeeds, ...
        1);
if isempty(R) || ...
        ~isstruct(R) || ...
        ~isfield(R,'metricsAvailable') || ...
        isempty(R.metricsAvailable) || ...
        ~isfield(R,'runSucceeded') || ...
        isempty(R.runSucceeded)
    return;
end
available = ...
    logical( ...
        R.metricsAvailable);
succeeded = ...
    logical( ...
        R.runSucceeded);
if size(available,2) ~= numberOfSeeds || ...
        size(succeeded,2) ~= numberOfSeeds
    return;
end
mask = ...
    all(available,1).' & ...
    all(succeeded,1).';
end
function mask = localStrictRunMask(R,numberOfSeeds)
mask = ...
    false( ...
        numberOfSeeds, ...
        1);
if isempty(R) || ...
        ~isstruct(R) || ...
        ~isfield(R,'strictRunSucceeded') || ...
        isempty(R.strictRunSucceeded)
    return;
end
strict = ...
    logical( ...
        R.strictRunSucceeded);
if size(strict,2) ~= numberOfSeeds
    return;
end
mask = ...
    all(strict,1).';
end
function displayValidationMessages(R)
if isempty(R) || ...
        ~isstruct(R)
    fprintf( ...
        '  No validation diagnostics available.\n');
    return;
end
if ~isfield(R,'messages') || ...
        isempty(R.messages)
    fprintf( ...
        '  No validation diagnostics available.\n');
    return;
end
messages = ...
    R.messages;
if ischar(messages) || ...
        isstring(messages)
    messages = ...
        cellstr( ...
            string(messages));
end
for k = 1:numel(messages)
    if isempty(messages{k})
        continue;
    end
    fprintf( ...
        '  [%d] %s\n', ...
        k, ...
        char( ...
            string(messages{k})));
end
end
function localRestoreControllerTuningFlag( ...
    previouslyExisted, ...
    previousValue)
try
    if previouslyExisted
        assignin( ...
            'base', ...
            'CONTROLLER_TUNING_ACTIVE', ...
            previousValue);
    else
        evalin( ...
            'base', ...
            'clear(''CONTROLLER_TUNING_ACTIVE'')');
    end
catch
end
end
function localCheckExpectedGain(T,path,expectedValue)
row = ...
    find( ...
        string(T.ParameterPath) == ...
        string(path), ...
        1, ...
        'first');
if isempty(row)
    error( ...
        'QuadrotorFramework:ControllerTuningExpectedBaselinePath', ...
        'Expected baseline gain "%s" is missing from the active C2 gain table.', ...
        path);
end
actualValue = ...
    double( ...
        T.EffectiveValue(row));
tolerance = ...
    max( ...
        1e-12, ...
        1e-10*max(abs(double(expectedValue)),1));
if ~isfinite(actualValue) || ...
        abs(actualValue-double(expectedValue)) > tolerance
    error( ...
        'QuadrotorFramework:ControllerTuningExpectedBaselineMismatch', ...
        'Baseline gain "%s" is %.15g but the final local campaign expects %.15g.', ...
        path, ...
        actualValue, ...
        double(expectedValue));
end
end

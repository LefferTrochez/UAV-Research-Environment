function CONTROLLER_TUNING_RESULT = tune_controller_from_scratch()
totalTimer = ...
    tic;
fprintf('\n');
fprintf( ...
    '==============================================================\n');
fprintf( ...
    ' AUTOMATIC CASCADED CONTROLLER TUNING — C2 / L3 / SCHEMA 3.0\n');
fprintf( ...
    '==============================================================\n');
CFG = ...
    controller_tuning_config();
modelName = ...
    CFG.modelName;
if ~isfield(CFG,'schemaVersion') || ...
        double(CFG.schemaVersion) < 3.0
    error( ...
        'QuadrotorFramework:ControllerTuningOldConfigurationSchema', ...
        ['controller_tuning_config.m must use controller gain ', ...
         'schema 3.0 or newer.']);
end
if ~isfield(CFG,'totalTunableGains') || ...
        CFG.totalTunableGains ~= 6
    error( ...
        'QuadrotorFramework:ControllerTuningGainCount', ...
        ['The final local C2/L3 campaign requires exactly ', ...
         '6 unique tunable gains.']);
end
if ~isfield(CFG,'numberOfStages') || ...
        CFG.numberOfStages ~= 3
    error( ...
        'QuadrotorFramework:ControllerTuningStageCount', ...
        'The final local C2/L3 campaign requires exactly 3 stages.');
end
if ~isfield(CFG,'totalStageParameters') || ...
        CFG.totalStageParameters ~= 9
    error( ...
        'QuadrotorFramework:ControllerTuningStageParameterCount', ...
        ['The final local C2/L3 campaign requires exactly ', ...
         '9 stage parameter entries across 6 unique gains.']);
end
if ~isfield(CFG,'policy') || ...
        ~isstruct(CFG.policy) || ...
        ~isfield(CFG.policy,'allowSequentialRetuning') || ...
        ~logical(CFG.policy.allowSequentialRetuning)
    error( ...
        'QuadrotorFramework:ControllerTuningSequentialRetuningDisabled', ...
        ['The final local C2/L3 campaign requires ', ...
         'CFG.policy.allowSequentialRetuning = true.']);
end
if ~isfield(CFG,'experiment') || ~isstruct(CFG.experiment)
    error('QuadrotorFramework:ControllerTuningExperimentConfig','CFG.experiment is required.');
end
if ~isfield(CFG.experiment,'controllerSet') || ~strcmpi(string(CFG.experiment.controllerSet),"C2")
    error('QuadrotorFramework:ControllerTuningControllerSet','This tuning campaign must target controller set C2.');
end
if ~isfield(CFG.experiment,'plantModels') || ~isequal(double(CFG.experiment.plantModels(:).'),3)
    error('QuadrotorFramework:ControllerTuningPlantModels','C2 tuning must evaluate L3 only.');
end
if ~isfield(CFG.experiment,'trajectoryID') || double(CFG.experiment.trajectoryID) ~= 2
    error('QuadrotorFramework:ControllerTuningTrajectory','C2 tuning must use trajectory 2.');
end
if ~isfield(CFG.experiment,'feedbackSource') || ~strcmpi(string(CFG.experiment.feedbackSource),"EST")
    error('QuadrotorFramework:ControllerTuningFeedback','C2 tuning must use EST controller feedback.');
end
if ~isfield(CFG.experiment,'metricStateSource') || ~strcmpi(string(CFG.experiment.metricStateSource),"TRUE")
    error('QuadrotorFramework:ControllerTuningMetricState','Controller performance metrics must use TRUE state.');
end
if CFG.optimizer.useParallel
    fprintf('\n');
    fprintf( ...
        ['NOTE: CFG.optimizer.useParallel was true. ', ...
         'It is being overridden to false for this campaign.\n']);
end
CFG.optimizer.useParallel = ...
    false;
CFG.runtime = ...
    struct();
CFG.runtime.executionMode = ...
    "SERIAL_SAFE";
CFG.runtime.parallelDisabled = ...
    true;
CFG.runtime.parallelDisabledReason = ...
    "PARSIM initialization instability";
CFG.runtime.resumeAllowed = ...
    false;
CFG.runtime.controllerGainSchema = ...
    "3.0";
if ~evalin( ...
        'base', ...
        'exist(''AUTOPILOT'',''var'')')
    error( ...
        'QuadrotorFramework:ControllerTuningMissingAutopilot', ...
        ['AUTOPILOT does not exist in the base workspace. ', ...
         'Run initialize_project before tune_controller_from_scratch.']);
end
AUTOPILOT_INITIAL = ...
    evalin( ...
        'base', ...
        'AUTOPILOT');
if ~isstruct(AUTOPILOT_INITIAL)
    error( ...
        'QuadrotorFramework:ControllerTuningInvalidAutopilot', ...
        'Base-workspace AUTOPILOT must be a structure.');
end
if ~isfield(AUTOPILOT_INITIAL,'info') || ~isstruct(AUTOPILOT_INITIAL.info) || ~isfield(AUTOPILOT_INITIAL.info,'activeController')
    error('QuadrotorFramework:ControllerTuningMissingActiveController','AUTOPILOT.info.activeController is required.');
end
if ~strcmpi(string(AUTOPILOT_INITIAL.info.activeController),"C2")
    error('QuadrotorFramework:ControllerTuningWrongActiveController','Initialize the project with L3 so that controller set C2 is active before tuning.');
end
if isfield(AUTOPILOT_INITIAL,'info') && ...
        isstruct(AUTOPILOT_INITIAL.info) && ...
        isfield( ...
            AUTOPILOT_INITIAL.info, ...
            'controllerGainSchema')
    autopilotSchema = ...
        string( ...
            AUTOPILOT_INITIAL.info.controllerGainSchema);
    if autopilotSchema ~= "3.0"
        error( ...
            'QuadrotorFramework:ControllerTuningAutopilotSchema', ...
            ['AUTOPILOT reports controller gain schema "%s". ', ...
             'Schema 3.0 is required.'], ...
            autopilotSchema);
    end
end
estimatorOverrideExists = ...
    evalin( ...
        'base', ...
        'exist(''ESTIMATOR_TUNING_OVERRIDE'',''var'')');
if estimatorOverrideExists
    estimatorOverride = ...
        evalin( ...
            'base', ...
            'ESTIMATOR_TUNING_OVERRIDE');
    if ~isempty(estimatorOverride)
        error( ...
            'QuadrotorFramework:ControllerTuningEstimatorOverride', ...
            ['ESTIMATOR_TUNING_OVERRIDE is currently active. ', ...
             'Clear it and run initialize_project before controller ', ...
             'tuning.']);
    end
end
if ~bdIsLoaded(modelName)
    load_system( ...
        modelName);
end
simulationStatus = ...
    get_param( ...
        modelName, ...
        'SimulationStatus');
if ~strcmpi( ...
        simulationStatus, ...
        'stopped')
    error( ...
        'QuadrotorFramework:ControllerTuningModelRunning', ...
        'Model "%s" must be stopped before tuning.', ...
        modelName);
end
modelDirty = ...
    get_param( ...
        modelName, ...
        'Dirty');
if strcmpi( ...
        modelDirty, ...
        'on')
    error( ...
        'QuadrotorFramework:ControllerTuningDirtyModel', ...
        ['Model "%s" contains unsaved changes. ', ...
         'Save the model before starting controller tuning.'], ...
        modelName);
end
INITIAL_GAIN_TABLE = ...
    controller_tuning_gain_table( ...
        AUTOPILOT_INITIAL);
if height(INITIAL_GAIN_TABLE) ~= 16
    error( ...
        'QuadrotorFramework:ControllerTuningInitialGainCount', ...
        ['controller_tuning_gain_table returned %d active C2 gains. ', ...
         'Exactly 16 are required by controller gain schema 3.0.'], ...
        height(INITIAL_GAIN_TABLE));
end
if isfield(CFG,'baseline') && isstruct(CFG.baseline) && isfield(CFG.baseline,'expectedC2')
    expectedBaseline = CFG.baseline.expectedC2;
    localCheckExpectedGain(INITIAL_GAIN_TABLE,"angularRate.roll.Kp",expectedBaseline.rollRateKp);
    localCheckExpectedGain(INITIAL_GAIN_TABLE,"angularRate.roll.Ki",expectedBaseline.rollRateKi);
    localCheckExpectedGain(INITIAL_GAIN_TABLE,"attitude.roll.Kp",expectedBaseline.rollAttitudeKp);
    localCheckExpectedGain(INITIAL_GAIN_TABLE,"angularRate.pitch.Kp",expectedBaseline.pitchRateKp);
    localCheckExpectedGain(INITIAL_GAIN_TABLE,"angularRate.pitch.Ki",expectedBaseline.pitchRateKi);
    localCheckExpectedGain(INITIAL_GAIN_TABLE,"attitude.pitch.Kp",expectedBaseline.pitchAttitudeKp);
end
configuredPaths = ...
    strings( ...
        0, ...
        1);
expectedStageObjectives = [ ...
    "rate_pitch"; ...
    "attitude_pitch"; ...
    "joint_roll_pitch"];
expectedStagePaths = { ...
    ["angularRate.pitch.Kp";"angularRate.pitch.Ki"]; ...
    "attitude.pitch.Kp"; ...
    ["angularRate.roll.Kp";"angularRate.roll.Ki";"attitude.roll.Kp";"angularRate.pitch.Kp";"angularRate.pitch.Ki";"attitude.pitch.Kp"]};
for stageIndex = 1:CFG.numberOfStages
    STAGE = ...
        CFG.stages(stageIndex);
    if lower(string(STAGE.objectiveType)) ~= expectedStageObjectives(stageIndex)
        error( ...
            'QuadrotorFramework:ControllerTuningStageObjectiveContract', ...
            'Stage %d has an invalid objectiveType for the final local C2/L3 campaign.', ...
            stageIndex);
    end
    stagePaths = ...
        string( ...
            STAGE.parameterPaths(:));
    expectedPaths = ...
        string( ...
            expectedStagePaths{stageIndex}(:));
    if numel(stagePaths) ~= numel(expectedPaths) || ...
            ~all(stagePaths == expectedPaths)
        error( ...
            'QuadrotorFramework:ControllerTuningStagePathContract', ...
            'Stage %d gain paths do not match the final local C2/L3 campaign.', ...
            stageIndex);
    end
    controller_tuning_gain_table( ...
        AUTOPILOT_INITIAL, ...
        STAGE.parameterPaths);
    configuredPaths = [ ...
        configuredPaths; ...
        string( ...
            STAGE.parameterPaths(:))];
end
if numel(configuredPaths) ~= CFG.totalStageParameters
    error( ...
        'QuadrotorFramework:ControllerTuningConfiguredStageParameterCount', ...
        ['The configured tuning stages contain %d parameter entries, ', ...
         'but CFG.totalStageParameters is %d.'], ...
        numel(configuredPaths), ...
        CFG.totalStageParameters);
end
uniqueConfiguredPaths = ...
    unique( ...
        configuredPaths, ...
        'stable');
if numel(uniqueConfiguredPaths) ~= CFG.totalTunableGains
    error( ...
        'QuadrotorFramework:ControllerTuningUniqueGainCount', ...
        ['The configured tuning stages contain %d unique gains, ', ...
         'but CFG.totalTunableGains is %d.'], ...
        numel(uniqueConfiguredPaths), ...
        CFG.totalTunableGains);
end
expectedUniquePaths = [ ...
    "angularRate.roll.Kp"; ...
    "angularRate.roll.Ki"; ...
    "attitude.roll.Kp"; ...
    "angularRate.pitch.Kp"; ...
    "angularRate.pitch.Ki"; ...
    "attitude.pitch.Kp"];
if ~all(ismember(expectedUniquePaths,uniqueConfiguredPaths)) || ...
        ~all(ismember(uniqueConfiguredPaths,expectedUniquePaths))
    error( ...
        'QuadrotorFramework:ControllerTuningGainContractMismatch', ...
        ['The final local C2/L3 campaign must tune exactly the ', ...
         'three roll and three pitch gains defined by the campaign.']);
end
pathCounts = ...
    zeros( ...
        numel(expectedUniquePaths), ...
        1);
for pathIndex = 1:numel(expectedUniquePaths)
    pathCounts(pathIndex) = ...
        nnz( ...
            configuredPaths == ...
            expectedUniquePaths(pathIndex));
end
expectedPathCounts = [1;1;1;2;2;2];
if ~isequal(pathCounts,expectedPathCounts)
    error( ...
        'QuadrotorFramework:ControllerTuningSequentialRetuningContract', ...
        ['The final local campaign requires roll gains once and ', ...
         'pitch gains twice across the three sequential stages.']);
end
authoritativePaths = ...
    string( ...
        INITIAL_GAIN_TABLE.ParameterPath);
if ~all(ismember(uniqueConfiguredPaths,authoritativePaths))
    error( ...
        'QuadrotorFramework:ControllerTuningGainContractMismatch', ...
        ['At least one configured C2 tuning gain is not present in ', ...
         'controller_tuning_gain_table.']);
end
fprintf('\n');
fprintf('Verified active controller gains:\n\n');
disp( ...
    INITIAL_GAIN_TABLE(:, ...
    {'Stage','Label','EffectiveValue'}));
tuningFlagPreviouslyExisted = ...
    evalin( ...
        'base', ...
        'exist(''CONTROLLER_TUNING_ACTIVE'',''var'')');
if tuningFlagPreviouslyExisted
    previousTuningFlagValue = ...
        evalin( ...
            'base', ...
            'CONTROLLER_TUNING_ACTIVE');
else
    previousTuningFlagValue = ...
        [];
end
assignin( ...
    'base', ...
    'CONTROLLER_TUNING_ACTIVE', ...
    true);
tuningFlagCleanup = ...
    onCleanup( ...
        @() localRestoreControllerTuningFlag( ...
            tuningFlagPreviouslyExisted, ...
            previousTuningFlagValue));
fprintf('\n');
fprintf( ...
    'Base CONTROLLER_TUNING_ACTIVE: TRUE\n');
controllerTuningFolder = ...
    fileparts( ...
        mfilename( ...
            'fullpath'));
projectRoot = ...
    fileparts( ...
        fileparts( ...
            controllerTuningFolder));
configuredRootFolder = ...
    char( ...
        string( ...
            CFG.output.rootFolder));
[~,resultsFolderName,resultsFolderExtension] = ...
    fileparts( ...
        configuredRootFolder);
resultsFolderName = ...
    [ ...
    resultsFolderName, ...
    resultsFolderExtension];
if isempty(resultsFolderName)
    resultsFolderName = ...
        'Results_C2';
end
rootFolder = ...
    fullfile( ...
        controllerTuningFolder, ...
        resultsFolderName);
if ~exist(rootFolder,'dir')
    [mkdirStatus,mkdirMessage] = ...
        mkdir( ...
            rootFolder);
    if ~mkdirStatus
        error( ...
            'QuadrotorFramework:ControllerTuningResultsFolder', ...
            'Unable to create controller tuning results folder "%s". %s', ...
            rootFolder, ...
            mkdirMessage);
    end
end
timestamp = ...
    char( ...
        datetime( ...
            'now', ...
            'Format', ...
            'yyyy-MM-dd_HH-mm-ss'));
runFolder = ...
    fullfile( ...
        rootFolder, ...
        [ ...
        'Controller_Tuning_C2_', ...
        timestamp]);
if exist(runFolder,'dir')
    error( ...
        'QuadrotorFramework:ControllerTuningRunFolderExists', ...
        'Controller tuning run folder already exists.');
end
mkdir( ...
    runFolder);
fprintf('\n');
fprintf( ...
    'NEW campaign. Resume is disabled.\n');
fprintf( ...
    'Results folder:\n%s\n\n', ...
    runFolder);
resultFile = ...
    fullfile( ...
        runFolder, ...
        CFG.output.resultFile);
stageResultsFile = ...
    fullfile( ...
        runFolder, ...
        CFG.output.stageResultsFile);
gainTableFile = ...
    fullfile( ...
        runFolder, ...
        CFG.output.gainTableFile);
validationFile = ...
    fullfile( ...
        runFolder, ...
        CFG.output.validationFile);
configurationFile = ...
    fullfile( ...
        runFolder, ...
        'Controller_Tuning_Config.mat');
partialResultFile = ...
    fullfile( ...
        runFolder, ...
        'Controller_Tuning_Partial.mat');
save( ...
    configurationFile, ...
    'CFG', ...
    '-v7.3');
snapshotFolder = ...
    fullfile( ...
        runFolder, ...
        'Code_Snapshot');
if ~exist(snapshotFolder,'dir')
    mkdir( ...
        snapshotFolder);
end
snapshotFiles = { ...
    'UAV_autopilot.m'; ...
    'controller_tuning_config.m'; ...
    'controller_tuning_gain_table.m'; ...
    'evaluate_controller_candidate.m'; ...
    'evaluate_controller_candidates_parallel.m'; ...
    'tune_controller_stage.m'; ...
    'tune_controller_from_scratch.m'; ...
    'tune_controller.m'; ...
    'apply_controller_tuning_result.m'};
for fileIndex = 1:numel(snapshotFiles)
    sourceFile = ...
        which( ...
            snapshotFiles{fileIndex});
    if isempty(sourceFile)
        warning( ...
            'QuadrotorFramework:ControllerTuningSnapshotMissing', ...
            'Snapshot source file not found: %s', ...
            snapshotFiles{fileIndex});
        continue;
    end
    try
        copyfile( ...
            sourceFile, ...
            fullfile( ...
                snapshotFolder, ...
                snapshotFiles{fileIndex}));
    catch ME
        warning( ...
            'QuadrotorFramework:ControllerTuningSnapshot', ...
            'Unable to snapshot %s: %s', ...
            snapshotFiles{fileIndex}, ...
            ME.message);
    end
end
METADATA = ...
    struct();
METADATA.StartTimestamp = ...
    timestamp;
METADATA.MATLABVersion = ...
    version;
METADATA.ModelName = ...
    modelName;
METADATA.ControllerGainSchema = ...
    "3.0";
METADATA.CampaignProfile = ...
    CFG.campaignProfile;
METADATA.ExecutionMode = ...
    CFG.runtime.executionMode;
METADATA.ControllerSet = ...
    string(CFG.experiment.controllerSet);
METADATA.PlantModels = ...
    double(CFG.experiment.plantModels(:).');
METADATA.PlantWeights = ...
    double(CFG.experiment.plantWeights(:).');
METADATA.TrajectoryID = ...
    double(CFG.experiment.trajectoryID);
METADATA.FeedbackSource = ...
    string(CFG.experiment.feedbackSource);
METADATA.MetricStateSource = ...
    string(CFG.experiment.metricStateSource);
METADATA.DisturbancesEnabled = ...
    CFG.experiment.disturbancesEnabled;
METADATA.OperatorMode = ...
    CFG.experiment.operatorMode;
METADATA.TotalTunableGains = ...
    CFG.totalTunableGains;
METADATA.TotalRequestedEvaluations = ...
    CFG.totalRequestedFunctionEvaluations;
METADATA.NumberOfStages = ...
    CFG.numberOfStages;
METADATA.RunFolder = ...
    runFolder;
METADATA.ProjectRoot = ...
    projectRoot;
METADATA.Resumed = ...
    false;
METADATA.ResumeAllowed = ...
    false;
STAGE_RESULTS = ...
    repmat( ...
        localEmptyStageSummary(), ...
        CFG.numberOfStages, ...
        1);
STAGE_RESULTS_FULL = ...
    cell( ...
        CFG.numberOfStages, ...
        1);
FROZEN_AUTOPILOT = ...
    AUTOPILOT_INITIAL;
completedStages = ...
    0;
controller_tuning_gain_table( ...
    FROZEN_AUTOPILOT);
fprintf('\n');
fprintf( ...
    '==============================================================\n');
fprintf( ...
    ' STARTING NEW INSIDE-OUT CONTROLLER TUNING CAMPAIGN\n');
fprintf( ...
    '==============================================================\n');
fprintf( ...
    'Controller schema:         3.0\n');
fprintf( ...
    'Controller set:            %s\n', ...
    string(CFG.experiment.controllerSet));
plantModelText = ...
    strjoin( ...
        compose( ...
            "L%d", ...
            double(CFG.experiment.plantModels(:).')), ...
        " + ");
fprintf( ...
    'Plant models:              %s\n', ...
    char(plantModelText));
fprintf( ...
    'Trajectory ID:             %d\n', ...
    CFG.experiment.trajectoryID);
fprintf( ...
    'Controller feedback:       %s\n', ...
    string(CFG.experiment.feedbackSource));
fprintf( ...
    'Metric state source:       %s\n', ...
    string(CFG.experiment.metricStateSource));
fprintf( ...
    'Execution:                 SERIAL SAFE\n');
fprintf( ...
    'Active tunable gains:      %d\n', ...
    CFG.totalTunableGains);
fprintf( ...
    'Requested candidate evals: %d\n', ...
    CFG.totalRequestedFunctionEvaluations);
fprintf( ...
    'Stage validation:          1-SEED MISSION GATE + FINAL 3-SEED STRICT\n');
fprintf( ...
    'Max global degradation:    %.1f %%\n', ...
    100 * CFG.policy.maximumMissionCostDegradationFraction);
fprintf( ...
    'Max worst-plant degrade:   %.1f %%\n', ...
    100 * CFG.policy.maximumWorstPlantCostDegradationFraction);
fprintf( ...
    'Resume:                    DISABLED\n');
fprintf( ...
    'Starting stage:            1 — %s\n', ...
    CFG.stages(1).name);
fprintf( ...
    '==============================================================\n\n');
for stageIndex = 1:CFG.numberOfStages
    STAGE = ...
        CFG.stages(stageIndex);
    fprintf('\n');
    fprintf( ...
        '##############################################################\n');
    fprintf( ...
        ' STAGE %d/%d — %s\n', ...
        stageIndex, ...
        CFG.numberOfStages, ...
        STAGE.name);
    fprintf( ...
        '##############################################################\n');
    try
        PRE_STAGE_AUTOPILOT = ...
            FROZEN_AUTOPILOT;
        [ ...
            currentStageResult, ...
            stageAutopilotOut] = ...
            tune_controller_stage( ...
                CFG, ...
                STAGE, ...
                PRE_STAGE_AUTOPILOT, ...
                runFolder);
        [stageSafetyContractPass,stageSafetyMode] = ...
            localStageAcceptanceContract( ...
                currentStageResult, ...
                stageIndex);
        if currentStageResult.accepted
            if ~stageSafetyContractPass
                error( ...
                    'QuadrotorFramework:ControllerStageAcceptedWithoutSafetyPass', ...
                    ['Stage %d was marked accepted but its mission-safety ', ...
                     'contract is internally inconsistent.'], ...
                    stageIndex);
            end
            FROZEN_AUTOPILOT = ...
                stageAutopilotOut;
            fprintf( ...
                'Stage acceptance mode:      %s\n', ...
                char(stageSafetyMode));
        else
            FROZEN_AUTOPILOT = ...
                PRE_STAGE_AUTOPILOT;
        end
        controller_tuning_gain_table( ...
            FROZEN_AUTOPILOT);
        STAGE_RESULTS(stageIndex) = ...
            localStageSummaryFromResult( ...
                currentStageResult);
        STAGE_RESULTS_FULL{stageIndex} = ...
            currentStageResult;
        completedStages = ...
            stageIndex;
        save( ...
            stageResultsFile, ...
            'STAGE_RESULTS', ...
            'STAGE_RESULTS_FULL', ...
            'completedStages', ...
            '-v7.3');
        PARTIAL_RESULT = ...
            localBuildPartialResult( ...
                completedStages, ...
                FROZEN_AUTOPILOT, ...
                STAGE_RESULTS, ...
                STAGE_RESULTS_FULL, ...
                runFolder);
        save( ...
            partialResultFile, ...
            'PARTIAL_RESULT', ...
            '-v7.3');
        fprintf('\n');
        if currentStageResult.accepted
            fprintf( ...
                ['Stage %d accepted, mission-safety validated, ', ...
                 'and FROZEN.\n'], ...
                stageIndex);
        else
            fprintf( ...
                ['Stage %d rejected. Last globally valid controller ', ...
                 'was restored and kept.\n'], ...
                stageIndex);
        end
    catch ME
        fprintf('\n');
        fprintf( ...
            '!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n');
        fprintf( ...
            ' CONTROLLER TUNING STOPPED\n');
        fprintf( ...
            '!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n');
        fprintf( ...
            'Failed stage: %d — %s\n', ...
            stageIndex, ...
            STAGE.name);
        fprintf( ...
            'Identifier:   %s\n', ...
            ME.identifier);
        fprintf( ...
            'Message:      %s\n', ...
            ME.message);
        FAILURE = ...
            struct();
        FAILURE.schemaVersion = ...
            3.0;
        FAILURE.ControllerGainSchema = ...
            "3.0";
        FAILURE.Timestamp = ...
            char( ...
                datetime( ...
                    'now', ...
                    'Format', ...
                    'yyyy-MM-dd_HH-mm-ss'));
        FAILURE.StageIndex = ...
            stageIndex;
        FAILURE.Stage = ...
            STAGE;
        FAILURE.CompletedStages = ...
            completedStages;
        FAILURE.LastFrozenAutopilot = ...
            FROZEN_AUTOPILOT;
        FAILURE.Identifier = ...
            ME.identifier;
        FAILURE.Message = ...
            ME.message;
        FAILURE.Stack = ...
            ME.stack;
        FAILURE.RunFolder = ...
            runFolder;
        FAILURE.ResumeAllowed = ...
            false;
        save( ...
            fullfile( ...
                runFolder, ...
                'Controller_Tuning_FAILURE.mat'), ...
            'FAILURE', ...
            '-v7.3');
        save( ...
            stageResultsFile, ...
            'STAGE_RESULTS', ...
            'STAGE_RESULTS_FULL', ...
            'completedStages', ...
            '-v7.3');
        PARTIAL_RESULT = ...
            localBuildPartialResult( ...
                completedStages, ...
                FROZEN_AUTOPILOT, ...
                STAGE_RESULTS, ...
                STAGE_RESULTS_FULL, ...
                runFolder);
        save( ...
            partialResultFile, ...
            'PARTIAL_RESULT', ...
            '-v7.3');
        fprintf('\n');
        fprintf( ...
            ['A progress snapshot was saved for diagnostics only.\n', ...
             'The next tune_controller_from_scratch invocation will start a NEW ', ...
             'campaign from Stage 1.\n\n']);
        rethrow(ME);
    end
end
FINAL_GAIN_TABLE_RAW = ...
    controller_tuning_gain_table( ...
        FROZEN_AUTOPILOT);
if height(FINAL_GAIN_TABLE_RAW) ~= ...
        height(INITIAL_GAIN_TABLE)
    error( ...
        'QuadrotorFramework:ControllerTuningFinalGainCount', ...
        'Final controller gain table must preserve the complete controller gain contract.');
end
if ~all(ismember(uniqueConfiguredPaths,string(FINAL_GAIN_TABLE_RAW.ParameterPath)))
    error( ...
        'QuadrotorFramework:ControllerTuningFinalConfiguredGains', ...
        'The final controller no longer contains every configured C2 tuning gain.');
end
if ~all( ...
        INITIAL_GAIN_TABLE.ParameterPath == ...
        FINAL_GAIN_TABLE_RAW.ParameterPath)
    error( ...
        'QuadrotorFramework:ControllerTuningFinalGainOrder', ...
        'Initial and final controller gain contracts do not match.');
end
ParameterPath = ...
    INITIAL_GAIN_TABLE.ParameterPath;
Label = ...
    INITIAL_GAIN_TABLE.Label;
Stage = ...
    INITIAL_GAIN_TABLE.Stage;
InitialValue = ...
    INITIAL_GAIN_TABLE.EffectiveValue;

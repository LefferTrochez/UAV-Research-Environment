function [pass,mode] = localStageAcceptanceContract(R,stageIndex)
requiredFields = { ...
    'accepted'; ...
    'missionValidationPerformed'; ...
    'missionComparisonAvailable'; ...
    'candidateMissionFeasibilityPass'; ...
    'missionValidationValid'; ...
    'missionCostPass'; ...
    'worstPlantPass'; ...
    'missionSafetyPass'};
if ~isstruct(R)
    error( ...
        'QuadrotorFramework:ControllerStageSafetyContract', ...
        'Stage %d did not return a structure.', ...
        stageIndex);
end
for fieldIndex = 1:numel(requiredFields)
    if ~isfield(R,requiredFields{fieldIndex})
        error( ...
            'QuadrotorFramework:ControllerStageSafetyContract', ...
            'Stage %d did not return required safety field "%s".', ...
            stageIndex, ...
            requiredFields{fieldIndex});
    end
end
accepted = ...
    localLogicalScalar( ...
        R.accepted, ...
        'accepted', ...
        stageIndex);
missionValidationPerformed = ...
    localLogicalScalar( ...
        R.missionValidationPerformed, ...
        'missionValidationPerformed', ...
        stageIndex);
comparisonAvailable = ...
    localLogicalScalar( ...
        R.missionComparisonAvailable, ...
        'missionComparisonAvailable', ...
        stageIndex);
candidateMissionFeasibilityPass = ...
    localLogicalScalar( ...
        R.candidateMissionFeasibilityPass, ...
        'candidateMissionFeasibilityPass', ...
        stageIndex);
missionValidationValid = ...
    localLogicalScalar( ...
        R.missionValidationValid, ...
        'missionValidationValid', ...
        stageIndex);
missionCostPass = ...
    localLogicalScalar( ...
        R.missionCostPass, ...
        'missionCostPass', ...
        stageIndex);
worstPlantPass = ...
    localLogicalScalar( ...
        R.worstPlantPass, ...
        'worstPlantPass', ...
        stageIndex);
missionSafetyPass = ...
    localLogicalScalar( ...
        R.missionSafetyPass, ...
        'missionSafetyPass', ...
        stageIndex);
if comparisonAvailable
    mode = ...
        "NORMALIZED_COMPARISON";
    pass = ...
        missionValidationPerformed && ...
        candidateMissionFeasibilityPass && ...
        missionValidationValid && ...
        missionCostPass && ...
        worstPlantPass && ...
        missionSafetyPass;
else
    mode = ...
        "FEASIBILITY_BOOTSTRAP";
    pass = ...
        missionValidationPerformed && ...
        candidateMissionFeasibilityPass && ...
        missionSafetyPass;
end
if accepted && ~pass
    error( ...
        'QuadrotorFramework:ControllerStageSafetyContractInconsistent', ...
        ['Stage %d reports accepted=true but its %s safety contract ', ...
         'does not pass.'], ...
        stageIndex, ...
        char(mode));
end
end

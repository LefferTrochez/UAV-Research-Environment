    W.rmse * ...
    ratioMetric( ...
        rmseValue, ...
        baselineRMSE, ...
        minimum) + ...
    W.p95 * ...
    ratioMetric( ...
        p95Value, ...
        baselineP95, ...
        minimum) + ...
    W.controlEffort * ...
    ratioMetric( ...
        effortValue, ...
        baselineEffort, ...
        minimum) + ...
    W.controlVariation * ...

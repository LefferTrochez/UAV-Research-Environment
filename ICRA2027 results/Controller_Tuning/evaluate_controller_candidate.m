end
function commonTime = pairCommonTime( ...
    t1, ...
    t2, ...
    tStart, ...
    tEnd, ...
    sampleRate_Hz)
actualStart = ...
    max( ...
        [ ...
        tStart, ...
        min(t1), ...
        min(t2)]);
actualEnd = ...
    min( ...
        [ ...
        tEnd, ...
        max(t1), ...
        max(t2)]);
if ~isfinite(actualStart) || ...
        ~isfinite(actualEnd) || ...
        actualEnd <= actualStart
    error( ...
        'QuadrotorFramework:ControllerPairWindow', ...
        'No common time interval exists for paired controller signals.');
end
numberOfSamples = ...
    max( ...
        2, ...
        round( ...
            (actualEnd-actualStart) * ...
            sampleRate_Hz) + ...
        1);
commonTime = ...
    linspace( ...
        actualStart, ...
        actualEnd, ...
        numberOfSamples).';
end

        minimum);
end
function r = ratioMetric( ...
    value, ...
    baseline, ...
    minimum)
value = ...
    double(value);
baseline = ...
    double(baseline);
if ~isfinite(value) || ...
        value < 0 || ...
        ~isfinite(baseline) || ...
        baseline < 0
    r = ...
        inf;
    return;
end
if baseline <= minimum
    if value <= minimum
        r = ...
            1;
    else
        r = ...
            1 + ...
            value / ...
            minimum;
    end
else
    r = ...
        value / ...
        baseline;
end
end
function r = saturationCost( ...
    value, ...
    baseline, ...
    minimum)

function MISSION = evaluateMissionAcceptance( ...
    t, ...
    Telemetry)
if size(Telemetry,2) < 8
    error( ...
        'QuadrotorFramework:ControllerTelemetrySize', ...
        'Telemetry must contain at least eight columns.');
end
Phase = ...
    round( ...
        double( ...
            Telemetry(:,2)));
CGSComplete = ...
    double( ...
        Telemetry(:,4)) > ...
    0.5;
Landed = ...
    double( ...
        Telemetry(:,8)) > ...
    0.5;
previousPhase = [ ...
    NaN; ...
    Phase(1:end-1)];
missionStartIndex = ...
    find( ...
        Phase == 1 & ...
        previousPhase ~= 1, ...
        1, ...
        'first');
if isempty(missionStartIndex)
    error( ...
        'QuadrotorFramework:ControllerNoTakeoff', ...
        'No TAKEOFF phase was detected.');
end
if size(Telemetry,2) >= 59
    values = ...
        Telemetry( ...
            missionStartIndex:end, ...
            59);
    valid = ...
        isfinite(values) & ...
        values >= 3 & ...
        abs(values-round(values)) < 1e-9;
    firstValid = ...
        find( ...
            valid, ...
            1, ...
            'first');
    if isempty(firstValid)
        error( ...
            'QuadrotorFramework:ControllerInvalidNumWaypoints', ...
            'No valid NumWaypoints value was found.');
    end
    N = ...
        round( ...
            values(firstValid));
else
    N = ...
        7;
end
completePhase = ...
    2*N - 2;
abortedPhase = ...
    2*N - 1;
airborneRelative = ...
    find( ...
        ~Landed(missionStartIndex:end), ...
        1, ...
        'first');
if isempty(airborneRelative)
    error( ...
        'QuadrotorFramework:ControllerNoAirborneState', ...
        'Vehicle never became airborne.');
end
airborneIndex = ...
    missionStartIndex + ...
    airborneRelative - ...
    1;
completeRelative = ...
    find( ...
        CGSComplete(airborneIndex:end), ...
        1, ...
        'first');
NavigationCompleted = ...
    ~isempty(completeRelative);
if NavigationCompleted
    navigationCompleteIndex = ...
        airborneIndex + ...
        completeRelative - ...
        1;
else
    navigationCompleteIndex = ...
        NaN;
end
FailsafeAborted = ...
    any( ...
        Phase(missionStartIndex:end) == ...
        abortedPhase);
LandedConfirmed = ...
    false;
landingIndex = ...
    NaN;
if NavigationCompleted
    landedAfterComplete = ...
        Landed(navigationCompleteIndex:end);
    previousLanded = [ ...
        Landed(max( ...
            missionStartIndex, ...
            navigationCompleteIndex-1)); ...
        landedAfterComplete(1:end-1)];
    landingRelative = ...
        find( ...
            landedAfterComplete & ...
            ~previousLanded, ...
            1, ...
            'first');
    if ~isempty(landingRelative)
        landingIndex = ...
            navigationCompleteIndex + ...
            landingRelative - ...
            1;
        LandedConfirmed = ...
            true;
    elseif Landed(end)
        landingIndex = ...
            find( ...
                Landed, ...
                1, ...
                'last');
        LandedConfirmed = ...
            true;
    end
end
MISSION = ...
    struct();
MISSION.NumWaypoints = ...
    N;
MISSION.CompletePhase = ...
    completePhase;
MISSION.AbortedPhase = ...
    abortedPhase;
MISSION.NavigationCompleted = ...
    NavigationCompleted;
MISSION.LandedConfirmed = ...
    LandedConfirmed;
MISSION.FailsafeAborted = ...
    FailsafeAborted;
MISSION.Completed = ...
    NavigationCompleted && ...
    LandedConfirmed && ...
    ~FailsafeAborted;
MISSION.MissionStartTime_s = ...
    t(missionStartIndex);
if NavigationCompleted
    MISSION.NavigationCompleteTime_s = ...
        t(navigationCompleteIndex);
else
    MISSION.NavigationCompleteTime_s = ...
        NaN;
end
if LandedConfirmed
    MISSION.LandingTime_s = ...
        t(landingIndex);
else
    MISSION.LandingTime_s = ...
        NaN;
end
end
function STATUS = evaluateMissionRequirementStatus( ...
    MISSION, ...
    CFG)
identifiers = ...
    strings( ...
        0, ...
        1);
messages = ...
    strings( ...
        0, ...
        1);
if CFG.simulation.requireMissionCompletion && ...
        ~MISSION.NavigationCompleted
    identifiers(end+1,1) = ...
        "QuadrotorFramework:ControllerTuningMissionIncomplete";
    messages(end+1,1) = ...
        "CGS Complete was not reached.";
end
if CFG.simulation.requireLanded && ...
        ~MISSION.LandedConfirmed
    identifiers(end+1,1) = ...
        "QuadrotorFramework:ControllerTuningNoLanding";
    messages(end+1,1) = ...
        "Final physical landing was not confirmed.";
end
if CFG.simulation.rejectFailsafe && ...
        MISSION.FailsafeAborted
    identifiers(end+1,1) = ...
        "QuadrotorFramework:ControllerTuningFailsafe";
    messages(end+1,1) = ...
        "Mission entered the generic ABORTED/failsafe phase.";
end
STATUS = ...
    struct();
STATUS.accepted = ...
    isempty(identifiers);
STATUS.softFailure = ...
    ~STATUS.accepted;
STATUS.identifiers = ...
    identifiers;
STATUS.messages = ...
    messages;
if STATUS.accepted
    STATUS.message = ...
        'OK';
else
    parts = ...
        strings( ...
            numel(identifiers), ...
            1);
    for k = 1:numel(identifiers)
        parts(k) = ...
            identifiers(k) + ...
            ": " + ...
            messages(k);
    end
    STATUS.message = ...
        char( ...
            strjoin( ...
                parts, ...
                ' | '));
end
end
function verifyEstimatedFeedback( ...
    Telemetry, ...
    CFG)
if size(Telemetry,2) < 58
    error('QuadrotorFramework:ControllerEstimatedFeedbackTelemetry','Telemetry does not contain TRUE/EST feedback channels.');
end
Selected = double(Telemetry(:,12:14));
True = double(Telemetry(:,50:52));
Estimated = double(Telemetry(:,56:58));
valid = all(isfinite(Selected),2) & all(isfinite(True),2) & all(isfinite(Estimated),2);
Selected = Selected(valid,:);
True = True(valid,:);
Estimated = Estimated(valid,:);
if size(Selected,1) < 10
    error('QuadrotorFramework:ControllerEstimatedFeedbackSamples','Insufficient telemetry for EST-feedback verification.');
end
maximumLagSamples = max(1,round(CFG.experiment.estimatedFeedbackMaximumLag_s * CFG.simulation.metricSampleRate_Hz));
selectedVsEst = bestAlignedRMSE(Selected,Estimated,maximumLagSamples);
selectedVsTrue = bestAlignedRMSE(Selected,True,maximumLagSamples);
strictPass = selectedVsEst <= CFG.experiment.estimatedFeedbackTolerance_m;
relativePass = selectedVsEst <= CFG.experiment.estimatedFeedbackRelativeTolerance * max(selectedVsTrue,CFG.experiment.estimatedFeedbackTolerance_m);
if ~(strictPass || relativePass)
    error('QuadrotorFramework:ControllerTuningNotEstimatedFeedback',['Controller feedback does not appear to be EST. Selected-vs-EST RMSE = %.6g m, Selected-vs-TRUE RMSE = %.6g m.'],selectedVsEst,selectedVsTrue);
end
end
function bestRMSE = bestAlignedRMSE( ...
    A, ...
    B, ...
    maximumLag)
bestRMSE = ...
    inf;
for lag = -maximumLag:maximumLag
    if lag >= 0
        indexA = ...
            (1+lag):size(A,1);
        indexB = ...
            1:(size(B,1)-lag);
    else
        lagAbs = ...
            abs(lag);
        indexA = ...
            1:(size(A,1)-lagAbs);
        indexB = ...
            (1+lagAbs):size(B,1);
    end
    if numel(indexA) < 5 || ...
            numel(indexB) < 5
        continue;
    end
    D = ...
        A(indexA,:) - ...
        B(indexB,:);
    value = ...
        sqrt( ...
            mean( ...
                sum( ...
                    D.^2, ...
                    2), ...
                'omitnan'));
    if isfinite(value)
        bestRMSE = ...
            min( ...
                bestRMSE, ...
                value);
    end
end
end
function WP = waypointMetrics( ...
    Telemetry, ...
    directionMode)
Phase = ...
    round( ...
        Telemetry(:,2));
PositionTrue = ...
    double( ...
        Telemetry(:,50:52));
[MissionPlan,N] = ...
    decodeMissionPlan( ...
        Telemetry);
arrival = [];
holdRMSE = [];
overshoot = [];
for pointIndex = 2:(N-1)
    movePhase = ...
        2*pointIndex - 3;
    holdPhase = ...
        movePhase + 1;
    moveStart = ...
        find( ...
            Phase == movePhase, ...
            1, ...
            'first');
    holdIndices = ...
        find( ...
            Phase == holdPhase);
    if isempty(moveStart) || ...
            isempty(holdIndices)
        continue;
    end
    holdStart = ...
        holdIndices(1);
    holdEnd = ...
        holdIndices(end);
    target = ...
        MissionPlan(1:3,pointIndex).';
    previous = ...
        MissionPlan(1:3,pointIndex-1).';
    segment = ...
        target - ...
        previous;
    switch lower(directionMode)
        case 'vertical'
            if abs(segment(3)) <= 1e-8
                continue;
            end
            arrivalError = ...
                abs( ...
                    PositionTrue(holdStart,3) - ...
                    target(3));
            holdError = ...
                abs( ...
                    PositionTrue(holdIndices,3) - ...
                    target(3));
            signDirection = ...
                sign(segment(3));
            projected = ...
                ( ...
                PositionTrue(moveStart:holdEnd,3) - ...
                target(3)) .* ...
                signDirection;
        case 'horizontal'
            horizontalSegment = ...
                segment(1:2);
            distance = ...
                norm(horizontalSegment);
            if distance <= 1e-8
                continue;
            end
            arrivalError = ...
                norm( ...
                    PositionTrue(holdStart,1:2) - ...
                    target(1:2));
            holdError = ...
                sqrt( ...
                    sum( ...
                        ( ...
                        PositionTrue(holdIndices,1:2) - ...
                        target(1:2)).^2, ...
                        2));
            directionUnit = ...
                horizontalSegment / ...
                distance;
            projected = ...
                ( ...
                PositionTrue(moveStart:holdEnd,1:2) - ...
                target(1:2)) * ...
                directionUnit.';
        otherwise
            error( ...
                'QuadrotorFramework:ControllerWaypointMetricMode', ...
                'Unknown waypoint metric mode.');
    end
    arrival(end+1,1) = ...
        arrivalError;
    holdRMSE(end+1,1) = ...
        sqrt( ...
            mean( ...
                holdError.^2, ...
                'omitnan'));
    overshoot(end+1,1) = ...
        max( ...
            0, ...
            max( ...
                projected, ...
                [], ...
                'omitnan'));
end
WP = ...
    struct();
if isempty(arrival)
    WP.ArrivalMean = ...
        0;
    WP.HoldRMSEMean = ...
        0;
    WP.OvershootMaximum = ...
        0;
else
    WP.ArrivalMean = ...
        mean( ...
            arrival, ...
            'omitnan');
    WP.HoldRMSEMean = ...
        mean( ...
            holdRMSE, ...
            'omitnan');
    WP.OvershootMaximum = ...
        max( ...
            overshoot, ...
            [], ...
            'omitnan');
end
end
function [MissionPlan,N] = decodeMissionPlan(Telemetry)
telemetryLength = ...
    size( ...
        Telemetry, ...
        2);
if telemetryLength == 58
    N = ...
        7;
    MissionPlan = ...
        zeros( ...
            4, ...
            7);
    sample = ...
        Telemetry(1,:);
    MissionPlan(1,:) = sample(15:21);
    MissionPlan(2,:) = sample(22:28);
    MissionPlan(3,:) = sample(29:35);
    MissionPlan(4,:) = sample(36:42);
    return;
end
if telemetryLength < 71 || ...
        mod(telemetryLength-59,4) ~= 0
    error( ...
        'QuadrotorFramework:ControllerMissionPlanTelemetry', ...
        'Invalid generic telemetry size.');
end
M = ...
    (telemetryLength-59) / ...
    4;
rawN = ...
    Telemetry(:,59);
validN = ...
    isfinite(rawN) & ...
    rawN >= 3 & ...
    rawN <= M & ...
    abs(rawN-round(rawN)) < 1e-9;
index = ...
    find( ...
        validN, ...
        1, ...
        'first');
if isempty(index)
    error( ...
        'QuadrotorFramework:ControllerMissionPlanNumWaypoints', ...
        'Unable to determine NumWaypoints.');
end
N = ...
    round( ...
        rawN(index));
sample = ...
    Telemetry(index,:);
northStart = 60;
eastStart  = 60 + M;
downStart  = 60 + 2*M;
yawStart   = 60 + 3*M;
MissionPlan = ...
    zeros( ...
        4, ...
        N);
MissionPlan(1,:) = ...
    sample( ...
        northStart : ...
        northStart+N-1);
MissionPlan(2,:) = ...
    sample( ...
        eastStart : ...
        eastStart+N-1);
MissionPlan(3,:) = ...
    sample( ...
        downStart : ...
        downStart+N-1);
MissionPlan(4,:) = ...
    sample( ...
        yawStart : ...
        yawStart+N-1);
end
function [J,RESULT] = finalizeCandidate( ...
    CANDIDATE, ...
    RUN, ...
    runSucceeded, ...
    strictRunSucceeded, ...
    metricsAvailable, ...
    softBaselineAccepted, ...
    messages, ...
    baselineMetrics, ...
    CFG, ...
    STAGE, ...
    missionPolicy)
RESULT = emptyCandidateResult();
RESULT.z = CANDIDATE.z;
RESULT.multipliers = CANDIDATE.multipliers;
RESULT.gainValues = CANDIDATE.gainValues;
RESULT.gainTable = CANDIDATE.gainTable;
RESULT.metrics = RUN;
RESULT.runSucceeded = runSucceeded;
RESULT.strictRunSucceeded = strictRunSucceeded;
RESULT.metricsAvailable = metricsAvailable;
RESULT.softBaselineAccepted = softBaselineAccepted;
RESULT.missionPolicy = string(missionPolicy);
RESULT.messages = messages;
RESULT.stageID = STAGE.id;
RESULT.stageName = STAGE.name;
RESULT.plantModels = double(CFG.experiment.plantModels(:));
RESULT.plantWeights = double(CFG.experiment.plantWeights(:));
RESULT.controllerSet = string(CFG.experiment.controllerSet);
RESULT.trajectoryID = double(CFG.experiment.trajectoryID);
RESULT.feedbackSource = string(CFG.experiment.feedbackSource);
RESULT.metricStateSource = string(CFG.experiment.metricStateSource);
if isempty(baselineMetrics)
    RESULT.success = all(runSucceeded(:)) && all(metricsAvailable(:));
    RESULT.strictMissionSuccess = all(strictRunSucceeded(:));
    RESULT.softBaselineUsed = any(softBaselineAccepted(:));
    RESULT.cost = NaN;
    RESULT.runCosts = [];
    J = NaN;
    return;
end
RESULT.strictMissionSuccess = all(strictRunSucceeded(:));
RESULT.softBaselineUsed = any(softBaselineAccepted(:));
if strcmp(missionPolicy,'strict')
    candidateRunsUsable = ...
        all(runSucceeded(:)) && ...
        all(strictRunSucceeded(:)) && ...
        all(metricsAvailable(:));
else
    candidateRunsUsable = ...
        all(runSucceeded(:)) && ...
        all(metricsAvailable(:));
end
if ~candidateRunsUsable
    J = CFG.cost.failurePenalty;
    RESULT.success = false;
    RESULT.cost = J;
    RESULT.runCosts = [];
    return;
end
numberOfPlants = numel(CFG.experiment.plantModels);
if size(RUN,1) ~= numberOfPlants
    error('QuadrotorFramework:ControllerRunPlantCount','Candidate metrics do not match configured plant count.');
end
if isscalar(baselineMetrics) && numel(RUN) > 1
    baselineMetrics = repmat(baselineMetrics,size(RUN));
end
if numel(baselineMetrics) ~= numel(RUN)
    error('QuadrotorFramework:ControllerBaselineMetricCount',['Baseline metric count (%d) does not match candidate run count (%d).'],numel(baselineMetrics),numel(RUN));
end
if ~isequal(size(baselineMetrics),size(RUN))
    baselineMetrics = reshape(baselineMetrics,size(RUN));
end
runCost = zeros(size(RUN));
for runIndex = 1:numel(RUN)
    runCost(runIndex) = stageCost(RUN(runIndex),baselineMetrics(runIndex),CFG,STAGE);
end
softMissionPenalty = ...
    2.0;
if isfield(CFG,'cost') && ...
        isstruct(CFG.cost) && ...
        isfield(CFG.cost,'softMissionPenalty')
    softMissionPenalty = ...
        double( ...
            CFG.cost.softMissionPenalty);
end
if ~isscalar(softMissionPenalty) || ...
        ~isfinite(softMissionPenalty) || ...
        softMissionPenalty < 0
    error( ...
        'QuadrotorFramework:ControllerSoftMissionPenalty', ...
        'CFG.cost.softMissionPenalty must be a finite nonnegative scalar.');
end
if strcmp(missionPolicy,'baseline') && ...
        any(softBaselineAccepted(:))
    runCost = ...
        runCost + ...
        softMissionPenalty * ...
        double(softBaselineAccepted);
end
if any(~isfinite(runCost(:))) || any(runCost(:) >= CFG.cost.failurePenalty)
    J = CFG.cost.failurePenalty;
    RESULT.success = false;
    RESULT.cost = J;
    RESULT.runCosts = runCost;
    return;
end
plantWeights = double(CFG.experiment.plantWeights(:));
seedMeanCost = mean(runCost,2);
switch lower(char(CFG.experiment.plantAggregation))
    case 'weighted_mean'
        J = sum(plantWeights .* seedMeanCost);
    case 'worst_case'
        J = max(seedMeanCost);
    otherwise
        error('QuadrotorFramework:ControllerPlantAggregation','Unknown plant aggregation "%s".',CFG.experiment.plantAggregation);
end
J = J + CFG.cost.parameterRegularizationWeight * mean(CANDIDATE.z.^2);
if ~isfinite(J) || J < 0
    J = CFG.cost.failurePenalty;
end
RESULT.success = J < CFG.cost.failurePenalty;
RESULT.cost = J;
RESULT.runCosts = runCost;
RESULT.plantMeanCosts = seedMeanCost;
end
function J = stageCost( ...
    M, ...
    B, ...
    CFG, ...
    STAGE)
minimum = ...
    CFG.cost.minimumNormalization;
objectiveType = ...
    lower( ...
        char(STAGE.objectiveType));
if strcmp(objectiveType,'joint_roll_pitch')
    rateCost = ...
        trackingMetricCost( ...
            M.RateTrackingRMSE, ...
            M.RateTrackingP95, ...
            M.RateControlEffort, ...
            M.RateControlVariation, ...
            M.RateSaturationFraction, ...
            B.RateTrackingRMSE, ...
            B.RateTrackingP95, ...
            B.RateControlEffort, ...
            B.RateControlVariation, ...
            B.RateSaturationFraction, ...
            CFG.cost.tracking, ...
            minimum);
    attitudeCost = ...
        trackingMetricCost( ...
            M.AttitudeTrackingRMSE, ...
            M.AttitudeTrackingP95, ...
            M.AttitudeControlEffort, ...
            M.AttitudeControlVariation, ...
            M.AttitudeSaturationFraction, ...
            B.AttitudeTrackingRMSE, ...
            B.AttitudeTrackingP95, ...
            B.AttitudeControlEffort, ...
            B.AttitudeControlVariation, ...
            B.AttitudeSaturationFraction, ...
            CFG.cost.tracking, ...
            minimum);
    rateWeight = ...
        0.5;
    attitudeWeight = ...
        0.5;
    if isfield(CFG.cost,'joint') && ...
            isstruct(CFG.cost.joint)
        if isfield(CFG.cost.joint,'rateWeight')
            rateWeight = ...
                double(CFG.cost.joint.rateWeight);
        end
        if isfield(CFG.cost.joint,'attitudeWeight')
            attitudeWeight = ...
                double(CFG.cost.joint.attitudeWeight);
        end
    end
    if ~isscalar(rateWeight) || ...
            ~isscalar(attitudeWeight) || ...
            ~isfinite(rateWeight) || ...
            ~isfinite(attitudeWeight) || ...
            rateWeight < 0 || ...
            attitudeWeight < 0 || ...
            abs(rateWeight+attitudeWeight-1) > 1e-12
        error( ...
            'QuadrotorFramework:ControllerJointObjectiveWeights', ...
            'Joint roll-pitch objective weights must be finite, nonnegative, and sum to one.');
    end
    J = ...
        rateWeight*rateCost + ...
        attitudeWeight*attitudeCost;
elseif ismember( ...
        objectiveType, ...
        { ...
        'rate_pitch', ...
        'rate_roll_pitch', ...
        'rate_yaw', ...
        'attitude_pitch', ...
        'attitude_roll_pitch', ...
        'yaw_angle', ...
        'vertical_velocity', ...
        'horizontal_velocity'})
    J = ...
        trackingMetricCost( ...
            M.TrackingRMSE, ...
            M.TrackingP95, ...
            M.ControlEffort, ...
            M.ControlVariation, ...
            M.SaturationFraction, ...
            B.TrackingRMSE, ...
            B.TrackingP95, ...
            B.ControlEffort, ...
            B.ControlVariation, ...
            B.SaturationFraction, ...
            CFG.cost.tracking, ...
            minimum);
else
    W = ...
        CFG.cost.position;
    J = ...
        W.rmse * ...
        ratioMetric( ...
            M.PositionRMSE, ...
            B.PositionRMSE, ...
            minimum) + ...
        W.p95 * ...
        ratioMetric( ...
            M.PositionP95, ...
            B.PositionP95, ...
            minimum) + ...
        W.maximumError * ...
        ratioMetric( ...
            M.PositionMaximumError, ...
            B.PositionMaximumError, ...
            minimum) + ...
        W.waypointArrival * ...
        ratioMetric( ...
            M.WaypointArrivalMean, ...
            B.WaypointArrivalMean, ...
            minimum) + ...
        W.holdRMSE * ...
        ratioMetric( ...
            M.HoldRMSEMean, ...
            B.HoldRMSEMean, ...
            minimum) + ...
        W.overshoot * ...
        ratioMetric( ...
            M.OvershootMaximum, ...
            B.OvershootMaximum, ...
            minimum) + ...
        W.controlVariation * ...
        ratioMetric( ...
            M.MotorVariationRMS_rad_s2, ...
            B.MotorVariationRMS_rad_s2, ...
            minimum);
end
end
function J = trackingMetricCost( ...
    rmseValue, ...
    p95Value, ...
    effortValue, ...
    variationValue, ...
    saturationValue, ...
    baselineRMSE, ...
    baselineP95, ...
    baselineEffort, ...
    baselineVariation, ...
    baselineSaturation, ...
    W, ...
    minimum)

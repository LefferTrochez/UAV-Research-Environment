        value < 0 || ...
        ~isfinite(baseline) || ...
        baseline < 0
    r = ...
        inf;
    return;
end
if baseline <= minimum && ...
        value <= minimum
    r = ...
        1;
    return;
end
r = ...
    ratioMetric( ...
        value, ...
        baseline, ...
        minimum);
end

function [J, RESULT] = evaluate_controller_candidate( ...
    z, ...
    CFG, ...
    STAGE, ...
    frozenAutopilot, ...
    baselineMetrics, ...
    executionMode, ...
    seedOffsets, ...
    missionPolicy)
narginchk(4,8);
if nargin < 5
    baselineMetrics = ...
        [];
end
if nargin < 6 || ...
        isempty(executionMode)
    executionMode = ...
        'auto';
end
if nargin < 7 || ...
        isempty(seedOffsets)
    seedOffsets = ...
        CFG.experiment.optimizationSeedOffset;
end
if nargin < 8 || ...
        isempty(missionPolicy)
    missionPolicy = ...
        'strict';
end
missionPolicy = ...
    lower( ...
        strtrim( ...
            char( ...
                string(missionPolicy))));
if ~ismember( ...
        missionPolicy, ...
        {'strict','baseline'})
    error( ...
        'QuadrotorFramework:ControllerTuningMissionPolicy', ...
        'missionPolicy must be strict or baseline.');
end
seedOffsets = ...
    double( ...
        seedOffsets(:));
if isempty(seedOffsets) || ...
        any(~isfinite(seedOffsets))
    error( ...
        'QuadrotorFramework:ControllerTuningSeedOffsets', ...
        'seedOffsets must contain finite values.');
end
if numel(unique(seedOffsets)) ~= ...
        numel(seedOffsets)
    error( ...
        'QuadrotorFramework:ControllerTuningDuplicateSeeds', ...
        'seedOffsets must be unique.');
end
validateConfiguration( ...
    CFG, ...
    STAGE, ...
    frozenAutopilot);
numberOfParameters = ...
    STAGE.numberOfParameters;
Z = ...
    normalizeCandidateMatrix( ...
        z, ...
        numberOfParameters);
numberOfCandidates = ...
    size( ...
        Z, ...
        1);
mode = ...
    lower( ...
        strtrim( ...
            char(executionMode)));
if ~ismember( ...
        mode, ...
        {'auto','serial','parallel'})
    error( ...
        'QuadrotorFramework:ControllerTuningExecutionMode', ...
        'executionMode must be auto, serial, or parallel.');
end
parallelEnabled = ...
    false;
if isfield(CFG,'optimizer') && ...
        isfield(CFG.optimizer,'useParallel')
    parallelEnabled = ...
        logical( ...
            CFG.optimizer.useParallel);
end
if strcmp(mode,'auto')
    if parallelEnabled && ...
            numberOfCandidates > 1
        mode = ...
            'parallel';
    else
        mode = ...
            'serial';
    end
end
switch mode
    case 'serial'
        if numberOfCandidates == 1
            [J,RESULT] = ...
                evaluateSingleCandidate( ...
                    Z(1,:).', ...
                    CFG, ...
                    STAGE, ...
                    frozenAutopilot, ...
                    baselineMetrics, ...
                    seedOffsets, ...
                    missionPolicy);
        else
            [J,RESULT] = ...
                evaluateCandidateBatchSerial( ...
                    Z, ...
                    CFG, ...
                    STAGE, ...
                    frozenAutopilot, ...
                    baselineMetrics, ...
                    seedOffsets, ...
                    missionPolicy);
        end
    case 'parallel'
        if ~parallelEnabled
            error( ...
                'QuadrotorFramework:ControllerParallelDisabled', ...
                [ ...
                'Parallel controller evaluation was requested, but ', ...
                'CFG.optimizer.useParallel is false.']);
        end
        [J,RESULT] = ...
            evaluateCandidateBatchParallel( ...
                Z, ...
                CFG, ...
                STAGE, ...
                frozenAutopilot, ...
                baselineMetrics, ...
                seedOffsets, ...
                missionPolicy);
end
end
function validateConfiguration( ...
    CFG, ...
    STAGE, ...
    frozenAutopilot)
if ~isstruct(CFG) || ~isstruct(STAGE) || ~isstruct(frozenAutopilot)
    error('QuadrotorFramework:ControllerTuningConfiguration','CFG, STAGE and frozenAutopilot must be structures.');
end
requiredStageFields = {'id','name','objectiveType','parameterPaths','numberOfParameters','lowerLog10Multiplier','upperLog10Multiplier'};
for k = 1:numel(requiredStageFields)
    if ~isfield(STAGE,requiredStageFields{k})
        error('QuadrotorFramework:ControllerStageConfiguration','Missing STAGE.%s.',requiredStageFields{k});
    end
end
if numel(STAGE.parameterPaths) ~= STAGE.numberOfParameters
    error('QuadrotorFramework:ControllerStageParameterCount','Stage parameter count is inconsistent.');
end
requiredSimulationFields = {'metricSampleRate_Hz';'disablePacing';'useAutomaticProtocolStopTime';'requireMissionCompletion';'requireLanded';'rejectFailsafe'};
for k = 1:numel(requiredSimulationFields)
    if ~isfield(CFG.simulation,requiredSimulationFields{k})
        error('QuadrotorFramework:ControllerSimulationConfiguration','Missing CFG.simulation.%s.',requiredSimulationFields{k});
    end
end
requiredExperimentFields = {'controllerSet';'plantModels';'plantWeights';'disturbancesEnabled';'operatorMode';'trajectoryID';'feedbackSource';'metricStateSource';'requireEstimatedFeedback';'estimatedFeedbackTolerance_m';'estimatedFeedbackRelativeTolerance';'estimatedFeedbackMaximumLag_s'};
for k = 1:numel(requiredExperimentFields)
    if ~isfield(CFG.experiment,requiredExperimentFields{k})
        error('QuadrotorFramework:ControllerExperimentConfiguration','Missing CFG.experiment.%s.',requiredExperimentFields{k});
    end
end
controllerSet = upper(string(CFG.experiment.controllerSet));
if ~ismember(controllerSet,["C1","C2"])
    error('QuadrotorFramework:ControllerSet','CFG.experiment.controllerSet must be C1 or C2.');
end
plantModels = double(CFG.experiment.plantModels(:));
plantWeights = double(CFG.experiment.plantWeights(:));
if isempty(plantModels) || any(~ismember(plantModels,[1 2 3])) || numel(unique(plantModels)) ~= numel(plantModels)
    error('QuadrotorFramework:ControllerPlantModels','CFG.experiment.plantModels must contain unique values from [1 2 3].');
end
if numel(plantWeights) ~= numel(plantModels) || any(~isfinite(plantWeights)) || any(plantWeights < 0) || abs(sum(plantWeights)-1) > 1e-12
    error('QuadrotorFramework:ControllerPlantWeights','CFG.experiment.plantWeights must be finite, nonnegative, match plantModels, and sum to one.');
end
if controllerSet == "C1" && ~isequal(plantModels(:).',[1 2])
    error('QuadrotorFramework:C1PlantModels','C1 tuning must evaluate L1 and L2 jointly.');
end
if controllerSet == "C2" && ~isequal(plantModels(:).',3)
    error('QuadrotorFramework:C2PlantModels','C2 tuning must evaluate L3.');
end
trajectoryID = double(CFG.experiment.trajectoryID);
if ~isscalar(trajectoryID) || ~isfinite(trajectoryID) || trajectoryID ~= round(trajectoryID) || trajectoryID < 1
    error('QuadrotorFramework:ControllerTrajectoryID','CFG.experiment.trajectoryID must be a positive integer.');
end
feedbackSource = upper(string(CFG.experiment.feedbackSource));
if ~ismember(feedbackSource,["TRUE","EST"])
    error('QuadrotorFramework:ControllerFeedbackSource','CFG.experiment.feedbackSource must be TRUE or EST.');
end
metricStateSource = upper(string(CFG.experiment.metricStateSource));
if metricStateSource ~= "TRUE"
    error('QuadrotorFramework:ControllerMetricStateSource','Controller tuning metrics must use TRUE physical states.');
end
if CFG.experiment.requireEstimatedFeedback && feedbackSource ~= "EST"
    error('QuadrotorFramework:ControllerEstimatedFeedbackRequired','requireEstimatedFeedback requires feedbackSource = EST.');
end
if CFG.experiment.estimatedFeedbackTolerance_m < 0 || CFG.experiment.estimatedFeedbackRelativeTolerance < 0 || CFG.experiment.estimatedFeedbackMaximumLag_s < 0
    error('QuadrotorFramework:ControllerFeedbackTolerance','Estimated-feedback verification tolerances must be nonnegative.');
end
controller_tuning_gain_table(frozenAutopilot,STAGE.parameterPaths);
end
function Z = normalizeCandidateMatrix( ...
    z, ...
    numberOfParameters)
z = ...
    double(z);
if isempty(z)
    error( ...
        'QuadrotorFramework:ControllerCandidateEmpty', ...
        'Controller candidate cannot be empty.');
end
if isvector(z)
    if numel(z) ~= ...
            numberOfParameters
        error( ...
            'QuadrotorFramework:ControllerCandidateSize', ...
            'Candidate must contain %d parameters.', ...
            numberOfParameters);
    end
    Z = ...
        reshape( ...
            z, ...
            1, ...
            numberOfParameters);
elseif size(z,2) == ...
        numberOfParameters
    Z = ...
        z;
elseif size(z,1) == ...
        numberOfParameters
    Z = ...
        z.';
else
    error( ...
        'QuadrotorFramework:ControllerCandidateMatrix', ...
        'Candidate matrix must be N-by-%d.', ...
        numberOfParameters);
end
if any(~isfinite(Z),'all')
    error( ...
        'QuadrotorFramework:ControllerCandidateNonfinite', ...
        'Controller candidate matrix contains NaN or Inf.');
end
end
function [J,RESULT] = evaluateSingleCandidate( ...
    z, ...
    CFG, ...
    STAGE, ...
    frozenAutopilot, ...
    baselineMetrics, ...
    seedOffsets, ...
    missionPolicy)
z = double(z(:));
if ~candidateWithinBounds(z,STAGE)
    [J,RESULT] = invalidCandidateResult(z,CFG,STAGE,'Candidate is nonfinite or outside configured bounds.');
    return;
end
try
    CANDIDATE = buildCandidate(z,STAGE,frozenAutopilot);
catch ME
    [J,RESULT] = invalidCandidateResult(z,CFG,STAGE,sprintf('%s: %s',ME.identifier,ME.message));
    return;
end
CONTEXT = getSimulationContext(CFG);
plantModels = double(CFG.experiment.plantModels(:));
numberOfPlants = numel(plantModels);
numberOfSeeds = numel(seedOffsets);
allowSoftBaseline = strcmp(missionPolicy,'baseline');
RUN = repmat(emptyMetricStructure(),numberOfPlants,numberOfSeeds);
runSucceeded = false(numberOfPlants,numberOfSeeds);
strictRunSucceeded = false(numberOfPlants,numberOfSeeds);
metricsAvailable = false(numberOfPlants,numberOfSeeds);
softBaselineAccepted = false(numberOfPlants,numberOfSeeds);
messages = cell(numberOfPlants,numberOfSeeds);
for seedIndex = 1:numberOfSeeds
    for plantIndex = 1:numberOfPlants
        plantModel = plantModels(plantIndex);
        try
            simIn = buildSimulationInput(CANDIDATE.AUTOPILOT,seedOffsets(seedIndex),plantModel,CONTEXT,CFG);
            out = sim(simIn);
            [M,MISSION_STATUS] = extractControllerMetrics(out,CANDIDATE.AUTOPILOT,CFG,STAGE);
            M.SeedOffset = seedOffsets(seedIndex);
            M.PlantModel = plantModel;
            M.success = true;
            RUN(plantIndex,seedIndex) = M;
            metricsAvailable(plantIndex,seedIndex) = true;
            strictRunSucceeded(plantIndex,seedIndex) = MISSION_STATUS.accepted;
            if MISSION_STATUS.accepted
                runSucceeded(plantIndex,seedIndex) = true;
                messages{plantIndex,seedIndex} = 'OK';
            elseif allowSoftBaseline && MISSION_STATUS.softFailure
                runSucceeded(plantIndex,seedIndex) = true;
                softBaselineAccepted(plantIndex,seedIndex) = true;
                messages{plantIndex,seedIndex} = MISSION_STATUS.message;
            else
                runSucceeded(plantIndex,seedIndex) = false;
                messages{plantIndex,seedIndex} = MISSION_STATUS.message;
            end
        catch ME
            runSucceeded(plantIndex,seedIndex) = false;
            strictRunSucceeded(plantIndex,seedIndex) = false;
            metricsAvailable(plantIndex,seedIndex) = false;
            softBaselineAccepted(plantIndex,seedIndex) = false;
            messages{plantIndex,seedIndex} = sprintf('%s: %s',ME.identifier,ME.message);
        end
    end
end
[J,RESULT] = finalizeCandidate(CANDIDATE,RUN,runSucceeded,strictRunSucceeded,metricsAvailable,softBaselineAccepted,messages,baselineMetrics,CFG,STAGE,missionPolicy);
end
function [J,RESULT] = evaluateCandidateBatchSerial( ...
    Z, ...
    CFG, ...
    STAGE, ...
    frozenAutopilot, ...
    baselineMetrics, ...
    seedOffsets, ...
    missionPolicy)
numberOfCandidates = ...
    size( ...
        Z, ...
        1);
J = ...
    CFG.cost.failurePenalty .* ...
    ones( ...
        numberOfCandidates, ...
        1);
RESULT = ...
    repmat( ...
        emptyCandidateResult(), ...
        numberOfCandidates, ...
        1);
for candidateIndex = 1:numberOfCandidates
    [ ...
        J(candidateIndex), ...
        RESULT(candidateIndex)] = ...
        evaluateSingleCandidate( ...
            Z(candidateIndex,:).', ...
            CFG, ...
            STAGE, ...
            frozenAutopilot, ...
            baselineMetrics, ...
            seedOffsets, ...
            missionPolicy);
end
end
function [J,RESULT] = evaluateCandidateBatchParallel( ...
    Z, ...
    CFG, ...
    STAGE, ...
    frozenAutopilot, ...
    baselineMetrics, ...
    seedOffsets, ...
    missionPolicy)
[J,RESULT] = evaluateCandidateBatchSerial(Z,CFG,STAGE,frozenAutopilot,baselineMetrics,seedOffsets,missionPolicy);
end
function CANDIDATE = buildCandidate( ...
    z, ...
    STAGE, ...
    frozenAutopilot)
[baselineTable,~] = ...
    controller_tuning_gain_table( ...
        frozenAutopilot, ...
        STAGE.parameterPaths);
baselineValues = ...
    double( ...
        baselineTable.EffectiveValue);
multipliers = ...
    10 .^ ...
    double(z(:));
candidateValues = ...
    baselineValues .* ...
    multipliers;
[gainTable,AUTOPILOT] = ...
    controller_tuning_gain_table( ...
        frozenAutopilot, ...
        STAGE.parameterPaths, ...
        candidateValues);
CANDIDATE = ...
    struct();
CANDIDATE.z = ...
    double(z(:));
CANDIDATE.multipliers = ...
    multipliers;
CANDIDATE.baselineValues = ...
    baselineValues;
CANDIDATE.gainValues = ...
    candidateValues;
CANDIDATE.gainTable = ...
    gainTable;
CANDIDATE.AUTOPILOT = ...
    AUTOPILOT;
end
function valid = candidateWithinBounds( ...
    z, ...
    STAGE)
z = ...
    double(z(:));
lower = ...
    double( ...
        STAGE.lowerLog10Multiplier(:));
upper = ...
    double( ...
        STAGE.upperLog10Multiplier(:));
valid = ...
    numel(z) == STAGE.numberOfParameters && ...
    numel(lower) == STAGE.numberOfParameters && ...
    numel(upper) == STAGE.numberOfParameters && ...
    all(isfinite(z)) && ...
    all(z >= lower) && ...
    all(z <= upper);
end
function CONTEXT = getSimulationContext(CFG)
requiredVariables = {'P_ENV','SENSOR','ESTIMATOR','AUTO_PROTOCOL','TRAJECTORY_LIBRARY','MAX_WAYPOINTS'};
for k = 1:numel(requiredVariables)
    variableName = requiredVariables{k};
    if ~evalin('base',sprintf('exist(''%s'',''var'')',variableName))
        error('QuadrotorFramework:ControllerTuningMissingWorkspaceVariable',['Missing base-workspace variable %s. Run initialize_project first.'],variableName);
    end
end
CONTEXT = struct();
CONTEXT.modelName = CFG.modelName;
CONTEXT.P_ENV = evalin('base','P_ENV');
CONTEXT.SENSOR = evalin('base','SENSOR');
CONTEXT.ESTIMATOR = evalin('base','ESTIMATOR');
CONTEXT.AUTO_PROTOCOL = evalin('base','AUTO_PROTOCOL');
CONTEXT.TRAJECTORY_LIBRARY = evalin('base','TRAJECTORY_LIBRARY');
CONTEXT.MAX_WAYPOINTS = evalin('base','MAX_WAYPOINTS');
trajectoryID = double(CFG.experiment.trajectoryID);
if trajectoryID < 1 || trajectoryID > numel(CONTEXT.TRAJECTORY_LIBRARY)
    error('QuadrotorFramework:ControllerTuningTrajectoryID','Requested trajectory %d is outside TRAJECTORY_LIBRARY.',trajectoryID);
end
selectedTrajectory = CONTEXT.TRAJECTORY_LIBRARY(trajectoryID);
CONTEXT.TRAJECTORY_ID = uint8(trajectoryID);
CONTEXT.TRAJECTORY_CONFIG = struct();
CONTEXT.TRAJECTORY_CONFIG.numberOfTrajectories = numel(CONTEXT.TRAJECTORY_LIBRARY);
CONTEXT.TRAJECTORY_CONFIG.maxWaypoints = CONTEXT.MAX_WAYPOINTS;
CONTEXT.TRAJECTORY_CONFIG.selectedID = CONTEXT.TRAJECTORY_ID;
CONTEXT.TRAJECTORY_CONFIG.selectedName = selectedTrajectory.name;
CONTEXT.TRAJECTORY_CONFIG.selectedNumWaypoints = selectedTrajectory.numWaypoints;
CONTEXT.TRAJECTORY_CONFIG.numberOfWaypointsPerTrajectory = arrayfun(@(x) double(x.numWaypoints),CONTEXT.TRAJECTORY_LIBRARY);
CONTEXT.TRAJECTORY_CONFIG.selectedPassThroughIntermediate = logical(selectedTrajectory.passThroughIntermediate);
CONTEXT.TRAJECTORY_CONFIG.selectedMissionPlanBuffer = zeros(4,double(CONTEXT.MAX_WAYPOINTS));
CONTEXT.TRAJECTORY_CONFIG.selectedMissionPlanBuffer(:,1:double(selectedTrajectory.numWaypoints)) = selectedTrajectory.missionPlanRelative;
protocolRow = trajectoryID;
CONTEXT.AUTO_PROTOCOL.selected.armTime_s = CONTEXT.AUTO_PROTOCOL.schedule_s(protocolRow,CONTEXT.AUTO_PROTOCOL.column.arm);
CONTEXT.AUTO_PROTOCOL.selected.runTime_s = CONTEXT.AUTO_PROTOCOL.schedule_s(protocolRow,CONTEXT.AUTO_PROTOCOL.column.run);
CONTEXT.AUTO_PROTOCOL.selected.disarmTime_s = CONTEXT.AUTO_PROTOCOL.schedule_s(protocolRow,CONTEXT.AUTO_PROTOCOL.column.disarm);
CONTEXT.AUTO_PROTOCOL.selected.stopTime_s = CONTEXT.AUTO_PROTOCOL.schedule_s(protocolRow,CONTEXT.AUTO_PROTOCOL.column.stop);
CONTEXT.AUTO_PROTOCOL.selected.name = char(selectedTrajectory.name);
if CFG.simulation.useAutomaticProtocolStopTime
    CONTEXT.stopTime_s = double(CONTEXT.AUTO_PROTOCOL.selected.stopTime_s);
else
    CONTEXT.stopTime_s = double(CFG.simulation.stopTime_s);
end
if ~isscalar(CONTEXT.stopTime_s) || ~isfinite(CONTEXT.stopTime_s) || CONTEXT.stopTime_s <= 0
    error('QuadrotorFramework:ControllerTuningStopTimeValue','Controller tuning Stop Time must be finite and positive.');
end
feedbackSource = upper(string(CFG.experiment.feedbackSource));
if feedbackSource == "TRUE"
    CONTEXT.feedbackSwitchSetting = '1';
elseif feedbackSource == "EST"
    CONTEXT.feedbackSwitchSetting = '0';
else
    error('QuadrotorFramework:ControllerFeedbackSource','Unknown feedback source.');
end
CONTEXT.feedbackSwitchPath = [CONTEXT.modelName '/Manual Switch'];
if ~bdIsLoaded(CONTEXT.modelName)
    load_system(CONTEXT.modelName);
end
simulationStatus = get_param(CONTEXT.modelName,'SimulationStatus');
if ~strcmpi(simulationStatus,'stopped')
    error('QuadrotorFramework:ControllerEvaluationModelRunning','Model must be stopped before evaluating a controller candidate.');
end
end
function simIn = buildSimulationInput( ...
    AUTOPILOT, ...
    seedOffset, ...
    plantModel, ...
    CONTEXT, ...
    CFG)
SENSOR = applySensorSeedOffset(CONTEXT.SENSOR,seedOffset);
AUTOPILOT.info.activeController = char(upper(string(CFG.experiment.controllerSet)));
simIn = Simulink.SimulationInput(CONTEXT.modelName);
simIn = simIn.setVariable('P_ENV',CONTEXT.P_ENV);
simIn = simIn.setVariable('SENSOR',SENSOR);
simIn = simIn.setVariable('ESTIMATOR',CONTEXT.ESTIMATOR);
simIn = simIn.setVariable('AUTOPILOT',AUTOPILOT);
simIn = simIn.setVariable('AUTO_PROTOCOL',CONTEXT.AUTO_PROTOCOL);
simIn = simIn.setVariable('TRAJECTORY_ID',CONTEXT.TRAJECTORY_ID);
simIn = simIn.setVariable('TRAJECTORY_CONFIG',CONTEXT.TRAJECTORY_CONFIG);
simIn = simIn.setVariable('MAX_WAYPOINTS',CONTEXT.MAX_WAYPOINTS);
simIn = simIn.setVariable('UAV_MODEL',uint8(plantModel));
simIn = simIn.setVariable('DIST_ENABLE',logical(CFG.experiment.disturbancesEnabled));
simIn = simIn.setVariable('OPERATOR_MODE',uint8(CFG.experiment.operatorMode));
simIn = simIn.setVariable('ESTIMATOR_TUNING_OVERRIDE',[]);
simIn = simIn.setVariable('ESTIMATOR_TUNING_SILENT',true);
simIn = simIn.setVariable('CONTROLLER_TUNING_ACTIVE',true);
simIn = simIn.setBlockParameter(CONTEXT.feedbackSwitchPath,'CurrentSetting',CONTEXT.feedbackSwitchSetting);
simIn = simIn.setModelParameter('StopTime',sprintf('%.15g',CONTEXT.stopTime_s),'ReturnWorkspaceOutputs','on');
if CFG.simulation.disablePacing
    try
        simIn = simIn.setModelParameter('EnablePacing','off');
    catch
    end
end
end
function SENSOR = applySensorSeedOffset( ...
    SENSOR, ...
    seedOffset)
seedOffset = ...
    double(seedOffset);
if ~isscalar(seedOffset) || ...
        ~isfinite(seedOffset)
    error( ...
        'QuadrotorFramework:ControllerTuningSeedOffset', ...
        'Sensor seed offset must be finite.');
end
seedFields = { ...
    {'IMU','seed'}; ...
    {'GPS','seed'}; ...
    {'Barometer','seed'}};
for k = 1:numel(seedFields)
    path = ...
        seedFields{k};
    if isfield(SENSOR,path{1}) && ...
            isfield(SENSOR.(path{1}),path{2})
        SENSOR.(path{1}).(path{2}) = ...
            round( ...
                double( ...
                    SENSOR.(path{1}).(path{2})) + ...
                seedOffset);
    end
end
end
function [M,MISSION_STATUS] = extractControllerMetrics( ...
    out, ...
    AUTOPILOT, ...
    CFG, ...
    STAGE)
availableLogs = ...
    who(out);
requiredLogs = { ...
    'omegaLog', ...
    'controlAxesLog', ...
    'cmdAttitudeLog', ...
    'cmdAngularRateLog', ...
    'cgsLog', ...
    'trueStatesLog', ...
    'liveTelemetryLog'};
for k = 1:numel(requiredLogs)
    if ~ismember( ...
            requiredLogs{k}, ...
            availableLogs)
        error( ...
            'QuadrotorFramework:ControllerTuningMissingLog', ...
            'Missing simulation output out.%s.', ...
            requiredLogs{k});
    end
end
CGS = ...
    out.cgsLog;
TRUE = ...
    out.trueStatesLog;
LIVE = ...
    out.liveTelemetryLog;
[tTelemetry,Telemetry] = ...
    signalMatrix( ...
        LIVE);
MISSION = ...
    evaluateMissionAcceptance( ...
        tTelemetry, ...
        Telemetry);
if CFG.experiment.requireEstimatedFeedback
    verifyEstimatedFeedback(Telemetry,CFG);
end
MISSION_STATUS = ...
    evaluateMissionRequirementStatus( ...
        MISSION, ...
        CFG);
tStart = ...
    MISSION.MissionStartTime_s;
if MISSION.NavigationCompleted && ...
        isfinite(MISSION.NavigationCompleteTime_s)
    tEnd = ...
        MISSION.NavigationCompleteTime_s;
else
    finiteTelemetryTime = ...
        tTelemetry( ...
            isfinite(tTelemetry));
    if isempty(finiteTelemetryTime)
        error( ...
            'QuadrotorFramework:ControllerTuningTelemetryTime', ...
            'No finite telemetry time is available for partial-mission metrics.');
    end
    tEnd = ...
        finiteTelemetryTime(end);
end
if ~isfinite(tStart) || ...
        ~isfinite(tEnd) || ...
        tEnd <= tStart
    error( ...
        'QuadrotorFramework:ControllerTuningMetricWindow', ...
        'No valid mission metric window is available.');
end
[tOmega,Omega] = ...
    signalMatrix( ...
        out.omegaLog);
if size(Omega,2) ~= 4
    error( ...
        'QuadrotorFramework:ControllerTuningOmegaSize', ...
        'omegaLog must contain four motor speeds.');
end
omegaMask = ...
    windowMask( ...
        tOmega, ...
        tStart, ...
        tEnd);
OmegaWindow = ...
    Omega(omegaMask,:);
omegaVariation = ...
    derivativeRMS( ...
        tOmega(omegaMask), ...
        OmegaWindow);
[tRollAxis,rollAxis] = ...
    extractBusField( ...
        out.controlAxesLog, ...
        {'rollAxis'});
[tPitchAxis,pitchAxis] = ...
    extractBusField( ...
        out.controlAxesLog, ...
        {'pitchAxis'});
[tYawAxis,yawAxis] = ...
    extractBusField( ...
        out.controlAxesLog, ...
        {'yawAxis'});
[tThrustAxis,thrustAxis] = ...
    extractBusField( ...
        out.controlAxesLog, ...
        {'thrustAxis'});
rollAxis = ...
    rollAxis(:,1);
pitchAxis = ...
    pitchAxis(:,1);
yawAxis = ...
    yawAxis(:,1);
thrustAxis = ...
    thrustAxis(:,1);
[tCmdAttitude,CmdAttitude] = ...
    signalMatrix( ...
        out.cmdAttitudeLog);
[tEuler,Euler] = extractBusField(TRUE,{'Attitude','Euler'});
if size(CmdAttitude,2) ~= 2 || size(Euler,2) ~= 3
    error('QuadrotorFramework:ControllerTuningAttitudeLogSize','Invalid TRUE attitude log dimensions.');
end
[tCmdRate,CmdRate] = ...
    signalMatrix( ...
        out.cmdAngularRateLog);
[tRate,Rate] = extractBusField(TRUE,{'AngularRate'});
if size(CmdRate,2) ~= 3 || size(Rate,2) ~= 3
    error('QuadrotorFramework:ControllerTuningRateLogSize','Invalid TRUE angular-rate log dimensions.');
end
[tTruePosition,TruePosition] = ...
    extractBusField( ...
        TRUE, ...
        {'Position'});
[tTrueVelocity,TrueVelocity] = ...
    extractBusField( ...
        TRUE, ...
        {'Velocity'});
if size(TruePosition,2) ~= 3 || ...
        size(TrueVelocity,2) ~= 3
    error( ...
        'QuadrotorFramework:ControllerTuningTrueStateSize', ...
        'TRUE Position/Velocity must contain [N E D].');
end
[tPositionRef,PositionRef] = ...
    extractBusField( ...
        CGS, ...
        {'Position_ref'});
[tYawRef,YawRef] = ...
    extractBusField( ...
        CGS, ...
        {'Yaw_ref'});
YawRef = ...
    YawRef(:,1);
if size(PositionRef,2) ~= 3
    error( ...

function [STAGE_RESULT, frozenAutopilotOut] = tune_controller_stage( ...
    CFG, ...
    STAGE, ...
    frozenAutopilotIn, ...
    runFolder)
narginchk(3,4);
if nargin < 4 || ...
        isempty(runFolder)
    runFolder = ...
        fullfile( ...
            pwd, ...
            CFG.output.rootFolder);
end
if ~isstruct(CFG)
    error( ...
        'QuadrotorFramework:ControllerStageInvalidCFG', ...
        'CFG must be a structure.');
end
if ~isstruct(STAGE)
    error( ...
        'QuadrotorFramework:ControllerStageInvalidStage', ...
        'STAGE must be a structure.');
end
if ~isstruct(frozenAutopilotIn)
    error( ...
        'QuadrotorFramework:ControllerStageInvalidAutopilot', ...
        'frozenAutopilotIn must be a structure.');
end
if ~isfield(CFG,'schemaVersion') || double(CFG.schemaVersion) < 3.0
    error('QuadrotorFramework:ControllerStageSchema','Controller tuning requires configuration schema 3.0 or newer.');
end
if ~isfield(CFG,'experiment') || ~isstruct(CFG.experiment)
    error('QuadrotorFramework:ControllerStageExperiment','CFG.experiment is required.');
end
if ~isfield(CFG.experiment,'controllerSet') || ~strcmpi(string(CFG.experiment.controllerSet),"C2")
    error('QuadrotorFramework:ControllerStageControllerSet','This stage tuner is configured for controller set C2.');
end
if ~isfield(CFG.experiment,'plantModels') || ~isequal(double(CFG.experiment.plantModels(:).'),3)
    error('QuadrotorFramework:ControllerStagePlantModels','C2 tuning must evaluate L3 only.');
end
if ~isfield(CFG.experiment,'trajectoryID') || double(CFG.experiment.trajectoryID) ~= 2
    error('QuadrotorFramework:ControllerStageTrajectory','C2 tuning must use trajectory 2.');
end
if ~isfield(CFG.experiment,'feedbackSource') || ~strcmpi(string(CFG.experiment.feedbackSource),"EST")
    error('QuadrotorFramework:ControllerStageFeedback','C2 tuning must use EST controller feedback.');
end
if ~isfield(CFG.experiment,'metricStateSource') || ~strcmpi(string(CFG.experiment.metricStateSource),"TRUE")
    error('QuadrotorFramework:ControllerStageMetricState','Controller performance metrics must use TRUE state.');
end
if ~isfield(frozenAutopilotIn,'info') || ~isstruct(frozenAutopilotIn.info) || ~isfield(frozenAutopilotIn.info,'controllerGainSchema') || string(frozenAutopilotIn.info.controllerGainSchema) ~= "3.0"
    error('QuadrotorFramework:ControllerStageAutopilotSchema','frozenAutopilotIn must use controller gain schema 3.0.');
end
if ~isfield(frozenAutopilotIn.info,'activeController') || ~strcmpi(string(frozenAutopilotIn.info.activeController),"C2")
    error('QuadrotorFramework:ControllerStageActiveController','frozenAutopilotIn must have controller set C2 active.');
end
requestedLowerLog10Multiplier = double(STAGE.lowerLog10Multiplier(:));
requestedUpperLog10Multiplier = double(STAGE.upperLog10Multiplier(:));
[STAGE,SAFETY_BOUNDS] = localApplySafetyBounds(STAGE,CFG);
requiredStageFields = { ...
    'id'; ...
    'name'; ...
    'key'; ...
    'objectiveType'; ...
    'parameterPaths'; ...
    'parameterLabels'; ...
    'numberOfParameters'; ...
    'lowerLog10Multiplier'; ...
    'upperLog10Multiplier'; ...
    'initialPoint'; ...
    'minSurrogatePoints'; ...
    'maxFunctionEvaluations'};
for fieldIndex = 1:numel(requiredStageFields)
    fieldName = ...
        requiredStageFields{fieldIndex};
    if ~isfield(STAGE,fieldName)
        error( ...
            'QuadrotorFramework:ControllerStageMissingField', ...
            'STAGE.%s is required.', ...
            fieldName);
    end
end
numberOfParameters = ...
    double( ...
        STAGE.numberOfParameters);
if ~isscalar(numberOfParameters) || ...
        ~isfinite(numberOfParameters) || ...
        numberOfParameters < 1 || ...
        numberOfParameters ~= floor(numberOfParameters)
    error( ...
        'QuadrotorFramework:ControllerStageParameterCount', ...
        'STAGE.numberOfParameters must be a positive integer.');
end
if numel(STAGE.parameterPaths) ~= ...
        numberOfParameters
    error( ...
        'QuadrotorFramework:ControllerStageParameterPathCount', ...
        ['Stage "%s" declares %d parameters but contains %d ', ...
         'parameter paths.'], ...
        STAGE.name, ...
        numberOfParameters, ...
        numel(STAGE.parameterPaths));
end
if numel(STAGE.parameterLabels) ~= ...
        numberOfParameters
    error( ...
        'QuadrotorFramework:ControllerStageParameterLabelCount', ...
        ['Stage "%s" declares %d parameters but contains %d ', ...
         'parameter labels.'], ...
        STAGE.name, ...
        numberOfParameters, ...
        numel(STAGE.parameterLabels));
end
localValidateFinalLocalStageContract( ...
    STAGE);
if ~isfield(CFG,'policy') || ...
        ~isstruct(CFG.policy)
    error( ...
        'QuadrotorFramework:ControllerStagePolicy', ...
        'CFG.policy is required.');
end
requiredPolicyFields = { ...
    'runParallelPreflightEachStage'; ...
    'validateEachStage'; ...
    'serialBestCheckEachStage'; ...
    'keepBaselineIfNoImprovement'; ...
    'minimumImprovementFraction'};
for fieldIndex = 1:numel(requiredPolicyFields)
    fieldName = ...
        requiredPolicyFields{fieldIndex};
    if ~isfield(CFG.policy,fieldName)
        error( ...
            'QuadrotorFramework:ControllerStageMissingPolicy', ...
            'CFG.policy.%s is required.', ...
            fieldName);
    end
end
if ~isfield(CFG,'optimizer') || ...
        ~isstruct(CFG.optimizer)
    error( ...
        'QuadrotorFramework:ControllerStageOptimizer', ...
        'CFG.optimizer is required.');
end
requiredOptimizerFields = { ...
    'useParallel'; ...
    'batchSize'; ...
    'display'; ...
    'randomSeed'};
for fieldIndex = 1:numel(requiredOptimizerFields)
    fieldName = ...
        requiredOptimizerFields{fieldIndex};
    if ~isfield(CFG.optimizer,fieldName)
        error( ...
            'QuadrotorFramework:ControllerStageMissingOptimizerField', ...
            'CFG.optimizer.%s is required.', ...
            fieldName);
    end
end
try
    initialGainTable = ...
        controller_tuning_gain_table( ...
            frozenAutopilotIn, ...
            STAGE.parameterPaths);
catch ME
    error( ...
        'QuadrotorFramework:ControllerStageGainContract', ...
        ['Stage "%s" is not compatible with the current ', ...
         'controller gain schema.\n\n%s'], ...
        STAGE.name, ...
        ME.message);
end
if ~exist(runFolder,'dir')
    mkdir(runFolder);
end
stageKey = ...
    char( ...
        STAGE.key);
stageFolder = ...
    fullfile( ...
        runFolder, ...
        sprintf( ...
            'Stage_%02d_%s', ...
            STAGE.id, ...
            stageKey));
if ~exist(stageFolder,'dir')
    mkdir(stageFolder);
end
stageResultFile = ...
    fullfile( ...
        stageFolder, ...
        'Stage_Result.mat');
checkpointFile = ...
    fullfile( ...
        stageFolder, ...
        'SurrogateOpt_Checkpoint.mat');
if exist(checkpointFile,'file')
    delete(checkpointFile);
end
fprintf('\n');
fprintf( ...
    '==============================================================\n');
fprintf( ...
    ' CONTROLLER FAST TUNING — STAGE %d/%d\n', ...
    STAGE.id, ...
    CFG.numberOfStages);
fprintf( ...
    '==============================================================\n');
fprintf( ...
    'Stage:                     %s\n', ...
    STAGE.name);
fprintf( ...
    'Controller set:            %s\n', ...
    string(CFG.experiment.controllerSet));
plantModelText = ...
    strjoin( ...
        compose( ...
            "L%d", ...
            double(CFG.experiment.plantModels(:).')), ...
        " + ");
fprintf( ...
    'Plant models:              %s\n', ...
    char(plantModelText));
fprintf( ...
    'Trajectory ID:             %d\n', ...
    CFG.experiment.trajectoryID);
fprintf( ...
    'Feedback:                  %s\n', ...
    string(CFG.experiment.feedbackSource));
fprintf( ...
    'Metric state source:       %s\n', ...
    string(CFG.experiment.metricStateSource));
fprintf( ...
    'Parameters:                %d\n', ...
    numberOfParameters);
fprintf( ...
    'Function evaluations:      %d\n', ...
    STAGE.maxFunctionEvaluations);
fprintf( ...
    'Safety multiplier range:   [%.3f, %.3f]\n', ...
    SAFETY_BOUNDS.minimumMultiplier, ...
    SAFETY_BOUNDS.maximumMultiplier);
fprintf( ...
    'Min surrogate points:      %d\n', ...
    STAGE.minSurrogatePoints);
fprintf( ...
    'Optimization seed offset:  %g\n', ...
    CFG.experiment.optimizationSeedOffset);
fprintf( ...
    'Batch preflight:           %d\n', ...
    CFG.policy.runParallelPreflightEachStage);
fprintf( ...
    'Stage multi-seed validate: %d\n', ...
    CFG.policy.validateEachStage);
fprintf( ...
    'Serial best check:         %d\n', ...
    CFG.policy.serialBestCheckEachStage);
fprintf( ...
    'Baseline feasibility mode: SOFT MISSION FAILURES RECOVERABLE\n');
fprintf( ...
    'Optimizer mission policy:  SOFT-COST / STRICT BEST-CANDIDATE CHECK\n');
fprintf( ...
    '--------------------------------------------------------------\n');
fprintf('\nCurrent frozen gains:\n\n');
disp( ...
    initialGainTable(:, ...
    {'Label','EffectiveValue'}));
z0 = ...
    zeros( ...
        numberOfParameters, ...
        1);
fprintf('\n');
fprintf('Evaluating optimization baseline...\n');
requestedOptimizationSeedOffset = ...
    double( ...
        CFG.experiment.optimizationSeedOffset);
optimizationSeedCandidates = ...
    requestedOptimizationSeedOffset;
stageValidationSeedsConfigured = ...
    localStageSeedOffsets( ...
        CFG);
if ~isempty(stageValidationSeedsConfigured)
    optimizationSeedCandidates = [ ...
        optimizationSeedCandidates; ...
        stageValidationSeedsConfigured(:)];
end
optimizationSeedCandidates = ...
    unique( ...
        optimizationSeedCandidates(:), ...
        'stable');
if any(~isfinite(optimizationSeedCandidates))
    error( ...
        'QuadrotorFramework:ControllerStageOptimizationSeeds', ...
        'Optimization seed candidates must be finite.');
end
BASELINE_OPT = ...
    [];
optimizationSeedOffsetUsed = ...
    NaN;
baselineOptimizationAttempts = ...
    repmat( ...
        struct( ...
            'seedOffset',NaN, ...
            'success',false, ...
            'softFailureOnly',false, ...
            'messages',{{}}), ...
        numel(optimizationSeedCandidates), ...
        1);
for seedCandidateIndex = 1:numel(optimizationSeedCandidates)
    currentSeedOffset = ...
        optimizationSeedCandidates(seedCandidateIndex);
    [~,BASELINE_TRIAL] = ...
        evaluate_controller_candidate( ...
            z0, ...
            CFG, ...
            STAGE, ...
            frozenAutopilotIn, ...
            [], ...
            'serial', ...
            currentSeedOffset, ...
            'baseline');
    baselineOptimizationAttempts(seedCandidateIndex).seedOffset = ...
        currentSeedOffset;
    baselineOptimizationAttempts(seedCandidateIndex).success = ...
        logical(BASELINE_TRIAL.success);
    baselineOptimizationAttempts(seedCandidateIndex).messages = ...
        BASELINE_TRIAL.messages;
    baselineOptimizationAttempts(seedCandidateIndex).softFailureOnly = ...
        localSoftBaselineFailureOnly( ...
            BASELINE_TRIAL);
    if BASELINE_TRIAL.success
        BASELINE_OPT = ...
            BASELINE_TRIAL;
        optimizationSeedOffsetUsed = ...
            currentSeedOffset;
        break;
    end
    fprintf( ...
        '\nOptimization baseline seed %g did not complete the strict mission.\n', ...
        currentSeedOffset);
    displayMessages( ...
        BASELINE_TRIAL.messages);
    if ~localSoftBaselineFailureOnly(BASELINE_TRIAL)
        error( ...
            'QuadrotorFramework:ControllerStageBaselineHardFailure', ...
            ['Optimization baseline failed for stage "%s" because of a ', ...
             'nonrecoverable simulation, logging, configuration, or numerical error.'], ...
            STAGE.name);
    end
end
if isempty(BASELINE_OPT) || ...
        ~isfinite(optimizationSeedOffsetUsed)
    error( ...
        'QuadrotorFramework:ControllerStageNoUsableBaselineSeed', ...
        ['No deterministic seed produced a complete baseline mission for stage "%s". ', ...
         'A finite successful baseline metric is required to normalize the optimizer. ', ...
         'Soft mission failures are recoverable in validation, but the optimization ', ...
         'objective itself requires at least one successful baseline seed.'], ...
        STAGE.name);
end
OPTIMIZATION_CFG = ...
    CFG;
OPTIMIZATION_CFG.experiment.optimizationSeedOffset = ...
    optimizationSeedOffsetUsed;
CFG.experiment.optimizationSeedOffset = ...
    optimizationSeedOffsetUsed;
baselineOptimizationRecoverable = ...
    optimizationSeedOffsetUsed ~= ...
    requestedOptimizationSeedOffset || ...
    ( ...
    isfield(BASELINE_OPT,'softBaselineUsed') && ...
    logical(BASELINE_OPT.softBaselineUsed));
baselineOptimizationUsable = ...
    true;
baselineOptimizationMetrics = ...
    BASELINE_OPT.metrics;
baselineOptimizationCost = ...
    1.0;
fprintf( ...
    'Optimization baseline seed: %g\n', ...
    optimizationSeedOffsetUsed);
if optimizationSeedOffsetUsed ~= requestedOptimizationSeedOffset
    fprintf( ...
        'Baseline seed fallback:    USED (requested %g)\n', ...
        requestedOptimizationSeedOffset);
else
    fprintf( ...
        'Baseline seed fallback:    NOT NEEDED\n');
end
if isfield(BASELINE_OPT,'softBaselineUsed') && ...
        logical(BASELINE_OPT.softBaselineUsed)
    fprintf( ...
        'Baseline mission status:   PARTIAL/SOFT — METRICS USED FOR NORMALIZATION\n');
else
    fprintf( ...
        'Baseline mission status:   STRICT PASS\n');
end
fprintf( ...
    'Baseline normalized cost:  %.6f\n', ...
    baselineOptimizationCost);
fprintf( ...
    'Optimizer seed actually used: %g\n', ...
    optimizationSeedOffsetUsed);
PREFLIGHT = ...
    struct();
PREFLIGHT.performed = ...
    false;
PREFLIGHT.success = ...
    true;
PREFLIGHT.cost = ...
    NaN;
PREFLIGHT.result = ...
    [];
if CFG.policy.runParallelPreflightEachStage
    fprintf('\n');
    fprintf('Running batch-objective preflight...\n');
    [preflightCost,preflightResult] = ...
        evaluate_controller_candidates_parallel( ...
            z0.', ...
            OPTIMIZATION_CFG, ...
            STAGE, ...
            frozenAutopilotIn, ...
            baselineOptimizationMetrics);
    preflightValid = ...
        ~isempty(preflightCost) && ...
        isfinite(preflightCost(1)) && ...
        preflightCost(1) < CFG.cost.failurePenalty && ...
        preflightResult(1).success;
    PREFLIGHT.performed = ...
        true;
    PREFLIGHT.success = ...
        preflightValid;
    PREFLIGHT.cost = ...
        preflightCost(1);
    PREFLIGHT.result = ...
        preflightResult;
    if ~preflightValid
        error( ...
            'QuadrotorFramework:ControllerStageBatchPreflight', ...
            ['Batch objective preflight failed for stage "%s".'], ...
            STAGE.name);
    end
    fprintf( ...
        'Batch preflight cost:      %.6f\n', ...
        preflightCost(1));
    fprintf( ...
        'Batch preflight:           OK\n');
else
    fprintf( ...
        'Batch preflight:           SKIPPED (fast campaign)\n');
end
lowerBounds = ...
    double( ...
        STAGE.lowerLog10Multiplier(:));
upperBounds = ...
    double( ...
        STAGE.upperLog10Multiplier(:));
initialPoint = ...
    double( ...
        STAGE.initialPoint(:).');
if numel(lowerBounds) ~= ...
        numberOfParameters || ...
        numel(upperBounds) ~= ...
        numberOfParameters
    error( ...
        'QuadrotorFramework:ControllerStageOptimizerBounds', ...
        'Stage optimizer bounds have incorrect dimensions.');
end
if numel(initialPoint) ~= ...
        numberOfParameters
    error( ...
        'QuadrotorFramework:ControllerStageInitialPoint', ...
        'Stage initial point has incorrect dimensions.');
end
if any(~isfinite(lowerBounds)) || ...
        any(~isfinite(upperBounds)) || ...
        any(lowerBounds >= upperBounds)
    error( ...
        'QuadrotorFramework:ControllerStageInvalidOptimizerBounds', ...
        'Stage optimizer bounds are invalid.');
end
if any(~isfinite(initialPoint)) || ...
        any(initialPoint(:) < lowerBounds) || ...
        any(initialPoint(:) > upperBounds)
    error( ...
        'QuadrotorFramework:ControllerStageInvalidInitialPoint', ...
        'Stage initial point is outside the configured bounds.');
end
useVectorizedObjective = ...
    logical( ...
        CFG.optimizer.useParallel);
if useVectorizedObjective
    options = ...
        optimoptions( ...
            'surrogateopt', ...
            ...
            'MaxFunctionEvaluations', ...
            STAGE.maxFunctionEvaluations, ...
            ...
            'MinSurrogatePoints', ...
            STAGE.minSurrogatePoints, ...
            ...
            'UseParallel', ...
            false, ...
            ...
            'UseVectorized', ...
            true, ...
            ...
            'BatchUpdateInterval', ...
            CFG.optimizer.batchSize, ...
            ...
            'InitialPoints', ...
            initialPoint, ...
            ...
            'CheckpointFile', ...
            checkpointFile, ...
            ...
            'Display', ...
            CFG.optimizer.display);
    objectiveFunction = ...
        @(Z) controllerObjectiveBatch( ...
            Z, ...
            OPTIMIZATION_CFG, ...
            STAGE, ...
            frozenAutopilotIn, ...
            baselineOptimizationMetrics);
else
    options = ...
        optimoptions( ...
            'surrogateopt', ...
            ...
            'MaxFunctionEvaluations', ...
            STAGE.maxFunctionEvaluations, ...
            ...
            'MinSurrogatePoints', ...
            STAGE.minSurrogatePoints, ...
            ...
            'UseParallel', ...
            false, ...
            ...
            'UseVectorized', ...
            false, ...
            ...
            'InitialPoints', ...
            initialPoint, ...
            ...
            'CheckpointFile', ...
            checkpointFile, ...
            ...
            'Display', ...
            CFG.optimizer.display);
    objectiveFunction = ...
        @(z) controllerObjectiveSerial( ...
            z, ...
            OPTIMIZATION_CFG, ...
            STAGE, ...
            frozenAutopilotIn, ...
            baselineOptimizationMetrics);
end
options.PlotFcn = [];
options.OutputFcn = [];
stageRandomSeed = ...
    double( ...
        CFG.optimizer.randomSeed) + ...
    double( ...
        STAGE.id) - ...
    1;
rng( ...
    stageRandomSeed, ...
    'twister');
fprintf('\n');
if useVectorizedObjective
    fprintf( ...
        'Starting surrogateopt — vectorized batch objective...\n\n');
else
    fprintf( ...
        'Starting surrogateopt — SERIAL objective...\n\n');
end
optimizationStart = ...
    tic;
[ ...
    bestZ, ...
    optimizerCost, ...
    exitFlag, ...
    optimizerOutput, ...
    trials] = ...
    surrogateopt( ...
        objectiveFunction, ...
        lowerBounds, ...
        upperBounds, ...
        options);
optimizationTime_s = ...
    toc( ...
        optimizationStart);
bestZ = ...
    double( ...
        bestZ(:));
optimizerCost = ...
    double( ...
        optimizerCost);
fprintf('\n');
fprintf('Optimization completed.\n');
fprintf( ...
    'Optimizer reported cost:   %.6f\n', ...
    optimizerCost);
fprintf( ...
    'Optimization time:         %.2f min\n', ...
    optimizationTime_s/60);
BEST_SERIAL = ...
    [];
bestSerialCost = ...
    CFG.cost.failurePenalty;
bestSerialValid = ...
    false;
if CFG.policy.serialBestCheckEachStage
    fprintf('\n');
    fprintf('Serially re-evaluating best candidate...\n');
    [bestSerialCost,BEST_SERIAL] = ...
        evaluate_controller_candidate( ...
            bestZ, ...
            OPTIMIZATION_CFG, ...
            STAGE, ...
            frozenAutopilotIn, ...
            baselineOptimizationMetrics, ...
            'serial', ...
            optimizationSeedOffsetUsed, ...
            'strict');
    bestSerialValid = ...
        BEST_SERIAL.success && ...
        isfinite(bestSerialCost) && ...
        bestSerialCost < ...
        CFG.cost.failurePenalty;
else
    error( ...
        'QuadrotorFramework:ControllerSerialBestRequired', ...
        ['serialBestCheckEachStage=false is not supported for the ', ...
         'current scientific tuning workflow.']);
end
if ~bestSerialValid
    fprintf('\n');
    fprintf('Best candidate serial check FAILED.\n');
    displayMessages( ...
        BEST_SERIAL.messages);
end
fprintf( ...
    'Serial best cost:          %.6f\n', ...
    bestSerialCost);
if bestSerialValid
    [bestGainTable,tunedAutopilot] = ...
        controller_tuning_gain_table( ...
            frozenAutopilotIn, ...
            STAGE.parameterPaths, ...
            BEST_SERIAL.gainValues);
else
    bestGainTable = ...
        initialGainTable;
    tunedAutopilot = ...
        frozenAutopilotIn;
end
minimumImprovement = ...
    double( ...
        CFG.policy.minimumImprovementFraction);
if bestSerialValid
    optimizationImprovementFraction = ...
        1 - ...
        bestSerialCost / ...
        baselineOptimizationCost;
else
    optimizationImprovementFraction = ...
        -Inf;
end
optimizationFeasibilityBootstrap = ...
    bestSerialValid && ...
    isfield(BASELINE_OPT,'softBaselineUsed') && ...
    logical(BASELINE_OPT.softBaselineUsed);
optimizationImproved = ...
    bestSerialValid && ...
    ( ...
    optimizationImprovementFraction >= ...
    minimumImprovement || ...
    optimizationFeasibilityBootstrap);
if optimizationFeasibilityBootstrap
    fprintf( ...
        'Optimization decision:      FEASIBILITY BOOTSTRAP ENABLED\n');
end
BASELINE_VALIDATION = ...
    localNotPerformedValidation( ...
        'Stage-level validation disabled by configuration.');
TUNED_VALIDATION = ...
    localNotPerformedValidation( ...
        'Normalized stage validation was not performed.');
TUNED_VALIDATION_FEASIBILITY = ...
    localNotPerformedValidation( ...
        'Strict stage feasibility validation was not performed.');
baselineValidationValid = ...
    NaN;
baselineValidationRecoverable = ...
    false;
baselineValidationUsable = ...
    NaN;
baselineValidationComparableSeeds = ...
    [];
baselineValidationSuccessfulSeeds = ...
    [];
baselineValidationFailedSeeds = ...
    [];
validationComparisonAvailable = ...
    false;
tunedValidationValid = ...
    NaN;
stageValidationFeasibilityPass = ...
    NaN;
stageValidationPass = ...
    true;
validationCost = ...
    NaN;
validationImprovementFraction = ...
    NaN;
validationImproved = ...
    NaN;
stageValidationPerformed = ...
    false;
if CFG.policy.validateEachStage
    stageValidationPerformed = ...
        true;
    validationSeeds = ...
        localValidatedSeedOffsets( ...
            localStageSeedOffsets(CFG), ...
            'stage validation');
    fprintf('\n');
    fprintf( ...
        'Evaluating stage baseline on %d validation seeds...\n', ...
        numel(validationSeeds));
    [~,BASELINE_VALIDATION] = ...
        evaluate_controller_candidate( ...
            z0, ...
            CFG, ...
            STAGE, ...
            frozenAutopilotIn, ...
            [], ...
            'serial', ...
            validationSeeds, ...
            'baseline');
    baselineValidationUsableMask = ...
        localSuccessfulRunMask( ...
            BASELINE_VALIDATION, ...
            numel(validationSeeds));
    baselineValidationMask = ...
        localStrictRunMask( ...
            BASELINE_VALIDATION, ...
            numel(validationSeeds));
    baselineValidationValid = ...
        all(baselineValidationMask);
    baselineValidationSuccessfulSeeds = ...
        validationSeeds(baselineValidationMask);
    baselineValidationFailedSeeds = ...
        validationSeeds(~baselineValidationMask);
    baselineValidationUsable = ...
        any(baselineValidationUsableMask);
    baselineValidationRecoverable = ...
        ~baselineValidationValid && ...
        all(baselineValidationUsableMask);
    if ~baselineValidationValid
        fprintf('\nStage validation baseline messages:\n');
        displayMessages( ...
            BASELINE_VALIDATION.messages);
        if ~baselineValidationRecoverable
            error( ...
                'QuadrotorFramework:ControllerStageValidationBaselineHardFailure', ...
                ['Validation baseline failed for stage "%s" because at least one ', ...
                 'seed did not provide usable metrics.'], ...
                STAGE.name);
        end
        fprintf( ...
            'Stage baseline status:     SOFT MISSION FAILURE(S) — RECOVERABLE\n');
    end
    fprintf( ...
        'Baseline strict seeds:       %d/%d\n', ...
        nnz(baselineValidationMask), ...
        numel(validationSeeds));
    fprintf( ...
        'Baseline usable seeds:       %d/%d\n', ...
        nnz(baselineValidationUsableMask), ...
        numel(validationSeeds));
    validationComparisonAvailable = ...
        any(baselineValidationMask);
    if bestSerialValid && ...
            validationComparisonAvailable
        baselineValidationComparableSeeds = ...
            validationSeeds(baselineValidationMask);
        baselineValidationMetrics = ...
            BASELINE_VALIDATION.metrics(baselineValidationMask);
        fprintf( ...
            'Evaluating tuned candidate on %d comparable validation seeds...\n', ...
            numel(baselineValidationComparableSeeds));
        [validationCost,TUNED_VALIDATION] = ...
            evaluate_controller_candidate( ...
                bestZ, ...
                CFG, ...
                STAGE, ...
                frozenAutopilotIn, ...
                baselineValidationMetrics, ...
                'serial', ...
                baselineValidationComparableSeeds);
        tunedValidationValid = ...
            TUNED_VALIDATION.success && ...
            isfinite(validationCost) && ...
            validationCost < ...
            CFG.cost.failurePenalty;
        if tunedValidationValid
            validationImprovementFraction = ...
                1 - ...
                validationCost;
            validationImproved = ...
                validationImprovementFraction >= ...
                minimumImprovement;
        else
            validationImprovementFraction = ...
                -Inf;
            validationImproved = ...
                false;
        end

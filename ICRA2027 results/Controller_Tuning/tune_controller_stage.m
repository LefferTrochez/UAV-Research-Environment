function localValidateFinalLocalStageContract(STAGE)
stageId = ...
    double(STAGE.id);
objectiveType = ...
    lower( ...
        string(STAGE.objectiveType));
paths = ...
    string(STAGE.parameterPaths(:));
switch stageId
    case 1
        expectedObjective = ...
            "rate_pitch";
        expectedPaths = [ ...
            "angularRate.pitch.Kp"; ...
            "angularRate.pitch.Ki"];
    case 2
        expectedObjective = ...
            "attitude_pitch";
        expectedPaths = ...
            "attitude.pitch.Kp";
    case 3
        expectedObjective = ...
            "joint_roll_pitch";
        expectedPaths = [ ...
            "angularRate.roll.Kp"; ...
            "angularRate.roll.Ki"; ...
            "attitude.roll.Kp"; ...
            "angularRate.pitch.Kp"; ...
            "angularRate.pitch.Ki"; ...
            "attitude.pitch.Kp"];
    otherwise
        error( ...
            'QuadrotorFramework:ControllerStageFinalLocalStageID', ...
            'Final local C2/L3 tuning supports exactly stages 1, 2, and 3.');
end
if objectiveType ~= expectedObjective
    error( ...
        'QuadrotorFramework:ControllerStageObjectiveContract', ...
        'Stage %d must use objectiveType "%s", not "%s".', ...
        stageId, ...
        expectedObjective, ...
        objectiveType);
end
if numel(paths) ~= numel(expectedPaths) || ...
        ~all(paths == expectedPaths)
    error( ...
        'QuadrotorFramework:ControllerStageParameterContract', ...
        'Stage %d parameter paths do not match the final local C2/L3 campaign contract.', ...
        stageId);
end
if numel(unique(paths)) ~= numel(paths)
    error( ...
        'QuadrotorFramework:ControllerStageDuplicateParameter', ...
        'Stage %d contains duplicate gain paths.', ...
        stageId);
end
end

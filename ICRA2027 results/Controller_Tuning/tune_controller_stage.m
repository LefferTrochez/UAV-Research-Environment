        logical( ...
            RESULT.strictRunSucceeded(:));
    if numel(candidateMask) == expectedCount
        mask = ...
            candidateMask;
        return;
    end
end
if isfield(RESULT,'strictMissionSuccess') && ...
        logical(RESULT.strictMissionSuccess)
    mask(:) = ...
        true;
end
end

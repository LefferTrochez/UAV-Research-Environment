    end
end
if ~isscalar(minimumMultiplier) || ...
        ~isscalar(maximumMultiplier) || ...
        ~isfinite(minimumMultiplier) || ...
        ~isfinite(maximumMultiplier) || ...
        minimumMultiplier <= 0 || ...
        maximumMultiplier <= minimumMultiplier
    error( ...
        'QuadrotorFramework:ControllerStageSafetyMultiplierPolicy', ...
        'Configured safety multiplier bounds are invalid.');
end
safeLower = ...
    log10( ...
        minimumMultiplier);
safeUpper = ...
    log10( ...
        maximumMultiplier);
requestedLower = ...
    double( ...
        STAGE.lowerLog10Multiplier(:));
requestedUpper = ...
    double( ...
        STAGE.upperLog10Multiplier(:));
effectiveLower = ...
    max( ...
        requestedLower, ...
        safeLower);
effectiveUpper = ...
    min( ...
        requestedUpper, ...
        safeUpper);
if any(effectiveLower >= effectiveUpper)
    error( ...
        'QuadrotorFramework:ControllerStageSafetyBounds', ...
        'Safety-clipped optimizer bounds are invalid for stage "%s".', ...
        STAGE.name);
end
STAGE.lowerLog10Multiplier = ...
    reshape( ...
        effectiveLower, ...
        size(STAGE.lowerLog10Multiplier));
STAGE.upperLog10Multiplier = ...
    reshape( ...
        effectiveUpper, ...
        size(STAGE.upperLog10Multiplier));
initialPoint = ...
    double( ...
        STAGE.initialPoint(:));
initialPoint = ...
    min( ...
        max( ...
            initialPoint, ...
            effectiveLower), ...
        effectiveUpper);
STAGE.initialPoint = ...
    reshape( ...
        initialPoint, ...
        size(STAGE.initialPoint));
INFO = ...
    struct();
INFO.minimumMultiplier = ...
    minimumMultiplier;
INFO.maximumMultiplier = ...
    maximumMultiplier;
INFO.requestedLowerLog10Multiplier = ...
    requestedLower;
INFO.requestedUpperLog10Multiplier = ...
    requestedUpper;
INFO.effectiveLowerLog10Multiplier = ...
    effectiveLower;
INFO.effectiveUpperLog10Multiplier = ...
    effectiveUpper;
INFO.boundsWereClipped = ...
    any(abs(effectiveLower-requestedLower) > 1e-12) || ...
    any(abs(effectiveUpper-requestedUpper) > 1e-12);
end
function tf = localSoftBaselineFailureOnly(RESULT)
tf = ...
    true;
if ~isstruct(RESULT)
    tf = ...
        false;
    return;
end
if isfield(RESULT,'success') && ...
        logical(RESULT.success)
    return;
end
numberOfMessages = ...
    0;
if isfield(RESULT,'messages') && ...
        ~isempty(RESULT.messages)
    messages = ...
        RESULT.messages;
    if ischar(messages) || ...
            isstring(messages)
        messages = ...
            cellstr( ...
                string(messages));
    end
    if ~iscell(messages)
        tf = ...
            false;
        return;
    end
    failedMask = ...
        [];
    if isfield(RESULT,'runSucceeded') && ...
            ~isempty(RESULT.runSucceeded)
        failedMask = ...
            ~logical( ...
                RESULT.runSucceeded(:));
    end
    for messageIndex = 1:numel(messages)
        if ~isempty(failedMask) && ...
                numel(failedMask) == numel(messages) && ...
                ~failedMask(messageIndex)
            continue;
        end
        currentMessage = ...
            string( ...
                messages{messageIndex});
        if strlength(strtrim(currentMessage)) == 0 || ...
                strcmpi(strtrim(currentMessage),"OK")
            continue;
        end
        numberOfMessages = ...
            numberOfMessages + ...
            1;
        if ~localIsSoftBaselineMessage(currentMessage)
            tf = ...
                false;
            return;
        end
    end
else
    tf = ...
        false;
    return;
end
if numberOfMessages == 0
    tf = ...
        false;
end
end
function tf = localIsSoftBaselineMessage(messageText)
messageText = ...
    string( ...
        messageText);
softPatterns = [ ...
    "QuadrotorFramework:ControllerTuningMissionIncomplete"; ...
    "CGS Complete was not reached"; ...
    "QuadrotorFramework:ControllerTuningNoLanding"; ...
    "Final physical landing was not confirmed"; ...
    "QuadrotorFramework:ControllerTuningFailsafe"; ...
    "Mission entered the generic ABORTED/failsafe phase"; ...
    "QuadrotorFramework:ControllerNoTakeoff"; ...
    "No TAKEOFF phase was detected"; ...
    "QuadrotorFramework:ControllerNoAirborneState"; ...
    "Vehicle never became airborne"];
tf = ...
    false;
for patternIndex = 1:numel(softPatterns)
    if contains( ...
            messageText, ...
            softPatterns(patternIndex), ...
            'IgnoreCase', ...
            true)
        tf = ...
            true;
        return;
    end
end
end
function mask = localSuccessfulRunMask(RESULT,expectedCount)
mask = ...
    false( ...
        expectedCount, ...
        1);
if ~isstruct(RESULT)
    return;
end
if isfield(RESULT,'runSucceeded') && ...
        ~isempty(RESULT.runSucceeded)
    candidateMask = ...
        logical( ...
            RESULT.runSucceeded(:));
    if numel(candidateMask) == expectedCount
        mask = ...
            candidateMask;
        return;
    end
end
if isfield(RESULT,'success') && ...
        logical(RESULT.success)
    mask(:) = ...
        true;
end
end

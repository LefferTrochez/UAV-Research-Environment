    optimizerNonfiniteEvaluationCount;
TUNING_RESULT.FinalTrainingCost = ...
    bestCostCheck;
TUNING_RESULT.OptimizerCostDifference = ...
    costDifference;
TUNING_RESULT.NominalVector = ...
    nominalVector;
TUNING_RESULT.BestLog10Multiplier = ...
    bestZ;
TUNING_RESULT.BestMultiplier = ...
    bestMultipliers;
TUNING_RESULT.BestTunedVector = ...
    bestTunedVector;
TUNING_RESULT.BestOverride = ...
    bestOverride;
TUNING_RESULT.TrainingBaseline = ...
    trainingBaseline;
TUNING_RESULT.BestTraining = ...
    bestTraining;
TUNING_RESULT.ValidationBaseline = ...
    validationBaseline;
TUNING_RESULT.ValidationBaselinePassed = ...
    validationBaselinePassed;
TUNING_RESULT.BestValidation = ...
    bestValidation;

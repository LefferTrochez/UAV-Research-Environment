function printRunMessages( ...
    RESULT, ...
    seedOffsets)
seedOffsets = ...
    double( ...
        seedOffsets(:));
numberOfSeeds = ...
    numel( ...
        seedOffsets);
for seedIndex = ...
        1:numberOfSeeds
    message = ...
        'No result';
    if isfield(RESULT,'messages') && ...
            numel(RESULT.messages) >= seedIndex && ...
            ~isempty(RESULT.messages{seedIndex})
        message = ...
            RESULT.messages{seedIndex};
    end
    fprintf( ...
        '  Seed %g: %s\n', ...
        seedOffsets(seedIndex), ...
        message);
end

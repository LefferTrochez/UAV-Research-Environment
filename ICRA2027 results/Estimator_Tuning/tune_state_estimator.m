    'Velocity RMSE:              %.6f -> %.6f m/s\n', ...
    trainingBaseline.meanMetrics.VelocityRMSE_m_s, ...
    bestTraining.meanMetrics.VelocityRMSE_m_s);
fprintf( ...
    'Attitude RMSE:              %.6f -> %.6f deg\n', ...
    trainingBaseline.meanMetrics.AttitudeRMSE_deg, ...
    bestTraining.meanMetrics.AttitudeRMSE_deg);
fprintf('\nVALIDATION:\n');
if validationPassed
    fprintf( ...
        'Position RMSE:              %.6f -> %.6f m\n', ...
        validationBaseline.meanMetrics.PositionRMSE_m, ...
        bestValidation.meanMetrics.PositionRMSE_m);
    fprintf( ...
        'Horizontal Position RMSE:   %.6f -> %.6f m\n', ...
        validationBaseline.meanMetrics.HorizontalPositionRMSE_m, ...
        bestValidation.meanMetrics.HorizontalPositionRMSE_m);
    fprintf( ...
        'Velocity RMSE:              %.6f -> %.6f m/s\n', ...
        validationBaseline.meanMetrics.VelocityRMSE_m_s, ...
        bestValidation.meanMetrics.VelocityRMSE_m_s);
    fprintf( ...
        'Attitude RMSE:              %.6f -> %.6f deg\n', ...
        validationBaseline.meanMetrics.AttitudeRMSE_deg, ...
        bestValidation.meanMetrics.AttitudeRMSE_deg);
else
    fprintf( ...
        'Independent validation did NOT pass all seeds.\n');
    fprintf( ...
        ['The optimization result was saved anyway so that the ', ...
         'failure can be diagnosed without losing the campaign.\n']);
end
fprintf( ...
    '\nResults:\n%s\n', ...
    runFolder);
fprintf( ...
    '\nIMPORTANT: production estimator was NOT overwritten.\n');
fprintf('==============================================================\n\n');
end

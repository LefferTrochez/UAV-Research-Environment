    sqrt(mean(PositionError.^2,1));
M.VelocityAxisRMSE_m_s = ...
    sqrt(mean(VelocityError.^2,1));
M.EulerAxisRMSE_deg = ...
    sqrt(mean(EulerError_deg.^2,1));
M.AngularRateAxisRMSE_rad_s = ...
    sqrt(mean(AngularRateError.^2,1));
M.AccelerationAxisRMSE_m_s2 = ...
    sqrt(mean(AccelerationError.^2,1));
M.MissionStartTime_s = ...
    missionStartTime;
M.MissionEndTime_s = ...
    missionEndTime;
M.MetricStartTime_s = ...
    metricStart;
M.MetricEndTime_s = ...
    metricEnd;
M.MetricSamples = ...

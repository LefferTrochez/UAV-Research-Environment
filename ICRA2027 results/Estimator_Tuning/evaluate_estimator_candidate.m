        find( ...
            validNumWaypoints, ...
            1, ...
            'first');
    if isempty(firstValidNumWaypoints)
        error( ...
            'QuadrotorFramework:EstimatorTuningInvalidNumWaypoints', ...
            ['Telemetry(59) did not contain a finite integer ', ...
             'NumWaypoints >= 3 after mission start.']);
    end
    missionNumWaypoints = ...
        round( ...
            numWaypointsTrace( ...
                firstValidNumWaypoints));
else
    missionNumWaypoints = 7;
end
completePhase = ...
    2 * missionNumWaypoints - 2;
abortedPhase = ...
    2 * missionNumWaypoints - 1;
postStartIndices = ...
    missionStartIndex:numel(Phase);
relativeAbortIndex = find( ...
    Phase(postStartIndices) == abortedPhase, ...
    1, ...
    'first');
if ~isempty(relativeAbortIndex)
    abortIndex = ...
        postStartIndices(relativeAbortIndex);
    error( ...
        'QuadrotorFramework:EstimatorTuningMissionAborted', ...
        ['Candidate entered generic ABORTED / navigation-failsafe ', ...
         'phase %d at t = %.6f s.'], ...
        abortedPhase, ...
        tTelemetry(abortIndex));
end
landedAfterMissionStart = ...
    Landed(missionStartIndex:end);
firstAirborneRelativeIndex = find( ...
    ~landedAfterMissionStart, ...
    1, ...
    'first');
if isempty(firstAirborneRelativeIndex)
    error( ...
        'QuadrotorFramework:EstimatorTuningNoAirborneState', ...
        ['Candidate never transitioned from Landed=true ', ...

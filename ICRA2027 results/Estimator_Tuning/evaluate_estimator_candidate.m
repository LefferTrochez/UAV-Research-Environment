    AccelerationNorm, ...
    metricTime);
M = emptyMetricStructure();
M.success = true;
M.PositionRMSE_m = ...
    rmsValue(PositionNorm);
M.HorizontalPositionRMSE_m = ...
    sqrt( ...
        mean( ...
            PositionError(:,1).^2 + ...
            PositionError(:,2).^2));
M.VelocityRMSE_m_s = ...
    rmsValue(VelocityNorm);
M.AttitudeRMSE_deg = ...
    rmsValue(AttitudeNorm_deg);
M.AngularRateRMSE_rad_s = ...
    rmsValue(AngularRateNorm);
M.AccelerationRMSE_m_s2 = ...
    rmsValue(AccelerationNorm);

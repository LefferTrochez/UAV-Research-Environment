end
relativeLandingIndex = ...
    landingSearchStart + ...
    landingRisingEdge - 1;
landingIndex = ...
    missionStartIndex + ...
    relativeLandingIndex - 1;
missionIndices = ...
    missionStartIndex:landingIndex;
completionSearchIndices = ...
    firstAirborneIndex:landingIndex;
cgsCompleteRising = ...
    CGSComplete & ...
    ~[ ...
        false; ...
        CGSComplete(1:end-1)];
relativeCompleteIndex = find( ...
    cgsCompleteRising(completionSearchIndices), ...
    1, ...
    'first');
if isempty(relativeCompleteIndex)
    error( ...
        'QuadrotorFramework:EstimatorTuningMissionIncomplete', ...
        ['Candidate landed without reaching a new CGS Complete event ', ...
         'after becoming airborne. Incomplete or failsafe missions ', ...
         'are invalid for estimator tuning.']);
end
navigationCompleteIndex = ...
    completionSearchIndices(relativeCompleteIndex);
navigationCompleteTime = ...
    tTelemetry(navigationCompleteIndex);
completePhaseSeen = any( ...
    Phase(missionIndices) == completePhase);
missionStartTime = ...
    tTelemetry(missionStartIndex);
missionEndTime = ...
    tTelemetry(landingIndex);
readinessTime = ...
    double( ...
        ESTIMATOR.validation.metricStartTime_s);
commonStart = max([ ...
    tPositionError(1), ...
    tVelocityError(1), ...
    tEulerError(1), ...
    tAngularRateError(1), ...
    tAccelerationError(1), ...
    tPositionNorm(1), ...
    tVelocityNorm(1), ...
    tAttitudeNorm(1), ...
    tAngularRateNorm(1), ...
    tAccelerationNorm(1)]);

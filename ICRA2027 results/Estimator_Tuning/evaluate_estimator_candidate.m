end
if size(Telemetry,2) >= 59
    numWaypointsTrace = ...
        double( ...
            Telemetry( ...
                missionStartIndex:end, ...
                59));
    validNumWaypoints = ...
        isfinite(numWaypointsTrace) & ...
        numWaypointsTrace >= 3 & ...
        abs( ...
            numWaypointsTrace - ...
            round(numWaypointsTrace)) <= 1e-9;

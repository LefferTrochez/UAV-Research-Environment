        M.SelectedVsEstRMSE_m, ...
        M.EstFeedbackBestLag_samples] = ...
        bestAlignedRMSE( ...
            selectedMission, ...
            estMission, ...
            maxLagSamples);
    strictTrueMatch = ...
        isfinite(M.SelectedVsTrueRMSE_m) && ...
        M.SelectedVsTrueRMSE_m <= ...
            CFG.simulation.trueFeedbackTolerance_m;
    decisiveTrueMatch = ...
        isfinite(M.SelectedVsTrueRMSE_m) && ...
        isfinite(M.SelectedVsEstRMSE_m) && ...
        M.SelectedVsEstRMSE_m > 0 && ...
        M.SelectedVsTrueRMSE_m <= ...
            0.05 * M.SelectedVsEstRMSE_m;
    M.TrueFeedbackVerified = ...
        strictTrueMatch || ...
        decisiveTrueMatch;
end
if CFG.simulation.requireTrueFeedback && ...
        ~M.TrueFeedbackVerified
    error( ...
        'QuadrotorFramework:EstimatorTuningRequiresTrueFeedback', ...
        [ ...
        'Estimator tuning requires TRUE feedback. ', ...
        'Delay-aware verification failed. ', ...
        'Operational-vs-TRUE RMSE = %.6g m ', ...
        '(zero-lag %.6g m, best lag %.0f samples); ', ...
        'Operational-vs-EST RMSE = %.6g m ', ...
        '(best lag %.0f samples).'], ...
        M.SelectedVsTrueRMSE_m, ...
        M.SelectedVsTrueZeroLagRMSE_m, ...
        M.TrueFeedbackBestLag_samples, ...
        M.SelectedVsEstRMSE_m, ...
        M.EstFeedbackBestLag_samples);
end
end
function [t,x] = signalMatrix(signal)
if isa(signal,'Simulink.SimulationData.Signal')
    signal = signal.Values;
end
if isa(signal,'timeseries')
    t = double(signal.Time(:));
    x = double(signal.Data);
elseif isstruct(signal) && ...
        isfield(signal,'Time') && ...
        isfield(signal,'Data')
    t = double(signal.Time(:));
    x = double(signal.Data);
else
    error( ...
        'QuadrotorFramework:EstimatorTuningSignalType', ...
        'Unsupported logged signal type.');
end
x = squeeze(x);
if isvector(x)
    x = x(:);
elseif size(x,1) ~= numel(t) && ...
        size(x,2) == numel(t)
    x = x.';
end
if size(x,1) ~= numel(t)
    error( ...
        'QuadrotorFramework:EstimatorTuningSignalDimensions', ...
        'Signal data and time dimensions do not agree.');
end
finiteTime = isfinite(t);
t = t(finiteTime);
x = x(finiteTime,:);
if isempty(t)
    error( ...
        'QuadrotorFramework:EstimatorTuningSignalEmpty', ...
        'Logged signal contains no finite timestamps.');
end
[t,uniqueIndex] = unique( ...
    t, ...
    'stable');
x = x(uniqueIndex,:);
if numel(t) < 2
    error( ...
        'QuadrotorFramework:EstimatorTuningSignalSamples', ...
        'Logged signal contains fewer than two unique samples.');
end
end

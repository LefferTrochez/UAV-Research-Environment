M.CompletePhase = ...
    completePhase;
M.CompletePhaseObserved = ...
    completePhaseSeen;
M.AbortedPhase = ...
    abortedPhase;
M.TrueFeedbackVerified = false;
M.SelectedVsTrueRMSE_m = NaN;
M.SelectedVsTrueZeroLagRMSE_m = NaN;
M.SelectedVsEstRMSE_m = NaN;
M.TrueFeedbackBestLag_samples = NaN;
M.EstFeedbackBestLag_samples = NaN;
if size(Telemetry,2) >= 58
    selectedPosition = ...
        double(Telemetry(:,12:14));
    truePosition = ...
        double(Telemetry(:,50:52));
    estPosition = ...
        double(Telemetry(:,56:58));

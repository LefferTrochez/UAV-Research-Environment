end
function valid = candidateWithinBounds( ...
    z, ...
    CFG)
z = double(z(:));
lowerBounds = double(CFG.lowerBounds(:));
upperBounds = double(CFG.upperBounds(:));
valid = ...
    numel(z) == CFG.numberOfParameters && ...
    all(isfinite(z)) && ...
    all(z >= lowerBounds) && ...
    all(z <= upperBounds);
end
function [J,RESULT] = finalizeCandidateEvaluation( ...
    CANDIDATE, ...
    RUN, ...
    runSucceeded, ...
    messages, ...
    baselineMetrics, ...
    CFG)
numberOfSeeds = numel(runSucceeded);
if numel(RUN) ~= numberOfSeeds
    error( ...
        'QuadrotorFramework:EstimatorCandidateMetricCount', ...
        'Candidate metric count does not match seed count.');
end
if isempty(baselineMetrics)
    J = NaN;
    RESULT = emptyCandidateResult();
    RESULT.success = ...
        all(runSucceeded);
    RESULT.cost = NaN;
    RESULT.z = CANDIDATE.z;
    RESULT.multipliers = CANDIDATE.multipliers;
    RESULT.tunedVector = CANDIDATE.tunedVector;
    RESULT.metrics = RUN;
    RESULT.runSucceeded = runSucceeded;
    RESULT.messages = messages;
    RESULT.runCost = NaN(numberOfSeeds,1);
    RESULT.meanMetrics = ...
        meanMetrics(RUN,runSucceeded);
    return;
end
if numel(baselineMetrics) ~= numberOfSeeds
    error( ...
        'QuadrotorFramework:EstimatorBaselineSeedCount', ...
        'Baseline seed count does not match candidate seed count.');
end
runCost = ...
    CFG.cost.failurePenalty * ...
    ones(numberOfSeeds,1);
for seedIndex = 1:numberOfSeeds
    if ~runSucceeded(seedIndex)
        continue;
    end
    B = baselineMetrics(seedIndex);
    M = RUN(seedIndex);
    if ~isfield(B,'success') || ...
            ~B.success
        error( ...
            'QuadrotorFramework:InvalidEstimatorBaseline', ...
            'Nominal estimator baseline contains a failed seed.');
    end
    runCost(seedIndex) = normalizedCost( ...
        M, ...
        B, ...
        CFG);
end
meanCost = mean(runCost);
stdCost = std(runCost);
worstCost = max(runCost);
regularization = ...
    CFG.cost.parameterRegularizationWeight * ...
    mean(CANDIDATE.z.^2);
candidateObjectiveValid = ...
    all(runSucceeded) && ...
    all(isfinite(runCost)) && ...
    all(runCost < CFG.cost.failurePenalty);
if candidateObjectiveValid
    J = ...
        meanCost + ...
        CFG.cost.seedStandardDeviationWeight * stdCost + ...
        CFG.cost.worstSeedWeight * ...
            max( ...
                0, ...
                worstCost - meanCost) + ...
        regularization;
    if ~isfinite(J) || ...
            J < 0 || ...
            J >= CFG.cost.failurePenalty
        J = CFG.cost.failurePenalty;
        candidateObjectiveValid = false;
    end
else
    J = CFG.cost.failurePenalty;
end
RESULT = emptyCandidateResult();
RESULT.success = ...
    candidateObjectiveValid;
RESULT.cost = J;
RESULT.z = CANDIDATE.z;
RESULT.multipliers = CANDIDATE.multipliers;
RESULT.tunedVector = CANDIDATE.tunedVector;
RESULT.metrics = RUN;
RESULT.runSucceeded = runSucceeded;
RESULT.messages = messages;
RESULT.runCost = runCost;
RESULT.meanCost = meanCost;
RESULT.stdCost = stdCost;
RESULT.worstCost = worstCost;
RESULT.regularization = regularization;
RESULT.meanMetrics = ...
    meanMetrics(RUN,runSucceeded);
end
function [J,RESULT] = invalidCandidateResult( ...
    z, ...
    CFG, ...
    nominalVector, ...
    baselineMetrics, ...
    message)
z = double(z(:));
if isempty(baselineMetrics)
    J = NaN;
else
    J = CFG.cost.failurePenalty;
end
RESULT = emptyCandidateResult();
RESULT.success = false;
RESULT.cost = J;
RESULT.z = z;
if numel(z) == CFG.numberOfParameters && ...
        all(isfinite(z))
    RESULT.multipliers = 10.^z;
    RESULT.tunedVector = ...
        nominalVector .* RESULT.multipliers;
end
numberOfSeeds = ...
    numel(CFG.training.seedOffsets);
RESULT.metrics = repmat( ...
    emptyMetricStructure(), ...
    numberOfSeeds, ...
    1);
RESULT.runSucceeded = false(numberOfSeeds,1);
RESULT.messages = repmat( ...
    {message}, ...
    numberOfSeeds, ...
    1);
RESULT.runCost = ...
    CFG.cost.failurePenalty * ...
    ones(numberOfSeeds,1);
RESULT.meanCost = ...
    CFG.cost.failurePenalty;
RESULT.stdCost = 0;
RESULT.worstCost = ...
    CFG.cost.failurePenalty;
RESULT.regularization = NaN;
RESULT.meanMetrics = ...
    meanMetrics( ...
        RESULT.metrics, ...
        RESULT.runSucceeded);
end
function J = normalizedCost(M,B,CFG)
minimumNormalization = ...
    CFG.cost.minimumNormalization;
ratioPosition = ...
    M.PositionRMSE_m / ...
    max( ...
        B.PositionRMSE_m, ...
        minimumNormalization);
ratioHorizontal = ...
    M.HorizontalPositionRMSE_m / ...
    max( ...
        B.HorizontalPositionRMSE_m, ...
        minimumNormalization);
ratioVelocity = ...
    M.VelocityRMSE_m_s / ...
    max( ...
        B.VelocityRMSE_m_s, ...
        minimumNormalization);
ratioAttitude = ...
    M.AttitudeRMSE_deg / ...
    max( ...
        B.AttitudeRMSE_deg, ...
        minimumNormalization);
ratioRate = ...
    M.AngularRateRMSE_rad_s / ...
    max( ...
        B.AngularRateRMSE_rad_s, ...
        minimumNormalization);
ratioAcceleration = ...
    M.AccelerationRMSE_m_s2 / ...
    max( ...
        B.AccelerationRMSE_m_s2, ...
        minimumNormalization);
ratioPositionP95 = ...
    M.PositionP95_m / ...
    max( ...
        B.PositionP95_m, ...
        minimumNormalization);
ratioAttitudeP95 = ...
    M.AttitudeP95_deg / ...
    max( ...
        B.AttitudeP95_deg, ...
        minimumNormalization);
W = CFG.cost.weight;
J = ...
    W.positionRMSE * ratioPosition + ...
    W.horizontalPositionRMSE * ratioHorizontal + ...
    W.velocityRMSE * ratioVelocity + ...
    W.attitudeRMSE * ratioAttitude + ...
    W.angularRateRMSE * ratioRate + ...
    W.accelerationRMSE * ratioAcceleration + ...
    W.positionP95 * ratioPositionP95 + ...
    W.attitudeP95 * ratioAttitudeP95;
if ~isfinite(J) || J < 0
    J = CFG.cost.failurePenalty;
end
end

end
end
function [bestRMSE,bestLag] = ...
    bestAlignedRMSE( ...
        selected, ...
        reference, ...
        maxLagSamples)
selected = double(selected);
reference = double(reference);
bestRMSE = Inf;
bestLag = NaN;
numberOfSamples = min( ...
    size(selected,1), ...
    size(reference,1));
selected = selected( ...
    1:numberOfSamples, ...
    :);
reference = reference( ...
    1:numberOfSamples, ...
    :);
if numberOfSamples < 2
    bestRMSE = NaN;
    return;
end
maxLagSamples = ...
    max( ...
        0, ...
        min( ...
            round(maxLagSamples), ...
            numberOfSamples-2));
for lag = -maxLagSamples:maxLagSamples
    if lag > 0
        selectedAligned = ...
            selected(1+lag:end,:);
        referenceAligned = ...
            reference(1:end-lag,:);
    elseif lag < 0
        shift = -lag;
        selectedAligned = ...
            selected(1:end-shift,:);
        referenceAligned = ...
            reference(1+shift:end,:);
    else
        selectedAligned = selected;
        referenceAligned = reference;
    end
    finiteRows = ...
        all(isfinite(selectedAligned),2) & ...
        all(isfinite(referenceAligned),2);
    if nnz(finiteRows) < 20
        continue;
    end
    difference = ...
        selectedAligned(finiteRows,:) - ...
        referenceAligned(finiteRows,:);
    currentRMSE = ...
        sqrt( ...
            mean( ...
                sum( ...
                    difference.^2, ...
                    2)));
    if isfinite(currentRMSE) && ...
            currentRMSE < bestRMSE
        bestRMSE = currentRMSE;
        bestLag = lag;
    end
end
if ~isfinite(bestRMSE)
    bestRMSE = NaN;
    bestLag = NaN;
end
end
function value = rmsValue(x)
x = double(x(:));
x = x(isfinite(x));
if isempty(x)
    value = NaN;
    return;
end
value = sqrt(mean(x.^2));
end
function value = percentile95(x)
x = double(x(:));
x = x(isfinite(x));
x = sort(x);
if isempty(x)
    value = NaN;
    return;
end
if numel(x) == 1
    value = x(1);
    return;
end
location = ...
    1 + ...
    0.95 * ...
    (numel(x)-1);
lowerIndex = floor(location);
upperIndex = ceil(location);
if lowerIndex == upperIndex
    value = x(lowerIndex);
else
    fraction = ...
        location - lowerIndex;
    value = ...
        (1-fraction) * x(lowerIndex) + ...
        fraction * x(upperIndex);
end
end

    tPositionError(end), ...
    tVelocityError(end), ...
    tEulerError(end), ...
    tAngularRateError(end), ...
    tAccelerationError(end), ...
    tPositionNorm(end), ...
    tVelocityNorm(end), ...
    tAttitudeNorm(end), ...
    tAngularRateNorm(end), ...
    tAccelerationNorm(end)]);
metricStart = max([ ...
    missionStartTime, ...
    readinessTime, ...
    commonStart]);
metricEnd = min( ...
    missionEndTime, ...
    commonEnd);
if metricEnd <= metricStart
    error( ...
        'QuadrotorFramework:EstimatorTuningEmptyWindow', ...
        [ ...
        'Estimator metric window is empty. ', ...
        'MissionStart=%.6f s, MissionEnd=%.6f s, ', ...
        'NavigationComplete=%.6f s, ', ...
        'Readiness=%.6f s, CommonStart=%.6f s, ', ...
        'CommonEnd=%.6f s, MetricStart=%.6f s, ', ...
        'MetricEnd=%.6f s.'], ...
        missionStartTime, ...
        missionEndTime, ...
        navigationCompleteTime, ...
        readinessTime, ...
        commonStart, ...
        commonEnd, ...
        metricStart, ...
        metricEnd);
end
Fs = CFG.simulation.metricSampleRate_Hz;
metricTime = ( ...
    metricStart: ...
    1/Fs: ...
    metricEnd).';
if isempty(metricTime)
    error( ...
        'QuadrotorFramework:EstimatorTuningMetricGrid', ...
        'Estimator metric time grid is empty.');
end
if metricTime(end) < ...
        metricEnd - 0.25/Fs
    metricTime(end+1,1) = metricEnd;
end

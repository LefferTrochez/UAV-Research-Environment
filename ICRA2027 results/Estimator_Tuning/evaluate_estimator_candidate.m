function [J, RESULT] = evaluate_estimator_candidate( ...
    z, ...
    CFG, ...
    nominalVector, ...
    baselineMetrics, ...
    executionMode)
if nargin < 4
    baselineMetrics = [];
end
if nargin < 5 || isempty(executionMode)
    executionMode = 'auto';
end
validateConfigurationContract(CFG);
nominalVector = double(nominalVector(:));
if numel(nominalVector) ~= CFG.numberOfParameters
    error( ...
        'QuadrotorFramework:EstimatorNominalVectorSize', ...
        'Nominal estimator vector must contain exactly 24 parameters.');
end
if any(~isfinite(nominalVector)) || any(nominalVector <= 0)
    error( ...
        'QuadrotorFramework:EstimatorNominalVectorValues', ...
        'Nominal estimator parameters must be finite and positive.');
end
Z = normalizeCandidateMatrix( ...
    z, ...
    CFG.numberOfParameters);
numberOfCandidates = size(Z,1);
mode = lower(strtrim(char(executionMode)));
validModes = { ...
    'auto', ...
    'serial', ...
    'parallel'};
if ~ismember(mode,validModes)
    error( ...
        'QuadrotorFramework:EstimatorCandidateExecutionMode', ...
        'executionMode must be auto, serial, or parallel.');
end
switch mode
    case 'serial'
        if numberOfCandidates ~= 1
            error( ...
                'QuadrotorFramework:EstimatorSerialCandidateCount', ...
                'Serial estimator evaluation accepts exactly one candidate.');
        end
        [J,RESULT] = evaluateSingleCandidate( ...
            Z(1,:).', ...
            CFG, ...
            nominalVector, ...
            baselineMetrics);
    case 'parallel'
        [J,RESULT] = evaluateCandidateBatchParallel( ...
            Z, ...
            CFG, ...
            nominalVector, ...
            baselineMetrics);
    otherwise
        if numberOfCandidates == 1
            [J,RESULT] = evaluateSingleCandidate( ...
                Z(1,:).', ...
                CFG, ...
                nominalVector, ...
                baselineMetrics);
        else
            [J,RESULT] = evaluateCandidateBatchParallel( ...
                Z, ...
                CFG, ...
                nominalVector, ...
                baselineMetrics);
        end
end
end
function validateConfigurationContract(CFG)
requiredTopFields = { ...
    'numberOfParameters', ...
    'parameterNames', ...
    'lowerBounds', ...
    'upperBounds', ...
    'training', ...
    'simulation', ...
    'cost', ...
    'modelName', ...
    'estimatorParameterFile'};
for fieldIndex = 1:numel(requiredTopFields)
    if ~isfield(CFG,requiredTopFields{fieldIndex})
        error( ...
            'QuadrotorFramework:EstimatorTuningConfiguration', ...
            'Missing CFG.%s.', ...
            requiredTopFields{fieldIndex});
    end
end
if CFG.numberOfParameters ~= 24
    error( ...
        'QuadrotorFramework:EstimatorTuningParameterCount', ...
        'Estimator tuning requires exactly 24 parameters.');
end
if numel(CFG.parameterNames) ~= CFG.numberOfParameters
    error( ...
        'QuadrotorFramework:EstimatorTuningParameterNames', ...
        'Estimator parameter-name count does not match configuration.');
end
if numel(unique(CFG.parameterNames)) ~= CFG.numberOfParameters
    error( ...
        'QuadrotorFramework:EstimatorTuningParameterNamesUnique', ...
        'Estimator parameter names must be unique.');
end
lowerBounds = double(CFG.lowerBounds(:));
upperBounds = double(CFG.upperBounds(:));
if numel(lowerBounds) ~= CFG.numberOfParameters || ...
        numel(upperBounds) ~= CFG.numberOfParameters
    error( ...
        'QuadrotorFramework:EstimatorTuningBoundsSize', ...
        'Estimator tuning bounds do not match parameter count.');
end
if any(~isfinite(lowerBounds)) || ...
        any(~isfinite(upperBounds)) || ...
        any(lowerBounds >= upperBounds)
    error( ...
        'QuadrotorFramework:EstimatorTuningBoundsValues', ...
        'Estimator tuning bounds are invalid.');
end
if ~isfield(CFG.training,'seedOffsets') || ...
        isempty(CFG.training.seedOffsets)
    error( ...
        'QuadrotorFramework:EstimatorTuningSeeds', ...
        'At least one estimator tuning seed is required.');
end
seedOffsets = double(CFG.training.seedOffsets(:));
if any(~isfinite(seedOffsets))
    error( ...
        'QuadrotorFramework:EstimatorTuningSeedFinite', ...
        'Estimator seed offsets must be finite.');
end
if numel(unique(seedOffsets)) ~= numel(seedOffsets)
    error( ...
        'QuadrotorFramework:EstimatorTuningSeedUnique', ...
        'Estimator seed offsets must be unique.');
end
if ~isfield(CFG.cost,'failurePenalty') || ...
        ~isscalar(CFG.cost.failurePenalty) || ...
        ~isfinite(CFG.cost.failurePenalty) || ...
        CFG.cost.failurePenalty <= 1
    error( ...
        'QuadrotorFramework:EstimatorTuningFailurePenalty', ...
        'Estimator failure penalty must be finite and greater than one.');
end
if ~isfield(CFG.cost,'minimumNormalization') || ...
        ~isscalar(CFG.cost.minimumNormalization) || ...
        ~isfinite(CFG.cost.minimumNormalization) || ...
        CFG.cost.minimumNormalization <= 0
    error( ...
        'QuadrotorFramework:EstimatorTuningNormalization', ...
        'Minimum normalization must be positive and finite.');
end
end
function Z = normalizeCandidateMatrix( ...
    z, ...
    numberOfParameters)
z = double(z);
if isempty(z)
    error( ...
        'QuadrotorFramework:EstimatorCandidateEmpty', ...
        'Estimator candidate input cannot be empty.');
end
if isvector(z)
    if numel(z) ~= numberOfParameters
        error( ...
            'QuadrotorFramework:EstimatorCandidateSize', ...
            'Candidate must contain exactly %d parameters.', ...
            numberOfParameters);
    end
    Z = reshape(z,1,numberOfParameters);
    return;
end
if size(z,2) == numberOfParameters
    Z = z;
elseif size(z,1) == numberOfParameters && ...
        size(z,2) ~= numberOfParameters
    Z = z.';
else
    error( ...
        'QuadrotorFramework:EstimatorCandidateMatrixSize', ...
        ['Candidate matrix must contain one candidate per row ', ...
         'with exactly %d columns.'], ...
        numberOfParameters);
end
end
function [J,RESULT] = evaluateSingleCandidate( ...
    z, ...
    CFG, ...
    nominalVector, ...
    baselineMetrics)
z = double(z(:));
if ~candidateWithinBounds(z,CFG)
    [J,RESULT] = invalidCandidateResult( ...
        z, ...
        CFG, ...
        nominalVector, ...
        baselineMetrics, ...
        'Candidate is nonfinite or outside configured bounds.');
    return;
end
CONTEXT = getSimulationContext(CFG);
try
    CANDIDATE = buildCandidateDefinition( ...
        z, ...
        CFG, ...
        nominalVector, ...
        CONTEXT);
catch ME
    [J,RESULT] = invalidCandidateResult( ...
        z, ...
        CFG, ...
        nominalVector, ...
        baselineMetrics, ...
        sprintf( ...
            '%s: %s', ...
            ME.identifier, ...
            ME.message));
    return;
end
seedOffsets = double(CFG.training.seedOffsets(:));
numberOfSeeds = numel(seedOffsets);
RUN = repmat( ...
    emptyMetricStructure(), ...
    numberOfSeeds, ...
    1);
runSucceeded = false(numberOfSeeds,1);
messages = cell(numberOfSeeds,1);
for seedIndex = 1:numberOfSeeds
    try
        simIn = buildSimulationInput( ...
            CANDIDATE.ESTIMATOR, ...
            CANDIDATE.override, ...
            seedOffsets(seedIndex), ...
            CONTEXT, ...
            CFG);
        out = sim(simIn);
        if ~isempty(out.ErrorMessage)
            error( ...
                'QuadrotorFramework:EstimatorSimulationError', ...
                '%s', ...
                out.ErrorMessage);
        end
        RUN(seedIndex) = extractMetrics( ...
            out, ...
            CANDIDATE.ESTIMATOR, ...
            CFG);
        RUN(seedIndex).SeedOffset = seedOffsets(seedIndex);
        RUN(seedIndex).success = true;
        runSucceeded(seedIndex) = true;
        messages{seedIndex} = 'OK';
    catch ME
        runSucceeded(seedIndex) = false;
        messages{seedIndex} = sprintf( ...
            '%s: %s', ...
            ME.identifier, ...
            ME.message);
    end
end
[J,RESULT] = finalizeCandidateEvaluation( ...
    CANDIDATE, ...
    RUN, ...
    runSucceeded, ...
    messages, ...
    baselineMetrics, ...
    CFG);
end
function [J,RESULT] = evaluateCandidateBatchParallel( ...
    Z, ...
    CFG, ...
    nominalVector, ...
    baselineMetrics)
if isempty(which('parsim'))
    error( ...
        'QuadrotorFramework:EstimatorParallelParsimMissing', ...
        ['parsim is not available on the MATLAB path. ', ...
         'Simulink is required for parallel estimator optimization.']);
end
if ~license('test','Simulink')
    error( ...
        'QuadrotorFramework:EstimatorParallelSimulinkLicense', ...
        'A valid Simulink license is required for PARSIM.');
end
if ~license('test','Distrib_Computing_Toolbox')
    error( ...
        'QuadrotorFramework:EstimatorParallelToolboxLicense', ...
        ['A valid Parallel Computing Toolbox license is required ', ...
         'for parallel estimator optimization.']);
end
if isempty(which('parpool')) || ...
        isempty(which('gcp'))
    error( ...
        'QuadrotorFramework:EstimatorParallelToolboxMissing', ...
        ['Parallel Computing Toolbox functions parpool/gcp ', ...
         'are not available on the MATLAB path.']);
end
parallelPool = gcp('nocreate');
if ~isempty(parallelPool) && ...
        isa(parallelPool,'parallel.ThreadPool')
    warning( ...
        'QuadrotorFramework:EstimatorParallelThreadPoolRestart', ...
        ['A thread-based parallel pool is active. It will be ', ...
         'replaced by a process-based pool for estimator tuning.']);
    delete(parallelPool);
    parallelPool = [];
end
if isempty(parallelPool)
    try
        parallelPool = parpool('Processes');
    catch ME
        error( ...
            'QuadrotorFramework:EstimatorParallelPoolCreation', ...
            ['Could not create a process-based parallel pool. ', ...
             'Original error: %s'], ...
            ME.message);
    end
end
if isempty(parallelPool) || ...
        ~isvalid(parallelPool) || ...
        parallelPool.NumWorkers < 1
    error( ...
        'QuadrotorFramework:EstimatorParallelWorkers', ...
        'Parallel pool is invalid or contains no workers.');
end
numberOfCandidates = size(Z,1);
seedOffsets = double(CFG.training.seedOffsets(:));
numberOfSeeds = numel(seedOffsets);
J = CFG.cost.failurePenalty * ...
    ones(numberOfCandidates,1);
RESULT = repmat( ...
    emptyCandidateResult(), ...
    numberOfCandidates, ...
    1);
CONTEXT = getSimulationContext(CFG);
if strcmp( ...
        get_param(CONTEXT.modelName,'Dirty'), ...
        'on')
    error( ...
        'QuadrotorFramework:EstimatorParallelUnsavedModel', ...
        ['The model %s has unsaved changes. Save the model before ', ...
         'parallel estimator evaluation.'], ...
        CONTEXT.modelName);
end
candidateValid = false(numberOfCandidates,1);
candidateDefinition = cell(numberOfCandidates,1);
candidateBuildMessage = cell(numberOfCandidates,1);
for candidateIndex = 1:numberOfCandidates
    currentZ = double(Z(candidateIndex,:).');
    if ~candidateWithinBounds(currentZ,CFG)
        candidateBuildMessage{candidateIndex} = ...
            'Candidate is nonfinite or outside configured bounds.';
        [ ...
            J(candidateIndex), ...
            RESULT(candidateIndex)] = ...
            invalidCandidateResult( ...
                currentZ, ...
                CFG, ...
                nominalVector, ...
                baselineMetrics, ...
                candidateBuildMessage{candidateIndex});
        continue;
    end
    try
        candidateDefinition{candidateIndex} = ...
            buildCandidateDefinition( ...
                currentZ, ...
                CFG, ...
                nominalVector, ...
                CONTEXT);
        candidateValid(candidateIndex) = true;
        candidateBuildMessage{candidateIndex} = 'OK';
    catch ME
        candidateBuildMessage{candidateIndex} = sprintf( ...
            '%s: %s', ...
            ME.identifier, ...
            ME.message);
        [ ...
            J(candidateIndex), ...
            RESULT(candidateIndex)] = ...
            invalidCandidateResult( ...
                currentZ, ...
                CFG, ...
                nominalVector, ...
                baselineMetrics, ...
                candidateBuildMessage{candidateIndex});
    end
end
validCandidateIndices = find(candidateValid);
if isempty(validCandidateIndices)
    return;
end
numberOfParallelRuns = ...
    numel(validCandidateIndices) * numberOfSeeds;
simIn(1,numberOfParallelRuns) = ...
    Simulink.SimulationInput(CONTEXT.modelName);
runCandidateIndex = zeros(numberOfParallelRuns,1);
runSeedIndex = zeros(numberOfParallelRuns,1);
runCounter = 0;
for validIndex = 1:numel(validCandidateIndices)
    candidateIndex = validCandidateIndices(validIndex);
    CANDIDATE = candidateDefinition{candidateIndex};
    for seedIndex = 1:numberOfSeeds
        runCounter = runCounter + 1;
        simIn(runCounter) = buildSimulationInput( ...
            CANDIDATE.ESTIMATOR, ...
            CANDIDATE.override, ...
            seedOffsets(seedIndex), ...
            CONTEXT, ...
            CFG);
        runCandidateIndex(runCounter) = candidateIndex;
        runSeedIndex(runCounter) = seedIndex;
    end
end
simOut = executeParallelSimulations( ...
    simIn, ...
    CONTEXT, ...
    CFG);
if numel(simOut) ~= numberOfParallelRuns
    error( ...
        'QuadrotorFramework:EstimatorParallelOutputCount', ...
        ['parsim returned %d outputs for %d requested simulations.'], ...
        numel(simOut), ...
        numberOfParallelRuns);
end
candidateRuns = cell(numberOfCandidates,1);
candidateRunSucceeded = cell(numberOfCandidates,1);
candidateMessages = cell(numberOfCandidates,1);
for validIndex = 1:numel(validCandidateIndices)
    candidateIndex = validCandidateIndices(validIndex);
    candidateRuns{candidateIndex} = repmat( ...
        emptyMetricStructure(), ...
        numberOfSeeds, ...
        1);
    candidateRunSucceeded{candidateIndex} = ...
        false(numberOfSeeds,1);
    candidateMessages{candidateIndex} = ...
        cell(numberOfSeeds,1);
end
for runIndex = 1:numberOfParallelRuns
    candidateIndex = runCandidateIndex(runIndex);
    seedIndex = runSeedIndex(runIndex);
    CANDIDATE = candidateDefinition{candidateIndex};
    out = simOut(runIndex);
    if ~isempty(out.ErrorMessage)
        candidateRunSucceeded{candidateIndex}(seedIndex) = false;
        candidateMessages{candidateIndex}{seedIndex} = ...
            sprintf( ...
                'Simulink:SimulationError: %s', ...
                out.ErrorMessage);
        continue;
    end
    try
        currentMetric = extractMetrics( ...
            out, ...
            CANDIDATE.ESTIMATOR, ...
            CFG);
        currentMetric.SeedOffset = seedOffsets(seedIndex);
        currentMetric.success = true;
        candidateRuns{candidateIndex}(seedIndex) = ...
            currentMetric;
        candidateRunSucceeded{candidateIndex}(seedIndex) = ...
            true;
        candidateMessages{candidateIndex}{seedIndex} = ...
            'OK';
    catch ME
        candidateRunSucceeded{candidateIndex}(seedIndex) = ...
            false;
        candidateMessages{candidateIndex}{seedIndex} = ...
            sprintf( ...
                '%s: %s', ...
                ME.identifier, ...
                ME.message);
    end
end
for validIndex = 1:numel(validCandidateIndices)
    candidateIndex = validCandidateIndices(validIndex);
    [ ...
        J(candidateIndex), ...
        RESULT(candidateIndex)] = ...
        finalizeCandidateEvaluation( ...
            candidateDefinition{candidateIndex}, ...
            candidateRuns{candidateIndex}, ...
            candidateRunSucceeded{candidateIndex}, ...
            candidateMessages{candidateIndex}, ...
            baselineMetrics, ...
            CFG);
end
J = double(J(:));
end
function simOut = executeParallelSimulations( ...
    simIn, ...
    CONTEXT, ...
    CFG)
persistent fastRestartUnsupported
if isempty(fastRestartUnsupported)
    fastRestartUnsupported = false;
end
useFastRestart = false;
if isfield(CFG,'optimizer') && ...
        isfield(CFG.optimizer,'parallelUseFastRestart') && ...
        ~isempty(CFG.optimizer.parallelUseFastRestart)
    useFastRestart = logical( ...
        CFG.optimizer.parallelUseFastRestart);
end
if fastRestartUnsupported
    useFastRestart = false;
end
setupFcn = @() parallelWorkerSetup( ...
    CONTEXT.projectRoot, ...
    CONTEXT.tuningFolder);
commonArguments = { ...
    'ShowProgress', ...
    'off', ...
    ...
    'ShowSimulationManager', ...
    'off', ...
    ...
    'TransferBaseWorkspaceVariables', ...
    'off', ...
    ...
    'ManageDependencies', ...
    'on', ...
    ...
    'StopOnError', ...
    'off', ...
    ...
    'SetupFcn', ...
    setupFcn};
if useFastRestart
    try
        simOut = parsim( ...
            simIn, ...
            commonArguments{:}, ...
            'UseFastRestart', ...
            'on');
        return;
    catch ME
        fastRestartUnsupported = true;
        warning( ...
            'QuadrotorFramework:EstimatorParallelFastRestartDisabled', ...
            [ ...
            'Fast Restart failed during estimator tuning and will ', ...
            'be disabled for subsequent batches.\nReason: %s'], ...
            ME.message);
    end
end
simOut = parsim( ...
    simIn, ...
    commonArguments{:}, ...
    'UseFastRestart', ...
    'off');
end
function parallelWorkerSetup( ...
    projectRoot, ...
    tuningFolder)
if exist(projectRoot,'dir') == 7
    addpath(projectRoot);
end
if exist(tuningFolder,'dir') == 7
    addpath(tuningFolder);
end
try
    cd(projectRoot);
catch
end
rehash;
end
function CONTEXT = getSimulationContext(CFG)
thisFile = mfilename('fullpath');
tuningFolder = fileparts(thisFile);
projectRoot = fileparts(tuningFolder);
requiredVariables = { ...
    'P_ENV', ...
    'SENSOR', ...
    'AUTO_PROTOCOL', ...
    'TRAJECTORY_ID'};
for variableIndex = 1:numel(requiredVariables)
    variableName = requiredVariables{variableIndex};
    if ~evalin( ...
            'base', ...
            sprintf( ...
                'exist(''%s'',''var'')', ...
                variableName))
        error( ...
            'QuadrotorFramework:EstimatorTuningNotInitialized', ...
            'Missing base-workspace variable %s.', ...
            variableName);
    end
end
CONTEXT = struct();
CONTEXT.projectRoot = projectRoot;
CONTEXT.tuningFolder = tuningFolder;
CONTEXT.modelName = CFG.modelName;
CONTEXT.P_ENV = evalin('base','P_ENV');
CONTEXT.SENSOR = evalin('base','SENSOR');
CONTEXT.AUTO_PROTOCOL = evalin('base','AUTO_PROTOCOL');
CONTEXT.TRAJECTORY_ID = evalin('base','TRAJECTORY_ID');
if ~isempty(CFG.training.trajectoryID)
    CONTEXT.TRAJECTORY_ID = ...
        uint8(CFG.training.trajectoryID);
end
CONTEXT.modelFile = fullfile( ...
    projectRoot, ...
    [CFG.modelName '.slx']);
if ~isfile(CONTEXT.modelFile)
    error( ...
        'QuadrotorFramework:EstimatorTuningModelMissing', ...
        'Could not find model file %s.', ...
        CONTEXT.modelFile);
end
if ~bdIsLoaded(CFG.modelName)
    load_system(CONTEXT.modelFile);
end
if ~strcmp( ...
        get_param(CFG.modelName,'SimulationStatus'), ...
        'stopped')
    error( ...
        'QuadrotorFramework:EstimatorTuningModelRunning', ...
        'Stop the Simulink model before estimator tuning.');
end
if ~isempty(CFG.simulation.stopTime_s)
    CONTEXT.stopTime_s = ...
        double(CFG.simulation.stopTime_s);
elseif CFG.simulation.useAutomaticProtocolStopTime
    trajectoryRow = ...
        double(CONTEXT.TRAJECTORY_ID);
    stopColumn = ...
        double(CONTEXT.AUTO_PROTOCOL.column.stop);
    CONTEXT.stopTime_s = ...
        double( ...
            CONTEXT.AUTO_PROTOCOL.schedule_s( ...
                trajectoryRow, ...
                stopColumn));
else
    CONTEXT.stopTime_s = ...
        str2double( ...
            get_param( ...
                CFG.modelName, ...
                'StopTime'));
end
if ~isscalar(CONTEXT.stopTime_s) || ...
        ~isfinite(CONTEXT.stopTime_s) || ...
        CONTEXT.stopTime_s <= 0
    error( ...
        'QuadrotorFramework:EstimatorTuningStopTime', ...
        'Estimator tuning simulation Stop Time is invalid.');
end
end
function CANDIDATE = buildCandidateDefinition( ...
    z, ...
    CFG, ...
    nominalVector, ...
    CONTEXT)
z = double(z(:));
multipliers = 10.^z;
tunedVector = nominalVector .* multipliers;
if any(~isfinite(multipliers)) || ...
        any(multipliers <= 0) || ...
        any(~isfinite(tunedVector)) || ...
        any(tunedVector <= 0)
    error( ...
        'QuadrotorFramework:EstimatorCandidateValues', ...
        'Candidate estimator parameters are invalid.');
end
override = struct();
for parameterIndex = 1:CFG.numberOfParameters
    parameterName = CFG.parameterNames{parameterIndex};
    override.(parameterName) = tunedVector(parameterIndex);
end
ESTIMATOR = buildCandidateEstimator( ...
    override, ...
    tunedVector, ...
    CONTEXT, ...
    CFG);
CANDIDATE = struct();
CANDIDATE.z = z;
CANDIDATE.multipliers = multipliers;
CANDIDATE.tunedVector = tunedVector;
CANDIDATE.override = override;
CANDIDATE.ESTIMATOR = ESTIMATOR;
end
function ESTIMATOR = buildCandidateEstimator( ...
    override, ...
    requestedVector, ...
    CONTEXT, ...
    CFG)
P_ENV = CONTEXT.P_ENV; %#ok<NASGU>
SENSOR = CONTEXT.SENSOR; %#ok<NASGU>
ESTIMATOR_TUNING_OVERRIDE = override; %#ok<NASGU>
ESTIMATOR_TUNING_SILENT = true; %#ok<NASGU>
estimatorFile = fullfile( ...
    CONTEXT.projectRoot, ...
    CFG.estimatorParameterFile);
if ~isfile(estimatorFile)
    error( ...
        'QuadrotorFramework:MissingEstimatorParameterFile', ...
        'Could not find %s.', ...
        estimatorFile);
end
run(estimatorFile);
if ~exist('ESTIMATOR','var') || ...
        ~isstruct(ESTIMATOR)
    error( ...
        'QuadrotorFramework:EstimatorCandidateBuild', ...
        'Candidate ESTIMATOR could not be constructed.');
end
if ~isfield(ESTIMATOR,'tuning') || ...
        ~isstruct(ESTIMATOR.tuning) || ...
        ~isfield(ESTIMATOR.tuning,'vector')
    error( ...
        'QuadrotorFramework:EstimatorCandidateVectorMissing', ...
        'Candidate ESTIMATOR does not contain ESTIMATOR.tuning.vector.');
end
candidateVectorBuilt = ...
    double(ESTIMATOR.tuning.vector(:));
requestedVector = ...
    double(requestedVector(:));
if numel(candidateVectorBuilt) ~= CFG.numberOfParameters
    error( ...
        'QuadrotorFramework:EstimatorCandidateBuiltVectorSize', ...
        'Built estimator tuning vector has incorrect dimension.');
end
absoluteError = abs( ...
    candidateVectorBuilt - requestedVector);
allowedError = ...
    1e-12 .* ...
    max( ...
        1.0, ...
        abs(requestedVector));
if any(~isfinite(candidateVectorBuilt)) || ...
        any(absoluteError > allowedError)
    error( ...
        'QuadrotorFramework:EstimatorCandidateOverrideFailed', ...
        ['UAV_state_estimator.m did not construct the exact ', ...
         'requested tuning vector.']);
end
end
function simIn = buildSimulationInput( ...
    ESTIMATOR, ...
    override, ...
    seedOffset, ...
    CONTEXT, ...
    CFG)
SENSOR = applySensorSeedOffset( ...
    CONTEXT.SENSOR, ...
    seedOffset);
simIn = ...
    Simulink.SimulationInput(CONTEXT.modelName);
simIn = simIn.setVariable( ...
    'P_ENV', ...
    CONTEXT.P_ENV);
simIn = simIn.setVariable( ...
    'SENSOR', ...
    SENSOR);
simIn = simIn.setVariable( ...
    'ESTIMATOR', ...
    ESTIMATOR);
simIn = simIn.setVariable( ...
    'AUTO_PROTOCOL', ...
    CONTEXT.AUTO_PROTOCOL);
simIn = simIn.setVariable( ...
    'TRAJECTORY_ID', ...
    uint8(CONTEXT.TRAJECTORY_ID));
simIn = simIn.setVariable( ...
    'UAV_MODEL', ...
    CFG.training.uavModel);
simIn = simIn.setVariable( ...
    'DIST_ENABLE', ...
    logical(CFG.training.disturbancesEnabled));
simIn = simIn.setVariable( ...
    'OPERATOR_MODE', ...
    uint8(CFG.training.operatorMode));
simIn = simIn.setVariable( ...
    'ESTIMATOR_TUNING_OVERRIDE', ...
    override);
simIn = simIn.setVariable( ...
    'ESTIMATOR_TUNING_SILENT', ...
    true);
simIn = simIn.setModelParameter( ...
    'StopTime', ...
    sprintf( ...
        '%.15g', ...
        CONTEXT.stopTime_s), ...
    ...
    'ReturnWorkspaceOutputs', ...
    'on');
if CFG.simulation.disablePacing
    try
        simIn = simIn.setModelParameter( ...
            'EnablePacing', ...
            'off');
    catch
    end
end
end
function SENSOR = applySensorSeedOffset( ...
    SENSOR, ...
    seedOffset)
seedOffset = double(seedOffset);
if ~isscalar(seedOffset) || ...
        ~isfinite(seedOffset)
    error( ...
        'QuadrotorFramework:EstimatorTuningSeedOffset', ...
        'Sensor seed offset must be a finite scalar.');
end
SENSOR.IMU.seed = round( ...
    double(SENSOR.IMU.seed) + seedOffset);
SENSOR.GPS.seed = round( ...
    double(SENSOR.GPS.seed) + seedOffset);
SENSOR.Barometer.seed = round( ...
    double(SENSOR.Barometer.seed) + seedOffset);
seedValues = [ ...
    SENSOR.IMU.seed, ...
    SENSOR.GPS.seed, ...
    SENSOR.Barometer.seed];
if any(~isfinite(seedValues)) || ...
        any(seedValues < 0)

end
Phase = ...
    round(double(Telemetry(:,2)));
CGSComplete = ...
    double(Telemetry(:,4)) > 0.5;
Landed = ...
    double(Telemetry(:,8)) > 0.5;
previousPhase = [ ...
    NaN; ...
    Phase(1:end-1)];
missionStartIndex = find( ...
    Phase == 1 & ...
    previousPhase ~= 1, ...
    1, ...
    'first');
if isempty(missionStartIndex)
    error( ...
        'QuadrotorFramework:EstimatorTuningNoMission', ...

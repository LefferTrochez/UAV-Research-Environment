    landedAfterMissionStart(landingSearchStart:end) & ...
    ~landedAfterMissionStart(landingSearchStart-1:end-1), ...
    1, ...
    'first');
if isempty(landingRisingEdge)
    error( ...
        'QuadrotorFramework:EstimatorTuningNoLanding', ...
        ['Candidate became airborne but did not produce a ', ...

[tAngularRateNorm,AngularRateNorm] = ...
    signalMatrix(NORMS.AngularRateErrorNorm);
[tAccelerationNorm,AccelerationNorm] = ...
    signalMatrix(NORMS.AccelerationErrorNorm);

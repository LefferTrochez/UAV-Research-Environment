    'REAL_DATA', ...
    'REAL_FLIGHT_INSPECTION', ...
    'REAL_FIGURES_FOLDER', ...
    'REAL_TABLES_FOLDER', ...
    'REAL_EXPERIMENT_DATA_FILE', ...
    'REAL_DATA_AVAILABILITY'};

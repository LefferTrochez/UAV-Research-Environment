    if ~exist(requiredVariables{k},'var')
        error( ...
            'RealFlight:MissingRequiredVariable', ...
            ['Required variable "%s" was not found.\n\n', ...
             'Run the previous real-flight scripts first.'], ...
            requiredVariables{k});
    end
end
attitudeAvailable = ...
    isfield(REAL_DATA,'State') && ...
    isfield(REAL_DATA.State,'Attitude') && ...
    ~isempty(REAL_DATA.State.Attitude);
navigationControllerAvailable = ...
    isfield(REAL_DATA,'Navigation') && ...
    isfield(REAL_DATA.Navigation,'Controller') && ...
    ~isempty(REAL_DATA.Navigation.Controller);
if ~attitudeAvailable
    error( ...
        'RealFlight:AttitudeUnavailable', ...
        'ATTITUDE telemetry is unavailable.');
end
attitudeCommandAvailable = ...
    navigationControllerAvailable;
if attitudeCommandAvailable
    attitudeCommandAvailabilityReason = ...
        "AVAILABLE";
else
    attitudeCommandAvailabilityReason = ...
        "NAV_CONTROLLER_OUTPUT_NOT_PRESENT";
end
trackingStart_s = ...
    REAL_FLIGHT_INSPECTION.CoreStartTime_s;
trackingEnd_s = ...
    REAL_FLIGHT_INSPECTION.CoreEndTime_s;
trackingWindowSource = ...
    "PRIMARY_ATTEMPT_WINDOW";
if ~isfinite(trackingStart_s) || ...
        ~isfinite(trackingEnd_s) || ...
        trackingEnd_s <= trackingStart_s
    error( ...
        'RealFlight:InvalidAttitudeTrackingWindow', ...
        ['The primary attitude tracking window is invalid. ', ...
         'Check REAL_FLIGHT_INSPECTION.CoreStartTime_s/CoreEndTime_s.']);
end
trackingDuration_s = ...
    trackingEnd_s - ...
    trackingStart_s;
ATT = ...
    REAL_DATA.State.Attitude;
attitudeMask = ...
    ATT.Time_s >= trackingStart_s & ...
    ATT.Time_s <= trackingEnd_s;
if nnz(attitudeMask) < 2
    error( ...
        'RealFlight:InsufficientAttitudeSamples', ...
        'Insufficient ATTITUDE samples exist in the tracking window.');
end
tAttitudeAbsolute = ...
    double( ...
        ATT.Time_s(attitudeMask));
Roll_deg = ...
    rad2deg( ...
        double( ...
            ATT.Roll_rad(attitudeMask)));
Pitch_deg = ...
    rad2deg( ...
        double( ...
            ATT.Pitch_rad(attitudeMask)));
Yaw_deg = ...
    rad2deg( ...
        double( ...
            ATT.Yaw_rad(attitudeMask)));
[tAttitudeAbsolute,order] = ...
    sort(tAttitudeAbsolute);
Roll_deg = ...
    Roll_deg(order);
Pitch_deg = ...
    Pitch_deg(order);
Yaw_deg = ...
    Yaw_deg(order);
[tAttitudeAbsolute,uniqueIndex] = ...
    unique( ...
        tAttitudeAbsolute, ...
        'stable');
Roll_deg = ...
    Roll_deg(uniqueIndex);
Pitch_deg = ...
    Pitch_deg(uniqueIndex);
Yaw_deg = ...
    Yaw_deg(uniqueIndex);
if attitudeCommandAvailable
    NAV = ...
        REAL_DATA.Navigation.Controller;
    commandMask = ...
        NAV.Time_s >= trackingStart_s & ...
        NAV.Time_s <= trackingEnd_s;
    if nnz(commandMask) >= 2
        tCommandAbsolute = ...
            double( ...
                NAV.Time_s(commandMask));
        RollCommand_deg = ...
            rad2deg( ...
                double( ...
                    NAV.NavRollCommand_rad(commandMask)));
        PitchCommand_deg = ...
            rad2deg( ...
                double( ...
                    NAV.NavPitchCommand_rad(commandMask)));
        [tCommandAbsolute,order] = ...
            sort(tCommandAbsolute);
        RollCommand_deg = ...
            RollCommand_deg(order);
        PitchCommand_deg = ...
            PitchCommand_deg(order);
        [tCommandAbsolute,uniqueIndex] = ...
            unique( ...
                tCommandAbsolute, ...
                'stable');
        RollCommand_deg = ...
            RollCommand_deg(uniqueIndex);
        PitchCommand_deg = ...
            PitchCommand_deg(uniqueIndex);
        commonStart_s = ...
            max( ...
                tCommandAbsolute(1), ...
                tAttitudeAbsolute(1));
        commonEnd_s = ...
            min( ...
                tCommandAbsolute(end), ...
                tAttitudeAbsolute(end));
        validCommandTime = ...
            tCommandAbsolute >= commonStart_s & ...
            tCommandAbsolute <= commonEnd_s;
        tMetricAbsolute = ...
            tCommandAbsolute(validCommandTime);
        RollCommandMetric_deg = ...
            RollCommand_deg(validCommandTime);
        PitchCommandMetric_deg = ...
            PitchCommand_deg(validCommandTime);
        if numel(tMetricAbsolute) >= 2
            RollMeasuredMetric_deg = ...
                interp1( ...
                    tAttitudeAbsolute, ...
                    Roll_deg, ...
                    tMetricAbsolute, ...
                    'linear');
            PitchMeasuredMetric_deg = ...
                interp1( ...
                    tAttitudeAbsolute, ...
                    Pitch_deg, ...
                    tMetricAbsolute, ...
                    'linear');
            validMetricRows = ...
                isfinite(tMetricAbsolute) & ...
                isfinite(RollCommandMetric_deg) & ...
                isfinite(PitchCommandMetric_deg) & ...
                isfinite(RollMeasuredMetric_deg) & ...
                isfinite(PitchMeasuredMetric_deg);
            tMetricAbsolute = ...
                tMetricAbsolute(validMetricRows);
            RollCommandMetric_deg = ...
                RollCommandMetric_deg(validMetricRows);
            PitchCommandMetric_deg = ...
                PitchCommandMetric_deg(validMetricRows);
            RollMeasuredMetric_deg = ...
                RollMeasuredMetric_deg(validMetricRows);
            PitchMeasuredMetric_deg = ...
                PitchMeasuredMetric_deg(validMetricRows);
        end
    else
        attitudeCommandAvailable = ...
            false;
        attitudeCommandAvailabilityReason = ...
            "INSUFFICIENT_NAV_CONTROLLER_OUTPUT_SAMPLES";
    end
end
if attitudeCommandAvailable
    if ~exist('tMetricAbsolute','var') || ...
            numel(tMetricAbsolute) < 2
        attitudeCommandAvailable = ...
            false;
        attitudeCommandAvailabilityReason = ...
            "NO_COMMON_COMMAND_ATTITUDE_TIME_SUPPORT";
    end
end

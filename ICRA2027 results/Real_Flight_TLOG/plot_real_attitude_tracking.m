    tAttitudeAbsolute - ...
    trackingStart_s;
if attitudeCommandAvailable
    tCommand = ...
        tCommandAbsolute - ...
        trackingStart_s;
    tMetric = ...
        tMetricAbsolute - ...
        trackingStart_s;
else
    tCommandAbsolute = ...
        zeros(0,1);
    tCommand = ...
        zeros(0,1);
    RollCommand_deg = ...
        NaN(0,1);
    PitchCommand_deg = ...
        NaN(0,1);
    tMetricAbsolute = ...
        tAttitudeAbsolute;
    tMetric = ...
        tAttitude;
    RollCommandMetric_deg = ...
        NaN(size(tMetricAbsolute));
    PitchCommandMetric_deg = ...
        NaN(size(tMetricAbsolute));
    RollMeasuredMetric_deg = ...
        Roll_deg;
    PitchMeasuredMetric_deg = ...
        Pitch_deg;
end
if attitudeCommandAvailable
    RollError_deg = ...
        RollMeasuredMetric_deg - ...
        RollCommandMetric_deg;
    PitchError_deg = ...
        PitchMeasuredMetric_deg - ...
        PitchCommandMetric_deg;
    RollTrackingRMSE_deg = ...
        sqrt( ...
            mean( ...
                RollError_deg.^2, ...
                'omitnan'));
    PitchTrackingRMSE_deg = ...
        sqrt( ...
            mean( ...
                PitchError_deg.^2, ...
                'omitnan'));
    RollTrackingMAE_deg = ...
        mean( ...
            abs(RollError_deg), ...
            'omitnan');
    PitchTrackingMAE_deg = ...
        mean( ...
            abs(PitchError_deg), ...
            'omitnan');
    RollTrackingMaxAbs_deg = ...
        max( ...
            abs(RollError_deg), ...
            [], ...
            'omitnan');
    PitchTrackingMaxAbs_deg = ...
        max( ...
            abs(PitchError_deg), ...
            [], ...
            'omitnan');
    MaxAbsRollCommand_deg = ...
        max( ...
            abs(RollCommandMetric_deg), ...
            [], ...
            'omitnan');
    MaxAbsPitchCommand_deg = ...
        max( ...
            abs(PitchCommandMetric_deg), ...
            [], ...
            'omitnan');
else
    RollError_deg = ...
        NaN(size(tMetricAbsolute));
    PitchError_deg = ...
        NaN(size(tMetricAbsolute));
    RollTrackingRMSE_deg = ...
        NaN;
    PitchTrackingRMSE_deg = ...
        NaN;
    RollTrackingMAE_deg = ...
        NaN;
    PitchTrackingMAE_deg = ...
        NaN;
    RollTrackingMaxAbs_deg = ...
        NaN;
    PitchTrackingMaxAbs_deg = ...
        NaN;

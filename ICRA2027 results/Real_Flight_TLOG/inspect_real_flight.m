function merged = localMergeSimpleIntervals( ...
    intervals, ...
    mergeGap_s, ...
    minimumDuration_s)
    merged = ...
        table();
    if isempty(intervals)
        return;
    end
    intervals = ...
        sortrows( ...
            intervals, ...
            'StartTime_s');
    starts = ...
        zeros(0,1);
    ends = ...
        zeros(0,1);
    currentStart = ...
        intervals.StartTime_s(1);
    currentEnd = ...
        intervals.EndTime_s(1);
    for k = 2:height(intervals)
        nextStart = ...
            intervals.StartTime_s(k);
        nextEnd = ...
            intervals.EndTime_s(k);
        if nextStart <= ...
                currentEnd + ...
                mergeGap_s
            currentEnd = ...
                max( ...
                    currentEnd, ...
                    nextEnd);
        else
            starts(end+1,1) = ...
                currentStart; %#ok<AGROW>
            ends(end+1,1) = ...
                currentEnd; %#ok<AGROW>
            currentStart = ...
                nextStart;
            currentEnd = ...
                nextEnd;
        end
    end
    starts(end+1,1) = ...
        currentStart;
    ends(end+1,1) = ...
        currentEnd;
    durations = ...
        ends - ...
        starts;
    keep = ...
        durations >= ...
        minimumDuration_s;
    StartTime_s = ...
        starts(keep);
    EndTime_s = ...
        ends(keep);
    Duration_s = ...
        durations(keep);
    merged = ...
        table( ...
            StartTime_s, ...
            EndTime_s, ...
            Duration_s);
end
function totalOverlap_s = localTotalOverlapDuration( ...
    candidateStart_s, ...
    candidateEnd_s, ...
    intervals)
    totalOverlap_s = ...
        0;
    if isempty(intervals)
        return;
    end
    for k = 1:height(intervals)
        overlapStart = ...
            max( ...
                candidateStart_s, ...
                intervals.StartTime_s(k));
        overlapEnd = ...
            min( ...
                candidateEnd_s, ...
                intervals.EndTime_s(k));
        totalOverlap_s = ...
            totalOverlap_s + ...
            max( ...
                0, ...
                overlapEnd - ...
                overlapStart);
    end
end

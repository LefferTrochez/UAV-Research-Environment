        numel(sourceNames);
    if numel(sourceNames) < ...
            F.minimumSourceCount
        return;
    end
    commonStart = ...
        max(sourceStarts);
    commonEnd = ...
        min(sourceEnds);
    commonDuration = ...
        commonEnd - ...
        commonStart;
    selectedStart = ...
        NaN;
    selectedEnd = ...
        NaN;
    selectedSources = ...
        strings(0,1);
    if isfinite(commonStart) && ...
            isfinite(commonEnd) && ...
            commonDuration >= ...
            F.minimumWindowDuration_s
        selectedStart = ...
            commonStart;
        selectedEnd = ...
            commonEnd;
        selectedSources = ...
            sourceNames;
        diagnostics.SelectionMethod = ...
            "COMMON_SUPPORT_ALL_AVAILABLE_SOURCES";
    else
        bestDuration = ...
            -Inf;
        bestStart = ...
            NaN;
        bestEnd = ...
            NaN;
        bestPair = ...
            zeros(0,1);
        for i = 1:numel(sourceNames)
            for j = i+1:numel(sourceNames)
                pairStart = ...
                    max( ...
                        sourceStarts(i), ...
                        sourceStarts(j));
                pairEnd = ...
                    min( ...
                        sourceEnds(i), ...
                        sourceEnds(j));
                pairDuration = ...
                    pairEnd - ...
                    pairStart;
                if pairDuration > ...
                        bestDuration
                    bestDuration = ...
                        pairDuration;
                    bestStart = ...
                        pairStart;
                    bestEnd = ...
                        pairEnd;
                    bestPair = ...
                        [i;j];
                end
            end
        end
        if isfinite(bestDuration) && ...
                bestDuration >= ...
                F.minimumWindowDuration_s
            selectedStart = ...
                bestStart;
            selectedEnd = ...
                bestEnd;
            spansWindow = ...
                sourceStarts <= selectedStart & ...
                sourceEnds >= selectedEnd;
            selectedSources = ...
                sourceNames(spansWindow);
            if numel(selectedSources) < ...
                    F.minimumSourceCount
                selectedSources = ...
                    sourceNames(bestPair);
            end
            diagnostics.SelectionMethod = ...
                "LONGEST_PAIRWISE_COMMON_SUPPORT";
        end
    end
    if ~isfinite(selectedStart) || ...
            ~isfinite(selectedEnd)
        return;
    end
    selectedStart = ...
        max( ...
            0, ...
            selectedStart);
    if isfinite(logDuration_s) && ...
            logDuration_s > 0
        selectedEnd = ...
            min( ...
                logDuration_s, ...
                selectedEnd);
    end
    selectedDuration = ...
        selectedEnd - ...
        selectedStart;
    if selectedDuration < ...
            F.minimumWindowDuration_s
        return;
    end
    if numel(selectedSources) < ...
            F.minimumSourceCount
        return;
    end
    Interval = ...
        1;
    StartTime_s = ...
        selectedStart;
    EndTime_s = ...
        selectedEnd;
    Duration_s = ...
        selectedDuration;
    SourceCount = ...
        numel(selectedSources);
    Sources = ...
        strjoin( ...
            selectedSources, ...
            "+");
    intervals = ...
        table( ...
            Interval, ...
            StartTime_s, ...
            EndTime_s, ...
            Duration_s, ...
            SourceCount, ...
            Sources);
    diagnostics.Accepted = ...
        true;
    diagnostics.SelectedStartTime_s = ...
        selectedStart;
    diagnostics.SelectedEndTime_s = ...
        selectedEnd;
    diagnostics.SelectedDuration_s = ...
        selectedDuration;
    diagnostics.SelectedSourceCount = ...
        SourceCount;
    diagnostics.SelectedSources = ...
        Sources;
end
function [names,starts,ends] = localAppendTelemetrySource( ...
    names, ...
    starts, ...
    ends, ...
    REAL_DATA, ...
    pathParts, ...
    sourceName)
    node = ...
        REAL_DATA;
    for k = 1:numel(pathParts)
        fieldName = ...
            pathParts{k};
        if ~isstruct(node) || ...
                ~isfield(node,fieldName)
            return;
        end
        node = ...
            node.(fieldName);
    end
    timeVector = ...
        localExtractTimeVector(node);
    timeVector = ...
        double(timeVector(:));
    timeVector = ...
        timeVector( ...
            isfinite(timeVector));
    if numel(timeVector) < 2
        return;
    end
    t0 = ...
        min(timeVector);
    t1 = ...
        max(timeVector);
    if ~isfinite(t0) || ...
            ~isfinite(t1) || ...
            t1 <= t0
        return;
    end
    names(end+1,1) = ...
        string(sourceName);
    starts(end+1,1) = ...
        t0;
    ends(end+1,1) = ...
        t1;
end
function timeVector = localExtractTimeVector(node)
    timeVector = ...
        zeros(0,1);
    try
        if istimetable(node)
            rowTimes = ...
                node.Properties.RowTimes;
            if isduration(rowTimes)
                timeVector = ...
                    seconds(rowTimes);
            elseif isdatetime(rowTimes)
                timeVector = ...
                    seconds( ...
                        rowTimes - ...
                        rowTimes(1));
            else
                timeVector = ...
                    double(rowTimes);
            end
            return;
        end
        if istable(node)
            if ismember( ...
                    'Time_s', ...
                    node.Properties.VariableNames)
                timeVector = ...
                    double(node.Time_s(:));
            end
            return;
        end
        if isstruct(node) && ...
                isfield(node,'Time_s')
            timeVector = ...
                double(node.Time_s(:));
        end
    catch
        timeVector = ...
            zeros(0,1);
    end
end
function baseline = localInitialBaseline( ...
    time_s, ...
    data, ...
    baselineWindow_s)
    time_s = ...
        double(time_s(:));
    data = ...
        double(data(:));
    valid = ...
        isfinite(time_s) & ...
        isfinite(data);
    time_s = ...
        time_s(valid);
    data = ...
        data(valid);
    baseline = ...
        NaN;
    if isempty(data)
        return;
    end
    t0 = ...
        time_s(1);
    baselineMask = ...
        time_s <= ...
        t0 + ...
        baselineWindow_s;
    baselineData = ...
        data(baselineMask);
    if isempty(baselineData)
        baselineData = ...
            data( ...
                1:min( ...
                    numel(data), ...
                    10));
    end
    baseline = ...
        median( ...
            baselineData, ...
            'omitnan');
    if ~isfinite(baseline)
        baseline = ...
            median( ...
                data, ...
                'omitnan');
    end
end

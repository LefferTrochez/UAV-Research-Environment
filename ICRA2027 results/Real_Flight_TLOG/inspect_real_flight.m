        REAL_ARMED_INTERVALS.EndTime_s;
    Duration_s = ...
        REAL_ARMED_INTERVALS.Duration_s;
    AirborneDetected = ...
        false(numberAttempts,1);
    AirborneDuration_s = ...
        zeros(numberAttempts,1);
    TakeoffStateDetected = ...
        false(numberAttempts,1);
    LandingStateDetected = ...
        false(numberAttempts,1);
    for k = 1:numberAttempts
        t0 = ...
            StartTime_s(k);
        t1 = ...
            EndTime_s(k);
        if airStateAvailable
            mask = ...
                LS.Time_s >= t0 & ...
                LS.Time_s <= t1;
            if any(mask)
                statesInside = ...
                    double(LS.LandedState(mask));
                AirborneDetected(k) = ...
                    any( ...
                        statesInside == 2 | ...
                        statesInside == 3 | ...
                        statesInside == 4);
                TakeoffStateDetected(k) = ...
                    any(statesInside == 3);
                LandingStateDetected(k) = ...
                    any(statesInside == 4);
            end
        end
        if ~isempty(REAL_AIRBORNE_INTERVALS)
            totalAirTime = ...
                0;
            for j = 1:height(REAL_AIRBORNE_INTERVALS)
                overlapStart = ...
                    max( ...
                        t0, ...
                        REAL_AIRBORNE_INTERVALS.StartTime_s(j));
                overlapEnd = ...
                    min( ...
                        t1, ...
                        REAL_AIRBORNE_INTERVALS.EndTime_s(j));
                overlapDuration = ...
                    max( ...
                        0, ...
                        overlapEnd - overlapStart);
                totalAirTime = ...
                    totalAirTime + ...
                    overlapDuration;
            end
            AirborneDuration_s(k) = ...
                totalAirTime;
        end
    end
    DetectionSource = ...
        repmat( ...
            "HEARTBEAT_ARMED", ...
            numberAttempts, ...
            1);
    REAL_FLIGHT_ATTEMPTS = ...
        table( ...
            Attempt, ...
            StartTime_s, ...
            EndTime_s, ...
            Duration_s, ...
            AirborneDetected, ...
            AirborneDuration_s, ...
            TakeoffStateDetected, ...
            LandingStateDetected, ...
            DetectionSource);

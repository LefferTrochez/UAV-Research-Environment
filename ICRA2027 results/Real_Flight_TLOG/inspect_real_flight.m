function intervals = logicalIntervals( ...
    time_s, ...
    state, ...
    minimumDuration_s)
    time_s = ...
        double(time_s(:));
    state = ...
        logical(state(:));
    valid = ...
        isfinite(time_s);
    time_s = ...
        time_s(valid);
    state = ...
        state(valid);
    if isempty(time_s)
        intervals = ...
            table();
        return;
    end
    [time_s,order] = ...
        sort(time_s);
    state = ...
        state(order);
    stateExtended = ...
        [false; state; false];
    transitions = ...
        diff(stateExtended);
    startIndices = ...
        find(transitions == 1);
    endIndices = ...
        find(transitions == -1) - 1;
    StartTime_s = ...
        time_s(startIndices);
    EndTime_s = ...
        time_s(endIndices);
    Duration_s = ...
        EndTime_s - ...
        StartTime_s;
    keep = ...
        Duration_s >= ...
        minimumDuration_s;
    StartTime_s = ...
        StartTime_s(keep);
    EndTime_s = ...
        EndTime_s(keep);
    Duration_s = ...
        Duration_s(keep);
    intervals = ...
        table( ...
            StartTime_s, ...
            EndTime_s, ...
            Duration_s);
end

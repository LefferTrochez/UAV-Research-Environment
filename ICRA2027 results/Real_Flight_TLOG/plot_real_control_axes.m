    "Actuator-space thrust/roll/pitch/yaw proxy derived from four motor " + ...
    "commands. Not equivalent to the internal Simulink controlAxesLog.";
availabilityIndex = ...
    find( ...
        REAL_DATA_AVAILABILITY.Signal == ...
        availabilitySignal, ...
        1);
if isempty(availabilityIndex)
    newRow = ...
        table( ...
            string(availabilitySignal), ...
            string("Controller"), ...
            string(availabilityStatus), ...
            string(availabilitySource), ...
            string(availabilityUnits), ...
            string(availabilityNote), ...
            'VariableNames', ...
            REAL_DATA_AVAILABILITY.Properties.VariableNames);
    REAL_DATA_AVAILABILITY = ...
        [ ...
            REAL_DATA_AVAILABILITY; ...
            newRow ...
        ];

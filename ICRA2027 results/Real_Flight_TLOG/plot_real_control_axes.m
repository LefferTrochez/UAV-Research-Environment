requiredVariables = { ...
    'REAL_MOTOR_PWM_DATA', ...
    'REAL_ACTUATION_RESULTS', ...
    'REAL_ACTUATOR_CONFIG', ...
    'REAL_FIGURES_FOLDER', ...
    'REAL_TABLES_FOLDER', ...
    'REAL_EXPERIMENT_DATA_FILE', ...
    'REAL_DATA_AVAILABILITY'};
for k = 1:numel(requiredVariables)
    if ~exist(requiredVariables{k},'var')
        error( ...
            'RealFlight:MissingRequiredVariable', ...
            ['Required variable "%s" was not found.\n\n', ...
             'Run the previous real-flight processing scripts first.'], ...
            requiredVariables{k});
    end
end
t = ...
    double( ...
        REAL_MOTOR_PWM_DATA.FlightTime_s);
U = [ ...
    double(REAL_MOTOR_PWM_DATA.Motor1_Normalized), ...
    double(REAL_MOTOR_PWM_DATA.Motor2_Normalized), ...
    double(REAL_MOTOR_PWM_DATA.Motor3_Normalized), ...
    double(REAL_MOTOR_PWM_DATA.Motor4_Normalized)];
validRows = ...
    isfinite(t) & ...
    all(isfinite(U),2);
t = ...
    t(validRows);
U = ...
    U(validRows,:);
if numel(t) < 2
    error( ...
        'RealFlight:InsufficientMotorData', ...
        ['Insufficient valid motor-command data exist for ', ...
         'control-axis reconstruction.']);
end
[t,order] = ...
    sort(t);
U = ...
    U(order,:);
u1 = ...
    U(:,1);
u2 = ...
    U(:,2);
u3 = ...
    U(:,3);
u4 = ...
    U(:,4);
thrustAxisProxy = ...
    ( ...
        u1 + ...
        u2 + ...
        u3 + ...
        u4 ...
    ) / 4;
rollAxisProxy = ...
    ( ...
        -u1 + ...
         u2 + ...
         u3 - ...
         u4 ...
    ) / 4;
pitchAxisProxy = ...
    ( ...
         u1 - ...
         u2 + ...
         u3 - ...
         u4 ...
    ) / 4;
yawAxisProxy = ...
    ( ...
         u1 + ...
         u2 - ...
         u3 - ...
         u4 ...
    ) / 4;
REAL_CONTROL_AXES_PROXY = ...
    table( ...
        t, ...
        thrustAxisProxy, ...
        rollAxisProxy, ...
        pitchAxisProxy, ...
        yawAxisProxy, ...
        'VariableNames', { ...
            'FlightTime_s', ...
            'ThrustAxisProxy_norm', ...
            'RollAxisProxy_norm', ...
            'PitchAxisProxy_norm', ...
            'YawAxisProxy_norm'});
ThrustAxisProxyRMS_norm = ...
    sqrt( ...
        mean( ...
            thrustAxisProxy.^2, ...
            'omitnan'));
RollAxisProxyRMS_norm = ...
    sqrt( ...
        mean( ...
            rollAxisProxy.^2, ...
            'omitnan'));
PitchAxisProxyRMS_norm = ...
    sqrt( ...
        mean( ...
            pitchAxisProxy.^2, ...
            'omitnan'));
YawAxisProxyRMS_norm = ...
    sqrt( ...
        mean( ...
            yawAxisProxy.^2, ...
            'omitnan'));
PeakAbsThrustAxisProxy_norm = ...
    max( ...
        abs(thrustAxisProxy), ...
        [], ...
        'omitnan');
PeakAbsRollAxisProxy_norm = ...
    max( ...
        abs(rollAxisProxy), ...
        [], ...
        'omitnan');
PeakAbsPitchAxisProxy_norm = ...
    max( ...
        abs(pitchAxisProxy), ...
        [], ...
        'omitnan');
PeakAbsYawAxisProxy_norm = ...
    max( ...
        abs(yawAxisProxy), ...
        [], ...
        'omitnan');
delete( ...
    findall( ...
        groot, ...
        'Type','figure', ...
        'Tag','RealFlight_ControlAxes'));

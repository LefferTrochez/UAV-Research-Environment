    ax2, ...
    'rollAxis — DERIVED PROXY');
xlim( ...
    ax2, ...
    [t(1) t(end)]);
ax3 = ...
    nexttile(tl07);
plot( ...
    ax3, ...
    t, ...
    pitchAxisProxy, ...
    'LineWidth',1.4);
yline( ...
    ax3, ...
    0, ...
    ':', ...
    'HandleVisibility','off');
grid(ax3,'on');
box(ax3,'on');
ylabel( ...
    ax3, ...
    'Normalized [-]');
title( ...
    ax3, ...
    'pitchAxis — DERIVED PROXY');
xlim( ...
    ax3, ...
    [t(1) t(end)]);
ax4 = ...
    nexttile(tl07);
plot( ...
    ax4, ...
    t, ...
    yawAxisProxy, ...
    'LineWidth',1.4);
yline( ...
    ax4, ...
    0, ...
    ':', ...
    'HandleVisibility','off');

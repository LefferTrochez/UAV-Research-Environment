    REAL_DATA_AVAILABILITY.Status(availabilityIndex) = ...
        string(availabilityStatus);
    REAL_DATA_AVAILABILITY.SourceMessage(availabilityIndex) = ...
        string(availabilitySource);
    REAL_DATA_AVAILABILITY.Units(availabilityIndex) = ...
        string(availabilityUnits);
    REAL_DATA_AVAILABILITY.Notes(availabilityIndex) = ...
        string(availabilityNote);

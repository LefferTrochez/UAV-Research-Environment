    ax1, ...
    [t(1) t(end)]);
ax2 = ...
    nexttile(tl07);
plot( ...
    ax2, ...
    t, ...
    rollAxisProxy, ...
    'LineWidth',1.4);
yline( ...
    ax2, ...
    0, ...
    ':', ...
    'HandleVisibility','off');
grid(ax2,'on');
box(ax2,'on');
ylabel( ...
    ax2, ...
    'Normalized [-]');

function t = realFlightRelativeTime(TT, logStart)
    rowTimes = ...
        TT.Properties.RowTimes;
    if isempty(rowTimes)
        error( ...
            'RealFlight:MissingRowTimes', ...
            'MAVLink timetable has no row times.');
    end
    if isdatetime(rowTimes)
        t = ...
            seconds( ...
                rowTimes - logStart);
    elseif isduration(rowTimes)
        t = ...
            seconds(rowTimes);
    elseif isnumeric(rowTimes)
        t = ...
            double(rowTimes(:));
    else
        error( ...
            'RealFlight:UnsupportedRowTimeType', ...
            'Unsupported MAVLink timetable row-time type.');
    end
    t = ...
        double(t(:));
end

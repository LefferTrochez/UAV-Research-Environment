function packVoltage_V = batteryPackVoltageFromMAVLink(voltageData)
    voltageData = ...
        double(voltageData);
    numberOfSamples = ...
        size(voltageData,1);
    packVoltage_V = ...
        NaN(numberOfSamples,1);
    for k = 1:numberOfSamples
        row = ...
            voltageData(k,:);
        valid = ...
            isfinite(row) & ...
            row > 0 & ...
            row < 65535;
        if any(valid)
            packVoltage_V(k) = ...
                sum(row(valid)) * ...
                1.0e-3;
        end
    end
end
function ned = geodeticToLocalNED(lla, homeLLA)
    a = ...
        6378137.0;
    f = ...
        1 / 298.257223563;
    e2 = ...
        f * (2 - f);
    xyz = ...
        geodeticToECEFLocal( ...
            lla(:,1), ...
            lla(:,2), ...
            lla(:,3), ...
            a, ...
            e2);
    xyz0 = ...
        geodeticToECEFLocal( ...
            homeLLA(1), ...
            homeLLA(2), ...
            homeLLA(3), ...
            a, ...
            e2);
    delta = ...
        xyz - xyz0;
    lat0 = ...
        deg2rad(homeLLA(1));
    lon0 = ...
        deg2rad(homeLLA(2));
    R = [ ...
        -sin(lat0)*cos(lon0), ...
        -sin(lat0)*sin(lon0), ...
         cos(lat0); ...
        -sin(lon0), ...
         cos(lon0), ...
         0; ...
        -cos(lat0)*cos(lon0), ...
        -cos(lat0)*sin(lon0), ...
        -sin(lat0)];
    ned = ...
        (R * delta.').';
end
function xyz = geodeticToECEFLocal( ...
    latitude_deg,longitude_deg,altitude_m,a,e2)
    latitude_rad = ...
        deg2rad(latitude_deg);
    longitude_rad = ...
        deg2rad(longitude_deg);
    sinLat = ...
        sin(latitude_rad);
    cosLat = ...
        cos(latitude_rad);
    N = ...
        a ./ ...
        sqrt( ...
            1 - ...
            e2 .* ...
            sinLat.^2);
    X = ...
        (N + altitude_m) .* ...
        cosLat .* ...
        cos(longitude_rad);
    Y = ...
        (N + altitude_m) .* ...
        cosLat .* ...
        sin(longitude_rad);
    Z = ...
        (N .* (1-e2) + altitude_m) .* ...
        sinLat;
    xyz = ...
        [X Y Z];
end

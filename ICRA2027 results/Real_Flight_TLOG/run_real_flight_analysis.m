RESULT = ...
    struct();
RESULT.Trajectory = ...
    "";
RESULT.TLOGFile = ...
    "";
RESULT.ResultName = ...
    "";
RESULT.Success = ...
    false;
RESULT.FailedStage = ...
    "";
RESULT.ErrorMessage = ...
    "";
RESULT.ResultFolder = ...
    "";
RESULT.FiguresFolder = ...
    "";
RESULT.TablesFolder = ...
    "";
RESULT.ExperimentDataFile = ...
    "";
RESULT.FiguresGenerated = ...
    0;
RESULT.CSVTablesGenerated = ...
    0;
RESULT.ProcessingTime_s = ...
    NaN;
end

requiredVariables = { ...
    'REAL_DATA', ...
    'REAL_FLIGHT_INSPECTION', ...
    'REAL_FIGURES_FOLDER', ...
    'REAL_EXPERIMENT_DATA_FILE'};
for k = 1:numel(requiredVariables)
    if ~exist(requiredVariables{k},'var')
        error( ...
            'RealFlight:MissingRequiredVariable', ...
            ['Required variable "%s" was not found.\n\n', ...
             'Run the previous processing scripts first.'], ...
            requiredVariables{k});
    end
end
if ~REAL_FLIGHT_INSPECTION.PrimaryAttemptAvailable
    error( ...
        'RealFlight:NoPrimaryFlightAttempt', ...
        'No primary real-flight analysis window is available.');
end
windowStart_s = ...
    REAL_FLIGHT_INSPECTION.InspectionStartTime_s;
windowEnd_s = ...
    REAL_FLIGHT_INSPECTION.InspectionEndTime_s;
coreStart_s = ...
    REAL_FLIGHT_INSPECTION.CoreStartTime_s;
coreEnd_s = ...
    REAL_FLIGHT_INSPECTION.CoreEndTime_s;
windowDuration_s = ...
    windowEnd_s - ...
    windowStart_s;
toPlotTime = ...
    @(t) double(t) - windowStart_s;
REAL_PLOT_DATA = ...
    struct();
REAL_PLOT_DATA.WindowStart_s = ...
    windowStart_s;
REAL_PLOT_DATA.WindowEnd_s = ...
    windowEnd_s;
REAL_PLOT_DATA.CoreStart_s = ...
    coreStart_s;
REAL_PLOT_DATA.CoreEnd_s = ...
    coreEnd_s;
REAL_PLOT_DATA.WindowDuration_s = ...
    windowDuration_s;
positionAvailable = ...
    false;
positionSource = ...
    "NOT_AVAILABLE";
tPosition = ...
    [];
PositionNED = ...
    [];
if isfield(REAL_DATA.State,'PositionNED') && ...
        ~isempty(REAL_DATA.State.PositionNED)
    TT = ...
        REAL_DATA.State.PositionNED;
    mask = ...
        TT.Time_s >= windowStart_s & ...
        TT.Time_s <= windowEnd_s;
    if any(mask)
        tPosition = ...
            toPlotTime( ...
                TT.Time_s(mask));
        PositionNED = [ ...
            TT.North_m(mask), ...
            TT.East_m(mask), ...
            TT.Down_m(mask)];
        positionAvailable = ...
            true;
        positionSource = ...
            "DIRECT/DERIVED_FROM_LLA";
    end
end
downFallbackAvailable = ...
    false;
tDownFallback = ...
    [];
downFallback_m = ...
    [];
if ~positionAvailable && ...
        isfield(REAL_DATA.State,'GlobalPosition') && ...
        ~isempty(REAL_DATA.State.GlobalPosition)
    GP = ...
        REAL_DATA.State.GlobalPosition;
    mask = ...
        GP.Time_s >= windowStart_s & ...
        GP.Time_s <= windowEnd_s;
    if any(mask)
        relAlt = ...
            double( ...
                GP.RelativeAltitude_m(mask));
        valid = ...
            isfinite(relAlt);
        if any(valid)
            tDownFallback = ...
                toPlotTime( ...
                    GP.Time_s(mask));
            downFallback_m = ...
                -relAlt;
            downFallbackAvailable = ...
                true;
        end
    end
end
velocityAvailable = ...
    false;
tVelocity = ...
    [];
VelocityNED = ...
    [];
if isfield(REAL_DATA.State,'VelocityNED') && ...
        ~isempty(REAL_DATA.State.VelocityNED)
    TT = ...
        REAL_DATA.State.VelocityNED;
    mask = ...
        TT.Time_s >= windowStart_s & ...
        TT.Time_s <= windowEnd_s;
    if any(mask)
        tVelocity = ...
            toPlotTime( ...
                TT.Time_s(mask));
        VelocityNED = [ ...
            TT.North_m_s(mask), ...
            TT.East_m_s(mask), ...
            TT.Down_m_s(mask)];
        velocityAvailable = ...
            true;
    end
end
attitudeAvailable = ...
    false;
tAttitude = ...
    [];
Euler_deg = ...
    [];
if isfield(REAL_DATA.State,'Attitude') && ...
        ~isempty(REAL_DATA.State.Attitude)
    TT = ...
        REAL_DATA.State.Attitude;
    mask = ...
        TT.Time_s >= windowStart_s & ...
        TT.Time_s <= windowEnd_s;
    if any(mask)
        tAttitude = ...
            toPlotTime( ...
                TT.Time_s(mask));
        Euler_deg = ...
            rad2deg( ...
                [ ...
                    TT.Roll_rad(mask), ...
                    TT.Pitch_rad(mask), ...
                    TT.Yaw_rad(mask) ...
                ]);
        attitudeAvailable = ...
            true;
    end
end
rateAvailable = ...
    false;
tRate = ...
    [];
AngularRate = ...
    [];
if isfield(REAL_DATA.State,'AngularRate') && ...
        ~isempty(REAL_DATA.State.AngularRate)
    TT = ...
        REAL_DATA.State.AngularRate;
    mask = ...
        TT.Time_s >= windowStart_s & ...
        TT.Time_s <= windowEnd_s;
    if any(mask)
        tRate = ...
            toPlotTime( ...
                TT.Time_s(mask));
        AngularRate = [ ...
            TT.P_rad_s(mask), ...
            TT.Q_rad_s(mask), ...
            TT.R_rad_s(mask)];
        rateAvailable = ...
            true;
    end
end
accelerationAvailable = ...
    false;
tAcceleration = ...
    [];
AccelerationNED = ...
    [];
if velocityAvailable
    tRaw = ...
        double(tVelocity(:));
    VRaw = ...
        double(VelocityNED);
    validRows = ...
        isfinite(tRaw) & ...
        all(isfinite(VRaw),2);
    tRaw = ...
        tRaw(validRows);
    VRaw = ...
        VRaw(validRows,:);
    [tUnique,uniqueIndices] = ...
        unique( ...
            tRaw, ...
            'stable');
    VUnique = ...
        VRaw(uniqueIndices,:);
    if numel(tUnique) >= 3
        aN = ...
            gradient( ...
                VUnique(:,1), ...
                tUnique);
        aE = ...
            gradient( ...
                VUnique(:,2), ...
                tUnique);
        aD = ...
            gradient( ...
                VUnique(:,3), ...
                tUnique);
        tAcceleration = ...
            tUnique;
        AccelerationNED = ...
            [aN aE aD];
        accelerationAvailable = ...
            true;
        REAL_PLOT_DATA.AccelerationNED = ...
            table( ...
                tAcceleration, ...
                aN, ...
                aE, ...
                aD, ...
                'VariableNames', { ...
                    'Time_s', ...
                    'North_m_s2', ...
                    'East_m_s2', ...
                    'Down_m_s2'});
        REAL_PLOT_DATA.AccelerationSource = ...
            "DERIVED_FROM_GLOBAL_POSITION_INT_VELOCITY";
    end
end
if ~accelerationAvailable
    REAL_PLOT_DATA.AccelerationSource = ...
        "NOT_AVAILABLE";
end
delete( ...
    findall( ...
        0, ...
        'Type','figure', ...
        'Tag','RealFlight_MainStates'));
delete( ...
    findall( ...
        0, ...
        'Type','figure', ...
        'Tag','RealFlight_DynamicStates'));
fig1 = ...
    figure( ...
        'Name','Real Flight - Main States', ...
        'Tag','RealFlight_MainStates', ...
        'Color','w');
tl = ...
    tiledlayout( ...
        3, ...
        3, ...
        'TileSpacing','compact', ...
        'Padding','compact');
title( ...
    tl, ...
    'Real Flight: Position, Velocity and Attitude');
labelsPosition = { ...
    'North', ...
    'East', ...
    'Down'};
for i = 1:3
    ax = ...
        nexttile;
    if positionAvailable
        plot( ...
            tPosition, ...
            PositionNED(:,i), ...
            'LineWidth',1.2);
        grid on;
        xlabel('Time [s]');
        ylabel( ...
            sprintf( ...
                '%s [m]', ...
                labelsPosition{i}));
        title( ...
            sprintf( ...
                'Position %s', ...
                labelsPosition{i}));
        xlim( ...
            [0 windowDuration_s]);
    elseif i == 3 && ...
            downFallbackAvailable
        plot( ...
            tDownFallback, ...
            downFallback_m, ...
            'LineWidth',1.2);
        grid on;
        xlabel('Time [s]');
        ylabel('Down [m]');
        title( ...
            'Position Down');
        xlim( ...
            [0 windowDuration_s]);
        legend( ...
            'REAL — derived from relative altitude', ...
            'Location','best');
    else
        axis(ax,'off');
        text( ...
            ax, ...
            0.5, ...
            0.55, ...
            sprintf( ...
                'Position %s', ...
                labelsPosition{i}), ...
            'Units','normalized', ...
            'HorizontalAlignment','center', ...
            'FontWeight','bold');
        text( ...
            ax, ...
            0.5, ...
            0.42, ...
            'NOT AVAILABLE', ...
            'Units','normalized', ...
            'HorizontalAlignment','center');
        text( ...
            ax, ...
            0.5, ...
            0.30, ...
            'No valid geographic HOME / GPS', ...
            'Units','normalized', ...
            'HorizontalAlignment','center', ...
            'FontSize',8);
    end
end
labelsVelocity = { ...
    'v_N', ...
    'v_E', ...
    'v_D'};
for i = 1:3
    ax = ...
        nexttile;
    if velocityAvailable
        plot( ...
            tVelocity, ...
            VelocityNED(:,i), ...
            'LineWidth',1.2);
        grid on;
        xlabel('Time [s]');
        ylabel('[m/s]');

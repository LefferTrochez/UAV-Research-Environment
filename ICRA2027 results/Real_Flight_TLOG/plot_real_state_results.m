            sprintf( ...
                '%s\nNOT AVAILABLE', ...
                labelsEuler{i}), ...
            'Units','normalized', ...
            'HorizontalAlignment','center');
    end
end
fig2 = ...
    figure( ...
        'Name','Real Flight - Dynamic States', ...
        'Tag','RealFlight_DynamicStates', ...
        'Color','w');

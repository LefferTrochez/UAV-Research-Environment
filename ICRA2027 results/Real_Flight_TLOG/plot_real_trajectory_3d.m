verticalBaseline_m = ...
    NaN;
if trajectorySource == "DERIVED_FROM_VELOCITY_NED" && ...
        isfield(REAL_DATA,'State') && ...
        isfield(REAL_DATA.State,'GlobalPosition') && ...
        ~isempty(REAL_DATA.State.GlobalPosition)
    GP = ...
        REAL_DATA.State.GlobalPosition;
    baselineMask = ...
        GP.Time_s >= coreStart_s & ...
        GP.Time_s <= trajectoryStart_s & ...
        isfinite(GP.RelativeAltitude_m);
    baselineValues = ...
        double( ...
            GP.RelativeAltitude_m(baselineMask));
    if ~isempty(baselineValues)
        verticalBaseline_m = ...
            median( ...
                baselineValues, ...
                'omitnan');
    else
        fallbackMask = ...
            GP.Time_s >= (trajectoryStart_s - 2.0) & ...
            GP.Time_s <= (trajectoryStart_s + 2.0) & ...
            isfinite(GP.RelativeAltitude_m);
        fallbackValues = ...
            double( ...
                GP.RelativeAltitude_m(fallbackMask));
        if ~isempty(fallbackValues)
            numberBaselineSamples = ...
                min( ...
                    10, ...
                    numel(fallbackValues));
            verticalBaseline_m = ...
                median( ...
                    fallbackValues(1:numberBaselineSamples), ...
                    'omitnan');
        end
    end
    verticalMask = ...
        GP.Time_s >= trajectoryStart_s & ...
        GP.Time_s <= trajectoryEnd_s;
    if nnz(verticalMask) >= 2 && ...
            isfinite(verticalBaseline_m)
        tVertical = ...
            double( ...
                GP.Time_s(verticalMask));
        relativeAltitude = ...
            double( ...
                GP.RelativeAltitude_m(verticalMask));
        validVertical = ...
            isfinite(tVertical) & ...
            isfinite(relativeAltitude);
        tVertical = ...
            tVertical(validVertical);
        relativeAltitude = ...
            relativeAltitude(validVertical);
        [tVertical,verticalOrder] = ...
            sort(tVertical);
        relativeAltitude = ...
            relativeAltitude(verticalOrder);
        [tVertical,uniqueVertical] = ...
            unique( ...
                tVertical, ...
                'last');
        relativeAltitude = ...
            relativeAltitude(uniqueVertical);
        if numel(tVertical) >= 2
            commonStart_s = ...
                max( ...
                    tTrajectoryAbsolute(1), ...
                    tVertical(1));
            commonEnd_s = ...
                min( ...
                    tTrajectoryAbsolute(end), ...
                    tVertical(end));
            commonMask = ...
                tTrajectoryAbsolute >= commonStart_s & ...
                tTrajectoryAbsolute <= commonEnd_s;
            if nnz(commonMask) >= 2
                tTrajectoryAbsolute = ...
                    tTrajectoryAbsolute(commonMask);
                North_m = ...
                    North_m(commonMask);
                East_m = ...
                    East_m(commonMask);
                relativeAltitudeInterp = ...
                    interp1( ...
                        tVertical, ...
                        relativeAltitude, ...
                        tTrajectoryAbsolute, ...
                        'linear', ...
                        NaN);
                AltitudeAGL_m = ...
                    relativeAltitudeInterp - ...
                    verticalBaseline_m;
                Down_m = ...
                    -AltitudeAGL_m;
                tTrajectory = ...
                    tTrajectoryAbsolute - ...
                    tTrajectoryAbsolute(1);
                verticalSource = ...
                    "GLOBAL_POSITION_INT_RELATIVE_ALT";
                trajectorySource = ...
                    "HYBRID_VELOCITY_XY_RELATIVE_ALT_Z";
                trajectoryClassification = ...
                    "DERIVED_HYBRID";
            end
        end
    end
end

            safeInterpLinear( ...
                tVelocity, ...
                vN, ...
                tEval);
        vEEval = ...
            safeInterpLinear( ...
                tVelocity, ...
                vE, ...
                tEval);
        vDEval = ...
            safeInterpLinear( ...
                tVelocity, ...
                vD, ...
                tEval);
        speedEval = ...
            sqrt( ...
                vNEval.^2 + ...
                vEEval.^2 + ...
                vDEval.^2);
        rateEval = ...
            safeInterpLinear( ...
                tRate, ...
                rateMagnitude, ...
                tEval);
        onGroundEval = ...
            safeInterpPrevious( ...
                tState, ...
                double(landedState == 1), ...
                tEval) > 0.5;
        stableCondition = ...
            onGroundEval & ...
            isfinite(speedEval) & ...
            isfinite(rateEval) & ...
            speedEval <= STABLE_SPEED_M_S & ...
            abs(vDEval) <= STABLE_VERTICAL_SPEED_M_S & ...
            abs(rollEval) <= STABLE_ROLL_DEG & ...
            abs(pitchEval) <= STABLE_PITCH_DEG & ...
            rateEval <= STABLE_ANGULAR_RATE_RAD_S;
        stableRelativeIndex = ...
            firstPersistentDurationReal( ...
                stableCondition, ...
                tEval, ...
                STABLE_DURATION_S);
        if ~isempty(stableRelativeIndex)
            StableDetected = ...
                true;
            StableTime_s = ...
                tEval(stableRelativeIndex);
        end
    end

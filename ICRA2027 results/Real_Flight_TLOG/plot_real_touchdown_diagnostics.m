function [detected,touchdownTime_s,diagnostics] = ...
    detectTelemetryTouchdownProxy( ...
        REAL_DATA, ...
        attemptStart_s, ...
        attemptEnd_s, ...
        F)
    detected = ...
        false;
    touchdownTime_s = ...
        NaN;
    diagnostics = ...
        struct();
    diagnostics.Attempted = ...
        true;
    diagnostics.Detected = ...
        false;
    diagnostics.Reason = ...
        "NO_VALID_TERMINAL_STABILITY_INTERVAL";
    diagnostics.VelocityAvailable = ...
        false;
    diagnostics.AltitudeAvailable = ...
        false;
    diagnostics.AttitudeAvailable = ...
        false;
    diagnostics.AngularRateAvailable = ...
        false;
    diagnostics.AngularRateInformative = ...
        false;
    diagnostics.AngularRateReason = ...
        "NOT_EVALUATED";
    diagnostics.TerminalAltitude_m = ...
        NaN;
    diagnostics.TerminalMedianSpeed_m_s = ...
        NaN;
    diagnostics.TerminalMedianVerticalSpeed_m_s = ...
        NaN;
    diagnostics.CandidateStartTime_s = ...
        NaN;
    diagnostics.SearchStartTime_s = ...
        max( ...
            attemptStart_s, ...
            attemptEnd_s - F.SearchTail_s);
    diagnostics.SearchEndTime_s = ...
        attemptEnd_s;
    if ~isfield(REAL_DATA,'State') || ...
            ~isfield(REAL_DATA.State,'VelocityNED') || ...
            isempty(REAL_DATA.State.VelocityNED)
        diagnostics.Reason = ...
            "VELOCITY_UNAVAILABLE";
        return;
    end
    VEL = ...
        REAL_DATA.State.VelocityNED;
    [tVel,vN,vE,vD] = ...
        sanitizeTimeSeries( ...
            double(VEL.Time_s), ...
            double(VEL.North_m_s), ...
            double(VEL.East_m_s), ...
            double(VEL.Down_m_s));
    if numel(tVel) < 5
        diagnostics.Reason = ...
            "INSUFFICIENT_VELOCITY_SAMPLES";
        return;
    end
    diagnostics.VelocityAvailable = ...
        true;
    searchMask = ...
        tVel >= diagnostics.SearchStartTime_s & ...
        tVel <= diagnostics.SearchEndTime_s;
    if nnz(searchMask) < 5
        diagnostics.Reason = ...
            "INSUFFICIENT_TERMINAL_VELOCITY_SUPPORT";
        return;
    end
    tEval = ...
        tVel(searchMask);
    vNEval = ...
        vN(searchMask);
    vEEval = ...
        vE(searchMask);
    vDEval = ...
        vD(searchMask);
    speedEval = ...
        sqrt( ...
            vNEval.^2 + ...
            vEEval.^2 + ...
            vDEval.^2);
    if ~isfield(REAL_DATA.State,'GlobalPosition') || ...
            isempty(REAL_DATA.State.GlobalPosition)
        diagnostics.Reason = ...
            "RELATIVE_ALTITUDE_UNAVAILABLE";
        return;
    end
    GP = ...
        REAL_DATA.State.GlobalPosition;
    [tAlt,relativeAltitude] = ...
        sanitizeTimeSeries( ...
            double(GP.Time_s), ...
            double(GP.RelativeAltitude_m));
    if numel(tAlt) < 2
        diagnostics.Reason = ...
            "INSUFFICIENT_ALTITUDE_SAMPLES";
        return;
    end
    diagnostics.AltitudeAvailable = ...
        true;
    terminalBaselineStart_s = ...
        max( ...
            attemptStart_s, ...
            attemptEnd_s - F.TerminalBaselineWindow_s);
    terminalAltitudeMask = ...
        tAlt >= terminalBaselineStart_s & ...
        tAlt <= attemptEnd_s & ...
        isfinite(relativeAltitude);
    if nnz(terminalAltitudeMask) < 2
        diagnostics.Reason = ...
            "TERMINAL_ALTITUDE_BASELINE_UNAVAILABLE";
        return;
    end
    terminalAltitude_m = ...
        median( ...
            relativeAltitude(terminalAltitudeMask), ...
            'omitnan');
    diagnostics.TerminalAltitude_m = ...
        terminalAltitude_m;
    altitudeEval = ...
        safeInterpLinear( ...
            tAlt, ...
            relativeAltitude, ...
            tEval);
    terminalVelocityMask = ...
        tEval >= terminalBaselineStart_s & ...
        tEval <= attemptEnd_s;
    if nnz(terminalVelocityMask) < 2
        diagnostics.Reason = ...
            "TERMINAL_VELOCITY_BASELINE_UNAVAILABLE";
        return;
    end
    diagnostics.TerminalMedianSpeed_m_s = ...
        median( ...
            speedEval(terminalVelocityMask), ...
            'omitnan');
    diagnostics.TerminalMedianVerticalSpeed_m_s = ...
        median( ...
            abs(vDEval(terminalVelocityMask)), ...
            'omitnan');
    if ~isfinite(diagnostics.TerminalMedianSpeed_m_s) || ...
            diagnostics.TerminalMedianSpeed_m_s > F.MaxSpeed_m_s
        diagnostics.Reason = ...
            "LOG_END_NOT_TRANSLATIONALLY_STABLE";
        return;
    end
    if ~isfinite(diagnostics.TerminalMedianVerticalSpeed_m_s) || ...
            diagnostics.TerminalMedianVerticalSpeed_m_s > ...
            F.MaxVerticalSpeed_m_s
        diagnostics.Reason = ...
            "LOG_END_NOT_VERTICALLY_STABLE";
        return;
    end
    stableCondition = ...
        isfinite(speedEval) & ...
        isfinite(vDEval) & ...
        isfinite(altitudeEval) & ...
        speedEval <= F.MaxSpeed_m_s & ...
        abs(vDEval) <= F.MaxVerticalSpeed_m_s & ...
        abs(altitudeEval-terminalAltitude_m) <= ...
        F.MaxAltitudeDeviation_m;
    if isfield(REAL_DATA.State,'Attitude') && ...
            ~isempty(REAL_DATA.State.Attitude)
        ATT = ...
            REAL_DATA.State.Attitude;
        [tAtt,rollRad,pitchRad] = ...
            sanitizeTimeSeries( ...
                double(ATT.Time_s), ...
                double(ATT.Roll_rad), ...
                double(ATT.Pitch_rad));
        if numel(tAtt) >= 2
            rollEval = ...
                rad2deg( ...
                    safeInterpLinear( ...
                        tAtt, ...
                        rollRad, ...
                        tEval));
            pitchEval = ...
                rad2deg( ...
                    safeInterpLinear( ...
                        tAtt, ...
                        pitchRad, ...
                        tEval));
            attitudeFinite = ...
                isfinite(rollEval) & ...
                isfinite(pitchEval);
            if any(attitudeFinite)
                diagnostics.AttitudeAvailable = ...
                    true;
                stableCondition = ...
                    stableCondition & ...
                    ( ...
                        ~attitudeFinite | ...
                        ( ...
                            abs(rollEval) <= F.MaxRoll_deg & ...
                            abs(pitchEval) <= F.MaxPitch_deg ...
                        ) ...
                    );
            end
        end
    end
    if isfield(REAL_DATA.State,'AngularRate') && ...
            ~isempty(REAL_DATA.State.AngularRate)
        RATE = ...
            REAL_DATA.State.AngularRate;
        [tRate,pRate,qRate,rRate] = ...
            sanitizeTimeSeries( ...
                double(RATE.Time_s), ...
                double(RATE.P_rad_s), ...
                double(RATE.Q_rad_s), ...
                double(RATE.R_rad_s));
        if numel(tRate) >= 2
            diagnostics.AngularRateAvailable = ...
                true;
            maximumAbsoluteRate_rad_s = ...
                max( ...
                    abs( ...
                        [ ...
                            pRate; ...
                            qRate; ...
                            rRate ...
                        ]), ...
                    [], ...
                    'omitnan');
            if isfinite(maximumAbsoluteRate_rad_s) && ...
                    maximumAbsoluteRate_rad_s > ...
                    F.RateZeroTolerance_rad_s
                diagnostics.AngularRateInformative = ...
                    true;
                diagnostics.AngularRateReason = ...
                    "DYNAMIC_RATE_INFORMATION_AVAILABLE";
                rateMagnitude = ...
                    sqrt( ...
                        pRate.^2 + ...
                        qRate.^2 + ...
                        rRate.^2);
                rateEval = ...
                    safeInterpLinear( ...
                        tRate, ...
                        rateMagnitude, ...
                        tEval);
                rateFinite = ...
                    isfinite(rateEval);
                if any(rateFinite)
                    stableCondition = ...
                        stableCondition & ...
                        ( ...
                            ~rateFinite | ...
                            rateEval <= F.MaxAngularRate_rad_s ...
                        );
                end
            else
                diagnostics.AngularRateInformative = ...
                    false;
                diagnostics.AngularRateReason = ...
                    "CONSTANT_ZERO_NON_INFORMATIVE";
            end
        else
            diagnostics.AngularRateReason = ...
                "INSUFFICIENT_RATE_SAMPLES";
        end
    else
        diagnostics.AngularRateReason = ...
            "ANGULAR_RATE_TELEMETRY_NOT_PRESENT";
    end
    stableStartIndex = ...
        firstPersistentDurationReal( ...
            stableCondition, ...
            tEval, ...
            F.MinimumStableDuration_s);
    if isempty(stableStartIndex)
        diagnostics.Reason = ...
            "NO_PERSISTENT_TERMINAL_STABILITY_INTERVAL";
        return;
    end
    touchdownTime_s = ...
        tEval(stableStartIndex);
    detected = ...
        true;
    diagnostics.Detected = ...
        true;
    diagnostics.CandidateStartTime_s = ...
        touchdownTime_s;
    diagnostics.Reason = ...
        "PERSISTENT_TERMINAL_STABILITY_NEAR_TERMINAL_ALTITUDE";
end
function varargout = sanitizeTimeSeries(time_s,varargin)
    time_s = ...
        double(time_s(:));
    n = ...
        numel(time_s);
    validTime = ...
        isfinite(time_s);
    time_s = ...
        time_s(validTime);
    data = ...
        cell(size(varargin));
    for i = 1:numel(varargin)
        x = ...
            varargin{i};
        x = ...
            x(:);
        if numel(x) ~= n
            error( ...
                'RealFlight:TimeSeriesSizeMismatch', ...
                'Time and data vectors must have equal lengths.');
        end
        data{i} = ...
            x(validTime);
    end
    [time_s,sortIndex] = ...
        sort(time_s);
    for i = 1:numel(data)
        data{i} = ...
            data{i}(sortIndex);
    end
    [time_s,uniqueIndex] = ...
        unique( ...
            time_s, ...
            'last');
    for i = 1:numel(data)
        data{i} = ...
            data{i}(uniqueIndex);
    end
    varargout = ...
        cell(1,1+numel(data));
    varargout{1} = ...
        time_s;
    for i = 1:numel(data)
        varargout{i+1} = ...
            data{i};
    end
end
function yq = safeInterpLinear(time_s,data,queryTime)
    [time_s,data] = ...
        sanitizeTimeSeries( ...
            time_s, ...
            data);
    if numel(time_s) < 2
        yq = ...
            NaN(size(queryTime));
        return;
    end
    yq = ...
        interp1( ...
            time_s, ...
            double(data), ...
            queryTime, ...
            'linear', ...
            NaN);
end
function yq = safeInterpPrevious(time_s,data,queryTime)
    [time_s,data] = ...
        sanitizeTimeSeries( ...
            time_s, ...
            data);
    if isempty(time_s)
        yq = ...
            NaN(size(queryTime));
        return;
    end
    if numel(time_s) == 1
        yq = ...
            NaN(size(queryTime));
        valid = ...
            queryTime >= time_s(1);
        yq(valid) = ...
            data(1);
        return;
    end
    yq = ...
        interp1( ...
            time_s, ...
            double(data), ...
            queryTime, ...
            'previous', ...
            NaN);
end
function firstIndex = firstPersistentDurationReal( ...
    condition, ...
    time_s, ...
    duration_s)
    firstIndex = ...
        [];
    condition = ...
        logical(condition(:));
    time_s = ...
        double(time_s(:));
    n = ...
        numel(condition);
    for i = 1:n
        if ~condition(i)
            continue;
        end
        j = ...
            i;
        while j < n && ...
                condition(j+1)
            j = ...
                j + 1;
        end
        if time_s(j) - ...
                time_s(i) >= duration_s
            firstIndex = ...
                i;
            return;
        end
    end
end

    campaignState.Status == "COMPLETE_EXISTING" | ...
    campaignState.Status == "COMPLETE_NEW";
failedMask = ...
    campaignState.Status == "FAILED";
completeCount = ...
    nnz(completeMask);
failedCount = ...
    nnz(failedMask);
remainingCount = ...
    totalRuns - ...
    completeCount;
fprintf('\n');

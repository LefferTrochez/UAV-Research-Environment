    'Failed this state:        %d\n', ...
    failedCount);
fprintf( ...
    'Remaining saved results:  %d\n', ...
    remainingCount);
if ~isempty(sessionDurations)
    meanDuration_s = ...
        mean( ...
            sessionDurations, ...
            'omitnan');
    if isfinite(meanDuration_s) && ...
            meanDuration_s > 0
        roughRemaining_s = ...
            meanDuration_s * ...

function CAMPAIGN = run_icra_campaign()
masterTimer = ...
    tic;
masterStartTime = ...
    datetime('now');
fprintf('\n');
fprintf('======================================================================\n');
fprintf(' ICRA 2027 FINAL SIMULATION CAMPAIGN\n');
fprintf(' QUADROTOR MULTI-FIDELITY BENCHMARK\n');
fprintf('======================================================================\n\n');
CFG = ...
    ICRA_experiment_config();
numberRuns = ...
    height(CFG.RunPlan);
if numberRuns < 1
    error( ...
        'ICRA2027:EmptyCampaign', ...
        'The official campaign contains no experiments.');
end
if numberRuns ~= 24
    error( ...
        'ICRA2027:UnexpectedFinalRunCount', ...
        ['The official final campaign must contain exactly 24 runs.\n', ...
         'Current run count: %d'], ...
        numberRuns);
end
if numel(CFG.Controllers) ~= 2 || ...
        any(string({CFG.Controllers.Status}) ~= "FINAL")
    error( ...
        'ICRA2027:ControllersNotFinal', ...
        ['Both controller definitions must exist and have Status="FINAL" ', ...
         'before the official campaign is launched.']);
end
if isequaln( ...
        CFG.Controllers(1).GainVector, ...
        CFG.Controllers(2).GainVector)
    error( ...
        'ICRA2027:ControllerGainSetsIdentical', ...
        ['C1 and C2 contain identical gain vectors.\n', ...
         'The final campaign requires the frozen, distinct C1 and C2 sets.']);
end
if string(CFG.Controllers(1).ID) ~= "C1" || ...
        string(CFG.Controllers(2).ID) ~= "C2"
    error( ...
        'ICRA2027:UnexpectedControllerIDs', ...
        'The final campaign requires controller IDs C1 and C2.');
end
if string(CFG.Simulation.ModelName) ~= "UAV_Research_Environment"
    error( ...
        'ICRA2027:UnexpectedModelName', ...
        ['The final campaign must run UAV_Research_Environment.\n', ...
         'Current model: %s'], ...
        string(CFG.Simulation.ModelName));
end
fprintf('Final-campaign preflight:   PASS\n');
fprintf('C1 source:                  %s\n',CFG.Controllers(1).Source);
fprintf('C2 source:                  %s\n',CFG.Controllers(2).Source);
fprintf('Official run count:         %d\n\n',numberRuns);
projectRoot = ...
    char(CFG.Paths.ProjectRoot);
experimentRoot = ...
    char(CFG.Paths.ExperimentRoot);
resultsRoot = ...
    char(CFG.Paths.ResultsRoot);
runsRoot = ...
    fullfile( ...
        resultsRoot, ...
        char(CFG.OutputLayout.RunsFolder));
metadataRoot = ...
    fullfile( ...
        resultsRoot, ...
        char(CFG.OutputLayout.MetadataFolder));
logsRoot = ...
    fullfile( ...
        resultsRoot, ...
        char(CFG.OutputLayout.LogsFolder));
requiredFolders = { ...
    resultsRoot, ...
    runsRoot, ...
    metadataRoot, ...
    logsRoot};
for k = 1:numel(requiredFolders)
    if ~exist(requiredFolders{k},'dir')
        mkdir(requiredFolders{k});
    end
end
addpath(projectRoot);
addpath(experimentRoot);
sessionTimestamp = ...
    datetime( ...
        'now', ...
        'Format','yyyy-MM-dd_HH-mm-ss');
sessionTimestampText = ...
    char(sessionTimestamp);
sessionID = ...
    string( ...
        sprintf( ...
            'ICRA2027_%s', ...
            sessionTimestampText));
sessionMetadataFolder = ...
    fullfile( ...
        metadataRoot, ...
        char(sessionID));
if ~exist(sessionMetadataFolder,'dir')
    mkdir(sessionMetadataFolder);
end
lockFile = ...
    fullfile( ...
        resultsRoot, ...
        'CAMPAIGN_RUNNING.lock');
localHandleExistingLock( ...
    lockFile);
lockFID = ...
    fopen( ...
        lockFile, ...
        'w');
if lockFID == -1
    error( ...
        'ICRA2027:CampaignLockCreationFailed', ...
        'Unable to create campaign lock file.');
end
fprintf( ...
    lockFID, ...
    'SessionID=%s\n', ...
    sessionID);
fprintf( ...
    lockFID, ...
    'Started=%s\n', ...
    char(masterStartTime));
fprintf( ...
    lockFID, ...
    'MATLAB=%s\n', ...
    version);
fprintf( ...
    lockFID, ...
    'ConfigurationSchema=%s\n', ...
    char(CFG.SchemaVersion));
fprintf( ...
    lockFID, ...
    'C1Source=%s\n', ...
    char(CFG.Controllers(1).Source));
fprintf( ...
    lockFID, ...
    'C2Source=%s\n', ...
    char(CFG.Controllers(2).Source));
fclose(lockFID);
lockCleanup = ...
    onCleanup( ...
        @() localRemoveLock(lockFile));
codeSnapshotFolder = ...
    fullfile( ...
        sessionMetadataFolder, ...
        'code_snapshot');
if ~exist(codeSnapshotFolder,'dir')
    mkdir(codeSnapshotFolder);
end
filesToSnapshot = { ...
    fullfile(experimentRoot,'ICRA_experiment_config.m'), ...
    fullfile(experimentRoot,'run_icra_experiment.m'), ...
    fullfile(experimentRoot,'save_icra_run.m'), ...
    fullfile(experimentRoot,'finalize_icra_campaign.m'), ...
    fullfile(experimentRoot,'run_icra_campaign.m'), ...
    fullfile(experimentRoot,'make_paper_tables.m'), ...
    fullfile(experimentRoot,'make_paper_figures.m'), ...
    fullfile(projectRoot,'initialize_project.m'), ...
    fullfile(projectRoot,'UAV_autopilot.m'), ...
    fullfile(projectRoot,'UAV_trajectories.m'), ...
    fullfile(projectRoot,'UAV_operator_protocols.m'), ...
    fullfile(projectRoot,'UAV_sensors.m'), ...
    fullfile(projectRoot,'UAV_state_estimator.m'), ...
    fullfile(projectRoot,'UAV_analytical.m'), ...
    fullfile(projectRoot,'UAV_block.m'), ...
    fullfile(projectRoot,'UAV_simscape.m'), ...
    fullfile(projectRoot,'Environment.m'), ...
    fullfile(projectRoot,'UAV_Research_Environment.slx')};
for k = 1:numel(filesToSnapshot)
    sourceFile = ...
        filesToSnapshot{k};
    if ~isfile(sourceFile)
        continue;
    end
    try
        copyfile( ...
            sourceFile, ...
            codeSnapshotFolder);
    catch ME
        warning( ...
            'ICRA2027:CodeSnapshotFailure', ...
            'Could not snapshot %s: %s', ...
            sourceFile, ...
            ME.message);
    end
end
CAMPAIGN_CONFIGURATION = ...
    CFG;
save( ...
    fullfile( ...
        sessionMetadataFolder, ...
        'campaign_configuration.mat'), ...
    'CAMPAIGN_CONFIGURATION', ...
    '-v7.3');
writetable( ...
    CFG.RunPlan, ...
    fullfile( ...
        sessionMetadataFolder, ...
        'campaign_run_plan.csv'));
RunNumber = ...
    double( ...
        CFG.RunPlan.RunNumber);
RunID = ...
    string( ...
        CFG.RunPlan.RunID);
ControllerID = ...
    string( ...
        CFG.RunPlan.ControllerID);
ControllerCode = ...
    string( ...
        CFG.RunPlan.ControllerCode);
TrajectoryID = ...
    double( ...
        CFG.RunPlan.TrajectoryID);
TrajectoryCode = ...
    string( ...
        CFG.RunPlan.TrajectoryCode);
PlantID = ...
    double( ...
        CFG.RunPlan.PlantID);
PlantCode = ...
    string( ...
        CFG.RunPlan.PlantCode);
DisturbanceID = ...
    string( ...
        CFG.RunPlan.DisturbanceID);
DisturbanceEnabled = ...
    logical( ...
        CFG.RunPlan.DisturbanceEnabled);
Status = ...
    repmat( ...
        "PENDING", ...
        numberRuns, ...
        1);
AttemptedThisSession = ...
    false(numberRuns,1);
StartedAt = ...
    repmat( ...
        NaT, ...
        numberRuns, ...
        1);
EndedAt = ...
    repmat( ...
        NaT, ...
        numberRuns, ...
        1);
ExecutionDuration_s = ...
    NaN(numberRuns,1);
SaveDuration_s = ...
    NaN(numberRuns,1);
RTF = ...
    NaN(numberRuns,1);
CTF = ...
    NaN(numberRuns,1);
MissionCompleted = ...
    false(numberRuns,1);
NavigationCompleted = ...
    false(numberRuns,1);
LandedConfirmed = ...
    false(numberRuns,1);
FailsafeAborted = ...
    false(numberRuns,1);
ErrorIdentifier = ...
    strings(numberRuns,1);
ErrorMessage = ...
    strings(numberRuns,1);
ConfigurationMatch = ...
    false(numberRuns,1);
ExistingRunFolder = ...
    false(numberRuns,1);
fprintf('\n');
fprintf('----------------------------------------------------------------------\n');
fprintf(' CHECKING EXISTING RESULTS\n');
fprintf('----------------------------------------------------------------------\n\n');
for runIndex = 1:numberRuns
    planRow = ...
        CFG.RunPlan(runIndex,:);
    currentRunFolder = ...
        fullfile( ...
            runsRoot, ...
            char(planRow.RunID));
    completeFlag = ...
        fullfile( ...
            currentRunFolder, ...
            'COMPLETE.flag');
    ExistingRunFolder(runIndex) = ...
        exist(currentRunFolder,'dir') == 7;
    if ~ExistingRunFolder(runIndex)
        Status(runIndex) = ...
            "PENDING";
        fprintf( ...
            '[%02d/%02d] %-18s  PENDING\n', ...
            runIndex, ...
            numberRuns, ...
            planRow.RunID);
        continue;
    end
    if isfile(completeFlag)
        [matchesCurrentConfiguration,reason] = ...
            localCompletedRunMatchesConfiguration( ...
                CFG, ...
                planRow, ...
                currentRunFolder);
        ConfigurationMatch(runIndex) = ...
            matchesCurrentConfiguration;
        if matchesCurrentConfiguration
            Status(runIndex) = ...
                "COMPLETE_EXISTING";
            fprintf( ...
                '[%02d/%02d] %-18s  COMPLETE / VALID\n', ...
                runIndex, ...
                numberRuns, ...
                planRow.RunID);
        else
            Status(runIndex) = ...
                "STALE_CONFIGURATION";
            fprintf( ...
                '[%02d/%02d] %-18s  STALE -> WILL RERUN\n', ...
                runIndex, ...
                numberRuns, ...
                planRow.RunID);
            fprintf( ...
                '          Reason: %s\n', ...
                reason);
        end
    else
        Status(runIndex) = ...
            "INCOMPLETE_EXISTING";
        fprintf( ...
            '[%02d/%02d] %-18s  INCOMPLETE -> WILL RERUN\n', ...
            runIndex, ...
            numberRuns, ...
            planRow.RunID);
    end
end
CAMPAIGN_STATE = ...
    table( ...
        RunNumber, ...
        RunID, ...
        ControllerID, ...
        ControllerCode, ...
        TrajectoryID, ...
        TrajectoryCode, ...
        PlantID, ...
        PlantCode, ...
        DisturbanceID, ...
        DisturbanceEnabled, ...
        Status, ...
        ExistingRunFolder, ...
        ConfigurationMatch, ...
        AttemptedThisSession, ...
        StartedAt, ...
        EndedAt, ...
        ExecutionDuration_s, ...
        SaveDuration_s, ...
        RTF, ...
        CTF, ...
        MissionCompleted, ...
        NavigationCompleted, ...
        LandedConfirmed, ...
        FailsafeAborted, ...
        ErrorIdentifier, ...
        ErrorMessage);
stateMATFile = ...
    fullfile( ...
        metadataRoot, ...
        'Campaign_State.mat');
stateCSVFile = ...
    fullfile( ...
        metadataRoot, ...
        'Campaign_State.csv');
sessionStateMATFile = ...
    fullfile( ...
        sessionMetadataFolder, ...
        'Campaign_State.mat');
sessionStateCSVFile = ...
    fullfile( ...
        sessionMetadataFolder, ...
        'Campaign_State.csv');
localSaveCampaignState( ...
    CAMPAIGN_STATE, ...
    stateMATFile, ...
    stateCSVFile, ...
    sessionStateMATFile, ...
    sessionStateCSVFile);
numberExistingValid = ...
    nnz( ...
        CAMPAIGN_STATE.Status == ...
        "COMPLETE_EXISTING");
numberPendingExecution = ...
    numberRuns - ...
    numberExistingValid;
fprintf('\n');
fprintf('======================================================================\n');
fprintf(' CAMPAIGN EXECUTION PLAN\n');
fprintf('======================================================================\n');
fprintf( ...
    'Total official runs:       %d\n', ...
    numberRuns);
fprintf( ...
    'Already saved/config-valid: %d\n', ...
    numberExistingValid);
fprintf( ...
    'Runs to execute:           %d\n', ...
    numberPendingExecution);
fprintf( ...
    'Resume enabled:            %s\n', ...
    localYesNo( ...
        CFG.Resume.Enabled));
fprintf( ...
    'Continue after failure:    %s\n', ...
    localYesNo( ...
        CFG.Simulation.ContinueAfterFailedRun));
fprintf('======================================================================\n\n');
sessionRunsAttempted = ...
    0;
sessionRunsCompleted = ...
    0;
sessionRunsFailed = ...
    0;
sessionRunDurations_s = ...
    zeros(0,1);
for runIndex = 1:numberRuns
    planRow = ...
        CFG.RunPlan(runIndex,:);
    currentStatus = ...
        CAMPAIGN_STATE.Status(runIndex);
    currentRunID = ...
        string(planRow.RunID);
    currentRunFolder = ...
        fullfile( ...
            runsRoot, ...
            char(currentRunID));
    if currentStatus == "COMPLETE_EXISTING" && ...
            CFG.Resume.Enabled && ...
            CFG.Resume.SkipCompletedRuns && ...
            ~CFG.Resume.OverwriteCompletedRuns
        fprintf('\n');
        fprintf('----------------------------------------------------------------------\n');
        fprintf( ...
            ' SKIP %02d/%02d — %s\n', ...
            runIndex, ...
            numberRuns, ...
            currentRunID);
        fprintf(' Existing result matches current configuration.\n');
        fprintf('----------------------------------------------------------------------\n');
        continue;
    end
    if currentStatus == "INCOMPLETE_EXISTING" && ...
            ~CFG.Resume.RerunFailedRuns
        fprintf('\n');
        fprintf( ...
            'Skipping incomplete run %s because RerunFailedRuns=false.\n', ...
            currentRunID);
        CAMPAIGN_STATE.Status(runIndex) = ...
            "SKIPPED_INCOMPLETE";
        localSaveCampaignState( ...
            CAMPAIGN_STATE, ...
            stateMATFile, ...
            stateCSVFile, ...
            sessionStateMATFile, ...
            sessionStateCSVFile);
        continue;
    end
    fprintf('\n');
    fprintf('\n');
    fprintf('######################################################################\n');
    fprintf('######################################################################\n');
    fprintf( ...
        ' OFFICIAL RUN %02d / %02d\n', ...
        runIndex, ...
        numberRuns);
    fprintf( ...
        ' %s\n', ...
        currentRunID);
    fprintf('######################################################################\n');
    fprintf('######################################################################\n\n');
    sessionRunsAttempted = ...
        sessionRunsAttempted + 1;
    CAMPAIGN_STATE.AttemptedThisSession(runIndex) = ...
        true;
    CAMPAIGN_STATE.StartedAt(runIndex) = ...
        datetime('now');
    CAMPAIGN_STATE.Status(runIndex) = ...
        "RUNNING";
    CAMPAIGN_STATE.ErrorIdentifier(runIndex) = ...
        "";
    CAMPAIGN_STATE.ErrorMessage(runIndex) = ...
        "";
    localSaveCampaignState( ...
        CAMPAIGN_STATE, ...
        stateMATFile, ...
        stateCSVFile, ...
        sessionStateMATFile, ...
        sessionStateCSVFile);
    runMasterTimer = ...
        tic;
    try
        RUN = ...
            run_icra_experiment( ...
                CFG, ...
                planRow);
        oldResultNeedsArchive = ...
            exist(currentRunFolder,'dir') == 7 && ...
            isfile( ...
                fullfile( ...
                    currentRunFolder, ...
                    'COMPLETE.flag'));
        if oldResultNeedsArchive
            archiveReason = ...
                "OFFICIAL_RERUN";
            if currentStatus == "STALE_CONFIGURATION"
                archiveReason = ...
                    "STALE_CONFIGURATION";
            elseif CFG.Resume.OverwriteCompletedRuns
                archiveReason = ...
                    "FORCED_OVERWRITE";
            end
            archivedFolder = ...
                localArchiveExistingRun( ...
                    currentRunFolder, ...
                    archiveReason);
            fprintf('\n');
            fprintf( ...
                'Previous completed result archived:\n%s\n', ...
                archivedFolder);
        end
        SAVED = ...
            save_icra_run( ...
                CFG, ...
                RUN);
        CAMPAIGN_STATE.EndedAt(runIndex) = ...
            datetime('now');
        CAMPAIGN_STATE.ExecutionDuration_s(runIndex) = ...
            toc(runMasterTimer);
        CAMPAIGN_STATE.SaveDuration_s(runIndex) = ...
            SAVED.SaveDuration_s;
        CAMPAIGN_STATE.RTF(runIndex) = ...
            RUN.Timing.RealTimeFactor_RTF;
        CAMPAIGN_STATE.CTF(runIndex) = ...
            RUN.Timing.ComputationalTimeFactor_CTF;
        if isfield(SAVED,'MissionOutcome')
            outcome = ...
                SAVED.MissionOutcome;
            if isfield(outcome,'Completed')
                CAMPAIGN_STATE.MissionCompleted(runIndex) = ...
                    logical(outcome.Completed);
            end
            if isfield(outcome,'NavigationCompleted')
                CAMPAIGN_STATE.NavigationCompleted(runIndex) = ...
                    logical(outcome.NavigationCompleted);
            end
            if isfield(outcome,'LandedConfirmed')
                CAMPAIGN_STATE.LandedConfirmed(runIndex) = ...
                    logical(outcome.LandedConfirmed);
            end
            if isfield(outcome,'FailsafeAborted')
                CAMPAIGN_STATE.FailsafeAborted(runIndex) = ...
                    logical(outcome.FailsafeAborted);
            end
        end
        CAMPAIGN_STATE.Status(runIndex) = ...
            "COMPLETE_NEW";
        CAMPAIGN_STATE.ConfigurationMatch(runIndex) = ...
            true;
        sessionRunsCompleted = ...
            sessionRunsCompleted + 1;
        sessionRunDurations_s(end+1,1) = ...
            CAMPAIGN_STATE.ExecutionDuration_s(runIndex); %#ok<AGROW>
        fprintf('\n');
        fprintf('**********************************************************************\n');
        fprintf( ...
            ' RUN %02d/%02d SAVED\n', ...
            runIndex, ...
            numberRuns);
        fprintf( ...
            ' Run ID:       %s\n', ...
            currentRunID);
        fprintf( ...
            ' Total time:   %.2f s\n', ...
            CAMPAIGN_STATE.ExecutionDuration_s(runIndex));
        fprintf( ...
            ' RTF:          %.4f\n', ...
            CAMPAIGN_STATE.RTF(runIndex));
        fprintf( ...
            ' Mission:      %s\n', ...
            localPassFail( ...
                CAMPAIGN_STATE.MissionCompleted(runIndex)));
        fprintf( ...
            ' Failsafe:     %s\n', ...
            localYesNo( ...
                CAMPAIGN_STATE.FailsafeAborted(runIndex)));
        fprintf('**********************************************************************\n');
    catch ME
        CAMPAIGN_STATE.EndedAt(runIndex) = ...
            datetime('now');
        CAMPAIGN_STATE.ExecutionDuration_s(runIndex) = ...
            toc(runMasterTimer);
        CAMPAIGN_STATE.Status(runIndex) = ...
            "FAILED";
        CAMPAIGN_STATE.ErrorIdentifier(runIndex) = ...
            string(ME.identifier);
        CAMPAIGN_STATE.ErrorMessage(runIndex) = ...
            string(ME.message);
        sessionRunsFailed = ...
            sessionRunsFailed + 1;
        localWriteFailureLog( ...
            logsRoot, ...
            sessionID, ...
            planRow, ...
            ME);
        fprintf('\n');
        fprintf('!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n');
        fprintf( ...
            ' RUN %02d/%02d FAILED\n', ...
            runIndex, ...
            numberRuns);
        fprintf( ...
            ' Run ID: %s\n', ...
            currentRunID);
        fprintf( ...
            ' Error:  %s\n', ...
            ME.message);
        fprintf('!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n');
        localSaveCampaignState( ...
            CAMPAIGN_STATE, ...
            stateMATFile, ...
            stateCSVFile, ...
            sessionStateMATFile, ...
            sessionStateCSVFile);
        if localIsUserInterrupt(ME)
            fprintf('\n');
            fprintf('Campaign interrupted by user.\n');
            fprintf('All completed runs and campaign state are preserved.\n\n');
            rethrow(ME);
        end
        if ~CFG.Simulation.ContinueAfterFailedRun
            fprintf('\n');
            fprintf('Campaign configured to stop after an experiment failure.\n');
            rethrow(ME);
        end
        fprintf('\n');
        fprintf('Continuing to next official experiment...\n');
    end
    localSaveCampaignState( ...
        CAMPAIGN_STATE, ...
        stateMATFile, ...
        stateCSVFile, ...
        sessionStateMATFile, ...
        sessionStateCSVFile);
    localDisplayProgress( ...
        CAMPAIGN_STATE, ...
        sessionRunDurations_s, ...
        runIndex, ...
        numberRuns);
end
localSaveCampaignState( ...
    CAMPAIGN_STATE, ...
    stateMATFile, ...
    stateCSVFile, ...
    sessionStateMATFile, ...
    sessionStateCSVFile);
fprintf('\n');
fprintf('\n');
fprintf('======================================================================\n');
fprintf(' ALL PLANNED EXECUTIONS PROCESSED\n');
fprintf(' STARTING FINAL CONSOLIDATION\n');
fprintf('======================================================================\n\n');
finalizationSuccess = ...
    false;
finalizationError = ...
    "";
FINAL = ...
    struct();
try
    FINAL = ...
        finalize_icra_campaign( ...
            CFG);
    finalizationSuccess = ...
        true;
catch ME
    finalizationError = ...
        string(ME.message);
    warning( ...
        'ICRA2027:FinalizationFailure', ...
        ['Simulation results are preserved, but final campaign ', ...
         'consolidation failed:\n%s'], ...
        ME.message);
end
CAMPAIGN = ...
    struct();
CAMPAIGN.SchemaVersion = ...
    CFG.SchemaVersion;
CAMPAIGN.SessionID = ...
    sessionID;
CAMPAIGN.StartTime = ...
    masterStartTime;
CAMPAIGN.EndTime = ...
    datetime('now');
CAMPAIGN.Duration_s = ...
    toc(masterTimer);
CAMPAIGN.Configuration = ...
    CFG;
CAMPAIGN.State = ...
    CAMPAIGN_STATE;
CAMPAIGN.RunsExpected = ...
    numberRuns;
CAMPAIGN.RunsAttemptedThisSession = ...
    sessionRunsAttempted;
CAMPAIGN.RunsCompletedThisSession = ...
    sessionRunsCompleted;
CAMPAIGN.RunsFailedThisSession = ...
    sessionRunsFailed;
CAMPAIGN.TotalCompleteResults = ...
    nnz( ...
        CAMPAIGN_STATE.Status == "COMPLETE_EXISTING" | ...
        CAMPAIGN_STATE.Status == "COMPLETE_NEW");
CAMPAIGN.TotalFailedResults = ...
    nnz( ...
        CAMPAIGN_STATE.Status == "FAILED");
savedResultMask = ...
    CAMPAIGN_STATE.Status == "COMPLETE_EXISTING" | ...
    CAMPAIGN_STATE.Status == "COMPLETE_NEW";
CAMPAIGN.TotalMissionSuccesses = ...
    nnz( ...
        savedResultMask & ...
        CAMPAIGN_STATE.MissionCompleted);
CAMPAIGN.TotalMissionFailures = ...
    nnz( ...
        savedResultMask & ...
        ~CAMPAIGN_STATE.MissionCompleted);
CAMPAIGN.FinalizationSuccess = ...
    finalizationSuccess;
CAMPAIGN.FinalizationError = ...
    finalizationError;
CAMPAIGN.Final = ...
    FINAL;
CAMPAIGN.ResultsRoot = ...
    string(resultsRoot);
CAMPAIGN.SessionMetadataFolder = ...
    string(sessionMetadataFolder);
sessionMasterFile = ...
    fullfile( ...
        sessionMetadataFolder, ...
        'Campaign_Master_Result.mat');
latestMasterFile = ...
    fullfile( ...
        metadataRoot, ...
        'Campaign_Master_Result.mat');
save( ...
    sessionMasterFile, ...
    'CAMPAIGN', ...
    '-v7.3');
save( ...
    latestMasterFile, ...
    'CAMPAIGN', ...
    '-v7.3');
SessionID = ...
    sessionID;
StartTime = ...
    masterStartTime;
EndTime = ...
    CAMPAIGN.EndTime;
Duration_s = ...
    CAMPAIGN.Duration_s;
RunsExpected = ...
    numberRuns;
RunsAttempted = ...
    sessionRunsAttempted;
RunsCompleted = ...
    sessionRunsCompleted;
RunsFailed = ...
    sessionRunsFailed;
TotalCompleteResults = ...
    CAMPAIGN.TotalCompleteResults;
FinalizationSuccess = ...
    finalizationSuccess;
CAMPAIGN_MASTER_SUMMARY = ...
    table( ...
        SessionID, ...
        StartTime, ...
        EndTime, ...
        Duration_s, ...
        RunsExpected, ...
        RunsAttempted, ...
        RunsCompleted, ...
        RunsFailed, ...
        TotalCompleteResults, ...
        FinalizationSuccess);
writetable( ...
    CAMPAIGN_MASTER_SUMMARY, ...
    fullfile( ...
        sessionMetadataFolder, ...
        'Campaign_Master_Summary.csv'));
writetable( ...
    CAMPAIGN_MASTER_SUMMARY, ...
    fullfile( ...
        metadataRoot, ...
        'Campaign_Master_Summary.csv'));
assignin( ...
    'base', ...
    'ICRA_CAMPAIGN_RESULT', ...
    CAMPAIGN);
assignin( ...
    'base', ...
    'ICRA_CAMPAIGN_CONFIGURATION', ...
    CFG);
if finalizationSuccess
    assignin( ...
        'base', ...
        'ICRA_FINAL_RESULTS', ...
        FINAL);
end
fprintf('\n');
fprintf('\n');
fprintf('######################################################################\n');
fprintf('######################################################################\n');
fprintf(' ICRA 2027 FINAL CAMPAIGN FINISHED\n');
fprintf('######################################################################\n');
fprintf('######################################################################\n\n');
fprintf( ...
    'Official experiments:        %d\n', ...
    numberRuns);
fprintf( ...
    'Attempted this session:      %d\n', ...
    sessionRunsAttempted);
fprintf( ...
    'Completed this session:      %d\n', ...
    sessionRunsCompleted);
fprintf( ...
    'Failed this session:         %d\n', ...
    sessionRunsFailed);
fprintf( ...

function [matches,reason] = localCompletedRunMatchesConfiguration( ...
    CFG, ...
    planRow, ...
    runFolder)
matches = ...
    false;
reason = ...
    "UNKNOWN";
manifestFile = ...
    fullfile( ...
        runFolder, ...
        'metadata', ...
        'run_manifest.mat');
controllerFile = ...
    fullfile( ...
        runFolder, ...
        'metadata', ...
        'controller_gains.mat');
if ~isfile(manifestFile)
    reason = ...
        "RUN_MANIFEST_MISSING";
    return;
end
if ~isfile(controllerFile)
    reason = ...
        "CONTROLLER_GAIN_RECORD_MISSING";
    return;
end
try
    manifestData = ...
        load( ...
            manifestFile, ...
            'RUN_MANIFEST');
    if ~isfield(manifestData,'RUN_MANIFEST')
        reason = ...
            "RUN_MANIFEST_VARIABLE_MISSING";
        return;
    end
    M = ...
        manifestData.RUN_MANIFEST;
catch ME
    reason = ...
        "RUN_MANIFEST_READ_ERROR: " + ...
        string(ME.message);
    return;
end
if ~isfield(M,'ConfigurationSchemaVersion') || ...
        string(M.ConfigurationSchemaVersion) ~= string(CFG.SchemaVersion)
    reason = ...
        "CONFIGURATION_SCHEMA_CHANGED";
    return;
end
comparisons = [ ...
    localStringFieldEquals(M,'ControllerID',string(planRow.ControllerID)), ...
    localNumericFieldEquals(M,'PlantID',double(planRow.PlantID)), ...
    localNumericFieldEquals(M,'TrajectoryID',double(planRow.TrajectoryID)), ...
    localStringFieldEquals(M,'DisturbanceID',string(planRow.DisturbanceID)), ...
    localLogicalFieldEquals(M,'DisturbanceEnabled',logical(planRow.DisturbanceEnabled)), ...
    localStringFieldEquals(M,'DisturbanceProfileID',string(planRow.DisturbanceProfileID)), ...
    localNumericFieldEquals(M,'DisturbanceSeed',double(planRow.DisturbanceSeed))];
if ~all(comparisons)
    reason = ...
        "EXPERIMENT_CONFIGURATION_CHANGED";
    return;
end
controllerIndex = ...
    double(planRow.ControllerIndex);
currentController = ...
    CFG.Controllers(controllerIndex);
if isfield(M,'ControllerSource')
    if string(M.ControllerSource) ~= ...
            string(currentController.Source)
        reason = ...
            "CONTROLLER_SOURCE_CHANGED";
        return;
    end
end
try
    gainData = ...
        load( ...
            controllerFile, ...
            'CONTROLLER_GAIN_VECTOR');
    if ~isfield( ...
            gainData, ...
            'CONTROLLER_GAIN_VECTOR')
        reason = ...
            "CONTROLLER_GAIN_VECTOR_MISSING";
        return;
    end
    savedGains = ...
        double( ...
            gainData.CONTROLLER_GAIN_VECTOR(:));
    currentGains = ...
        double( ...
            currentController.GainVector(:));
    if numel(savedGains) ~= ...
            numel(currentGains)
        reason = ...
            "CONTROLLER_GAIN_COUNT_CHANGED";
        return;
    end
    tolerance = ...
        1.0e-12;
    difference = ...
        abs( ...
            savedGains - ...
            currentGains);
    scale = ...
        max( ...
            1.0, ...
            abs(currentGains));
    if any( ...
            difference > ...
            tolerance .* scale)
        reason = ...
            "CONTROLLER_GAINS_CHANGED";
        return;
    end
catch ME
    reason = ...
        "CONTROLLER_GAIN_READ_ERROR: " + ...
        string(ME.message);
    return;
end
matches = ...
    true;
reason = ...
    "MATCH";
end
function match = localStringFieldEquals(S,fieldName,expected)
match = ...
    false;
if ~isfield(S,fieldName)
    return;
end
try
    match = ...
        string(S.(fieldName)) == ...
        string(expected);
catch
    match = ...
        false;
end
end
function match = localNumericFieldEquals(S,fieldName,expected)
match = ...
    false;
if ~isfield(S,fieldName)
    return;
end
try
    actual = ...
        double(S.(fieldName));
    expected = ...
        double(expected);
    if ~isscalar(actual) || ...
            ~isscalar(expected)
        return;
    end
    if isnan(actual) && ...
            isnan(expected)
        match = ...
            true;
        return;
    end
    tolerance = ...
        1.0e-12;
    match = ...
        abs(actual-expected) <= ...
        tolerance * ...
        max( ...
            1, ...
            abs(expected));
catch
    match = ...
        false;
end
end
function match = localLogicalFieldEquals(S,fieldName,expected)
match = ...
    false;
if ~isfield(S,fieldName)
    return;
end
try
    match = ...
        logical(S.(fieldName)) == ...
        logical(expected);
catch
    match = ...
        false;
end
end
function archiveFolder = localArchiveExistingRun( ...
    runFolder, ...
    archiveReason)
if ~exist(runFolder,'dir')
    archiveFolder = ...
        "";
    return;
end
timestamp = ...
    char( ...
        datetime( ...
            'now', ...
            'Format','yyyy-MM-dd_HH-mm-ss'));
archiveFolder = ...
    sprintf( ...
        '%s_ARCHIVE_%s_%s', ...
        runFolder, ...
        char(archiveReason), ...
        timestamp);
suffix = ...
    1;
baseArchiveFolder = ...
    archiveFolder;
while exist(archiveFolder,'dir')
    archiveFolder = ...
        sprintf( ...
            '%s_%02d', ...
            baseArchiveFolder, ...
            suffix);
    suffix = ...
        suffix + 1;
end
[success,message] = ...
    movefile( ...
        runFolder, ...
        archiveFolder);
if ~success
    error( ...
        'ICRA2027:RunArchiveFailure', ...
        ['Unable to archive previous run folder.\n\n', ...
         'Source:\n%s\n\n', ...
         'Destination:\n%s\n\n', ...
         'MATLAB message:\n%s'], ...
        runFolder, ...
        archiveFolder, ...
        message);
end
archiveFolder = ...
    string(archiveFolder);
end

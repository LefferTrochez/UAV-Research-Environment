end
function localHandleExistingLock(lockFile)
if ~isfile(lockFile)
    return;
end
fileInfo = ...
    dir(lockFile);
if isempty(fileInfo)
    return;
end
fileAgeHours = ...
    hours( ...
        datetime('now') - ...
        datetime(fileInfo.datenum,'ConvertFrom','datenum'));
if fileAgeHours >= 12
    staleName = ...
        sprintf( ...
            '%s_STALE_%s', ...
            lockFile, ...
            char( ...
                datetime( ...
                    'now', ...
                    'Format','yyyy-MM-dd_HH-mm-ss')));
    movefile( ...
        lockFile, ...
        staleName);
    warning( ...
        'ICRA2027:StaleCampaignLock', ...
        ['A stale campaign lock was detected and archived.\n', ...
         'Previous lock:\n%s'], ...
        staleName);
    return;
end
error( ...
    'ICRA2027:CampaignAlreadyRunning', ...
    ['CAMPAIGN_RUNNING.lock already exists.\n\n', ...
     'Another official campaign may currently be running.\n\n', ...
     'Lock file:\n%s\n\n', ...
     'Do not execute two campaigns simultaneously.'], ...
    lockFile);
end
function localRemoveLock(lockFile)

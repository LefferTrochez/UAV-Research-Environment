                localScalarSeconds( ...
                    localGetMember( ...
                        timingInfo, ...
                        'ExecutionElapsedWallTime'));
            timing.TerminationElapsedWallTime_s = ...
                localScalarSeconds( ...
                    localGetMember( ...
                        timingInfo, ...
                        'TerminationElapsedWallTime'));
            timing.TotalElapsedWallTime_s = ...
                localScalarSeconds( ...
                    localGetMember( ...
                        timingInfo, ...
                        'TotalElapsedWallTime'));
        end
    catch
    end
end
if ~isfinite(timing.SimulatedDuration_s) || ...
        timing.SimulatedDuration_s <= 0
    runRecordFile = ...
        fullfile( ...
            runFolder, ...
            'metadata', ...
            'run_record.mat');
    if isfile(runRecordFile)
        try
            loadedRun = ...
                load( ...
                    runRecordFile, ...
                    'RUN_RECORD');
            if isfield(loadedRun,'RUN_RECORD') && ...
                    isfield(loadedRun.RUN_RECORD,'Configuration') && ...
                    isfield(loadedRun.RUN_RECORD.Configuration,'StopTime_s')
                candidate = ...
                    localScalarSeconds( ...
                        loadedRun.RUN_RECORD.Configuration.StopTime_s);
                if isfinite(candidate) && ...
                        candidate > 0
                    timing.SimulatedDuration_s = ...
                        candidate;
                    timing.TimingSource = ...
                        "RUN_RECORD.Configuration.StopTime_s";
                end
            end
        catch
        end
    end
end
if ~isfinite(timing.SimulatedDuration_s) || ...
        timing.SimulatedDuration_s <= 0
    canonicalFile = ...
        fullfile( ...
            runFolder, ...
            'processed', ...
            'canonical_signals.mat');
    if isfile(canonicalFile)
        try
            loadedCanonical = ...
                load( ...
                    canonicalFile, ...
                    'CANONICAL');
            if isfield(loadedCanonical,'CANONICAL')
                candidate = ...
                    localCanonicalTimeExtent( ...
                        loadedCanonical.CANONICAL);
                if isfinite(candidate) && ...
                        candidate > 0
                    timing.SimulatedDuration_s = ...
                        candidate;
                    timing.TimingSource = ...
                        "CANONICAL native-time extent";
                end
            end
        catch
        end
    end
end
if isfile(legacyMetricsFile)
    try
        loadedMetrics = ...
            load( ...
                legacyMetricsFile, ...
                'CAMPAIGN_COMPUTATIONAL_COST');
        if isfield( ...
                loadedMetrics, ...
                'CAMPAIGN_COMPUTATIONAL_COST')
            oldCost = ...
                loadedMetrics.CAMPAIGN_COMPUTATIONAL_COST;
            if istable(oldCost) && ...
                    ~isempty(oldCost)
                if (~isfinite(timing.SimulatedDuration_s) || ...
                        timing.SimulatedDuration_s <= 0) && ...
                        ismember( ...
                            'SimulatedRunDuration_s', ...
                            oldCost.Properties.VariableNames)
                    candidate = ...
                        localScalarSeconds( ...
                            oldCost.SimulatedRunDuration_s(1));
                    if isfinite(candidate) && ...
                            candidate > 0
                        timing.SimulatedDuration_s = ...
                            candidate;
                        timing.TimingSource = ...
                            "LEGACY SimulatedRunDuration_s fallback";
                    end
                end
                if (~isfinite(timing.ExecutionElapsedWallTime_s) || ...
                        timing.ExecutionElapsedWallTime_s <= 0) && ...
                        ismember( ...
                            'ExecutionElapsedWallTime_s', ...
                            oldCost.Properties.VariableNames)
                    timing.ExecutionElapsedWallTime_s = ...
                        localScalarSeconds( ...
                            oldCost.ExecutionElapsedWallTime_s(1));
                end
                if ~isfinite(timing.InitializationElapsedWallTime_s) && ...
                        ismember( ...
                            'InitializationElapsedWallTime_s', ...
                            oldCost.Properties.VariableNames)
                    timing.InitializationElapsedWallTime_s = ...
                        localScalarSeconds( ...
                            oldCost.InitializationElapsedWallTime_s(1));
                end
                if ~isfinite(timing.TerminationElapsedWallTime_s) && ...
                        ismember( ...
                            'TerminationElapsedWallTime_s', ...
                            oldCost.Properties.VariableNames)
                    timing.TerminationElapsedWallTime_s = ...
                        localScalarSeconds( ...
                            oldCost.TerminationElapsedWallTime_s(1));
                end
                if ~isfinite(timing.TotalElapsedWallTime_s) && ...
                        ismember( ...
                            'TotalElapsedWallTime_s', ...
                            oldCost.Properties.VariableNames)
                    timing.TotalElapsedWallTime_s = ...
                        localScalarSeconds( ...
                            oldCost.TotalElapsedWallTime_s(1));
                end
            end
        end
    catch
    end
end
if isfinite(timing.SimulatedDuration_s) && ...
        timing.SimulatedDuration_s > 0 && ...
        isfinite(timing.ExecutionElapsedWallTime_s) && ...
        timing.ExecutionElapsedWallTime_s > 0
    timing.RTF = ...
        timing.SimulatedDuration_s / ...
        timing.ExecutionElapsedWallTime_s;
    timing.CTF = ...
        timing.ExecutionElapsedWallTime_s / ...
        timing.SimulatedDuration_s;
    timing.Valid = ...
        isfinite(timing.RTF) && ...
        timing.RTF > 0 && ...
        isfinite(timing.CTF) && ...
        timing.CTF > 0;
end
end
function value = localGetMember(S,memberName)
value = ...
    [];
if isempty(S)
    return;
end
try
    if isstruct(S)
        if isfield(S,memberName)
            value = ...
                S.(memberName);
        end
        return;
    end
    if isobject(S) && ...
            isprop(S,memberName)
        value = ...
            S.(memberName);
        return;
    end
catch
    value = ...
        [];
end
end
function value_s = localScalarSeconds(value)
value_s = ...
    NaN;
if isempty(value)
    return;
end
try
    if isduration(value)
        candidate = ...
            seconds(value);
    elseif isnumeric(value) || ...
            islogical(value)
        candidate = ...
            double(value);
    elseif ischar(value) || ...
            isstring(value)
        candidate = ...
            str2double( ...
                string(value));
    else
        candidate = ...
            double(value);
    end
    candidate = ...
        double(candidate);
    if isscalar(candidate) && ...
            isfinite(candidate)
        value_s = ...
            candidate;
    end
catch
    value_s = ...
        NaN;
end
end
function duration_s = localCanonicalTimeExtent(C)
duration_s = ...
    NaN;
candidateTime = ...
    zeros(0,1);
if isfield(C,'Time') && ...
        isstruct(C.Time) && ...
        isfield(C.Time,'Time_s') && ...
        ~isempty(C.Time.Time_s)
    candidateTime = ...
        double(C.Time.Time_s(:));
end
if isempty(candidateTime)
    candidateSignals = { ...
        {'True','Position'}, ...
        {'Estimated','Position'}, ...
        {'Reference','Position'}};
    for k = 1:numel(candidateSignals)
        path = ...
            candidateSignals{k};
        try
            S = ...
                C.(path{1}).(path{2});
            if isstruct(S) && ...
                    isfield(S,'Time_s') && ...
                    ~isempty(S.Time_s)
                candidateTime = ...
                    double(S.Time_s(:));
                break;
            end
        catch
        end
    end
end
candidateTime = ...
    candidateTime( ...
        isfinite(candidateTime));
if numel(candidateTime) >= 2
    duration_s = ...
        max(candidateTime) - ...
        min(candidateTime);
elseif numel(candidateTime) == 1
    duration_s = ...
        candidateTime(1);
end
end

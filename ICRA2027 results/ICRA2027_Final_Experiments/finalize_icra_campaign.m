for metricIndex = 1:size(metricDefinitions,1)
    metricField = ...
        metricDefinitions{metricIndex,1};
    outputFileName = ...
        metricDefinitions{metricIndex,2};
    MetricName(metricIndex) = ...
        string(metricField);
    combinedTable = ...
        table();
    runsUsed = ...
        0;
    if strcmp(metricField,'ComputationalCost')
        combinedTable = ...
            AUTHORITATIVE_COMPUTATIONAL_COST;
        runsUsed = ...
            nnz( ...
                CAMPAIGN_RUN_INDEX.RunStatus == "COMPLETE");
    else
    for runIndex = 1:numberRuns
        if CAMPAIGN_RUN_INDEX.RunStatus(runIndex) ~= "COMPLETE"
            continue;
        end
        currentMetricsFile = ...
            char( ...
                CAMPAIGN_RUN_INDEX.MetricsFile(runIndex));
        if ~isfile(currentMetricsFile)
            continue;
        end
        try
            loadedData = ...
                load( ...
                    currentMetricsFile, ...
                    'METRICS');
            if ~isfield(loadedData,'METRICS')
                continue;
            end
            METRICS = ...
                loadedData.METRICS;
            if ~isfield(METRICS,metricField)
                continue;
            end
            currentTable = ...
                METRICS.(metricField);
            if ~istable(currentTable)
                continue;
            end
            if isempty(currentTable)
                continue;
            end
            currentTable = ...
                localAddRunIdentifiers( ...
                    currentTable, ...
                    CAMPAIGN_RUN_INDEX(runIndex,:));
            if isempty(combinedTable)
                combinedTable = ...
                    currentTable;
                runsUsed = ...
                    runsUsed + 1;
            else
                try
                    combinedTable = ...
                        [ ...
                            combinedTable; ...
                            currentTable ...
                        ]; %#ok<AGROW>
                    runsUsed = ...
                        runsUsed + 1;
                catch ME
                    warning( ...
                        'ICRA2027:MetricSchemaMismatch', ...
                        ['Metric table "%s" from run %s could not be ', ...
                         'concatenated because its schema differs.\n%s'], ...
                        metricField, ...
                        CAMPAIGN_RUN_INDEX.RunID(runIndex), ...
                        ME.message);
                end
            end
        catch ME
            warning( ...
                'ICRA2027:MetricReadFailure', ...
                'Could not read %s from %s: %s', ...
                metricField, ...
                CAMPAIGN_RUN_INDEX.RunID(runIndex), ...
                ME.message);
        end
    end
    end
    MetricRunsFound(metricIndex) = ...
        runsUsed;
    MetricRowsFound(metricIndex) = ...
        height(combinedTable);
    ALL_METRICS.(metricField) = ...
        combinedTable;
    if ~isempty(combinedTable)
        writetable( ...
            combinedTable, ...
            fullfile( ...
                tablesRoot, ...
                outputFileName));
        fprintf( ...
            '%-30s : %4d rows from %2d runs\n', ...
            metricField, ...
            height(combinedTable), ...
            runsUsed);
    else
        fprintf( ...
            '%-30s : NOT AVAILABLE\n', ...
            metricField);
    end
end

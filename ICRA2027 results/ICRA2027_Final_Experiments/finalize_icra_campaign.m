function valid = localValidThreeAxisSignal(signal)
valid = ...
    false;
if ~isstruct(signal)
    return;
end
if ~isfield(signal,'Available') || ...
        ~logical(signal.Available)
    return;
end
if ~isfield(signal,'Time_s') || ...
        ~isfield(signal,'Data')
    return;
end
if isempty(signal.Time_s) || ...
        isempty(signal.Data)
    return;
end
if size(signal.Data,2) < 3
    return;
end
if size(signal.Data,1) ~= numel(signal.Time_s)
    return;
end
valid = ...
    true;
end
function localShadeDisturbanceWindows(ax,datasets)
windows = ...
    zeros(0,2);
for k = 1:numel(datasets)
    C = ...
        datasets(k).Canonical;
    if ~isfield(C,'Disturbance')
        continue;
    end
    D = ...
        C.Disturbance;
    if isfield(D,'Windows_s') && ...
            isnumeric(D.Windows_s) && ...
            size(D.Windows_s,2) == 2
        candidate = ...
            double(D.Windows_s);
        validRows = ...
            all(isfinite(candidate),2) & ...
            candidate(:,2) > candidate(:,1);
        candidate = ...
            candidate(validRows,:);
        if ~isempty(candidate)
            windows = ...
                candidate;
            break;
        end
    end
end
if isempty(windows)
    return;
end
currentYLim = ...
    ylim(ax);
holdState = ...
    ishold(ax);
hold(ax,'on');
for k = 1:size(windows,1)
    x0 = ...
        windows(k,1);
    x1 = ...
        windows(k,2);
    patch( ...
        ax, ...
        [x0 x1 x1 x0], ...
        [ ...
            currentYLim(1), ...
            currentYLim(1), ...
            currentYLim(2), ...
            currentYLim(2) ...
        ], ...
        [0.85 0.85 0.85], ...
        'FaceAlpha',0.25, ...
        'EdgeColor','none', ...
        'HandleVisibility','off');
end
children = ...
    ax.Children;
if numel(children) > 1
    try
        uistack( ...
            children( ...
                ~arrayfun( ...
                    @(x) isa(x,'matlab.graphics.primitive.Patch'), ...
                    children)), ...
            'top');
    catch
    end
end
ylim( ...
    ax, ...
    currentYLim);
if ~holdState
    hold(ax,'off');
end
end

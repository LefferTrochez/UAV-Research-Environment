            stopEventTime = ...
                localGetMember( ...
                    executionInfo, ...
                    'StopEventTime');
            stopTimeValue = ...
                localScalarSeconds( ...
                    stopEventTime);
            if isfinite(stopTimeValue) && ...
                    stopTimeValue > 0
                timing.SimulatedDuration_s = ...
                    stopTimeValue;
                timing.TimingSource = ...
                    "SimulationMetadata.ExecutionInfo.StopEventTime";

function RUN = run_icra_experiment(CFG, runSpecification)
if nargin < 2
    error( ...
        'ICRA2027:MissingRunSpecification', ...
        ['Usage:\n\n', ...
         '    RUN = run_icra_experiment(CFG,runSpecification)']);
end
if ~isstruct(CFG)
    error( ...
        'ICRA2027:InvalidConfiguration', ...
        'CFG must be the structure returned by ICRA_experiment_config.');
end
requiredCFGFields = { ...
    'SchemaVersion', ...
    'RunPlan', ...
    'Controllers', ...
    'ControllerGainNames', ...
    'Plants', ...
    'Trajectories', ...
    'DisturbanceConditions', ...
    'WorkspaceVariables', ...
    'Paths', ...
    'Simulation'};
for k = 1:numel(requiredCFGFields)
    if ~isfield(CFG,requiredCFGFields{k})
        error( ...
            'ICRA2027:IncompleteConfiguration', ...
            'CFG.%s is missing.', ...
            requiredCFGFields{k});
    end
end
if isnumeric(runSpecification) && ...
        isscalar(runSpecification)
    runNumber = ...
        double(runSpecification);
    if ~isfinite(runNumber) || ...
            runNumber < 1 || ...
            runNumber > height(CFG.RunPlan) || ...
            runNumber ~= round(runNumber)
        error( ...
            'ICRA2027:InvalidRunNumber', ...
            'Run number must be an integer between 1 and %d.', ...
            height(CFG.RunPlan));
    end
    runRow = ...
        CFG.RunPlan(runNumber,:);
elseif istable(runSpecification)
    if height(runSpecification) ~= 1
        error( ...
            'ICRA2027:InvalidRunSpecification', ...
            'A table run specification must contain exactly one row.');
    end
    runRow = ...
        runSpecification;
    runNumber = ...
        double(runRow.RunNumber);
else
    error( ...
        'ICRA2027:InvalidRunSpecification', ...
        ['runSpecification must be either a run number or ', ...
         'one row of CFG.RunPlan.']);
end
runID = ...
    string(runRow.RunID);
controllerIndex = ...
    double(runRow.ControllerIndex);
trajectoryID = ...
    double(runRow.TrajectoryID);
plantID = ...
    double(runRow.PlantID);
disturbanceEnabled = ...
    logical(runRow.DisturbanceEnabled);
disturbanceID = ...
    string(runRow.DisturbanceID);
disturbanceProfileID = ...
    string(runRow.DisturbanceProfileID);
disturbanceSeed = ...
    double(runRow.DisturbanceSeed);
if controllerIndex < 1 || ...
        controllerIndex > numel(CFG.Controllers)
    error( ...
        'ICRA2027:InvalidControllerIndex', ...
        'Controller index %d does not exist.', ...
        controllerIndex);
end
controller = ...
    CFG.Controllers(controllerIndex);
if string(controller.Status) ~= "FINAL"
    error( ...
        'ICRA2027:ControllerNotFinal', ...
        'Controller %s is not marked FINAL.', ...
        string(controller.ID));
end
if string(runRow.ControllerID) ~= string(controller.ID)
    error( ...
        'ICRA2027:ControllerRunPlanMismatch', ...
        ['RunPlan ControllerID does not match ControllerIndex.\n', ...
         'RunPlan: %s | Selected controller: %s'], ...
        string(runRow.ControllerID), ...
        string(controller.ID));
end
if any(~isfinite(double(controller.GainVector(:))))
    error( ...
        'ICRA2027:NonFiniteControllerGain', ...
        'Controller %s contains non-finite gains.', ...
        string(controller.ID));
end
if numel(controller.GainVector) ~= numel(CFG.ControllerGainNames)
    error( ...
        'ICRA2027:ControllerGainCountMismatch', ...
        ['Controller %s contains %d gain-vector elements; ', ...
         'the configuration expects %d.'], ...
        string(controller.ID), ...
        numel(controller.GainVector), ...
        numel(CFG.ControllerGainNames));
end
if ~ismember(plantID,[1 2 3])
    error( ...
        'ICRA2027:InvalidPlantID', ...
        'Plant ID must be 1, 2 or 3.');
end
validTrajectoryIDs = ...
    [CFG.Trajectories.ID];
if ~ismember(trajectoryID,validTrajectoryIDs)
    error( ...
        'ICRA2027:InvalidTrajectoryID', ...
        'Trajectory ID %d is not part of the campaign.', ...
        trajectoryID);
end
projectRoot = ...
    char(CFG.Paths.ProjectRoot);
experimentRoot = ...
    char(CFG.Paths.ExperimentRoot);
initializationFile = ...
    char(CFG.Paths.InitializationFile);
modelFile = ...
    char(CFG.Paths.ModelFile);
modelName = ...
    char(CFG.Simulation.ModelName);
if ~isfolder(projectRoot)
    error( ...
        'ICRA2027:ProjectRootNotFound', ...
        'Project root does not exist:\n%s', ...
        projectRoot);
end
if ~isfile(initializationFile)
    error( ...
        'ICRA2027:InitializationFileNotFound', ...
        'initialize_project.m was not found:\n%s', ...
        initializationFile);
end
if ~isfile(modelFile)
    error( ...
        'ICRA2027:ModelNotFound', ...
        'Simulink model was not found:\n%s', ...
        modelFile);
end
RUN = ...
    struct();
RUN.SchemaVersion = ...
    string(CFG.SchemaVersion);
RUN.Metadata = ...
    struct();
RUN.Metadata.ConfigurationSchemaVersion = ...
    string(CFG.SchemaVersion);
RUN.Metadata.RunNumber = ...
    runNumber;
RUN.Metadata.RunID = ...
    runID;
RUN.Metadata.ControllerID = ...
    string(controller.ID);
RUN.Metadata.ControllerCode = ...
    string(controller.Code);
RUN.Metadata.ControllerName = ...
    string(controller.Name);
RUN.Metadata.ControllerTunedPlant = ...
    string(controller.TunedPlant);
RUN.Metadata.ControllerSource = ...
    string(controller.Source);
RUN.Metadata.PlantID = ...
    plantID;
RUN.Metadata.PlantCode = ...
    string(runRow.PlantCode);
RUN.Metadata.PlantName = ...
    string(runRow.PlantName);
RUN.Metadata.TrajectoryID = ...
    trajectoryID;
RUN.Metadata.TrajectoryCode = ...
    string(runRow.TrajectoryCode);
RUN.Metadata.TrajectoryName = ...
    string(runRow.TrajectoryName);
RUN.Metadata.DisturbanceID = ...
    disturbanceID;
RUN.Metadata.DisturbanceEnabled = ...
    disturbanceEnabled;
RUN.Metadata.DisturbanceProfileID = ...
    disturbanceProfileID;
RUN.Metadata.DisturbanceSeed = ...
    disturbanceSeed;
RUN.Metadata.StartWallClock = ...
    datetime('now');
RUN.Metadata.EndWallClock = ...
    NaT;
RUN.Configuration = ...
    struct();
RUN.Configuration.ControllerGains = ...
    controller.Gains;
RUN.Configuration.ControllerGainVector = ...
    double(controller.GainVector(:));
RUN.Configuration.ControllerStatus = ...
    string(controller.Status);
RUN.Configuration.ControllerSource = ...
    string(controller.Source);
RUN.Configuration.ControllerTunedPlant = ...
    string(controller.TunedPlant);
RUN.Configuration.ControllerNormalizedTuningCost = ...
    double(controller.NormalizedTuningCost);
RUN.Configuration.ControllerGainNames = ...
    string(CFG.ControllerGainNames(:));
RUN.Configuration.LegacyAliasPolicy = ...
    "COMPATIBILITY_ONLY_AXIS_SPECIFIC_FIELDS_AUTHORITATIVE";
RUN.Configuration.DisturbanceRealizationRequested = ...
    disturbanceProfileID;
RUN.Configuration.DisturbanceSeedRequested = ...
    disturbanceSeed;
RUN.Status = ...
    struct();
RUN.Status.Success = ...
    false;
RUN.Status.SimulationCompleted = ...
    false;
RUN.Status.SimulationError = ...
    false;
RUN.Status.ErrorIdentifier = ...
    "";
RUN.Status.ErrorMessage = ...
    "";
RUN.Status.StopEvent = ...
    "";
RUN.Timing = ...
    struct();
RUN.Timing.ProjectInitializationWallTime_s = ...
    NaN;
RUN.Timing.SimulationCallWallTime_s = ...
    NaN;
RUN.Timing.InitializationElapsedWallTime_s = ...
    NaN;
RUN.Timing.ExecutionElapsedWallTime_s = ...
    NaN;
RUN.Timing.TerminationElapsedWallTime_s = ...
    NaN;
RUN.Timing.TotalElapsedWallTime_s = ...
    NaN;
RUN.Timing.SimulatedDuration_s = ...
    NaN;
RUN.Timing.RealTimeFactor_RTF = ...
    NaN;
RUN.Timing.ComputationalTimeFactor_CTF = ...
    NaN;
RUN.Timing.SimulationStartTime_s = ...
    NaN;
RUN.Timing.SimulationStopTime_s = ...
    NaN;
RUN.Timing.SimulatedDurationSource = ...
    "";
RUN.Timing.ExecutionWallTimeSource = ...
    "";
RUN.SimulationOutput = ...
    [];
fprintf('\n');
fprintf('==============================================================\n');
fprintf(' ICRA 2027 EXPERIMENT\n');
fprintf('==============================================================\n');
fprintf( ...
    'Run:             %d / %d\n', ...
    runNumber, ...
    height(CFG.RunPlan));
fprintf( ...
    'Run ID:          %s\n', ...
    runID);
fprintf( ...
    'Controller:      %s\n', ...
    controller.Code);
fprintf( ...
    'Tuned on:        %s\n', ...
    controller.TunedPlant);
fprintf( ...
    'Trajectory:      T%d - %s\n', ...
    trajectoryID, ...
    runRow.TrajectoryName);
fprintf( ...
    'Plant:           L%d - %s\n', ...
    plantID, ...
    runRow.PlantName);
if disturbanceEnabled
    fprintf( ...
        'Disturbances:    ON [%s]\n', ...
        disturbanceProfileID);
else
    fprintf( ...
        'Disturbances:    OFF\n');
end
fprintf('==============================================================\n');
fprintf('\n');
localCloseInteractiveGUI();
if bdIsLoaded(modelName)
    simulationStatus = ...
        get_param( ...
            modelName, ...
            'SimulationStatus');
    if ~strcmpi(simulationStatus,'stopped')
        error( ...
            'ICRA2027:ModelAlreadyRunning', ...
            ['UAV_Research_Environment is already running.\n', ...
             'Stop the current simulation before starting the campaign.']);
    end
end
addpath(projectRoot);
addpath(experimentRoot);
previousRngState = ...
    rng;
rngCleanup = ...
    onCleanup( ...
        @() rng(previousRngState)); %#ok<NASGU>
matlabRandomSeed = ...
    double( ...
        mod( ...
            round(disturbanceSeed), ...
            2^32));
rng( ...
    matlabRandomSeed, ...
    'twister');
RUN.Configuration.MATLABRandomSeedApplied = ...
    matlabRandomSeed;
RUN.Configuration.RandomSeedPolicy = ...
    "RESET_BEFORE_EACH_RUN_COMMON_RANDOM_NUMBERS";
assignin( ...
    'base', ...
    'UAV_MODEL', ...
    plantID);
assignin( ...
    'base', ...
    'TRAJECTORY_ID', ...
    trajectoryID);
assignin( ...
    'base', ...
    'DIST_ENABLE', ...
    disturbanceEnabled);
assignin( ...
    'base', ...
    'OPERATOR_MODE', ...
    uint8(1));
assignin( ...
    'base', ...
    'SAVE_METRICS_REQUESTED', ...
    false);
assignin( ...
    'base', ...
    'ICRA_ACTIVE_CONTROLLER', ...
    string(controller.ID));
assignin( ...
    'base', ...
    'ICRA_ACTIVE_CONTROLLER_CODE', ...
    string(controller.Code));
assignin( ...
    'base', ...
    'ICRA_ACTIVE_RUN_ID', ...
    runID);
assignin( ...
    'base', ...
    'ICRA_DISTURBANCE_PROFILE_ID', ...
    disturbanceProfileID);
assignin( ...
    'base', ...
    'ICRA_DISTURBANCE_SEED', ...
    disturbanceSeed);
assignin( ...
    'base', ...
    'RESULT_CUSTOM_NAME', ...
    char(runID));
evalin( ...
    'base', ...
    'clear out');
fprintf('Initializing project...\n');
initializationTimer = ...
    tic;
try
    escapedInitializationFile = ...
        strrep( ...
            initializationFile, ...
            '''', ...
            '''''');
    initializationCommand = ...
        sprintf( ...
            'run(''%s'');', ...
            escapedInitializationFile);
    evalin( ...
        'base', ...
        initializationCommand);
catch ME
    RUN.Status.SimulationError = ...
        true;
    RUN.Status.ErrorIdentifier = ...
        string(ME.identifier);
    RUN.Status.ErrorMessage = ...
        string(ME.message);
    RUN.Metadata.EndWallClock = ...
        datetime('now');
    rethrow(ME);
end
RUN.Timing.ProjectInitializationWallTime_s = ...
    toc(initializationTimer);
actualPlantID = ...
    double( ...
        evalin( ...
            'base', ...
            'UAV_MODEL'));
actualTrajectoryID = ...
    double( ...
        evalin( ...
            'base', ...
            'TRAJECTORY_ID'));
actualDisturbanceEnabled = ...
    logical( ...
        evalin( ...
            'base', ...
            'DIST_ENABLE'));
actualOperatorMode = ...
    uint8( ...
        evalin( ...
            'base', ...
            'OPERATOR_MODE'));
if actualPlantID ~= plantID
    error( ...
        'ICRA2027:PlantSelectionChanged', ...
        ['initialize_project changed UAV_MODEL.\n', ...
         'Requested: %d | Actual: %d'], ...
        plantID, ...
        actualPlantID);
end
if actualTrajectoryID ~= trajectoryID
    error( ...
        'ICRA2027:TrajectorySelectionChanged', ...
        ['initialize_project changed TRAJECTORY_ID.\n', ...
         'Requested: %d | Actual: %d'], ...
        trajectoryID, ...
        actualTrajectoryID);
end
if actualDisturbanceEnabled ~= disturbanceEnabled
    error( ...
        'ICRA2027:DisturbanceSelectionChanged', ...
        'initialize_project changed DIST_ENABLE.');
end
if actualOperatorMode ~= uint8(1)
    error( ...
        'ICRA2027:OperatorModeChanged', ...
        'The final campaign requires AUTOMATIC operator mode.');
end
assignin( ...
    'base', ...
    'ICRA_ACTIVE_CONTROLLER', ...
    string(controller.ID));
assignin( ...
    'base', ...
    'ICRA_ACTIVE_CONTROLLER_CODE', ...
    string(controller.Code));
assignin( ...
    'base', ...
    'ICRA_ACTIVE_RUN_ID', ...
    runID);
assignin( ...
    'base', ...
    'ICRA_DISTURBANCE_PROFILE_ID', ...
    disturbanceProfileID);
assignin( ...
    'base', ...
    'ICRA_DISTURBANCE_SEED', ...
    disturbanceSeed);
verifiedControllerID = ...
    string( ...
        evalin( ...
            'base', ...
            'ICRA_ACTIVE_CONTROLLER'));
verifiedDisturbanceSeed = ...
    double( ...
        evalin( ...
            'base', ...
            'ICRA_DISTURBANCE_SEED'));
if verifiedControllerID ~= string(controller.ID)
    error( ...
        'ICRA2027:ControllerMetadataChanged', ...
        'ICRA_ACTIVE_CONTROLLER does not match the requested controller.');
end
if verifiedDisturbanceSeed ~= disturbanceSeed
    error( ...
        'ICRA2027:DisturbanceSeedChanged', ...
        ['ICRA_DISTURBANCE_SEED changed unexpectedly.\n', ...
         'Requested: %.0f | Actual: %.0f'], ...
        disturbanceSeed, ...
        verifiedDisturbanceSeed);
end
if ~evalin( ...
        'base', ...
        'exist(''AUTOPILOT'',''var'')')
    error( ...
        'ICRA2027:AutopilotUnavailable', ...
        'AUTOPILOT was not created by initialize_project.m.');
end
AUTOPILOT = ...
    evalin( ...
        'base', ...
        'AUTOPILOT');
AUTOPILOT = ...
    localApplyControllerGains( ...
        AUTOPILOT, ...
        controller);
AUTOPILOT.info.controllerGainSource = ...
    char(controller.Code);
AUTOPILOT.info.controllerTuningCampaign = ...
    char(controller.Source);
AUTOPILOT.info.ICRAControllerID = ...
    char(controller.ID);
AUTOPILOT.info.ICRAControllerTunedPlant = ...
    char(controller.TunedPlant);
assignin( ...
    'base', ...
    'AUTOPILOT', ...
    AUTOPILOT);
activeGainVector = ...
    localExtractGainVector( ...
        AUTOPILOT);
requestedGainVector = ...
    double( ...
        controller.GainVector(:));
if numel(activeGainVector) ~= numel(requestedGainVector)
    error( ...
        'ICRA2027:GainVerificationFailed', ...
        'Controller gain-vector dimensions do not match.');
end
gainTolerance = ...
    1.0e-12;
if any( ...
        abs( ...
            activeGainVector - ...
            requestedGainVector) > ...
        gainTolerance .* ...
        max( ...
            1.0, ...
            abs(requestedGainVector)))
    error( ...
        'ICRA2027:GainVerificationFailed', ...
        ['The active AUTOPILOT gains do not match ', ...
         'the selected controller configuration.']);
end
RUN.Configuration.ActiveGainVectorVerified = ...
    activeGainVector;
RUN.Configuration.ActiveGainVerificationPassed = ...
    true;
fprintf( ...
    'Authoritative controller gain audit: PASS (%d values)\n', ...
    numel(activeGainVector));
if ~bdIsLoaded(modelName)
    load_system(modelFile);
end
operatorModeBlock = ...
    [ ...
        modelName, ...
        '/Remote Controller/Operator Mode'];
armCommandBlock = ...
    [ ...
        modelName, ...
        '/Remote Controller/Arm Command'];
runRequestBlock = ...
    [ ...
        modelName, ...
        '/Remote Controller/Run Trajectory Request ID'];
if getSimulinkBlockHandle(operatorModeBlock) == -1
    error( ...
        'ICRA2027:OperatorModeBlockMissing', ...
        'Required block was not found:\n%s', ...
        operatorModeBlock);
end
if getSimulinkBlockHandle(armCommandBlock) == -1
    error( ...
        'ICRA2027:ArmCommandBlockMissing', ...
        'Required block was not found:\n%s', ...
        armCommandBlock);
end
if getSimulinkBlockHandle(runRequestBlock) == -1
    error( ...
        'ICRA2027:RunRequestBlockMissing', ...
        'Required block was not found:\n%s', ...
        runRequestBlock);
end
set_param( ...
    operatorModeBlock, ...
    'Value', ...
    'OPERATOR_MODE');
set_param( ...
    armCommandBlock, ...
    'Value', ...
    'false');
set_param( ...
    runRequestBlock, ...
    'Value', ...
    'uint32(0)');
if ~evalin( ...
        'base', ...
        'exist(''AUTO_PROTOCOL'',''var'')')
    error( ...
        'ICRA2027:AutomaticProtocolUnavailable', ...
        'AUTO_PROTOCOL was not created by initialize_project.m.');
end
AUTO_PROTOCOL = ...
    evalin( ...
        'base', ...
        'AUTO_PROTOCOL');
stopTime_s = ...
    localGetAutomaticStopTime( ...
        AUTO_PROTOCOL, ...
        trajectoryID);
set_param( ...
    modelName, ...
    'StopTime', ...
    num2str( ...
        stopTime_s, ...
        '%.15g'));
RUN.Configuration.StopTime_s = ...
    stopTime_s;
set_param( ...
    modelName, ...
    'ReturnWorkspaceOutputs', ...
    'on');
set_param( ...
    modelName, ...
    'ReturnWorkspaceOutputsName', ...
    'out');
try
    set_param( ...
        modelName, ...
        'EnablePacing', ...
        'off');
catch ME
    warning( ...
        'ICRA2027:PacingConfigurationWarning', ...
        'Unable to explicitly disable pacing: %s', ...
        ME.message);
end
try
    set_param( ...
        modelName, ...
        'FastRestart', ...
        'off');
catch
end
RUN.Configuration.UAV_MODEL = ...
    actualPlantID;
RUN.Configuration.TRAJECTORY_ID = ...
    actualTrajectoryID;
RUN.Configuration.DIST_ENABLE = ...
    actualDisturbanceEnabled;
RUN.Configuration.OPERATOR_MODE = ...
    actualOperatorMode;
RUN.Configuration.AutomaticProtocol = ...
    AUTO_PROTOCOL;
RUN.Configuration.AutopilotSnapshot = ...
    AUTOPILOT;
if evalin( ...
        'base', ...
        'exist(''TRAJECTORY'',''var'')')
    RUN.Configuration.TrajectorySnapshot = ...
        evalin( ...
            'base', ...
            'TRAJECTORY');
else
    RUN.Configuration.TrajectorySnapshot = ...
        struct();
end
if evalin( ...
        'base', ...
        'exist(''BENCHMARK_METRICS'',''var'')')
    RUN.Configuration.BenchmarkMetrics = ...
        evalin( ...
            'base', ...
            'BENCHMARK_METRICS');
else
    RUN.Configuration.BenchmarkMetrics = ...
        struct();
end
fprintf('\n');
fprintf('--------------------------------------------------------------\n');
fprintf(' VERIFIED EXPERIMENT CONFIGURATION\n');
fprintf('--------------------------------------------------------------\n');
fprintf( ...
    'Plant:            L%d\n', ...
    actualPlantID);
fprintf( ...
    'Trajectory:       %d\n', ...
    actualTrajectoryID);
fprintf( ...
    'Controller:       %s\n', ...
    controller.Code);
fprintf( ...
    'Controller source:%s\n', ...
    controller.Source);
fprintf( ...
    'MATLAB RNG seed:  %.0f\n', ...
    matlabRandomSeed);
fprintf( ...
    'Disturbances:     %s\n', ...
    localOnOffText( ...
        actualDisturbanceEnabled));
fprintf( ...
    'Operator mode:    AUTOMATIC\n');
fprintf( ...
    'Stop time:        %.3f s\n', ...
    stopTime_s);
fprintf( ...
    'Pacing:           OFF\n');
fprintf( ...
    'Gain verification: PASS\n');
fprintf('--------------------------------------------------------------\n');
fprintf('\n');
fprintf( ...
    'Starting simulation for %s...\n\n', ...
    runID);
simulationTimer = ...
    tic;
try
    simOut = ...
        sim( ...
            modelName);
    RUN.Timing.SimulationCallWallTime_s = ...
        toc(simulationTimer);
    RUN.SimulationOutput = ...
        simOut;
    assignin( ...
        'base', ...
        'out', ...
        simOut);
    RUN.Status.SimulationCompleted = ...
        true;
catch ME
    RUN.Timing.SimulationCallWallTime_s = ...
        toc(simulationTimer);
    RUN.Status.SimulationError = ...
        true;
    RUN.Status.ErrorIdentifier = ...
        string(ME.identifier);
    RUN.Status.ErrorMessage = ...
        string(ME.message);
    RUN.Metadata.EndWallClock = ...
        datetime('now');
    fprintf('\n');
    fprintf('==============================================================\n');
    fprintf(' EXPERIMENT FAILED\n');
    fprintf('==============================================================\n');
    fprintf( ...
        'Run ID: %s\n', ...
        runID);
    fprintf( ...
        'Error:  %s\n', ...
        ME.message);
    fprintf('==============================================================\n\n');
    rethrow(ME);
end
RUN = ...
    localRecoverSimulationTiming( ...
        RUN, ...
        simOut);
RUN.Status.StopEvent = ...
    "ReachedStopTime";
try
    simulationMetadata = ...
        simOut.SimulationMetadata;
    executionInfo = ...
        simulationMetadata.ExecutionInfo;
    stopEvent = ...
        localGetTextMember( ...
            executionInfo, ...
            'StopEvent');
    if strlength(stopEvent) > 0
        RUN.Status.StopEvent = ...
            stopEvent;
    end
catch
end
RUN.Status.Success = ...
    RUN.Status.SimulationCompleted && ...
    ~RUN.Status.SimulationError;
RUN.Metadata.EndWallClock = ...
    datetime('now');
fprintf('\n');
fprintf('==============================================================\n');
fprintf(' ICRA EXPERIMENT SIMULATION COMPLETE\n');
fprintf('==============================================================\n');
fprintf( ...
    'Run ID:                   %s\n', ...
    runID);
fprintf( ...
    'Simulation completed:     YES\n');
fprintf( ...
    'Simulated duration:       %.3f s\n', ...
    RUN.Timing.SimulatedDuration_s);
fprintf( ...
    'Duration source:          %s\n', ...
    RUN.Timing.SimulatedDurationSource);
fprintf( ...
    'Execution wall time:      %.3f s\n', ...
    RUN.Timing.ExecutionElapsedWallTime_s);
fprintf( ...
    'RTF:                      %.4f\n', ...
    RUN.Timing.RealTimeFactor_RTF);
fprintf( ...
    'CTF:                      %.4f\n', ...
    RUN.Timing.ComputationalTimeFactor_CTF);
fprintf('\n');
fprintf( ...
    'Data are still in memory.\n');
fprintf( ...
    'save_icra_run.m will persist this experiment.\n');
fprintf('==============================================================\n');
fprintf('\n');
end
function AUTOPILOT = localApplyControllerGains( ...
    AUTOPILOT, ...
    controller)
G = ...
    controller.Gains;
AUTOPILOT.horizontal.position.north.Kp = ...
    G.horizontal.position.north.Kp;
AUTOPILOT.horizontal.position.east.Kp = ...
    G.horizontal.position.east.Kp;
AUTOPILOT.horizontal.velocity.x.Kp = ...
    G.horizontal.velocity.x.Kp;
AUTOPILOT.horizontal.velocity.x.Kd = ...
    G.horizontal.velocity.x.Kd;
AUTOPILOT.horizontal.velocity.x.N = ...
    G.horizontal.velocity.x.N;
AUTOPILOT.horizontal.velocity.y.Kp = ...
    G.horizontal.velocity.y.Kp;
AUTOPILOT.vertical.altitude.Kp = ...
    G.vertical.altitude.Kp;
AUTOPILOT.vertical.velocity.Kp = ...
    G.vertical.velocity.Kp;
AUTOPILOT.yaw.angle.Kp = ...
    G.yaw.angle.Kp;

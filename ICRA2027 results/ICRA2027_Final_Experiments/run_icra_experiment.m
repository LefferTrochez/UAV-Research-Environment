function stopTime_s = localGetAutomaticStopTime( ...
    AUTO_PROTOCOL, ...
    trajectoryID)
if isfield(AUTO_PROTOCOL,'selected') && ...
        isstruct(AUTO_PROTOCOL.selected) && ...
        isfield(AUTO_PROTOCOL.selected,'stopTime_s')
    stopTime_s = ...
        double( ...
            AUTO_PROTOCOL.selected.stopTime_s);
elseif isfield(AUTO_PROTOCOL,'schedule_s')
    if isfield(AUTO_PROTOCOL,'column') && ...
            isfield(AUTO_PROTOCOL.column,'stop')
        stopColumn = ...
            double( ...
                AUTO_PROTOCOL.column.stop);
    else
        stopColumn = ...
            4;
    end
    if trajectoryID > ...
            size(AUTO_PROTOCOL.schedule_s,1)
        error( ...
            'ICRA2027:AutomaticProtocolTrajectoryMissing', ...
            'AUTO_PROTOCOL has no row for trajectory %d.', ...
            trajectoryID);
    end
    stopTime_s = ...
        double( ...
            AUTO_PROTOCOL.schedule_s( ...
                trajectoryID, ...
                stopColumn));
else
    error( ...
        'ICRA2027:AutomaticStopTimeUnavailable', ...
        'Unable to determine automatic protocol Stop Time.');
end
if ~isscalar(stopTime_s) || ...
        ~isfinite(stopTime_s) || ...
        stopTime_s <= 0
    error( ...
        'ICRA2027:InvalidAutomaticStopTime', ...
        'Automatic Stop Time must be finite and greater than zero.');
end
end
function RUN = localRecoverSimulationTiming( ...
    RUN, ...
    simOut)
simulatedDuration_s = ...
    NaN;
simulationStartTime_s = ...
    NaN;
simulationStopTime_s = ...
    NaN;
simulatedDurationSource = ...
    "";
try
    simulationMetadata = ...
        simOut.SimulationMetadata;
    executionInfo = ...
        simulationMetadata.ExecutionInfo;
    modelInfo = ...
        simulationMetadata.ModelInfo;
    executionStopTime_s = ...
        localGetNumericMember( ...
            executionInfo, ...
            'StopEventTime');
    modelStartTime_s = ...
        localGetNumericMember( ...
            modelInfo, ...
            'StartTime');
    modelStopTime_s = ...
        localGetNumericMember( ...
            modelInfo, ...
            'StopTime');
    if isfinite(modelStartTime_s)
        simulationStartTime_s = ...
            modelStartTime_s;
    else
        simulationStartTime_s = ...
            NaN;
    end
    if isfinite(executionStopTime_s)
        simulationStopTime_s = ...
            executionStopTime_s;
        simulatedDurationSource = ...
            "SimulationMetadata.ExecutionInfo.StopEventTime";
    elseif isfinite(modelStopTime_s)
        simulationStopTime_s = ...
            modelStopTime_s;
        simulatedDurationSource = ...
            "SimulationMetadata.ModelInfo.StopTime";
    end
    if isfinite(simulationStopTime_s)
        if isfinite(simulationStartTime_s)
            simulatedDuration_s = ...
                simulationStopTime_s - ...
                simulationStartTime_s;
        else
            simulatedDuration_s = ...
                simulationStopTime_s;
        end
    end
catch
end
if ~isfinite(simulatedDuration_s) || ...
        simulatedDuration_s <= 0
    try
        variables = ...
            who(simOut);
        if ismember('tout',variables)
            t = ...
                simOut.tout;
            if isa(t,'timeseries')
                timeVector = ...
                    double(t.Time(:));
            else
                timeVector = ...
                    double(t(:));
            end
            timeVector = ...
                timeVector( ...
                    isfinite(timeVector));
            if numel(timeVector) >= 2
                simulationStartTime_s = ...
                    timeVector(1);
                simulationStopTime_s = ...
                    timeVector(end);
                simulatedDuration_s = ...
                    simulationStopTime_s - ...
                    simulationStartTime_s;
                simulatedDurationSource = ...
                    "SimulationOutput.tout";
            elseif numel(timeVector) == 1 && ...
                    timeVector(1) > 0
                simulationStartTime_s = ...
                    0.0;
                simulationStopTime_s = ...
                    timeVector(1);
                simulatedDuration_s = ...
                    timeVector(1);
                simulatedDurationSource = ...
                    "SimulationOutput.tout_single_sample";
            end
        end
    catch
    end
end
if ~isfinite(simulatedDuration_s) || ...
        simulatedDuration_s <= 0
    try
        configuredStopTime_s = ...
            double( ...
                RUN.Configuration.StopTime_s);
        if isfinite(configuredStopTime_s) && ...
                configuredStopTime_s > 0
            simulationStartTime_s = ...
                0.0;
            simulationStopTime_s = ...
                configuredStopTime_s;
            simulatedDuration_s = ...
                configuredStopTime_s;
            simulatedDurationSource = ...
                "RUN.Configuration.StopTime_s";
        end
    catch
        simulatedDuration_s = ...
            NaN;
    end
end
if ~isfinite(simulatedDuration_s) || ...
        simulatedDuration_s <= 0
    simulatedDuration_s = ...
        NaN;
    simulationStartTime_s = ...
        NaN;
    simulationStopTime_s = ...
        NaN;
    simulatedDurationSource = ...
        "UNAVAILABLE";
end
RUN.Timing.SimulationStartTime_s = ...
    simulationStartTime_s;
RUN.Timing.SimulationStopTime_s = ...
    simulationStopTime_s;
RUN.Timing.SimulatedDuration_s = ...
    simulatedDuration_s;
RUN.Timing.SimulatedDurationSource = ...
    simulatedDurationSource;
initializationElapsed_s = ...
    NaN;
executionElapsed_s = ...
    NaN;
terminationElapsed_s = ...
    NaN;
totalElapsed_s = ...
    NaN;
executionWallTimeSource = ...
    "";
try
    timingInfo = ...
        simOut.SimulationMetadata.TimingInfo;
    initializationElapsed_s = ...
        localGetTimingValue( ...
            timingInfo, ...
            'InitializationElapsedWallTime');
    executionElapsed_s = ...
        localGetTimingValue( ...
            timingInfo, ...
            'ExecutionElapsedWallTime');
    terminationElapsed_s = ...
        localGetTimingValue( ...
            timingInfo, ...
            'TerminationElapsedWallTime');
    totalElapsed_s = ...
        localGetTimingValue( ...
            timingInfo, ...
            'TotalElapsedWallTime');
    if isfinite(executionElapsed_s) && ...
            executionElapsed_s > 0
        executionWallTimeSource = ...
            "SimulationMetadata.TimingInfo.ExecutionElapsedWallTime";
    end
catch
end
RUN.Timing.InitializationElapsedWallTime_s = ...
    initializationElapsed_s;
RUN.Timing.ExecutionElapsedWallTime_s = ...
    executionElapsed_s;
RUN.Timing.TerminationElapsedWallTime_s = ...
    terminationElapsed_s;
RUN.Timing.TotalElapsedWallTime_s = ...
    totalElapsed_s;
if ~isfinite(RUN.Timing.TotalElapsedWallTime_s) || ...
        RUN.Timing.TotalElapsedWallTime_s <= 0
    RUN.Timing.TotalElapsedWallTime_s = ...
        RUN.Timing.SimulationCallWallTime_s;
end
if ~isfinite(RUN.Timing.ExecutionElapsedWallTime_s) || ...
        RUN.Timing.ExecutionElapsedWallTime_s <= 0
    RUN.Timing.ExecutionElapsedWallTime_s = ...
        RUN.Timing.SimulationCallWallTime_s;
    executionWallTimeSource = ...
        "tic/toc around sim() fallback";
end
RUN.Timing.ExecutionWallTimeSource = ...
    executionWallTimeSource;
RUN.Timing.RealTimeFactor_RTF = ...
    NaN;
RUN.Timing.ComputationalTimeFactor_CTF = ...
    NaN;
if isfinite(RUN.Timing.SimulatedDuration_s) && ...
        RUN.Timing.SimulatedDuration_s > 0 && ...
        isfinite(RUN.Timing.ExecutionElapsedWallTime_s) && ...
        RUN.Timing.ExecutionElapsedWallTime_s > 0
    RUN.Timing.RealTimeFactor_RTF = ...
        RUN.Timing.SimulatedDuration_s / ...
        RUN.Timing.ExecutionElapsedWallTime_s;
    RUN.Timing.ComputationalTimeFactor_CTF = ...
        RUN.Timing.ExecutionElapsedWallTime_s / ...
        RUN.Timing.SimulatedDuration_s;
end
if isfinite(RUN.Timing.RealTimeFactor_RTF) && ...
        RUN.Timing.RealTimeFactor_RTF > 0 && ...
        isfinite(RUN.Timing.ComputationalTimeFactor_CTF) && ...
        RUN.Timing.ComputationalTimeFactor_CTF > 0
    reciprocalError = ...
        abs( ...
            RUN.Timing.RealTimeFactor_RTF * ...
            RUN.Timing.ComputationalTimeFactor_CTF - ...
            1.0);
    if reciprocalError > 1.0e-10
        warning( ...
            'ICRA2027:RTFCTFConsistencyWarning', ...
            ['RTF and CTF are not reciprocal within numerical ', ...
             'tolerance. Check timing metadata.']);
    end
end
end
function value = localGetTimingValue(S,fieldName)
value = ...
    NaN;
try
    if isstruct(S)
        if isfield(S,fieldName)
            candidate = ...
                double( ...
                    S.(fieldName));
            if isscalar(candidate) && ...
                    isfinite(candidate)
                value = ...
                    candidate;
            end
        end
    else
        if isprop(S,fieldName)
            candidate = ...
                double( ...
                    S.(fieldName));
            if isscalar(candidate) && ...
                    isfinite(candidate)
                value = ...
                    candidate;
            end
        end
    end
catch
    value = ...
        NaN;
end
end
function value = localGetNumericMember(S,memberName)
value = ...
    NaN;
try
    if isstruct(S)
        if ~isfield(S,memberName)
            return;
        end
        candidate = ...
            S.(memberName);
    else
        if ~isprop(S,memberName)
            return;
        end
        candidate = ...
            S.(memberName);
    end
    candidate = ...
        double(candidate);
    if isscalar(candidate) && ...
            isfinite(candidate)
        value = ...
            candidate;
    end
catch
    value = ...
        NaN;
end
end

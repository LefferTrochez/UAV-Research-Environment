function paths = localRecursiveNameSearch( ...
    value, ...
    currentPath, ...
    keywords, ...
    depth, ...
    maxDepth)
paths = ...
    strings(0,1);
if depth > maxDepth
    return;
end
if ~isstruct(value)
    return;
end
fieldNames = ...
    fieldnames(value);
for k = 1:numel(fieldNames)
    fieldName = ...
        fieldNames{k};
    if strlength(currentPath) == 0
        childPath = ...
            string(fieldName);
    else
        childPath = ...
            currentPath + ...
            "." + ...
            string(fieldName);
    end
    lowerName = ...
        lower(fieldName);
    matchesKeyword = ...
        false;
    for j = 1:numel(keywords)
        if contains( ...
                lowerName, ...
                keywords{j})
            matchesKeyword = ...
                true;
            break;
        end
    end
    if matchesKeyword
        paths(end+1,1) = ...
            childPath; %#ok<AGROW>
    end
    childValue = ...
        value.(fieldName);
    if isstruct(childValue) && ...
            isscalar(childValue)
        childPaths = ...
            localRecursiveNameSearch( ...
                childValue, ...
                childPath, ...
                keywords, ...
                depth + 1, ...
                maxDepth);
        paths = ...
            [ ...
                paths; ...
                childPaths ...
            ]; %#ok<AGROW>
    end
end
end

function SIGNAL = localSignalToCanonical(value)
SIGNAL = ...
    localEmptyCanonicalSignal();
if isempty(value)
    return;
end
try
    if isa(value,'timeseries')
        SIGNAL.Time_s = ...
            double( ...
                value.Time(:));
        data = ...
            double( ...
                value.Data);
        SIGNAL.Data = ...
            localNormalizeSignalData( ...
                data, ...
                numel(SIGNAL.Time_s));
        SIGNAL.SourceType = ...
            "timeseries";
        SIGNAL.Available = ...
            true;
        return;
    end
catch
end
try
    if istimetable(value)
        rowTimes = ...
            value.Properties.RowTimes;
        if isduration(rowTimes)
            SIGNAL.Time_s = ...
                seconds(rowTimes);
        elseif isdatetime(rowTimes)
            SIGNAL.Time_s = ...
                seconds( ...
                    rowTimes - ...
                    rowTimes(1));
        else
            SIGNAL.Time_s = ...
                double(rowTimes);
        end
        numericData = ...
            value{:,:};
        if isnumeric(numericData)
            SIGNAL.Data = ...
                double(numericData);
            SIGNAL.SourceType = ...
                "timetable";
            SIGNAL.Available = ...
                true;
        end
        return;
    end
catch
end
try
    if isnumeric(value) || ...
            islogical(value)
        numericValue = ...
            double(value);
        if isvector(numericValue)
            numericValue = ...
                numericValue(:);
        end
        SIGNAL.Data = ...
            numericValue;
        SIGNAL.Time_s = ...
            NaN( ...
                size(numericValue,1), ...
                1);
        SIGNAL.SourceType = ...
            "numeric";
        SIGNAL.Available = ...
            true;
        return;
    end
catch
end
SIGNAL.SourceType = ...
    string(class(value));
end

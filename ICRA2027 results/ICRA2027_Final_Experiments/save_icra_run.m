function SAVED = save_icra_run(CFG,RUN)
if nargin < 2
    error( ...
        'ICRA2027:MissingSaveInputs', ...
        'Usage: SAVED = save_icra_run(CFG,RUN)');
end
if ~isstruct(CFG)
    error( ...
        'ICRA2027:InvalidConfiguration', ...
        'CFG must be a structure.');
end
if ~isstruct(RUN)
    error( ...
        'ICRA2027:InvalidRunStructure', ...
        'RUN must be the output of run_icra_experiment.');
end
if ~isfield(RUN,'Metadata') || ...
        ~isfield(RUN.Metadata,'RunID')
    error( ...
        'ICRA2027:MissingRunID', ...
        'RUN.Metadata.RunID is unavailable.');
end
if ~isfield(RUN,'SimulationOutput') || ...
        isempty(RUN.SimulationOutput)
    error( ...
        'ICRA2027:MissingSimulationOutput', ...
        'RUN.SimulationOutput is unavailable.');
end
if ~isa( ...
        RUN.SimulationOutput, ...
        'Simulink.SimulationOutput')
    error( ...
        'ICRA2027:InvalidSimulationOutput', ...
        'RUN.SimulationOutput must be Simulink.SimulationOutput.');
end
runID = ...
    string(RUN.Metadata.RunID);
runNumber = ...
    double(RUN.Metadata.RunNumber);
simOut = ...
    RUN.SimulationOutput;
projectRoot = ...
    char(CFG.Paths.ProjectRoot);
resultsRoot = ...
    char(CFG.Paths.ResultsRoot);
if ~isfield(CFG,'ControllerGainNames') || ...
        ~isfield(CFG,'Controllers') || ...
        ~isfield(CFG,'SchemaVersion')
    error( ...
        'ICRA2027:IncompleteSaveConfiguration', ...
        ['CFG is missing controller-audit or schema information required ', ...
         'for the final campaign.']);
end
controllerIDs = ...
    string( ...
        {CFG.Controllers.ID});
currentControllerIndex = ...
    find( ...
        controllerIDs == string(RUN.Metadata.ControllerID), ...
        1, ...
        'first');
if isempty(currentControllerIndex)
    error( ...
        'ICRA2027:SaveControllerNotFound', ...
        'Controller %s is not present in CFG.Controllers.', ...
        string(RUN.Metadata.ControllerID));
end
currentController = ...
    CFG.Controllers(currentControllerIndex);
if string(currentController.Status) ~= "FINAL"
    error( ...
        'ICRA2027:SaveControllerNotFinal', ...
        'Controller %s is not marked FINAL.', ...
        string(currentController.ID));
end
savedRunGainVector = ...
    double( ...
        RUN.Configuration.ControllerGainVector(:));
currentConfigGainVector = ...
    double( ...
        currentController.GainVector(:));
if numel(savedRunGainVector) ~= numel(currentConfigGainVector) || ...
        numel(savedRunGainVector) ~= numel(CFG.ControllerGainNames)
    error( ...
        'ICRA2027:SaveControllerGainCountMismatch', ...
        ['Controller gain-vector dimensions are inconsistent at save time. ', ...
         'Run=%d | CFG=%d | Names=%d'], ...
        numel(savedRunGainVector), ...
        numel(currentConfigGainVector), ...
        numel(CFG.ControllerGainNames));
end
gainTolerance = ...
    1.0e-12;
gainDifference = ...
    abs( ...
        savedRunGainVector - ...
        currentConfigGainVector);
gainScale = ...
    max( ...
        1.0, ...
        abs(currentConfigGainVector));
if any( ...
        gainDifference > ...
        gainTolerance .* gainScale)
    error( ...
        'ICRA2027:SaveControllerGainMismatch', ...
        ['The controller gains stored in RUN no longer match the current ', ...
         'official controller definition. Refusing to mislabel the run.']);
end
if isfield(RUN.Configuration,'ActiveGainVerificationPassed') && ...
        ~logical(RUN.Configuration.ActiveGainVerificationPassed)
    error( ...
        'ICRA2027:ActiveGainVerificationNotPassed', ...
        'The active-controller gain verification was not passed.');
end
if ~exist(resultsRoot,'dir')
    mkdir(resultsRoot);
end
runsRoot = ...
    fullfile( ...
        resultsRoot, ...
        char(CFG.OutputLayout.RunsFolder));
if ~exist(runsRoot,'dir')
    mkdir(runsRoot);
end
runFolder = ...
    fullfile( ...
        runsRoot, ...
        char(runID));
completeFlagFile = ...
    fullfile( ...
        runFolder, ...
        'COMPLETE.flag');
if exist(runFolder,'dir')
    previousComplete = ...
        isfile(completeFlagFile);
    if previousComplete && ...
            ~CFG.Resume.OverwriteCompletedRuns
        error( ...
            'ICRA2027:RunAlreadySaved', ...
            ['Run %s already contains COMPLETE.flag.\n', ...
             'It will not be overwritten.'], ...
            runID);
    end
    backupTimestamp = ...
        char( ...
            datetime( ...
                'now', ...
                'Format','yyyy-MM-dd_HH-mm-ss'));
    backupFolder = ...
        sprintf( ...
            '%s_BACKUP_%s', ...
            runFolder, ...
            backupTimestamp);
    movefile( ...
        runFolder, ...
        backupFolder);
end
mkdir(runFolder);
rawFolder = ...
    fullfile( ...
        runFolder, ...
        'raw');
processedFolder = ...
    fullfile( ...
        runFolder, ...
        'processed');
tablesFolder = ...
    fullfile( ...
        runFolder, ...
        'tables');
figuresFolder = ...
    fullfile( ...
        runFolder, ...
        'figures');
metadataFolder = ...
    fullfile( ...
        runFolder, ...
        'metadata');
logsFolder = ...
    fullfile( ...
        runFolder, ...
        'logs');
foldersToCreate = { ...
    rawFolder, ...
    processedFolder, ...
    tablesFolder, ...
    figuresFolder, ...
    metadataFolder, ...
    logsFolder};
for k = 1:numel(foldersToCreate)
    if ~exist(foldersToCreate{k},'dir')
        mkdir(foldersToCreate{k});
    end
end
SAVED = ...
    struct();
SAVED.SchemaVersion = ...
    string(CFG.SchemaVersion);
SAVED.ConfigurationSchemaVersion = ...
    string(CFG.SchemaVersion);
SAVED.RunID = ...
    runID;
SAVED.RunNumber = ...
    runNumber;
SAVED.RunFolder = ...
    string(runFolder);
SAVED.RawFolder = ...
    string(rawFolder);
SAVED.ProcessedFolder = ...
    string(processedFolder);
SAVED.TablesFolder = ...
    string(tablesFolder);
SAVED.FiguresFolder = ...
    string(figuresFolder);
SAVED.MetadataFolder = ...
    string(metadataFolder);
SAVED.LogsFolder = ...
    string(logsFolder);
SAVED.Success = ...
    false;
SAVED.CompletedFlagWritten = ...
    false;
SAVED.PostProcessing = ...
    struct();
saveStartTime = ...
    datetime('now');
saveTimer = ...
    tic;
fprintf('\n');
fprintf('==============================================================\n');
fprintf(' SAVING ICRA 2027 RUN\n');
fprintf('==============================================================\n');
fprintf( ...
    'Run:        %d\n', ...
    runNumber);
fprintf( ...
    'Run ID:     %s\n', ...
    runID);
fprintf( ...
    'Folder:\n%s\n', ...
    runFolder);
fprintf('==============================================================\n\n');
assignin( ...
    'base', ...
    'out', ...
    simOut);
assignin( ...
    'base', ...
    'SAVE_METRICS_REQUESTED', ...
    false);
fprintf('Capturing complete SimulationOutput...\n');
simulationVariableNames = ...
    string( ...
        who(simOut));
RAW_LOGS = ...
    struct();
rawCaptureStatus = ...
    strings( ...
        numel(simulationVariableNames), ...
        1);
for k = 1:numel(simulationVariableNames)
    variableName = ...
        simulationVariableNames(k);
    safeFieldName = ...
        matlab.lang.makeValidName( ...
            char(variableName));
    try
        RAW_LOGS.(safeFieldName) = ...
            simOut.get( ...
                char(variableName));
        rawCaptureStatus(k) = ...
            "OK";
    catch ME
        rawCaptureStatus(k) = ...
            "FAILED: " + ...
            string(ME.message);
    end
end
RAW_LOG_INVENTORY = ...
    table( ...
        simulationVariableNames, ...
        rawCaptureStatus, ...
        'VariableNames',{ ...
            'SimulationOutputVariable', ...
            'CaptureStatus'});
writetable( ...
    RAW_LOG_INVENTORY, ...
    fullfile( ...
        tablesFolder, ...
        'Raw_Log_Inventory.csv'));
rawDataFile = ...
    fullfile( ...
        rawFolder, ...
        'raw_simulation_logs.mat');
save( ...
    rawDataFile, ...
    'RAW_LOGS', ...
    'RAW_LOG_INVENTORY', ...
    'simulationVariableNames', ...
    '-v7.3');
SIMULATION_METADATA = ...
    struct();
try
    SIMULATION_METADATA = ...
        simOut.SimulationMetadata;
catch
    SIMULATION_METADATA = ...
        struct();
end
save( ...
    fullfile( ...
        metadataFolder, ...
        'simulation_metadata.mat'), ...
    'SIMULATION_METADATA', ...
    '-v7.3');
snapshotVariableNames = { ...
    'AUTOPILOT', ...
    'ESTIMATOR', ...
    'SENSOR', ...
    'ENVIRONMENT', ...
    'TRAJECTORY', ...
    'TRAJECTORY_LIBRARY', ...
    'AUTO_PROTOCOL', ...
    'BENCHMARK_METRICS', ...
    'A_UAV', ...
    'B_UAV', ...
    'S_UAV', ...
    'UAV_CONTACT', ...
    'A_UAV_CONTACT', ...
    'B_UAV_CONTACT', ...
    'ICRA_ACTIVE_CONTROLLER', ...
    'ICRA_ACTIVE_CONTROLLER_CODE', ...
    'ICRA_ACTIVE_RUN_ID', ...
    'ICRA_DISTURBANCE_PROFILE_ID', ...
    'ICRA_DISTURBANCE_SEED'};
CONFIG_SNAPSHOT = ...
    struct();
SnapshotVariable = ...
    strings( ...
        numel(snapshotVariableNames), ...
        1);
SnapshotAvailable = ...
    false( ...
        numel(snapshotVariableNames), ...
        1);
for k = 1:numel(snapshotVariableNames)
    variableName = ...
        snapshotVariableNames{k};
    SnapshotVariable(k) = ...
        string(variableName);
    variableExists = ...
        evalin( ...
            'base', ...
            sprintf( ...
                'exist(''%s'',''var'')', ...
                variableName));
    if variableExists
        try
            CONFIG_SNAPSHOT.(variableName) = ...
                evalin( ...
                    'base', ...
                    variableName);
            SnapshotAvailable(k) = ...
                true;
        catch
            SnapshotAvailable(k) = ...
                false;
        end
    end
end
CONFIG_SNAPSHOT_INVENTORY = ...
    table( ...
        SnapshotVariable, ...
        SnapshotAvailable);
save( ...
    fullfile( ...
        metadataFolder, ...
        'configuration_snapshot.mat'), ...
    'CONFIG_SNAPSHOT', ...
    'CONFIG_SNAPSHOT_INVENTORY', ...
    '-v7.3');
writetable( ...
    CONFIG_SNAPSHOT_INVENTORY, ...
    fullfile( ...
        tablesFolder, ...
        'Configuration_Snapshot_Inventory.csv'));
CONTROLLER_GAINS = ...
    RUN.Configuration.ControllerGains;
CONTROLLER_GAIN_VECTOR = ...
    double( ...
        RUN.Configuration.ControllerGainVector(:));
CONTROLLER_GAIN_NAMES = ...
    string( ...
        CFG.ControllerGainNames(:));
CONTROLLER_PROVENANCE = ...
    struct();
CONTROLLER_PROVENANCE.ControllerID = ...
    string(RUN.Metadata.ControllerID);
CONTROLLER_PROVENANCE.ControllerCode = ...
    string(RUN.Metadata.ControllerCode);
CONTROLLER_PROVENANCE.ControllerSource = ...
    string(RUN.Metadata.ControllerSource);
CONTROLLER_PROVENANCE.ControllerTunedPlant = ...
    string(RUN.Metadata.ControllerTunedPlant);
CONTROLLER_PROVENANCE.ControllerStatus = ...
    string(RUN.Configuration.ControllerStatus);
CONTROLLER_PROVENANCE.NormalizedTuningCost = ...
    double(RUN.Configuration.ControllerNormalizedTuningCost);
CONTROLLER_PROVENANCE.ConfigurationSchemaVersion = ...
    string(CFG.SchemaVersion);
if isfield(RUN.Configuration,'MATLABRandomSeedApplied')
    CONTROLLER_PROVENANCE.MATLABRandomSeedApplied = ...
        double(RUN.Configuration.MATLABRandomSeedApplied);
else
    CONTROLLER_PROVENANCE.MATLABRandomSeedApplied = ...
        NaN;
end
if isfield(RUN.Configuration,'LegacyAliasPolicy')
    CONTROLLER_PROVENANCE.LegacyAliasPolicy = ...
        string(RUN.Configuration.LegacyAliasPolicy);
else
    CONTROLLER_PROVENANCE.LegacyAliasPolicy = ...
        "UNAVAILABLE";
end
CONTROLLER_GAIN_TABLE = ...
    table( ...
        CONTROLLER_GAIN_NAMES, ...
        CONTROLLER_GAIN_VECTOR, ...
        'VariableNames',{ ...
            'Parameter', ...
            'Value'});
writetable( ...
    CONTROLLER_GAIN_TABLE, ...
    fullfile( ...
        tablesFolder, ...
        'Controller_Gains.csv'));
save( ...
    fullfile( ...
        metadataFolder, ...
        'controller_gains.mat'), ...
    'CONTROLLER_GAINS', ...
    'CONTROLLER_GAIN_NAMES', ...
    'CONTROLLER_GAIN_VECTOR', ...
    'CONTROLLER_GAIN_TABLE', ...
    'CONTROLLER_PROVENANCE');
fprintf('Building canonical signal dataset...\n');
CANONICAL = ...
    struct();
CANONICAL.SchemaVersion = ...
    string(CFG.SchemaVersion);
CANONICAL.RunID = ...
    runID;
CANONICAL.NavigationFrame = ...
    "NED";
CANONICAL.BodyFrame = ...
    "FRD";
CANONICAL.Time = ...
    localGetTopLevelSignal( ...
        RAW_LOGS, ...
        'tout');
CANONICAL.Reference = ...
    struct();
if isfield(RAW_LOGS,'cgsLog')
    CGS = ...
        RAW_LOGS.cgsLog;
    CANONICAL.Reference.Position = ...
        localGetNestedSignal( ...
            CGS, ...
            {'Position_ref'});
    CANONICAL.Reference.VelocityNE = ...
        localGetNestedSignal( ...
            CGS, ...
            {'Velocity_ref_NE'});
    CANONICAL.Reference.VelocityD = ...
        localGetNestedSignal( ...
            CGS, ...
            {'Velocity_ref_D'});
    CANONICAL.Reference.Yaw = ...
        localGetNestedSignal( ...
            CGS, ...
            {'Yaw_ref'});
    CANONICAL.Reference.YawRate = ...
        localGetNestedSignal( ...
            CGS, ...
            {'YawRate_ref'});
    CANONICAL.Reference.Phase = ...
        localGetNestedSignal( ...
            CGS, ...
            {'Phase'});
    CANONICAL.Reference.Active = ...
        localGetNestedSignal( ...
            CGS, ...
            {'Active'});
    CANONICAL.Reference.Complete = ...
        localGetNestedSignal( ...
            CGS, ...
            {'Complete'});
end
CANONICAL.True = ...
    localExtractStateBus( ...
        RAW_LOGS, ...
        'trueStatesLog');
CANONICAL.Estimated = ...
    localExtractStateBus( ...
        RAW_LOGS, ...
        'estStatesLog');
CANONICAL.Selected = ...
    struct();
if isfield(RAW_LOGS,'selectedEulerLog')
    CANONICAL.Selected.Euler = ...
        localSignalToCanonical( ...
            RAW_LOGS.selectedEulerLog);
end
if isfield(RAW_LOGS,'selectedAngularRateLog')
    CANONICAL.Selected.AngularRate = ...
        localSignalToCanonical( ...
            RAW_LOGS.selectedAngularRateLog);
end
CANONICAL.Actuation = ...
    struct();
if isfield(RAW_LOGS,'omegaLog')
    CANONICAL.Actuation.Omega = ...
        localSignalToCanonical( ...
            RAW_LOGS.omegaLog);
end
if isfield(RAW_LOGS,'controlAxesLog')
    CONTROL_AXES = ...
        RAW_LOGS.controlAxesLog;
    CANONICAL.Actuation.ThrustAxis = ...
        localGetNestedSignal( ...
            CONTROL_AXES, ...
            {'thrustAxis'});
    CANONICAL.Actuation.RollAxis = ...
        localGetNestedSignal( ...
            CONTROL_AXES, ...
            {'rollAxis'});
    CANONICAL.Actuation.PitchAxis = ...
        localGetNestedSignal( ...
            CONTROL_AXES, ...
            {'pitchAxis'});
    CANONICAL.Actuation.YawAxis = ...
        localGetNestedSignal( ...
            CONTROL_AXES, ...
            {'yawAxis'});
end
CANONICAL.Commands = ...
    struct();
if isfield(RAW_LOGS,'cmdAttitudeLog')
    CANONICAL.Commands.Attitude = ...
        localSignalToCanonical( ...
            RAW_LOGS.cmdAttitudeLog);
end
if isfield(RAW_LOGS,'cmdAngularRateLog')
    CANONICAL.Commands.AngularRate = ...
        localSignalToCanonical( ...
            RAW_LOGS.cmdAngularRateLog);
end
CANONICAL.Mission = ...
    struct();
if isfield(RAW_LOGS,'liveTelemetryLog')
    CANONICAL.Mission.LiveTelemetry = ...
        localSignalToCanonical( ...
            RAW_LOGS.liveTelemetryLog);
end
CANONICAL.EstimatorComparison = ...
    struct();
if isfield(RAW_LOGS,'estimatorComparisonLog')
    CANONICAL.EstimatorComparison.Raw = ...
        localSignalToCanonical( ...
            RAW_LOGS.estimatorComparisonLog);
end
fprintf('Searching saved logs for disturbance signals...\n');
DISTURBANCE_EVIDENCE = ...
    localFindDisturbanceEvidence( ...
        RAW_LOGS);
DISTURBANCE_EVIDENCE.WindVelocity = ...
    localEmptyCanonicalSignal();
DISTURBANCE_EVIDENCE.WindVelocityLogged = ...
    false;
if isfield(RAW_LOGS,'windVelocityLog')
    DISTURBANCE_EVIDENCE.WindVelocity = ...
        localSignalToCanonical( ...
            RAW_LOGS.windVelocityLog);
    DISTURBANCE_EVIDENCE.WindVelocityLogged = ...
        logical( ...
            DISTURBANCE_EVIDENCE.WindVelocity.Available);
end
DISTURBANCE_EVIDENCE.WindAngularVelocity = ...
    localEmptyCanonicalSignal();
DISTURBANCE_EVIDENCE.WindAngularVelocityLogged = ...
    false;
if isfield(RAW_LOGS,'windAngularVelocityLog')
    DISTURBANCE_EVIDENCE.WindAngularVelocity = ...
        localSignalToCanonical( ...
            RAW_LOGS.windAngularVelocityLog);
    DISTURBANCE_EVIDENCE.WindAngularVelocityLogged = ...
        logical( ...
            DISTURBANCE_EVIDENCE.WindAngularVelocity.Available);
end
DISTURBANCE_EVIDENCE.RequestedEnabled = ...
    logical( ...
        RUN.Metadata.DisturbanceEnabled);
DISTURBANCE_EVIDENCE.RequestedProfileID = ...
    string( ...
        RUN.Metadata.DisturbanceProfileID);
DISTURBANCE_EVIDENCE.RequestedSeed = ...
    double( ...
        RUN.Metadata.DisturbanceSeed);
DISTURBANCE_EVIDENCE.ActivationThreshold = ...
    1.0e-9;
DISTURBANCE_EVIDENCE.LinearWindActive = ...
    false;
DISTURBANCE_EVIDENCE.AngularWindActive = ...
    false;
DISTURBANCE_EVIDENCE.PeakLinearWindMagnitude = ...
    NaN;
DISTURBANCE_EVIDENCE.PeakAngularWindMagnitude = ...
    NaN;
DISTURBANCE_EVIDENCE.LinearWindWindows_s = ...
    zeros(0,2);
DISTURBANCE_EVIDENCE.AngularWindWindows_s = ...
    zeros(0,2);
if DISTURBANCE_EVIDENCE.WindVelocityLogged
    [ ...
        DISTURBANCE_EVIDENCE.LinearWindActive, ...
        DISTURBANCE_EVIDENCE.PeakLinearWindMagnitude, ...
        DISTURBANCE_EVIDENCE.LinearWindWindows_s ...
    ] = ...
        localAnalyzeDisturbanceSignal( ...
            DISTURBANCE_EVIDENCE.WindVelocity, ...
            DISTURBANCE_EVIDENCE.ActivationThreshold);
end
if DISTURBANCE_EVIDENCE.WindAngularVelocityLogged
    [ ...
        DISTURBANCE_EVIDENCE.AngularWindActive, ...
        DISTURBANCE_EVIDENCE.PeakAngularWindMagnitude, ...
        DISTURBANCE_EVIDENCE.AngularWindWindows_s ...
    ] = ...
        localAnalyzeDisturbanceSignal( ...
            DISTURBANCE_EVIDENCE.WindAngularVelocity, ...
            DISTURBANCE_EVIDENCE.ActivationThreshold);
end
DISTURBANCE_EVIDENCE.Windows_s = ...
    localMergeDisturbanceWindows( ...
        [ ...
            DISTURBANCE_EVIDENCE.LinearWindWindows_s; ...
            DISTURBANCE_EVIDENCE.AngularWindWindows_s ...
        ]);
DISTURBANCE_EVIDENCE.AppliedDetected = ...
    logical( ...
        DISTURBANCE_EVIDENCE.LinearWindActive || ...
        DISTURBANCE_EVIDENCE.AngularWindActive);
DISTURBANCE_EVIDENCE.ActiveDuration_s = ...
    localTotalWindowDuration( ...
        DISTURBANCE_EVIDENCE.Windows_s);
DISTURBANCE_EVIDENCE.Found = ...
    logical( ...
        DISTURBANCE_EVIDENCE.Found || ...
        DISTURBANCE_EVIDENCE.WindVelocityLogged || ...
        DISTURBANCE_EVIDENCE.WindAngularVelocityLogged);
DISTURBANCE_EVIDENCE.ExplicitLogsComplete = ...
    logical( ...
        DISTURBANCE_EVIDENCE.WindVelocityLogged && ...
        DISTURBANCE_EVIDENCE.WindAngularVelocityLogged);
if DISTURBANCE_EVIDENCE.RequestedEnabled
    DISTURBANCE_EVIDENCE.RequestConsistencyPassed = ...
        logical( ...
            DISTURBANCE_EVIDENCE.AppliedDetected);
else
    DISTURBANCE_EVIDENCE.RequestConsistencyPassed = ...
        logical( ...
            ~DISTURBANCE_EVIDENCE.AppliedDetected);
end
DISTURBANCE_EVIDENCE.ValidationPassed = ...
    logical( ...
        DISTURBANCE_EVIDENCE.ExplicitLogsComplete && ...
        DISTURBANCE_EVIDENCE.RequestConsistencyPassed);
CANONICAL.Disturbance = ...
    DISTURBANCE_EVIDENCE;
save( ...
    fullfile( ...
        processedFolder, ...
        'canonical_signals.mat'), ...
    'CANONICAL', ...
    '-v7.3');
save( ...
    fullfile( ...
        processedFolder, ...
        'disturbance_evidence.mat'), ...
    'DISTURBANCE_EVIDENCE', ...
    '-v7.3');
if ~isempty(DISTURBANCE_EVIDENCE.Paths)
    DisturbanceSignalPath = ...
        DISTURBANCE_EVIDENCE.Paths(:);
    DISTURBANCE_SIGNAL_INVENTORY = ...
        table( ...
            DisturbanceSignalPath);
else
    DISTURBANCE_SIGNAL_INVENTORY = ...
        table( ...
            strings(0,1), ...
            'VariableNames',{ ...
                'DisturbanceSignalPath'});
end
writetable( ...
    DISTURBANCE_SIGNAL_INVENTORY, ...
    fullfile( ...
        tablesFolder, ...
        'Disturbance_Signal_Inventory.csv'));
if RUN.Metadata.DisturbanceEnabled && ...
        ~(DISTURBANCE_EVIDENCE.WindVelocityLogged && ...
          DISTURBANCE_EVIDENCE.WindAngularVelocityLogged)
    warning( ...
        'ICRA2027:ExplicitDisturbanceLogsMissing', ...
        ['DIST was requested for run %s, but the explicit disturbance ', ...
         'logs are incomplete.\n', ...
         'Expected SimulationOutput variables:\n', ...
         '    windVelocityLog\n', ...
         '    windAngularVelocityLog\n', ...
         'Raw SimulationOutput data were still preserved.'], ...
        runID);
end
if RUN.Metadata.DisturbanceEnabled && ...
        DISTURBANCE_EVIDENCE.WindVelocityLogged && ...
        DISTURBANCE_EVIDENCE.WindAngularVelocityLogged && ...
        ~DISTURBANCE_EVIDENCE.AppliedDetected
    warning( ...
        'ICRA2027:DisturbanceRequestedButZero', ...
        ['DIST was requested for run %s and both explicit wind logs ', ...
         'were found, but no non-zero applied disturbance was detected.\n', ...
         'Verify the Wind Disturbances variant / enable logic before ', ...
         'accepting this run as a disturbed experiment.'], ...
        runID);
end
if ~RUN.Metadata.DisturbanceEnabled && ...
        DISTURBANCE_EVIDENCE.AppliedDetected
    warning( ...
        'ICRA2027:UnexpectedNominalDisturbance', ...
        ['NOM was requested for run %s, but a non-zero disturbance ', ...
         'was detected in the explicitly logged wind outputs.'], ...
        runID);
end
fprintf('\n');
fprintf('Running project post-processing...\n');
metricVariablesToClear = { ...
    'SummaryMetrics', ...
    'AxisMetrics', ...
    'EstimatorMissionMetrics', ...
    'ActuationMetrics', ...
    'ControllerDiagnostics', ...
    'MissionMetrics', ...
    'WaypointMetrics', ...
    'TouchdownMetrics'};
for clearIndex = 1:numel(metricVariablesToClear)
    evalin( ...
        'base', ...
        sprintf( ...
            'clear %s', ...
            metricVariablesToClear{clearIndex}));
end
staleFigures = ...
    findall( ...
        groot, ...
        'Type','figure');
for figureIndex = 1:numel(staleFigures)
    try
        staleTag = ...
            string(staleFigures(figureIndex).Tag);
        if contains( ...
                upper(staleTag), ...
                "UAV_REMOTE_GUI")
            continue;
        end
        delete( ...
            staleFigures(figureIndex));
    catch
    end
end
postProcessors = { ...
    'Estimator', ...
        fullfile(projectRoot,'plot_estimator_results.m'); ...
    'Trajectory3D', ...
        fullfile(projectRoot,'plot_trajectory_3d.m'); ...
    'Controller', ...
        fullfile(projectRoot,'plot_controller_results.m'); ...
    'Mission', ...
        fullfile(projectRoot,'plot_mission_results.m'); ...
    'Touchdown', ...
        fullfile(projectRoot,'plot_touchdown_diagnostics.m')};
PostProcessor = ...
    strings( ...
        size(postProcessors,1), ...
        1);
Status = ...
    strings( ...
        size(postProcessors,1), ...
        1);
Message = ...
    strings( ...
        size(postProcessors,1), ...
        1);
Duration_s = ...

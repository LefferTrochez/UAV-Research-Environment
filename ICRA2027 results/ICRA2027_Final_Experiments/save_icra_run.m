function [activeDetected,peakMagnitude,windows_s] = ...
    localAnalyzeDisturbanceSignal(SIGNAL,threshold)
activeDetected = ...
    false;
peakMagnitude = ...
    NaN;
windows_s = ...
    zeros(0,2);
if ~isstruct(SIGNAL) || ...
        ~isfield(SIGNAL,'Available') || ...
        ~logical(SIGNAL.Available) || ...
        ~isfield(SIGNAL,'Time_s') || ...
        ~isfield(SIGNAL,'Data')
    return;
end
time_s = ...
    double( ...
        SIGNAL.Time_s(:));
data = ...
    double( ...
        SIGNAL.Data);
if isempty(time_s) || ...
        isempty(data)
    return;
end
if size(data,1) ~= numel(time_s)
    return;
end
validTime = ...
    isfinite(time_s);
if ~any(validTime)
    return;
end
time_s = ...
    time_s(validTime);
data = ...
    data(validTime,:);
if isempty(data)
    return;
end
finiteData = ...
    data;
finiteData(~isfinite(finiteData)) = ...
    0;
if isvector(finiteData)
    magnitude = ...
        abs( ...
            finiteData(:));
else
    magnitude = ...
        sqrt( ...
            sum( ...
                finiteData.^2, ...
                2));
end
if isempty(magnitude)
    return;
end
peakMagnitude = ...
    max( ...
        magnitude, ...
        [], ...
        'omitnan');
activeMask = ...
    magnitude > ...
    threshold;
activeDetected = ...
    any(activeMask);
if ~activeDetected
    return;
end
windows_s = ...
    localLogicalMaskToWindows( ...
        time_s, ...
        activeMask);
end
function windows_s = localLogicalMaskToWindows(time_s,activeMask)
windows_s = ...
    zeros(0,2);
time_s = ...
    double( ...
        time_s(:));
activeMask = ...
    logical( ...
        activeMask(:));
if isempty(time_s) || ...
        numel(time_s) ~= numel(activeMask)
    return;
end
valid = ...
    isfinite(time_s);
time_s = ...
    time_s(valid);
activeMask = ...
    activeMask(valid);
if isempty(time_s) || ...
        ~any(activeMask)
    return;
end
[time_s,order] = ...
    sort( ...
        time_s);
activeMask = ...
    activeMask(order);
[uniqueTime,~,groupIndex] = ...
    unique( ...
        time_s);
if numel(uniqueTime) ~= numel(time_s)
    aggregatedMask = ...
        accumarray( ...
            groupIndex, ...
            double(activeMask), ...
            [], ...
            @max, ...
            0) > 0;
    time_s = ...
        uniqueTime;
    activeMask = ...
        aggregatedMask;
end
transitions = ...
    diff( ...
        [ ...
            false; ...
            activeMask; ...
            false ...
        ]);
startIndex = ...
    find( ...
        transitions == 1);
endIndex = ...
    find( ...
        transitions == -1) - 1;
windows_s = ...
    [ ...
        time_s(startIndex), ...
        time_s(endIndex) ...
    ];
for k = 1:size(windows_s,1)
    if windows_s(k,2) <= windows_s(k,1)
        idx = ...
            startIndex(k);
        if idx < numel(time_s)
            windows_s(k,2) = ...
                time_s(idx+1);
        elseif idx > 1
            dt = ...
                time_s(idx) - ...
                time_s(idx-1);
            if isfinite(dt) && ...
                    dt > 0
                windows_s(k,2) = ...
                    time_s(idx) + ...
                    dt;
            end
        end
    end
end
validWindows = ...
    all( ...
        isfinite(windows_s), ...
        2) & ...
    windows_s(:,2) >= ...
    windows_s(:,1);
windows_s = ...
    windows_s(validWindows,:);
end
function mergedWindows_s = localMergeDisturbanceWindows(windows_s)
mergedWindows_s = ...
    zeros(0,2);
if isempty(windows_s) || ...
        size(windows_s,2) ~= 2
    return;
end
windows_s = ...
    double( ...
        windows_s);
validRows = ...
    all( ...
        isfinite(windows_s), ...
        2) & ...
    windows_s(:,2) >= ...
    windows_s(:,1);
windows_s = ...
    windows_s(validRows,:);
if isempty(windows_s)
    return;
end
windows_s = ...
    sortrows( ...
        windows_s, ...
        1);
currentWindow = ...
    windows_s(1,:);
for k = 2:size(windows_s,1)
    candidate = ...
        windows_s(k,:);
    tolerance = ...
        1.0e-9 * ...
        max( ...
            1.0, ...
            max(abs([currentWindow candidate])));
    if candidate(1) <= ...
            currentWindow(2) + ...
            tolerance
        currentWindow(2) = ...
            max( ...
                currentWindow(2), ...
                candidate(2));
    else
        mergedWindows_s(end+1,:) = ...
            currentWindow; %#ok<AGROW>
        currentWindow = ...
            candidate;
    end
end
mergedWindows_s(end+1,:) = ...
    currentWindow;
end

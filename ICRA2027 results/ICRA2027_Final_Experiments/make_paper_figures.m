        'LineWidth',simEndLineWidth, ...
        'HandleVisibility','off');
    yl = ylim(ax);
    yText = ...
        yl(2) - 0.06*(yl(2)-yl(1));
    text( ...
        ax, ...
        simEndMarker_s + 0.25, ...
        yText, ...

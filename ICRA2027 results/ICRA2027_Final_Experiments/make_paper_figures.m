R = char(CFG.Paths.ResultsRoot);
tablesDir = fullfile(R,'tables');
runsDir   = fullfile(R,'runs');
outDir    = fullfile(R,'paper_figures');
if ~exist(outDir,'dir')
    mkdir(outDir);
end
experimentRoot = fileparts(R);
frameworkRoot  = fileparts(experimentRoot);
realMatFile = fullfile( ...
    frameworkRoot, ...
    'Real_Flight_TLOG', ...
    'results', ...
    'REAL_T2', ...
    'experiment_data.mat');
if ~isfile(realMatFile)
    error('REAL T2 file not found:\n%s',realMatFile);
end
controllerCsv = fullfile( ...
    tablesDir, ...
    'ICRA_Controller_Diagnostics.csv');
if ~isfile(controllerCsv)
    error('Controller diagnostics table not found:\n%s',controllerCsv);
end
C = readtable( ...
    controllerCsv, ...
    'VariableNamingRule','preserve');
C = selectOfficial(C);
C = C( ...
    string(C.TrajectoryCode_ICRA)=="T2" & ...
    string(C.DisturbanceID_ICRA)=="DIST",:);
requiredTimingVars = { ...
    'MissionStartTime_s', ...
    'NavigationEndTime_s'};
for k = 1:numel(requiredTimingVars)
    if ~ismember(requiredTimingVars{k},C.Properties.VariableNames)
        error( ...
            'Controller diagnostics table is missing %s.', ...
            requiredTimingVars{k});
    end
end
levels = ["L1","L2","L3"];
traj   = "T2";
cond   = "DIST";
RF = load( ...
    realMatFile, ...
    'REAL_DATA', ...
    'REAL_ATTITUDE_TRACKING_RESULTS');
if ~isfield(RF,'REAL_DATA')
    error('REAL_DATA is missing.');
end
if ~isfield(RF,'REAL_ATTITUDE_TRACKING_RESULTS')
    error('REAL_ATTITUDE_TRACKING_RESULTS is missing.');
end
if ~isfield(RF.REAL_DATA,'State') || ...
        ~isfield(RF.REAL_DATA.State,'Attitude')
    error('REAL_DATA.State.Attitude is unavailable.');
end
ATT = RF.REAL_DATA.State.Attitude;
requiredRealFields = { ...
    'Time_s', ...
    'Roll_rad', ...
    'Pitch_rad', ...
    'Yaw_rad'};
if ~istable(ATT)
    error('REAL_DATA.State.Attitude must be a table.');
end
for k = 1:numel(requiredRealFields)
    if ~ismember(requiredRealFields{k},ATT.Properties.VariableNames)
        error( ...
            'REAL attitude table is missing %s.', ...
            requiredRealFields{k});
    end
end
modelColors = lines(3);
realColor   = [0.00 0.60 0.00];
fontSize         = 10;
lineWidth        = 1.20;
realLineWidth    = 1.45;
attitudePad_deg  = 0.50;
simEndLineColor  = [0.30 0.30 0.30];
simEndLineWidth  = 1.35;
attNames = ["Roll","Pitch","Yaw"];
SIM_DISPLAY_TRIM_s = 7.5;
realStart_s = ...
    double(RF.REAL_ATTITUDE_TRACKING_RESULTS.StartTime_s);
realEnd_s = ...
    double(RF.REAL_ATTITUDE_TRACKING_RESULTS.EndTime_s);
if ~isfinite(realStart_s) || ...
        ~isfinite(realEnd_s) || ...
        realEnd_s <= realStart_s
    error('Invalid REAL attitude window.');
end
realMask = ...
    double(ATT.Time_s) >= realStart_s & ...
    double(ATT.Time_s) <= realEnd_s;
if nnz(realMask)<2
    error('Insufficient REAL attitude samples.');
end
tRealRaw = double(ATT.Time_s(realMask));
tReal = tRealRaw - tRealRaw(1);
realEuler_deg = [ ...
    rad2deg(double(ATT.Roll_rad(realMask))), ...
    rad2deg(double(ATT.Pitch_rad(realMask))), ...
    rad2deg(double(ATT.Yaw_rad(realMask)))];
realEuler_deg(:,3) = ...
    mod(realEuler_deg(:,3)+180,360)-180;
realDuration_s = tReal(end);
simData = struct([]);
originalSimDurations_s = NaN(3,1);
retainedDurations_s    = NaN(3,1);
displayDurations_s     = NaN(3,1);
timeScaleFactors       = NaN(3,1);
for il = 1:3
    lev = levels(il);
    cr = getRow(C,lev,traj);
    missionStart_s = ...
        double(cr.MissionStartTime_s);
    navigationEnd_s = ...
        double(cr.NavigationEndTime_s);
    originalDuration_s = ...
        navigationEnd_s - missionStart_s;
    retainedDuration_s = ...
        originalDuration_s - SIM_DISPLAY_TRIM_s;
    if retainedDuration_s <= 0
        error( ...
            ['SIM display trim %.3f s exceeds or equals ', ...
             'trajectory duration for %s.'], ...
            SIM_DISPLAY_TRIM_s,lev);
    end
    runID = officialRunID( ...
        lev, ...
        traj, ...
        cond);
    S = loadCanonical( ...
        runsDir, ...
        runID);
    if isfield(S,'Selected') && ...
            isfield(S.Selected,'Euler') && ...
            signalAvailable(S.Selected.Euler)
        stateSig = S.Selected.Euler;
    elseif isfield(S,'True') && ...
            isfield(S.True,'Euler') && ...
            signalAvailable(S.True.Euler)
        stateSig = S.True.Euler;
    else
        error('Euler state unavailable for %s.',runID);
    end
    [ts,xs] = getSignalData(stateSig);
    plotStartAbs_s = ...
        missionStart_s + SIM_DISPLAY_TRIM_s;
    [ts,xs] = cropSignal( ...
        ts, ...
        xs, ...
        plotStartAbs_s, ...
        navigationEnd_s);
    if isempty(xs) || ...
            size(xs,2)<3 || ...
            numel(ts)<2
        error( ...
            'Invalid Euler state for %s after %.3f-s trim.', ...
            runID,SIM_DISPLAY_TRIM_s);
    end
    tRetained = ts - ts(1);
    retainedActualDuration_s = ...
        tRetained(end);
    if ~isfinite(retainedActualDuration_s) || ...
            retainedActualDuration_s<=0
        error('Invalid retained duration for %s.',runID);
    end
    tSim = ...
        tRetained .* ...
        (originalDuration_s / retainedActualDuration_s);
    simEuler_deg = rad2deg(xs);
    simEuler_deg(:,3) = ...
        mod(simEuler_deg(:,3)+180,360)-180;
    simData(il).Level = lev;
    simData(il).RunID = runID;
    simData(il).t = tSim;
    simData(il).Euler_deg = simEuler_deg;
    originalSimDurations_s(il) = ...
        originalDuration_s;
    retainedDurations_s(il) = ...
        retainedActualDuration_s;
    displayDurations_s(il) = ...
        tSim(end);
    timeScaleFactors(il) = ...
        tSim(end) / retainedActualDuration_s;
end

            ySim, ...
            '-', ...
            'Color',modelColors(il,:), ...
            'LineWidth',lineWidth, ...
            'DisplayName', ...
            sprintf('%s Estimated State',simData(il).Level));
        yAll = [yAll; ySim]; %#ok<AGROW>
    end
    yReal = ...
        realEuler_deg(:,ia);
    plot( ...
        ax, ...
        tReal, ...
        yReal, ...
        '-', ...
        'Color',realColor, ...
        'LineWidth',realLineWidth, ...

function T = selectOfficial(T)
    required = { ...
        'PlantCode_ICRA', ...
        'ControllerID_ICRA'};
    for k = 1:numel(required)
        if ~ismember(required{k},T.Properties.VariableNames)
            error( ...
                'Table is missing required column: %s', ...
                required{k});
        end
    end
    level = string(T.PlantCode_ICRA);
    ctrl  = string(T.ControllerID_ICRA);
    keep = ...
        (level=="L1" & ctrl=="C1") | ...
        (level=="L2" & ctrl=="C1") | ...
        (level=="L3" & ctrl=="C2");
    T = T(keep,:);
end
function r = getRow(T,level,traj)
    required = { ...
        'PlantCode_ICRA', ...
        'TrajectoryCode_ICRA', ...
        'DisturbanceID_ICRA'};
    for k = 1:numel(required)
        if ~ismember(required{k},T.Properties.VariableNames)
            error( ...
                'Table is missing required column: %s', ...
                required{k});
        end
    end
    idx = ...
        string(T.PlantCode_ICRA)==string(level) & ...
        string(T.TrajectoryCode_ICRA)==string(traj) & ...
        string(T.DisturbanceID_ICRA)=="DIST";
    if nnz(idx)~=1
        error( ...
            'Expected one row for %s/%s/DIST; found %d.', ...
            level, ...
            traj, ...
            nnz(idx));
    end
    r = T(idx,:);
end
function runID = officialRunID(level,traj,cond)
    level = string(level);
    if level=="L1" || level=="L2"
        controller = "C1";
    elseif level=="L3"
        controller = "C2";
    else
        error( ...
            'Unknown fidelity level: %s.', ...
            level);
    end
    runID = ...
        controller + "_" + ...
        string(traj) + "_" + ...
        level + "_" + ...
        string(cond);
end
function C = loadCanonical(runsDir,runID)
    file = fullfile( ...
        runsDir, ...
        char(runID), ...
        'processed', ...
        'canonical_signals.mat');
    if ~isfile(file)
        error( ...
            'Canonical file not found:\n%s', ...
            file);
    end
    S = load( ...
        file, ...
        'CANONICAL');
    if ~isfield(S,'CANONICAL')
        error( ...
            'CANONICAL missing in:\n%s', ...
            file);
    end
    C = S.CANONICAL;
end
function tf = signalAvailable(S)
    tf = ...
        isstruct(S) && ...
        isfield(S,'Data') && ...
        ~isempty(S.Data);
    if tf && isfield(S,'Available')
        tf = tf && logical(S.Available);
    end
end
function [t,x] = getSignalData(S)
    t = [];
    x = [];
    if ~signalAvailable(S)
        return
    end
    x = squeeze(double(S.Data));
    if isvector(x)
        x = x(:);
    end
    if isfield(S,'Time_s') && ...
            ~isempty(S.Time_s)
        t = double(S.Time_s(:));
    end
    if ~isempty(t) && ...
            size(x,1)~=numel(t) && ...
            size(x,2)==numel(t)
        x = x.';
    end
    if isempty(t) || ...
            size(x,1)~=numel(t) || ...
            all(~isfinite(t))
        t = (0:size(x,1)-1).';
    end
    good = isfinite(t);
    if size(x,2)==1
        good = ...
            good & isfinite(x);
    else
        good = ...
            good & any(isfinite(x),2);
    end
    t = t(good,:);
    x = x(good,:);
end
function [tOut,xOut] = cropSignal(t,x,t0,t1)
    tOut = [];
    xOut = [];
    if isempty(t) || isempty(x)
        return
    end
    idx = ...
        t>=double(t0) & ...
        t<=double(t1);
    tOut = t(idx,:);
    xOut = x(idx,:);
end
function setTightYLimits(ax,y,minPad)
    y = y(isfinite(y));
    if isempty(y)
        return
    end
    yMin = min(y);
    yMax = max(y);
    span = yMax-yMin;
    if span<=0
        pad = ...
            max( ...
            minPad, ...
            0.05*max(abs(yMax),1));
    else
        pad = ...
            max( ...
            minPad, ...
            0.03*span);
    end
    ylim( ...
        ax, ...
        [yMin-pad, ...
         yMax+pad]);
end
function savePaperFigure(f,outDir,baseName)
    pngFile = ...
        fullfile( ...
        outDir, ...
        [baseName '.png']);
    pdfFile = ...
        fullfile( ...
        outDir, ...
        [baseName '.pdf']);
    figFile = ...
        fullfile( ...
        outDir, ...
        [baseName '.fig']);
    exportgraphics( ...
        f, ...
        pngFile, ...
        'Resolution',600);
    exportgraphics( ...
        f, ...
        pdfFile, ...
        'ContentType','vector');
    savefig( ...
        f, ...
        figFile);
end

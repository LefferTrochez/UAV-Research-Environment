function RunPlan = localBuildRunPlan( ...
    Controllers, ...
    Trajectories, ...
    Plants, ...
    DisturbanceConditions)
numberRuns = ...
    numel(Controllers) * ...
    numel(Trajectories) * ...
    numel(Plants) * ...
    numel(DisturbanceConditions);
RunNumber = ...
    zeros(numberRuns,1);
RunID = ...
    strings(numberRuns,1);
ControllerIndex = ...
    zeros(numberRuns,1);
ControllerID = ...
    strings(numberRuns,1);
ControllerCode = ...
    strings(numberRuns,1);
ControllerName = ...
    strings(numberRuns,1);
ControllerTunedPlant = ...
    strings(numberRuns,1);
TrajectoryID = ...
    zeros(numberRuns,1);
TrajectoryCode = ...
    strings(numberRuns,1);
TrajectoryName = ...
    strings(numberRuns,1);
PlantID = ...
    zeros(numberRuns,1);
PlantCode = ...
    strings(numberRuns,1);
PlantName = ...
    strings(numberRuns,1);
DisturbanceID = ...
    strings(numberRuns,1);
DisturbanceEnabled = ...
    false(numberRuns,1);
DisturbanceProfileID = ...
    strings(numberRuns,1);
DisturbanceSeed = ...
    zeros(numberRuns,1);
runIndex = ...
    0;
for controllerIndex = 1:numel(Controllers)
    for trajectoryIndex = 1:numel(Trajectories)
        for disturbanceIndex = 1:numel(DisturbanceConditions)
            for plantIndex = 1:numel(Plants)
                runIndex = ...
                    runIndex + 1;
                controller = ...
                    Controllers(controllerIndex);
                trajectory = ...
                    Trajectories(trajectoryIndex);
                plant = ...
                    Plants(plantIndex);
                disturbance = ...
                    DisturbanceConditions(disturbanceIndex);
                RunNumber(runIndex) = ...
                    runIndex;
                RunID(runIndex) = ...
                    sprintf( ...
                        '%s_%s_%s_%s', ...
                        controller.ID, ...
                        trajectory.Code, ...
                        plant.Code, ...
                        disturbance.ID);
                ControllerIndex(runIndex) = ...
                    controller.Index;
                ControllerID(runIndex) = ...
                    controller.ID;
                ControllerCode(runIndex) = ...
                    controller.Code;
                ControllerName(runIndex) = ...
                    controller.Name;
                ControllerTunedPlant(runIndex) = ...
                    controller.TunedPlant;
                TrajectoryID(runIndex) = ...
                    trajectory.ID;
                TrajectoryCode(runIndex) = ...
                    trajectory.Code;
                TrajectoryName(runIndex) = ...
                    trajectory.Name;
                PlantID(runIndex) = ...
                    plant.ID;
                PlantCode(runIndex) = ...
                    plant.Code;
                PlantName(runIndex) = ...
                    plant.Name;
                DisturbanceID(runIndex) = ...
                    disturbance.ID;
                DisturbanceEnabled(runIndex) = ...
                    disturbance.Enabled;
                DisturbanceProfileID(runIndex) = ...
                    disturbance.ProfileID;
                DisturbanceSeed(runIndex) = ...
                    disturbance.RandomSeed;
            end
        end
    end
end
RunPlan = ...
    table( ...
        RunNumber, ...
        RunID, ...
        ControllerIndex, ...
        ControllerID, ...
        ControllerCode, ...
        ControllerName, ...
        ControllerTunedPlant, ...
        TrajectoryID, ...
        TrajectoryCode, ...
        TrajectoryName, ...
        PlantID, ...
        PlantCode, ...
        PlantName, ...
        DisturbanceID, ...
        DisturbanceEnabled, ...
        DisturbanceProfileID, ...
        DisturbanceSeed);
end
function localValidateConfiguration(CFG)
if ~isfile(CFG.Paths.ModelFile)
    error( ...
        'ICRA2027:ModelFileNotFound', ...
        'Simulink model was not found:\n%s', ...
        CFG.Paths.ModelFile);
end
if ~isfile(CFG.Paths.InitializationFile)
    error( ...
        'ICRA2027:InitializationFileNotFound', ...
        'initialize_project.m was not found:\n%s', ...
        CFG.Paths.InitializationFile);
end
if ~isfile(CFG.Paths.AutopilotFile)
    error( ...
        'ICRA2027:AutopilotFileNotFound', ...
        'UAV_autopilot.m was not found:\n%s', ...
        CFG.Paths.AutopilotFile);
end
if numel(CFG.Controllers) ~= 2
    error( ...
        'ICRA2027:InvalidControllerCount', ...
        'The current final campaign requires exactly 2 controllers.');
end
if numel(CFG.Trajectories) ~= 2
    error( ...
        'ICRA2027:InvalidTrajectoryCount', ...
        'The current final campaign requires exactly 2 trajectories.');
end
if numel(CFG.Plants) ~= 3
    error( ...
        'ICRA2027:InvalidPlantCount', ...
        'The current final campaign requires exactly 3 plant models.');
end
if numel(CFG.DisturbanceConditions) ~= 2
    error( ...
        'ICRA2027:InvalidDisturbanceConditionCount', ...
        'The current final campaign requires NOM and DIST conditions.');
end
if CFG.NumberOfRuns ~= 24
    error( ...
        'ICRA2027:InvalidRunCount', ...
        ['The final campaign must contain exactly 24 runs.\n', ...
         'Current configuration contains %d runs.'], ...
        CFG.NumberOfRuns);
end
if numel(unique(CFG.RunPlan.RunID)) ~= ...
        CFG.NumberOfRuns
    error( ...
        'ICRA2027:DuplicateRunID', ...
        'Duplicate experiment RunID values were detected.');
end
expectedPlantIDs = ...
    [1 2 3];
actualPlantIDs = ...
    [CFG.Plants.ID];
if ~isequal(actualPlantIDs, expectedPlantIDs)
    error( ...
        'ICRA2027:InvalidPlantIDs', ...
        'Plant IDs must be [1 2 3] for L1/L2/L3.');
end
expectedTrajectoryIDs = ...
    [1 2];
actualTrajectoryIDs = ...
    [CFG.Trajectories.ID];
if ~isequal(actualTrajectoryIDs, expectedTrajectoryIDs)
    error( ...
        'ICRA2027:InvalidTrajectoryIDs', ...
        'Final paper trajectory IDs must currently be [1 2].');
end
numberExpectedGains = ...
    numel(CFG.ControllerGainNames);
for controllerIndex = 1:numel(CFG.Controllers)
    currentGainVector = ...
        CFG.Controllers(controllerIndex).GainVector;
    if numel(currentGainVector) ~= numberExpectedGains
        error( ...
            'ICRA2027:InvalidControllerGainCount', ...
            ['Controller %s contains %d gains; expected %d.'], ...
            CFG.Controllers(controllerIndex).ID, ...
            numel(currentGainVector), ...
            numberExpectedGains);
    end
    if any(~isfinite(currentGainVector))
        error( ...
            'ICRA2027:InvalidControllerGain', ...
            'Controller %s contains non-finite gain values.', ...
            CFG.Controllers(controllerIndex).ID);
    end
end
end

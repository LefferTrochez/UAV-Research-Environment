function [genericTelemetry,maxWaypoints] = ...
        detectGenericTouchdownTelemetry(numberOfColumns)
    genericTelemetry = ...
        numberOfColumns >= (59 + 4*3) && ...
        mod(numberOfColumns-59,4) == 0;
    if genericTelemetry
        maxWaypoints = ...

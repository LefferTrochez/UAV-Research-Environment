function firstIndex = firstPersistentTrueForDurationTouchdown( ...
    logicalVector, ...
    timeVector, ...
    durationRequired_s)
    logicalVector = ...
        logical( ...
            logicalVector(:));
    timeVector = ...
        double( ...
            timeVector(:));
    firstIndex = ...
        [];
    if isempty(logicalVector) || ...
            numel(logicalVector) ~= numel(timeVector) || ...
            ~isfinite(durationRequired_s) || ...
            durationRequired_s < 0
        return;
    end
    if any(~isfinite(timeVector)) || ...
            any(diff(timeVector) < 0)
        return;
    end
    runStart = ...
        0;
    for k = 1:numel(logicalVector)
        if logicalVector(k)
            if runStart == 0
                runStart = ...
                    k;
            end
            if timeVector(k) - ...
                    timeVector(runStart) >= ...
                    durationRequired_s
                firstIndex = ...
                    runStart;
                return;
            end
        else
            runStart = ...
                0;
        end
    end
end

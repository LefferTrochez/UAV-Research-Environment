function Xquery = resampleMatrixTouchdown(tSource,XSource,tQuery)
    tSource = ...
        double( ...
            tSource(:));
    tQuery = ...
        double( ...
            tQuery(:));
    XSource = ...
        double(XSource);
    if size(XSource,1) ~= numel(tSource)
        error( ...
            'Source matrix row count does not match source time vector.');
    end
    if numel(tSource) == numel(tQuery) && ...
            all(abs(tSource-tQuery) <= 1e-12)
        Xquery = ...
            XSource;
        return;
    end
    finiteTimeMask = ...
        isfinite(tSource);
    tSource = ...
        tSource(finiteTimeMask);
    XSource = ...
        XSource(finiteTimeMask,:);
    [tUnique,uniqueIndex] = ...
        unique( ...
            tSource, ...
            'stable');
    XUnique = ...
        XSource( ...
            uniqueIndex, ...
            :);
    if isempty(tUnique)
        error( ...
            'Touchdown source signal contains no finite timestamps.');
    end
    if any(tQuery < tUnique(1)-1e-9) || ...
            any(tQuery > tUnique(end)+1e-9)
        error( ...
            ['Touchdown telemetry time base exceeds one of the ', ...
             'required source-log time intervals.']);
    end
    if numel(tUnique) == 1
        Xquery = ...
            repmat( ...
                XUnique(1,:), ...
                numel(tQuery), ...
                1);
        return;
    end
    Xquery = ...
        NaN( ...
            numel(tQuery), ...
            size(XUnique,2));
    for column = 1:size(XUnique,2)
        sourceColumn = ...
            XUnique(:,column);
        finiteSignalMask = ...
            isfinite(sourceColumn);
        if nnz(finiteSignalMask) == 0
            continue;
        end
        tSignal = ...
            tUnique(finiteSignalMask);
        xSignal = ...
            sourceColumn(finiteSignalMask);
        if numel(tSignal) == 1
            Xquery(:,column) = ...
                xSignal(1);
        else
            Xquery(:,column) = ...
                interp1( ...
                    tSignal, ...
                    xSignal, ...
                    tQuery, ...
                    'linear', ...
                    NaN);
        end
    end
end
function X = timeseriesDataToMatrixTouchdown(data,nt)
    D = ...
        squeeze( ...
            data);
    if isempty(D)
        X = ...
            zeros(0,0);
        return;
    end
    if nt == 1
        X = ...
            reshape( ...
                D, ...
                1, ...
                []);
        return;
    end
    if isvector(D)
        if numel(D) == nt
            X = ...
                D(:);
        else
            error( ...
                'Unable to determine logged signal orientation.');
        end
        return;
    end
    if size(D,1) == nt
        X = ...
            reshape( ...
                D, ...
                nt, ...
                []);
    elseif size(D,2) == nt
        X = ...
            D.';
    elseif size(D,ndims(D)) == nt
        order = [ ...
            ndims(D), ...
            1:(ndims(D)-1)];
        D = ...
            permute( ...
                D, ...
                order);
        X = ...
            reshape( ...
                D, ...
                nt, ...
                []);
    else
        error( ...
            ['Unable to match logged signal dimensions ', ...
             'with its time vector.']);
    end
end
function firstIndex = firstPersistentTrueTouchdown(logicalVector,countRequired)
    logicalVector = ...
        logical( ...
            logicalVector(:));
    countRequired = ...
        max( ...
            1, ...
            round( ...
                countRequired));
    firstIndex = ...
        [];
    if isempty(logicalVector)
        return;
    end
    runCount = ...
        0;
    runStart = ...
        0;
    for k = 1:numel(logicalVector)
        if logicalVector(k)
            if runCount == 0
                runStart = ...
                    k;
            end
            runCount = ...
                runCount + 1;
            if runCount >= countRequired
                firstIndex = ...
                    runStart;
                return;
            end
        else
            runCount = ...
                0;
            runStart = ...
                0;
        end
    end
end
